def main():
    copied = 0
    skipped = 0
    missing = []

    for rel in FILES:
        # Пробуем источники: корень, templates/, Templates/, Shablony/
        src = ROOT / rel
        if not src.exists():
            src = ROOT / "templates" / rel
        if not src.exists():
            src = ROOT / "Templates" / rel
        if not src.exists():
            src = ROOT / "Shablony" / rel

        # Копируем в Shablony (основная папка)
        dst_shablony = SHABLONY / rel
        # Также копируем в Templates для совместимости
        dst_templates = TEMPLATES / rel

        if src.exists():
            # Копируем в Shablony
            dst_shablony.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst_shablony)
            # Копируем в Templates для совместимости
            dst_templates.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst_templates)
            print("OK:", rel)
            copied += 1
        else:
            print("НЕТ (пропуск):", rel)
            missing.append(rel)
            skipped += 1

    print("\n--- Итог ---")
    print("Скопировано в Shablony:", copied)
    print("Не найдено (пропущено):", skipped)
    if missing:
        print("\nНе найдены (добавьте вручную или положите в корень проекта):")
        for m in missing:
            print(" ", m)

if __name__ == "__main__":
    main()

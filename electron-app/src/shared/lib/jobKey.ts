// Ключ идемпотентности задачи конвертера: одно нажатие кнопки — один ключ.
// Повтор запроса с тем же ключом конвертер не запускает второй раз, а отдаёт
// ту же задачу (reused: true). Без ключа сорвавшийся POST даёт вторую
// конвертацию того же файла: двойное время и двойная память.

/** Уникальный ключ на одно нажатие. */
export function newJobKey(): string {
  try {
    // В проде окно грузится с file://, где randomUUID может быть недоступен.
    return crypto.randomUUID();
  } catch {
    return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  }
}

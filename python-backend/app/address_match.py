# -*- coding: utf-8 -*-
"""Сверка двух написаний ОДНОГО адреса.

Нужна там, где адрес есть и в документе, и в справочнике. Дословное сравнение
зажигало бы предупреждение почти на каждом заявлении: одно и то же место пишут
«117420, г. Москва, ул. Наметкина, д. 16, корп. 1» и «117420, Москва,
Наметкина ул., 16 корп.1».

Сверяются ТРИ составляющие (решение Андрея, 02.09.2026): ИНДЕКС, УЛИЦА, ДОМ.
Регион, район, форма населённого пункта, офис, помещение, этаж пишут вразнобой
и в сверке не участвуют.

Тип улицы (ул./пр-кт/наб.) в ключ НЕ входит: конвертер и сокращения корёжат
именно его, а совпадение индекса и номера дома при разном типе улицы в одном
городе — случай куда более редкий, чем «ул.» против «улица».

Все функции чистые.
"""
from __future__ import annotations

import re
from typing import Tuple

# Кавычки и неразрывные пробелы — до сопоставления (правило нормализации входа).
_SPACE_TABLE = {0x00A0: " ", 0x2007: " ", 0x202F: " ", 0x2011: "-", 0x2013: "-", 0x2014: "-"}
_QUOTES = "".join(chr(c) for c in (0xAB, 0xBB, 0x201C, 0x201D, 0x2018, 0x2019, 0x22, 0x27))

_TYPE_ALT = (
    r"ул|улиц[аеы]|пр-?кт|пр-?т|просп|проспект|пер|переул(?:ок|ке)|"
    r"наб|набережн(?:ая|ой)|б-?р|бульвар|ш|шоссе|пл|площад[ьи]|проезд|"
    r"туп|тупик|лини[яи]|алле[яи]|тракт|мкр|микрорайон|квартал"
)
# Слова, которые НЕ могут быть продолжением названия улицы: за ними идёт дом.
_NOT_NAME = r"д|дом|корп?|кори|корпус|стр|строение|вл|владение|зд|здание|пом|оф|кв|лит|литера|эт"

# Название улицы: до трёх слов, допускается числовое начало («8 Марта»,
# «1905 года»). Продолжение обрывается на метке дома — иначе «ул. Наметкина
# д. 16» без запятой съело бы «д» в название.
_NAME = (
    r"(?:\d+(?:-?[а-яё]+)?\s+)?"
    r"[а-яё][а-яё\-]*"
    r"(?:\s+(?!(?:" + _NOT_NAME + r")[\s.]|\d)[а-яё][а-яё\-]*){0,2}"
)

_STREET_PREFIX_RE = re.compile(
    r"(?:^|[,;(]|\s)(?:" + _TYPE_ALT + r")\.?\s+(?P<name>" + _NAME + r")",
    re.VERBOSE | re.IGNORECASE,
)
_STREET_SUFFIX_RE = re.compile(
    r"(?P<name>" + _NAME + r")\s*,?\s+(?:" + _TYPE_ALT + r")\.?(?=[\s,;)]|$)",
    re.VERBOSE | re.IGNORECASE,
)

_INDEX_RE = re.compile(r"(?<!\d)(\d{6})(?!\d)")

# Номер дома с явной меткой и номер сразу за названием улицы («…Морская, 29»).
# Буква дома пишется и слитно («19б»), и через дефис («11-А»), и отдельной
# литерой («11, лит. А») — все три сводятся к одному ключу «11а».
_HOUSE_NUM = r"\d+(?:\s*-\s*)?[а-яё]?"
_HOUSE_MARKED_RE = re.compile(r"\b(?:д|дом|вл|владение|зд|здание)\.?\s*(" + _HOUSE_NUM + r")(?![а-яё])")
_HOUSE_BARE_RE = re.compile(r"^[\s,]*(" + _HOUSE_NUM + r")(?![а-яё\d])")
# Корпус/строение/литера. «кори» — не опечатка: так конвертер печатает «корп».
# Порядок ветвей — от длинной к короткой, иначе «корп» разбирается как «к» + «орп»
# и номером дома становится буква. Граница после метки обязательна по той же причине.
_BUILDING_RE = re.compile(
    r"^[\s,/]*(?:(?P<k>корпус|корп|кори|кор|к)|(?P<s>строение|стр)|(?P<l>литера|лит))"
    r"(?![а-яё])\.?\s*(?P<num>\d+[а-яё]?|[а-яё])(?![а-яё])"
)


def _canon(value: str) -> str:
    """Единое написание до сопоставления: регистр, ё/е, кавычки, пробелы, дефисы."""
    text = (value or "").translate(_SPACE_TABLE)
    text = text.translate(str.maketrans("", "", _QUOTES))
    text = text.lower().replace("\u0451", "\u0435")
    return re.sub(r"\s+", " ", text).strip()


def address_index(value: str) -> str:
    """Почтовый индекс — первое шестизначное число."""
    m = _INDEX_RE.search(_canon(value))
    return m.group(1) if m else ""


def _street_match(canon: str):
    """Совпадение названия улицы: сначала «ул. Имя», затем «Имя ул.»."""
    return _STREET_PREFIX_RE.search(canon) or _STREET_SUFFIX_RE.search(canon)


def address_street(value: str) -> str:
    """Название улицы БЕЗ типа: «ул. Большая Морская» и «Большая Морская ул.» равны."""
    m = _street_match(_canon(value))
    if not m:
        return ""
    return re.sub(r"\s+", " ", m.group("name")).strip(" -,")


def address_house(value: str) -> str:
    """Дом с корпусом/строением одной строкой: «д. 16, корп. 1» -> «16к1»."""
    canon = _canon(value)
    street = _street_match(canon)
    # Искать дом ДО названия улицы бессмысленно: там индекс, регион и город.
    tail = canon[street.end():] if street else canon

    house = _HOUSE_BARE_RE.match(tail) if street else None
    if not house:
        house = _HOUSE_MARKED_RE.search(tail)
    if not house:
        return ""

    result = re.sub(r"[\s-]", "", house.group(1))
    building = _BUILDING_RE.match(tail[house.end():])
    if building:
        # Литера — та же буква дома, что и в «11-А», поэтому маркера не получает:
        # иначе «д. 11-А» и «д. 11, лит. А» дали бы разные ключи.
        marker = "к" if building.group("k") else ("с" if building.group("s") else "")
        result += marker + building.group("num")
    return result


def address_key(value: str) -> Tuple[str, str, str]:
    """Ключ сверки: (индекс, улица, дом). Пустая составляющая = «не нашли»."""
    return address_index(value), address_street(value), address_house(value)


def same_address(first: str, second: str) -> bool:
    """Один ли это адрес.

    Сравниваются только те составляющие, которые НАЙДЕНЫ у обеих сторон:
    отсутствие индекса в одном из написаний — не расхождение, а нехватка данных.
    Если общего не нашлось вовсе, адреса считаются одинаковыми: предупреждение
    без основания хуже, чем его отсутствие (правило «воздержание лучше догадки»).
    """
    # strict=True: обе стороны — ключ фиксированной длины, расхождение длин
    # означало бы поломку address_key, а не разные адреса.
    for mine, theirs in zip(address_key(first), address_key(second), strict=True):
        if mine and theirs and mine != theirs:
            return False
    return True

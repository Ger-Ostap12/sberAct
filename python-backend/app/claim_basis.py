# -*- coding: utf-8 -*-
"""Реестр ВИДОВ ОСНОВАНИЯ требования и общие форматы номера и даты.

Зачем. Разбор обязательств вырос из двадцати с лишним паттернов, каждый под свою
формулировку: отдельный для «кредитный договор», отдельный для «Договор займа»,
отдельный для «Договоров займа» во множественном числе, отдельный даже под
опечатку «эмисионного контракта». Новый вид требования означал новый паттерн, и
именно это в свежих заявлениях (31.08) дало девять пустых блоков: разбор ждал
кредитный договор, а там были судебный приказ, исполнительный документ и
соглашение о кредитовании.

Здесь виды лежат ДАННЫМИ. Добавление вида — строка в реестре, а не правка
логики. Список намеренно шире того, что встретилось: он закрывает и то, чего в
корпусе пока нет.

Морфология — через `\\w*` на окончании: «договора займа», «договором займа»,
«судебным приказом» ловятся тем же элементом реестра.
"""
from __future__ import annotations

import re
from typing import Dict, List

# Вид основания -> написания. Ключ становится `obligationType`, поэтому имена
# ключей совпадают с теми, что уже понимает генерация.
CLAIM_BASIS: Dict[str, List[str]] = {
    # --- Кредитные -----------------------------------------------------------
    "credit": [
        r"кредитн\w+\s+договор\w*",
        r"договор\w*\s+потребительского\s+кредита",
        r"соглашени\w*\s+о\s+кредитовании",
        r"кредитн\w+\s+лини\w+",
        r"договор\w*\s+об\s+открытии\s+кредитной\s+линии",
        r"овердрафт\w*",
        r"эмиссионн\w+\s+контракт\w*",
        # Опечатка встречается в заявлениях достаточно часто, чтобы держать её
        # в реестре, а не чинить отдельным паттерном.
        r"эмисионн\w+\s+контракт\w*",
        r"договор\w*\s+о\s+предоставлении\s+кредита",
        r"генеральн\w+\s+соглашени\w*",
    ],
    # --- Займы ----------------------------------------------------------------
    "loan": [
        r"договор\w*\s+займа",
        r"договор\w*\s+микрозайма",
        r"договор\w*\s+потребительского\s+займа",
        r"договор\w*\s+денежного\s+займа",
    ],
    # --- Обеспечение -----------------------------------------------------------
    "surety": [
        r"договор\w*\s+поручительства",
    ],
    "pledge": [
        r"договор\w*\s+залога",
        r"договор\w*\s+ипотеки",
        r"договор\w*\s+об\s+ипотеке",
    ],
    "guarantee": [
        r"(?:независим\w+|банковск\w+)\s+гаранти\w+",
    ],
    # --- Судебные акты ----------------------------------------------------------
    # Их не было ни в одном паттерне, а в свежих заявлениях они — основание
    # требования наравне с договором.
    "judicial": [
        r"судебн\w+\s+приказ\w*",
        r"исполнительн\w+\s+лист\w*",
        r"исполнительн\w+\s+документ\w*",
        r"решени\w*\s+суда",
        r"определени\w*\s+суда",
        r"постановлени\w*\s+суда",
        r"мирово\w*\s+соглашени\w*",
    ],
    # --- Переход прав -------------------------------------------------------------
    "assignment": [
        r"договор\w*\s+цессии",
        r"договор\w*\s+уступки(?:\s+прав\w*(?:\s+требовани\w*)?)?",
        r"соглашени\w*\s+об\s+уступке",
        r"договор\w*\s+факторинга",
    ],
    # --- Прочие обязательства ---------------------------------------------------------
    "other": [
        r"договор\w*\s+лизинга",
        r"договор\w*\s+аренды",
        r"договор\w*\s+поставки",
        r"договор\w*\s+подряда",
        r"договор\w*\s+оказания\s+услуг",
        r"договор\w*\s+энергоснабжения",
        r"договор\w*\s+управления",
        r"вексел\w+",
    ],
}

# Номер договора. Три отличия от прежних написаний, каждое из корпуса:
#   * ПРОБЕЛЫ ВНУТРИ номера — «№ 003 83 6 2312250225». Конвертация PDF->DOCX
#     разбивает длинный номер, и жёсткий класс терял такое обязательство целиком;
#   * скобочный второй номер — «№ 2431453618(10551861421)»;
#   * латиница вперемешку с кириллицей — след OCR и внутренних кодов банка.
#
# ⚠️ Продолжение через пробел обязано СОДЕРЖАТЬ ЦИФРУ. Без этого условия номер
# съедает соседние слова: из «№ 2-253/2026 от 16.03.2026» получалось
# «2-253/2026 от 16», а из «№ 2-1-733/2026 о взыскании» — «2-1-733/2026 о
# взыскании». Цифра — единственный признак, отделяющий кусок номера от русского
# слова, и он же пропускает «003 83 6 2312250225».
_NUM_CHAR = r"[A-Za-zА-ЯЁа-яё0-9/\-()]"
CONTRACT_NUMBER = (
    _NUM_CHAR + r"+"
    r"(?:[ ](?=" + _NUM_CHAR + r"*\d)" + _NUM_CHAR + r"+){0,4}"
)

# Дата договора во всех встреченных видах: 10.08.2024, 10/08/2024, 2024-08-10
# (ISO приходит от части МФО) и «22» октября 2025 года.
_MONTHS = (r"январ\w+|феврал\w+|март\w*|апрел\w+|ма[йя]\w*|июн\w+|июл\w+|"
           r"август\w*|сентябр\w+|октябр\w+|ноябр\w+|декабр\w+")
CONTRACT_DATE = (
    r"(?:\d{1,2}[.,/]\d{1,2}[.,/]\d{4}"
    r"|\d{4}-\d{2}-\d{2}"
    r"|[«\"]?\d{1,2}[»\"]?\s+(?:" + _MONTHS + r")\s+\d{4})"
)


def basis_alternation(kinds: List[str] | None = None) -> str:
    """Альтернатива из написаний реестра, длинные раньше коротких.

    Порядок обязателен: иначе «договор займа» будет съеден более коротким
    «договор» из другого вида, и тип основания определится неверно.
    """
    words: List[str] = []
    for kind, variants in CLAIM_BASIS.items():
        if kinds and kind not in kinds:
            continue
        words.extend(variants)
    return "|".join(sorted(set(words), key=len, reverse=True))


def basis_kind(text: str) -> str | None:
    """Вид основания по найденному написанию: «судебным приказом» -> judicial."""
    for kind, variants in CLAIM_BASIS.items():
        for variant in variants:
            if re.fullmatch(variant, text.strip(), re.IGNORECASE):
                return kind
    return None


def general_obligation_pattern() -> str:
    """Один паттерн на все виды: ОСНОВАНИЕ → № НОМЕР → (от ДАТА).

    Заменяет собой ряд написаний, но НЕ вытесняет существующие паттерны: в
    `_parse_obligations_fallback` совпадения всех паттернов складываются, а
    дубликаты снимаются позже (`_dedupe_obligations`). Поэтому добавление этого
    слоя может только ДОБАВИТЬ обязательство, но не отнять.

    Окно между основанием и номером короткое (60 символов): длиннее — и номер
    берётся из соседнего предложения.
    """
    return (
        r"(?:" + basis_alternation() + r")"
        r"[^.\n]{0,60}?№\s*(" + CONTRACT_NUMBER + r")"
        r"(?:[^.\n]{0,80}?от\s+(" + CONTRACT_DATE + r"))?"
    )

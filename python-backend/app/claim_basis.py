def basis_title(wording: str) -> str | None:
    """Название для карточки по НАЙДЕННОМУ в тексте написанию.

    «судебного приказа» -> «Судебный приказ», «Соглашение о кредитовании» ->
    «Соглашение о кредитовании», «кредитным договором» -> «Кредитный договор».
    None — если написание реестру неизвестно.
    """
    w = (wording or "").strip()
    if not w:
        return None
    for pattern, title in BASIS_TITLE.items():
        if re.fullmatch(pattern, w, re.IGNORECASE):
            return title
    kind = basis_kind(w)
    return KIND_TITLE.get(kind) if kind else None


# Виды, которые обязательством ДОЛЖНИКА быть не могут.
#
# Уступка (цессия, факторинг) — сделка МЕЖДУ КРЕДИТОРАМИ: старый кредитор
# передаёт новому право требования к должнику. Долг у должника от этого один
# и тот же, а карточка на номер договора уступки — лишнее обязательство,
# которого он никому не должен (свежие-30, -33, -34).
NOT_DEBTOR_OBLIGATION = ("assignment",)


def general_obligation_pattern() -> str:
    """Один паттерн на все виды: ОСНОВАНИЕ → № НОМЕР → (от ДАТА).

    Заменяет собой ряд написаний, но НЕ вытесняет существующие паттерны: в
    `_parse_obligations_fallback` совпадения всех паттернов складываются, а
    дубликаты снимаются позже (`_dedupe_obligations`). Поэтому добавление этого
    слоя может только ДОБАВИТЬ обязательство, но не отнять.

    Окно между основанием и номером короткое (60 символов): длиннее — и номер
    берётся из соседнего предложения.

    Виды из `NOT_DEBTOR_OBLIGATION` в паттерн не входят: они встречаются в тех
    же заявлениях, но долгом должника не являются.
    """
    kinds = [k for k in CLAIM_BASIS if k not in NOT_DEBTOR_OBLIGATION]
    return (
        r"(?:" + basis_alternation(kinds) + r")"
        r"[^.\n]{0,60}?№\s*(" + CONTRACT_NUMBER + r")"
        r"(?:[^.\n]{0,80}?от\s+(" + CONTRACT_DATE + r"))?"
    )

# -*- coding: utf-8 -*-
"""Исход по иску (режим «Ипотека»): маркеры [888] и [889].

Юрист выбирает исход радиогруппой «Удовлетворение иска»
(`ClaimResolutionSection.tsx`), значение приходит в поле `claimResolution`.
Отсюда берутся два текста:

* `[888]` — формулировка исхода в резолютивке («…исковые требования – [888].»);
* `[889]` — отдельный абзац об отказе в остальной части. Осмыслен ТОЛЬКО при
  частичном удовлетворении: при «полностью» отказывать не в чем, при «отказать»
  отказано уже всё. В этих двух случаях поле остаётся пустым, и общая зачистка
  пустых маркеров снимает `[889]` вместе с абзацем.

Модуль без побочных эффектов — только данные и одна чистая функция, чтобы
формулировки можно было проверять тестами, не собирая .docx.
"""
from __future__ import annotations

from typing import Optional

# Ключи — значения радиогруппы во фронте. Менять их в отрыве от
# ClaimResolutionSection.tsx нельзя: связь держится на этих строках.
CLAIM_RESOLUTION_TEXTS = {
    "full": "удовлетворить",
    "partial": "удовлетворить частично",
    "deny": "отказать в удовлетворении",
}

# [989] в шаблоне — наименование истца. Здесь подставляем его сразу, а не
# оставляем литеральный маркер: абзац [889] вставляется в документ тем же
# проходом маппинга, и вложенный маркер до замены [989] уже не доживёт.
_PARTIAL_DENIAL = "В удовлетворении остальной части заявленных исковых требований {creditor} – отказать."

PARTIAL = "partial"


def build_partial_denial(creditor_name: Optional[str]) -> str:
    """Абзац [889] для частичного удовлетворения.

    Без наименования истца оставляем литеральный `[989]`: пустое место в акте
    юрист заметит, а подстановка пустой строки дала бы «требований  – отказать»
    с двойным пробелом и незаметной дырой.
    """
    creditor = str(creditor_name or "").strip()
    return _PARTIAL_DENIAL.format(creditor=creditor or "[989]")

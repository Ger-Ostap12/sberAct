"""Дата и время судебного заседания [99] словами: «14 октября 2026 года в 14 часов 58 минут»."""

import re

МЕСЯЦЫ_РОДИТЕЛЬНЫЙ = (
    "", "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)

# Вход приходит из datetime-local («2026-10-14T14:58») и из ручного ввода.
_ДАТА_ВРЕМЯ = re.compile(
    r"^\s*(?:"
    r"(?P<y1>\d{4})[.\-/](?P<m1>\d{1,2})[.\-/](?P<d1>\d{1,2})"
    r"|(?P<d2>\d{1,2})[.\-/](?P<m2>\d{1,2})[.\-/](?P<y2>\d{4})"
    r")"
    r"(?:[T\s]+(?P<час>\d{1,2})[:.\-](?P<мин>\d{1,2})(?::\d{1,2})?)?\s*$"
)


def _форма(число: int, одна: str, две: str, много: str) -> str:
    """Согласование слова с числом: 1 час, 2 часа, 5 часов, 11 часов."""
    если_сотня = число % 100
    if 11 <= если_сотня <= 14:
        return много
    последняя = число % 10
    if последняя == 1:
        return одна
    if последняя in (2, 3, 4):
        return две
    return много


def format_hearing_datetime(значение: str) -> str:
    """Дату и время заседания — словами; неразобранное возвращаем как есть."""
    if not значение or not str(значение).strip():
        return значение
    m = _ДАТА_ВРЕМЯ.match(str(значение))
    if not m:
        return значение

    день = int(m.group("d1") or m.group("d2"))
    месяц = int(m.group("m1") or m.group("m2"))
    год = int(m.group("y1") or m.group("y2"))
    if not (1 <= день <= 31 and 1 <= месяц <= 12 and 1900 <= год <= 2100):
        return значение

    # Ведущий ноль сохраняем: «02 октября 2026 года в 09 часов 05 минут».
    итог = "%02d %s %d года" % (день, МЕСЯЦЫ_РОДИТЕЛЬНЫЙ[месяц], год)

    if m.group("час") is None:
        return итог
    часы, минуты = int(m.group("час")), int(m.group("мин"))
    if not (0 <= часы <= 23 and 0 <= минуты <= 59):
        return значение
    return "%s в %02d %s %02d %s" % (
        итог,
        часы, _форма(часы, "час", "часа", "часов"),
        минуты, _форма(минуты, "минуту", "минуты", "минут"),
    )

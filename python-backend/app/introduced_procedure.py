# -*- coding: utf-8 -*-
"""Процедура, уже ВВЕДЁННАЯ судом по делу: нужна заявлениям о включении в РТК."""
import logging
import re
from typing import Optional

logger = logging.getLogger(__name__)

# Отвечает на другой вопрос, чем determine_procedure_type: та называет процедуру
# дела (включая «умерший») и берёт её в том числе из просьбы заявителя, а здесь
# нужна процедура, которую суд УЖЕ ввёл, и ещё конкурсное с наблюдением.

# Триггеры только в форме свершившегося факта. Инфинитив «ввести» — это просьба
# заявителя, и он сюда намеренно не попадает.
_ТРИГГЕР = re.compile(r"введен[аоы]\b|введени[ие]\b|открыт[оа]\b", re.IGNORECASE)

# «О введении процедуры» — двусмысленно: это и публикация о факте, и просьба
# («ходатайствуем о введении реализации»). Принимаем только первое.
_ВВЕДЕНИЕ = re.compile(r"^введени[ие]$", re.IGNORECASE)
_ПУБЛИКАЦИЯ = re.compile(r"сообщени|публикац|опубликован|извещени", re.IGNORECASE)

# Окно после триггера: в него должно попасть название процедуры, иначе это
# цитата закона («требований, применяемых в деле о банкротстве»).
_ОКНО = 160

_ПРОЦЕДУРЫ = (
    ("realization", re.compile(r"реализаци\w*\s+имуществ", re.IGNORECASE)),
    ("restructuring", re.compile(r"реструктуризаци\w*\s+долг", re.IGNORECASE)),
    ("competition", re.compile(r"конкурсн\w*\s+производств", re.IGNORECASE)),
    ("observation", re.compile(r"наблюдени\w*", re.IGNORECASE)),
)

# Перенос приходит в двух видах: «граж- данина» и слипшийся «имуще-ства».
# Склейка нужна только этому поиску, поэтому с «Ростов-на-Дону» не считаемся.
_ПЕРЕНОС_С_ПРОБЕЛОМ = re.compile(r"([а-яё])-\s+([а-яё])", re.IGNORECASE)
_ПЕРЕНОС_СЛИТНЫЙ = re.compile(r"([а-яё]{3,})-([а-яё]{2,})", re.IGNORECASE)


def _сгладить(text: str) -> str:
    """Склеивает слова, разорванные переносом, и схлопывает пробелы."""
    без_переносов = _ПЕРЕНОС_СЛИТНЫЙ.sub(r"\1\2", _ПЕРЕНОС_С_ПРОБЕЛОМ.sub(r"\1\2", text))
    return re.sub(r"\s+", " ", без_переносов)


def detect_introduced_procedure(text: str) -> Optional[str]:
    """Введённая процедура: realization / restructuring / competition / observation."""
    if not text:
        return None
    гладкий = _сгладить(text)

    for триггер in _ТРИГГЕР.finditer(гладкий):
        if _ВВЕДЕНИЕ.match(триггер.group(0)):
            слева = гладкий[max(0, триггер.start() - 60):триггер.start()]
            if not _ПУБЛИКАЦИЯ.search(слева):
                continue
        окно = гладкий[триггер.end():триггер.end() + _ОКНО]
        найденные = []
        for имя, образец in _ПРОЦЕДУРЫ:
            m = образец.search(окно)
            if m:
                найденные.append((m.start(), имя))
        if найденные:
            найденные.sort()
            процедура = найденные[0][1]
            logger.info("Введённая процедура: %s («%s»)", процедура,
                        гладкий[триггер.start():триггер.end() + 60].strip())
            return процедура
    return None

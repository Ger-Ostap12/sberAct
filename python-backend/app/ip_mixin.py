    def _set_field(self, fields, normalized_text, key: str, patterns, postprocess=None, flags=re.IGNORECASE | re.MULTILINE):
        for pattern in patterns:
            match = re.search(pattern, normalized_text, flags)
            if match:
                value = match.group(1) if match.groups() else match.group(0)
                value = value.strip()
                value = self.clean_extracted_value(value)
                if postprocess:
                    value = postprocess(value)
                if value:
                    fields[key] = value
                    logger.info(f"Extracted {key}: {value}")
                    break

    def _clean_numeric(self, value: str) -> str:
        cleaned = value.replace('\u202f', ' ').replace('\xa0', ' ')
        cleaned = re.sub(r'\s*(?:руб\.?|рублей|₽)\.?$', '', cleaned, flags=re.IGNORECASE)
        cleaned = cleaned.strip()
        return cleaned


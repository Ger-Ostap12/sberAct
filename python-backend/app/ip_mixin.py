            if match and match.groups() and len(match.groups()) >= 2:
                # Извлекаем обе даты и формируем период в формате "с ДД.ММ.ГГГГ по ДД.ММ.ГГГГ"
                date_start = match.group(1).strip()
                date_end = match.group(2).strip()

                # Нормализуем даты (заменяем запятые на точки)
                date_start = date_start.replace(',', '.')
                date_end = date_end.replace(',', '.')

                # Формируем значение периода
                value = f"с {date_start} по {date_end}"
                fields["debtSnapshotDate"] = value
                logger.info(f" Extracted debtSnapshotDate from period: {value} (start: {date_start}, end: {date_end})")

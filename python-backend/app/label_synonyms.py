# --- Канонизация метки перед сопоставлением (§S.2.D) -------------------------
#
# Реестр выше ОБЕЩАЕТ, что перечисленные написания равнозначны, но основной путь
# извлечения его не читает: все паттерны держат написание метки в себе. Замер
# (`tests/measure_label_robustness.py`): подмена метки на её же зарегистрированный
# синоним ломала разбор у 42 документов из 47.
#
# Здесь — та часть обещания, которую можно сделать правдой БЕЗ риска для эталона.
# Ключ — написание, которого в корпусе нет НИ РАЗУ (проверено); значение — то, на
# котором разбор доказанно работает. Отсюда свойство: на корпусе канонизация —
# тождественная операция, и golden сдвинуться не может. Польза — на заявлениях,
# которых в корпусе нет.
#
# ⚠️ ГРУППЫ «УПРАВЛЯЮЩИЙ» ЗДЕСЬ НЕТ НАМЕРЕННО. «Финансовый» / «Конкурсный» /
# «Временный» / «Арбитражный» управляющий — это РАЗНЫЕ процедуры, а не синонимы:
# от того, какой назван, зависит `procedureType`. Свести их канонизацией значит
# внести настоящий баг в определение процедуры. Реестр держит их вместе только
# для поиска ГРАНИЦ блока, и это единственное, для чего их можно объединять.
#
# Расширять список — только сверив, что нового написания в корпусе нет: иначе
# канонизация перестанет быть тождественной и потянет за собой эталон.
# Различия ТОЛЬКО в регистре сюда не входят: сопоставление и так
# регистронезависимо (и паттерны компилируются с IGNORECASE), поэтому
# «Заявитель (Кредитор)» уже равно «Заявитель (кредитор)» — запись была бы пустой.
HEADER_CANONICAL = {
    "Должник (ответчик)": "Должник",
    "Заёмщик": "Должник",
    "Заемщик": "Должник",
    "Заявитель-кредитор": "Заявитель (кредитор)",
    "Кредитор (заявитель)": "Кредитор",
    "Заинтересованное лицо": "Третье лицо",
}


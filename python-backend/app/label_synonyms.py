# -*- coding: utf-8 -*-
"""Словарь синонимов меток для устойчивого к разным банкам разбора заявлений.

Разные банки называют одни и те же блоки/поля по-разному:
  должник: «Должник» / «Ответчик» / «Заёмщик»;
  кредитор: «Заявитель» / «Заявитель (Кредитор)» / «Истец» / «Кредитор» / «Взыскатель».
Чтобы извлекать значение РЯДОМ С ЕГО МЕТКОЙ (а не по позиции), держим синонимы
ЦЕНТРАЛИЗОВАННО и как ДАННЫЕ: поддержка нового банка = добавить пару строк сюда,
без правки логики разбора.

Списки упорядочены по приоритету (более специфичные/длинные — раньше), чтобы при
построении regex-альтернативы сначала матчился более точный вариант
(«Заявитель (Кредитор)» прежде «Заявитель»).
"""
from __future__ import annotations

import re
from typing import List

# --- Метки-заголовки блоков сторон ------------------------------------------
# Должник (он же ответчик/заёмщик в исковых/кредитных шаблонах).
DEBTOR_HEADER_LABELS: List[str] = [
    "Должник (ответчик)",
    "Должник",
    "Ответчик",
    "Заёмщик",
    "Заемщик",
]

# Кредитор/заявитель. ВАЖНО: «Заявитель (Кредитор)» раньше «Заявитель».
CREDITOR_HEADER_LABELS: List[str] = [
    "Заявитель (Кредитор)",
    "Заявитель (кредитор)",
    "Заявитель-кредитор",
    "Заявитель",
    "Истец",
    "Кредитор",
    "Взыскатель",
    "Кредитор (заявитель)",
]

# Третьи / заинтересованные лица.
THIRD_PARTY_HEADER_LABELS: List[str] = [
    "Заинтересованные лица",
    "Заинтересованное лицо",
    "Третьи лица",
    "Третье лицо",
]

# Арбитражный/финансовый управляющий.
MANAGER_HEADER_LABELS: List[str] = [
    "Финансовый управляющий",
    "Арбитражный управляющий",
    "Временный управляющий",
    "Конкурсный управляющий",
]

# --- Метки-подписи полей внутри блоков --------------------------------------
# Канонический ключ поля -> варианты подписи (как пишут в документах).
FIELD_LABELS = {
    "inn": ["ИНН"],
    "ogrn": ["ОГРН"],
    "ogrnip": ["ОГРНИП"],
    "kpp": ["КПП"],
    "snils": ["СНИЛС"],
    "passport": ["Паспорт", "Паспортные данные"],
    "birthDate": ["Дата рождения"],
    "birthPlace": ["Место рождения"],
    "address": [
        "Адрес регистрации",
        "Адрес местонахождения",
        "Адрес места нахождения",
        "Место нахождения",
        "Юридический адрес",
        "Адрес",
    ],
    "registrationDate": ["Дата государственной регистрации", "Дата регистрации"],
    "claimAmount": ["Размер требований", "Сумма требований", "Размер и состав требования"],
    "stateDuty": ["Госпошлина", "Государственная пошлина"],
}


def labels_alternation(labels: List[str]) -> str:
    """Строит regex-альтернативу из меток (экранирует, сохраняет порядок приоритета).

    Пример: ['Заявитель (Кредитор)', 'Заявитель'] -> 'Заявитель\\ \\(Кредитор\\)|Заявитель'
    Использовать внутри якоря метки: rf'(?:{labels_alternation(...)})\\s*:'
    """
    return "|".join(re.escape(lbl) for lbl in labels)


def header_pattern(labels: List[str]) -> str:
    """Regex для строки-заголовка блока: метка + двоеточие (с возможными пробелами).

    Совпадает, напр.: 'Заявитель (Кредитор):', 'Должник:', 'Заёмщик :'.
    """
    return rf"(?:{labels_alternation(labels)})\s*:"


def all_labels() -> List[str]:
    """Все метки реестра — заголовки блоков и подписи полей, длинные раньше.

    Нужны там, где важна не роль метки, а сам факт «здесь метка»: например, при
    канонизации переноса строки между меткой и значением (разные банки пишут
    «Должник: Иванов» и «Должник:\\nИванов» — для разбора это одно и то же).
    Сортировка по длине убывающе обязательна: иначе «Адрес» съест «Адрес
    регистрации» и хвост метки останется в значении.
    """
    labels = [
        *DEBTOR_HEADER_LABELS,
        *CREDITOR_HEADER_LABELS,
        *THIRD_PARTY_HEADER_LABELS,
        *MANAGER_HEADER_LABELS,
        *(lbl for variants in FIELD_LABELS.values() for lbl in variants),
    ]
    return sorted(set(labels), key=len, reverse=True)

# -*- coding: utf-8 -*-
"""Сравнение значения LLM со значением regex-разбора.

Ключевое: сравнивать голыми строками нельзя. «ООО Ромашка» и «Общество с
ограниченной ответственностью «Ромашка»» — одно и то же, и если показать это
юристу как расхождение, он перестанет доверять подсказкам целиком. Поэтому
перед сравнением снимаем формат: кавычки, пунктуацию, регистр и родовые слова
организационно-правовой формы.

Тот же код используют и бенчмарк, и прод-путь — иначе цифра качества бенчмарка
перестанет описывать то, что видит пользователь.
"""
import re

_NORM_RE = re.compile(r"[\s«»\"'.,]+")

# Родовые слова организационно-правовой формы: regex-эталон и ответ LLM часто
# расходятся ТОЛЬКО ими. Это не ошибка модели, а разный формат записи — тот же
# принцип, что _GENERIC в sro_registry.py.
_LEGAL_FORM_WORDS = {
    "ооо", "зао", "оао", "пао", "нао", "ао", "ип", "кфх",
    "общество", "ограниченной", "ответственностью", "акционерное",
    "акционерного", "публичное", "непубличное", "закрытое", "открытое",
    "товарищество", "индивидуальный", "предприниматель", "крестьянское",
    "фермерское", "хозяйство",
}


def norm(s: str) -> str:
    return _NORM_RE.sub("", (s or "").lower())


def core_name(s: str) -> str:
    words = re.sub(r"[«»\"'.,]+", " ", (s or "").lower()).split()
    return " ".join(w for w in words if w not in _LEGAL_FORM_WORDS)


def fuzzy_match(regex_val: str, llm_val: str) -> bool:
    """True — значения считаются согласованными, подсказку показывать не надо.

    Вхождение подстроки в обе стороны намеренно: одна сторона нередко полнее
    другой (адрес с индексом против адреса без), и это не расхождение по сути.
    Пустое значение с любой стороны согласованным НЕ считается — сравнивать
    нечего."""
    a, b = norm(regex_val), norm(llm_val)
    if not a or not b:
        return False
    if a in b or b in a:
        return True
    ca, cb = norm(core_name(regex_val)), norm(core_name(llm_val))
    if not ca or not cb:
        return False
    return ca in cb or cb in ca

# Отдельная задача от всего, что выше. Там модель ИЗВЛЕКАЕТ, и её ответ потом
# сравнивают с разбором; здесь она СУДИТ об уже готовом значении. Нужно это
# потому, что сравнение молчит, когда обе стороны ошиблись одинаково: в реальном
# случае в заявление между названием суда и адресом вставили строку-мусор, и
# regex, и модель прочитали её как часть адреса — расхождения не возникло.
#
# Поля нумеруем и просим вернуть НОМЕРА, а не названия: номер невозможно
# переврать падежом или сокращением, и обратное сопоставление выходит точным,
# а не «на что похоже».
#
# Формулировка намеренно перекошена в сторону молчания. Ложная тревога здесь
# дороже пропуска: пропущенное поле юрист всё равно вычитывает глазами, а
# несколько ложных срабатываний научат его игнорировать ВСЕ подсказки разом.

def build_df_mortgage_prompt(with_representatives: bool = True,
                            with_court: bool = True,
                            with_financial: bool = True) -> dict:
    """Промпт для ипотечных исков — фиксированная схема (не зависит от
    entityType/documentType-веток, в отличие от df_v7/df_v8), один few-shot
    с многодолжниковым делом + несовершеннолетним под законным представителем
    (реальный, не редкий паттерн корпуса — см. план).

    `with_representatives=False` — то же сужение схемы под контекст, что уже
    дало df_v7 (sroName 58%→97%): не просить у модели то, что всё равно будет
    отброшено. Представителей отдельно и точнее даёт _fetch_representative."""
    head = _DF_MORTGAGE_SCHEMA_HEAD if with_court else _DF_MORTGAGE_SCHEMA_HEAD_NOCOURT
    schema = head + (_DF_MORTGAGE_SCHEMA_REPS if with_representatives else "")
    # Без финансов схему нужно ЗАКРЫТЬ самим: хвост со скобкой уходит вместе с
    # блоком financial, а head заканчивается запятой.
    schema = (schema + _DF_MORTGAGE_SCHEMA_TAIL) if with_financial else (schema.rstrip(", ") + "}")
    # Именно replace, а не .format: в тексте промпта есть литеральные фигурные
    # скобки (перечисление полей объекта должника), и format на них падает.
    parts = [_DF_MORTGAGE_SYSTEM_HEAD.replace("{schema}", schema)]
    if with_representatives:
        parts.append(_DF_MORTGAGE_SYSTEM_REPS)
    if with_financial:
        parts.append(_DF_MORTGAGE_SYSTEM_TAIL)
    answer = _DF_MORTGAGE_FEWSHOT_ANSWER
    drop = {k for k, on in (("representatives", with_representatives),
                            ("court", with_court),
                            ("financial", with_financial)) if not on}
    if drop:
        answer = {k: v for k, v in answer.items() if k not in drop}
    return {
        "system": "".join(parts) + "\n" + _DF_V7_FORMAT_RULES,
        "grammar": False,
        "fewshot": [(_DF_MORTGAGE_FEWSHOT_USER,
                     json.dumps(answer, ensure_ascii=False))],
    }



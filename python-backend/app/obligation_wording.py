# -*- coding: utf-8 -*-
"""Как вид обязательства называется В ТЕКСТЕ АКТА.

Зачем. В шаблонах слово «кредитный договор» стоит ГОТОВЫМ ТЕКСТОМ — 298 мест
в 57 актах. Что бы разбор ни положил в карточку, акт говорил «кредитный
договор»: у самобанкрота с судебным приказом и у Альфы с соглашением о
кредитовании требование называлось не своим видом.

Маркер вместо слова не годится: шаблон требует СВОЮ форму («по кредитному
договору», «расторгнуть кредитный договор», «по кредитным договорам»), а в
карточке вид лежит в именительном падеже — подстановка дала бы «по Судебный
приказ». Поэтому форму берём ИЗ ШАБЛОНА: слово, которое там стоит, само
сообщает падеж и число, и вид ставится в ту же форму.

⚠️⚠️ СКЛОНЯТЬ НУЖНО ТОЛЬКО ГОЛОВУ. Наивное «склонять каждое слово» даёт
«договору поручительству»: зависимое слово в родительном падеже
(«поручительства», «займа», «цессии») и предложная группа («о кредитовании»)
остаются неизменными. Замер на всех 25 видах реестра: с этим правилом верны
все формы в оба числа, без него ломается большинство.
"""
from __future__ import annotations

import re
from typing import Optional, Tuple

try:
    from pymorphy3 import MorphAnalyzer
except ImportError:  # pragma: no cover - окружение без pymorphy3
    MorphAnalyzer = None  # type: ignore[assignment]

_morph = None


def _анализатор():
    global _morph
    if _morph is None and MorphAnalyzer is not None:
        _morph = MorphAnalyzer()
    return _morph


# Слово-тип, стоящее в шаблонах готовым текстом.
ШАБЛОННОЕ_СЛОВО = re.compile(r"кредитн\w+\s+договор\w*", re.IGNORECASE)

# Глаголы, которые требуют ВИНИТЕЛЬНОГО падежа. Нужны потому, что у
# «кредитный договор» (мужской неодушевлённый) именительный и винительный
# совпадают, а у подставляемого вида — нет: «заключили кредитнУЮ картУ».
#  Без привязки к концу строки: падеж задаёт глагол в НАЧАЛЕ предложения, а
# перечисление тянется далеко — «заключили: кредитный договор от …, кредитную
# карту от …». Поэтому вызывающий передаёт слева ВСЁ предложение до слова, и
# глагол ищется в нём целиком. Ложного срабатывания это не даёт: контекст
# смотрят только для формы, у которой именительный и винительный совпадают.
_ВИНИТЕЛЬНЫЙ_КОНТЕКСТ = re.compile(
    r"\b(?:заключ\w+|расторг\w+|выда\w+|подписа\w+|оформ\w+)\b", re.IGNORECASE)

_ПАДЕЖИ = ("nomn", "gent", "datv", "accs", "ablt", "loct")


def форма_шаблона(слово: str, слева: str = "") -> Tuple[str, str]:
    """(падеж, число) слова-типа, как оно стоит в шаблоне.

    «кредитному договору» -> ('datv', 'sing'); «кредитным договорам» ->
    ('datv', 'plur'). Неоднозначность именительный/винительный решается
    словом СЛЕВА: после «заключили» и «расторгнуть» — винительный.
    """
    морф = _анализатор()
    существительное = слово.split()[-1]
    падеж, число = "nomn", "sing"
    if морф is not None:
        разборы = [р for р in морф.parse(существительное) if "NOUN" in р.tag]
        if разборы:
            р = разборы[0]
            число = "plur" if р.tag.number == "plur" else "sing"
            # Все падежи, которые подходят этой словоформе.
            подходят = [п for п in _ПАДЕЖИ
                        if any(п in x.tag for x in разборы if x.tag.number == р.tag.number)]
            падеж = подходят[0] if подходят else "nomn"
            if "accs" in подходят and "nomn" in подходят:
                падеж = "accs" if _ВИНИТЕЛЬНЫЙ_КОНТЕКСТ.search(слева) else "nomn"
    else:  # pragma: no cover - окружение без pymorphy3
        число = "plur" if существительное.lower().endswith(
            ("ы", "ам", "ов", "ами", "ах")) else "sing"
    return падеж, число


def склонить(вид: str, падеж: str, число: str = "sing") -> str:
    """Вид обязательства в заданной форме. Склоняется только ГОЛОВА.

    Голова — первое существительное фразы; прилагательные перед ним с ним
    согласуются, всё после — остаётся как есть.
    """
    морф = _анализатор()
    if морф is None:  # pragma: no cover - окружение без pymorphy3
        return вид
    слова = вид.split()
    # Голова — первое существительное фразы.
    голова = next((i for i, с in enumerate(слова)
                   if "NOUN" in морф.parse(с)[0].tag), 0)
    разбор_головы = морф.parse(слова[голова])[0]
    род = разбор_головы.tag.gender
    множественно = число == "plur"
    вышло = list(слова)

    метки_головы = {падеж, "plur" if множественно else "sing"}
    новая_голова = разбор_головы.inflect(метки_головы)
    if новая_голова:
        вышло[голова] = новая_голова.word

    # ⚠️ Прилагательные согласуются С РОДОМ ГОЛОВЫ, и род приходится задавать
    # ЯВНО. pymorphy на `inflect({'accs','sing','inan'})` у женского
    # «кредитная» теряет род и отдаёт мужское «кредитный» — пометка
    # неодушевлённости существует только у мужского рода. Отсюда выходило
    # «заключили кредитный карту».
    #
    # Сама неодушевлённость тоже нужна: у одушевлённых винительный совпадает
    # с родительным, и без неё «кредитные карты» становились «кредитных».
    for i in range(голова):
        разбор = морф.parse(слова[i])[0]
        if "ADJF" not in разбор.tag and "PRTF" not in разбор.tag:
            continue
        метки = {падеж, "plur" if множественно else "sing"}
        if not множественно and род:
            метки.add(род)
        if падеж == "accs" and (множественно or род == "masc"):
            метки.add("inan")
        изменённое = разбор.inflect(метки)
        if изменённое:
            вышло[i] = изменённое.word
    итог = " ".join(вышло)
    # Регистр первой буквы — как было у шаблонного слова; его сохраняет
    # вызывающий, здесь только поддерживаем заглавную, если вид с заглавной.
    return итог[:1].upper() + итог[1:] if вид[:1].isupper() else итог


def как_в_шаблоне(вид: str, шаблонное: str, слева: str = "",
                  число: Optional[str] = None,
                  падеж: Optional[str] = None) -> Optional[str]:
    """Вид в той же форме, что слово-тип в шаблоне, и с тем же регистром.

    `число` переопределяет число шаблона. Нужно для смешанного случая: фраза
    «по кредитным договорам № …, № …» собирает несколько обязательств разных
    видов, и одним словом их не назвать — тогда каждое называется в
    ЕДИНСТВЕННОМ числе своим видом.

    `падеж` переопределяет падеж шаблона. Нужно для перечислений, где сам
    шаблон непоследователен: «задолженности ПО КРЕДИТНЫМ ДОГОВОРАМ от [100]
    № [110], КРЕДИТНЫЙ ДОГОВОР от [101] № [111]» — второй элемент стоит в
    именительном. Падеж перечисления задаёт его начало.

    None — если вид пуст или склонить не удалось (тогда вызывающий оставляет
    шаблонное слово как есть: лучше прежний текст, чем сломанная фраза).
    """
    вид = (вид or "").strip()
    if not вид:
        return None
    падеж_шаблона, число_шаблона = форма_шаблона(шаблонное, слева)
    падеж = падеж or падеж_шаблона
    число = число or число_шаблона
    результат = склонить(вид, падеж, число)
    if not результат:
        return None
    # Шаблон пишет слово со строчной («по кредитному договору»), реестр — с
    # заглавной («Кредитный договор»). Равняемся на шаблон.
    if шаблонное[:1].islower():
        результат = результат[:1].lower() + результат[1:]
    else:
        результат = результат[:1].upper() + результат[1:]
    return результат

"""Представитель истца: разбор по метке и по блоку подписи.

Чистые функции: текст -> имя. Ни состояния, ни побочных эффектов — так разбор
проверяется эталоном построчно и переиспользуется из любого mixin'а.

ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. До этого представитель извлекался только для ипотеки
(поле mortgageRepresentative22) и только по метке «Представитель истца:».
В заявлениях о банкротстве такой метки почти не бывает: имя стоит либо в
карточке кредитора в шапке («Представитель: Гайсина Дина Римовна»), либо в
блоке подписи в самом конце («Представитель ПАО Сбербанк\nпо доверенности
Юсупова Е.О.»), либо вовсе без слова «представитель» («По доверенности
№ 207C/ФЦ от 26.07.2023\nАлтынбаева Дарья Андреевна»).

ГЛАВНОЕ ПРАВИЛО — ПОЛНОЕ ИМЯ СИЛЬНЕЕ ИНИЦИАЛОВ, А НЕ «ШАПКА СИЛЬНЕЕ ПОДПИСИ».
Один документ почти всегда называет представителя дважды, и версии не совпадают:

Позиционное правило («бери из шапки») ломается на свежие-33, где шапка обрезана
до «Фамилия Имя», а правило «бери из подписи» ломается на трёх остальных.
Работает ранг ПОЛНОТЫ записи: Ф.И.О. целиком > Фамилия с инициалами.
Обрезанное «Фамилия Имя» не распознаётся вовсе — как форма имени оно не
существует, а паттерн из двух слов с заглавной ловит пол-документа
(«Банк Получателя», «Московское Представитель»).

Этот же ранг решает ловушку ипотеки: в конце ипотечных заявлений стоит
приложенное письмо банка со своей подписью («Представитель ПАО Сбербанк по
доверенности Резулов И.А.»), и это НЕ представитель истца. Полное имя из шапки
выигрывает у инициалов из чужого письма без единого исключения по типу
документа.
"""
import re
from typing import List, Optional, Tuple

# --- формы записи имени ------------------------------------------------------

# Слово имени: Titlecase либо КАПС (в шапках банков ФИО набирают капсом),
# допускаем дефис («Соловьёва-Седая»).
_СЛОВО = r"[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?"
_СЛОВО_КАПС = r"[А-ЯЁ]{2,}(?:-[А-ЯЁ]{2,})?"

РАНГ_ПОЛНОЕ = 1
РАНГ_ИНИЦИАЛЫ = 2

# «Чепелов Иван Александрович» / «ИВАНОВ ИВАН ИВАНОВИЧ». Регистр не смешиваем:
# «Банка ВТБ Иванов» — это не имя, а хвост названия организации.
_ПОЛНОЕ_RE = re.compile(
    r"""\b(?:
          {с}\s+{с}\s+{с}
        | {к}\s+{к}\s+{к}
    )\b""".format(с=_СЛОВО, к=_СЛОВО_КАПС),
    re.VERBOSE,
)

# «Юсупова Е.О.» / «Карпенко Е.А» (точка в конце теряется) / «СираевЭ.Р.»
# (пробел съеден конвертером — так и печатается в акте, значение не чиним).
_ИНИЦИАЛЫ_ПОСЛЕ_RE = re.compile(
    r"\b({с})\s*([А-ЯЁ]\.\s?[А-ЯЁ]\.?)(?![А-Яа-яЁё])".format(с=_СЛОВО)
)

# «В.А. Перец» / «П.Ф.Рець» / «М.С. Суроушкина».
_ИНИЦИАЛЫ_ДО_RE = re.compile(
    r"\b([А-ЯЁ]\.\s?[А-ЯЁ]\.)\s*({с})\b".format(с=_СЛОВО)
)

# --- якоря -------------------------------------------------------------------

# Заглавная «П» обязательна: в прозе слово идёт со строчной и всегда мимо цели
# («в отсутствие представителя ООО «ПКО «АСВ»», «Копия доверенности
# представителя»). «По доверенности» — самостоятельный якорь: у Совкомбанка
# слова «представитель» в блоке подписи нет вовсе.
_ЯКОРЬ_RE = re.compile(r"\b(?:Представител[ья]\w*|По\s+доверенности)\b")

# Представитель ОТВЕТЧИКА — другое лицо и другое поле формы.
_ЧУЖОЙ_ЯКОРЬ_RE = re.compile(r"Представител\w*\s+ответчик", re.IGNORECASE)

# Следующий раздел: дальше этой строки имени представителя быть не может.
# Сверяется по НАЧАЛУ строки — внутри строки те же слова встречаются в адресах
# и в названиях («ул. Банковская», «Дата гос. регистрации»).
_СТОП_СТРОКА_RE = re.compile(
    r"""^\s*(?:
        Должник | Кредитор | Заявитель | Взыскатель | Ответчик | Истец
      | Треть\w+\s+лиц\w* | Финансов\w+\s+управляющ\w*
      | ИНН | ОГРН | КПП | СНИЛС | БИК | ОКПО
      | Адрес | Почтов\w+\s+адрес | Место\s+нахождения
      | Тел | Телефон | Конт\w* | Факс | Эл | E-?mail | Электронн\w+\s+почт\w*
      | Исп\w* | Владелец | Сертификат | Действителен | Подпись
      | Банк | Получател\w* | Реквизит\w* | Корр\w* | Расчетн\w* | Расчётн\w*
      | Назначение | Баланс\w* | Номер\s+ссудн\w* | Счет | Счёт
      | Основн\w+\s+долг | Остаток | Срочн\w* | Причитающ\w* | Процент\w*
      | Неустойк\w* | Комисси\w* | Госпошлин\w* | Государственн\w+\s+пошлин\w*
      | Сумм\w* | Вид\s+обязательства
      | Дата | Приложени\w* | Копия | Выписка | Доверенность | Документ | Дело
    )\b""",
    re.IGNORECASE | re.VERBOSE,
)

# Строка-источник чужого имени: назад через перенос смотреть можно, но не сюда.
# «Исполнитель: Евгения Вячеславовна Моисеева» стоит ровно перед подписью
# представителя (корпус-64) и полным именем побеждает верные инициалы.
_ЧУЖАЯ_СТРОКА_RE = re.compile(
    r"^\s*(?:Исп|Исполнител|Владелец|Сертификат|Заемщик|Заёмщик|Должник|Ответчик)",
    re.IGNORECASE,
)

# Не имена, хотя по форме подходят: ОПФ и названия банков рядом с якорем.
_НЕ_ИМЯ = {
    "ПАО", "АО", "ООО", "НАО", "ЗАО", "ОАО", "ПКО", "МФК", "МКК", "СФО", "КБ",
    "БАНК", "БАНКА", "БАНКЕ", "СБЕРБАНК", "ВТБ", "ТБАНК", "АКЦИОНЕРНОГО",
    "ОБЩЕСТВА", "ФИЛИАЛ", "ОТДЕЛЕНИЕ", "ЦЕНТРАЛЬНЫЙ", "РОССИИ",
}

_ОКНО_СТРОК = 5          # сколько строк после якоря просматривать
_ОКНО_СИМВОЛОВ = 400     # и не больше этого — защита от текста без переносов


def _чужое(имя: str) -> bool:
    """Отсекает названия организаций, попавшие в форму имени."""
    слова = {re.sub(r"[^А-ЯЁ]", "", с.upper()) for с in имя.split()}
    return bool(слова & _НЕ_ИМЯ)


def _нормализовать(имя: str) -> str:
    """КАПС приводим к «Иванов Иван Иванович»; остальное — как в документе.

    Trim капса нужен для шапок банков («ИВАНОВ ИВАН ИВАНОВИЧ»), но общий
    Titlecase калечит инициалы: «В.А. Перец» -> «В.а. Перец», «СираевЭ.Р.» ->
    «Сираевэ.р.». Поэтому чиним только строки без единой строчной буквы.
    """
    имя = re.sub(r"\s+", " ", имя).strip(" ,;:")
    if re.search(r"[а-яё]", имя):
        return имя
    return " ".join("-".join(ч.capitalize() for ч in с.split("-"))
                    for с in имя.split())


def _имя_в_окне(окно: str, с_конца: bool = False) -> Optional[Tuple[int, str]]:
    """Возвращает (ранг, имя) — первое (или последнее) имя в куске текста."""
    кандидаты: List[Tuple[int, int, str]] = []
    for m in _ПОЛНОЕ_RE.finditer(окно):
        if not _чужое(m.group(0)):
            кандидаты.append((m.start(), РАНГ_ПОЛНОЕ, m.group(0)))
    # Склейку «СираевЭ.Р.» и потерянную точку «Карпенко Е.А» сохраняем как есть:
    # это то, что юрист увидит в акте, и правкой пробелов их не чинят.
    for m in _ИНИЦИАЛЫ_ПОСЛЕ_RE.finditer(окно):
        if not _чужое(m.group(1)):
            кандидаты.append((m.start(), РАНГ_ИНИЦИАЛЫ, m.group(0)))
    for m in _ИНИЦИАЛЫ_ДО_RE.finditer(окно):
        if not _чужое(m.group(2)):
            кандидаты.append((m.start(), РАНГ_ИНИЦИАЛЫ, m.group(0)))
    if not кандидаты:
        return None
    # Внутри одного окна побеждает ближайшее к якорю: вперёд — самое раннее,
    # назад — самое позднее (то, что прижато к слову «Представитель»).
    кандидаты.sort(key=lambda к: к[0], reverse=с_конца)
    поз, ранг, имя = кандидаты[0]
    return ранг, _нормализовать(имя)


def _окно_вперёд(текст: str, конец_якоря: int) -> str:
    """Хвост строки якоря плюс несколько строк до следующего раздела.

    Стоп-метки применяются СО ВТОРОЙ строки: на строке самого якоря те же слова
    — часть подписи («Представитель Банка ВТБ (ПАО), Тихомирова В.П.»).
    """
    кусок = текст[конец_якоря:конец_якоря + _ОКНО_СИМВОЛОВ]
    строки = кусок.split("\n")[:_ОКНО_СТРОК]
    собрано = [строки[0]]
    for строка in строки[1:]:
        if _СТОП_СТРОКА_RE.match(строка):
            break
        собрано.append(строка)
    return " ".join(собрано)


def _окно_назад(текст: str, начало_якоря: int) -> str:
    """Остаток строки перед якорем и, если он пуст, предыдущая строка.

    Нужно для вёрстки «<ФИО> Представитель АО «Экспобанк»» (корпус-11) и
    «<ФИО>\nПредставитель Заявителя по доверенности» (свежие-3).
    """
    кусок = текст[max(0, начало_якоря - _ОКНО_СИМВОЛОВ):начало_якоря]
    строки = кусок.split("\n")
    своя = строки[-1] if строки else ""
    if своя.strip():
        return своя
    предыдущая = строки[-2] if len(строки) >= 2 else ""
    if _ЧУЖАЯ_СТРОКА_RE.match(предыдущая):
        return ""
    return предыдущая


def extract_representative(text: str) -> Optional[str]:
    """ФИО представителя истца (заявителя) или None.

    Собирает кандидатов от всех якорей и возвращает самую полную запись; при
    равной полноте — самую раннюю в документе.
    """
    if not text:
        return None
    находки: List[Tuple[int, int, str]] = []
    for m in _ЯКОРЬ_RE.finditer(text):
        if _ЧУЖОЙ_ЯКОРЬ_RE.match(text, m.start()):
            continue
        найдено = _имя_в_окне(_окно_вперёд(text, m.end()))
        if not найдено:
            # Назад смотрим только когда вперёд пусто: иначе имя исполнителя
            # со строки выше перебивает верную подпись (корпус-64).
            найдено = _имя_в_окне(_окно_назад(text, m.start()), с_конца=True)
        if найдено:
            ранг, имя = найдено
            находки.append((ранг, m.start(), имя))
    if not находки:
        return None
    находки.sort(key=lambda н: (н[0], н[1]))
    return находки[0][2]

# -*- coding: utf-8 -*-
"""Реестр СРО арбитражных управляющих: сопоставление упоминания организации из
текста заявления с каноничной записью справочника `sro_data.py` и выдача её
полного наименования (`NAIM_FULL`).

Зачем: в заявлениях СРО пишут по-разному — короткой аббревиатурой («ПАУ ЦФО»),
с кавычками-ёлочками («Ассоциация МСРО «Содействие»»), со straight-кавычками
(«Ассоциация "СРО АУ "Меркурий"») и с хвостом ИНН/адреса. В акт нужно каноничное
полное имя.

Матч — по ОТЛИЧИТЕЛЬНЫМ токенам (не родовым «саморегулируемая организация…»):
отличительное слово/аббревиатура из упоминания ищется среди отличительных токенов
записи, причём и в коротком имени `NAIMK` (там живут аббревиатуры — «СЦЭАУ»,
«ЦФОП АПК», «РСОПАУ»), и в полном `NAIM_FULL`. Это снимает две беды старой версии:
(1) родовой токен в кавычках («Саморегулируемая организация арбитражных
управляющих») перебивал отличительный («Меркурий») и уводил в чужую запись
(Эгида); (2) аббревиатура из NAIMK не находилась, потому что в NAIM_FULL она
развёрнута словами. Чистая функция: строка → NAIM_FULL | None.
"""
import re
from typing import Dict, List, Optional, Set

from sro_data import SRO_DATA


def _norm(s: str) -> str:
    """Каноничная форма для сравнения: нижний регистр, ё→е, кавычки/пунктуация → пробел."""
    if not s:
        return ""
    s = s.lower().replace("ё", "е")
    s = re.sub(r"[^0-9a-zа-я]+", " ", s)  # всё, кроме букв/цифр → пробел (кавычки, тире, точки)
    return re.sub(r"\s+", " ", s).strip()


# Родовые слова названий СРО — не отличительные (есть почти в каждой записи).
_GENERIC: Set[str] = frozenset({
    "саморегулируемая", "саморегулируемой", "саморегулируемых", "организация",
    "организации", "арбитражных", "управляющих", "ассоциация", "ассоциации",
    "союз", "союза", "некоммерческое", "некоммерческого", "партнерство",
    "партнерства", "партнёрство", "межрегиональная", "межрегиональной",
    "профессиональных", "сро", "ау", "пау", "мсро", "сау", "самро", "объединение",
    "объединения",
})


# Родовые слова в родительном/др. падеже → именительный: чтобы упоминание
# «из числа членов Ассоциации Межрегиональной СРО…» канонически совпадало с
# NAIM_FULL «Ассоциация Межрегиональная СРО…». Нужно для записей, чьё имя целиком
# из родовых слов (МСРО АУ, МСО ПАУ) — отличительного токена у них нет.
_GEN_CANON: Dict[str, str] = {
    "ассоциации": "ассоциация", "организации": "организация",
    "партнерства": "партнерство", "союза": "союз",
    "саморегулируемой": "саморегулируемая", "межрегиональной": "межрегиональная",
    "некоммерческого": "некоммерческое", "региональной": "региональная",
}


def _canon(s: str) -> str:
    """Нормализованная форма со схлопнутым родительным падежом родовых слов."""
    return " ".join(_GEN_CANON.get(w, w) for w in _norm(s).split())


def _quoted_tokens(s: str) -> List[str]:
    """Отличительные наименования в кавычках («Содействие», "ДЕЛО», «ЦФОП АПК»)."""
    return [t.strip() for t in re.findall(r"[«\"“„'']([^«»\"“”„'']+)[»\"”'']", s) if t.strip()]


def _dist_tokens(s: str) -> Set[str]:
    """Отличительные токены строки: одиночные не-родовые слова (len≥3), многословные
    имена в кавычках и их «сжатые» (без пробелов) формы — для матча аббревиатур
    вроде «ЦФОП АПК»↔«ЦФОПАПК», «РСО ПАУ»↔«РСОПАУ»."""
    toks: Set[str] = set()
    for q in _quoted_tokens(s):
        qn = _norm(q)
        if not qn:
            continue
        # Кавычковый токен, целиком состоящий из родовых слов — не отличительный.
        if all(w in _GENERIC for w in qn.split()):
            continue
        if len(qn.replace(" ", "")) >= 3:
            toks.add(qn)
            toks.add(qn.replace(" ", ""))  # сжатая форма многословной аббревиатуры
    for w in _norm(s).split():
        if w not in _GENERIC and len(w) >= 3:
            toks.add(w)
    return toks


# Предрасчёт индекса (модуль грузится один раз).
_INDEX: List[Dict] = []
for _e in SRO_DATA:
    _naimk_n = _norm(_e["NAIMK"])
    _full_n = _norm(_e["NAIM_FULL"])
    _INDEX.append({
        "full": _e["NAIM_FULL"],
        "naimk_n": _naimk_n,
        "full_n": _full_n,
        "full_c": _canon(_e["NAIM_FULL"]),
        "naimk_c": _canon(_e["NAIMK"]),
        # Отличительные токены записи берём из NAIMK (аббревиатуры) и NAIM_FULL
        # (развёрнутые имена) — матч идёт по любому.
        "dist": _dist_tokens(_e["NAIMK"]) | _dist_tokens(_e["NAIM_FULL"]),
    })


def _word_in(token: str, hay: str) -> bool:
    return bool(re.search(r"\b" + re.escape(token) + r"\b", hay))


def resolve_sro(raw: Optional[str]) -> Optional[str]:
    """Возвращает NAIM_FULL записи СРО, наиболее соответствующей `raw`, или None.

    Слои по убыванию строгости:
      1) точное совпадение короткого имени NAIMK;
      2) совпадение по ОТЛИЧИТЕЛЬНЫМ токенам (одиночные не-родовые слова и
         имена в кавычках, в т.ч. сжатые аббревиатуры) — ранжирование по числу
         совпавших токенов, tie-break по пересечению слов NAIMK с `raw`;
      3) NAIMK как подстрока `raw` (снимает префикс/хвост реквизитов).
    Если отличительного сигнала нет — None (лучше оставить сырое, чем угадать чужое).
    """
    if not raw:
        return None
    rn = _norm(raw)
    if not rn:
        return None
    rn_toks = rn.split()
    rn_words = set(rn_toks)
    # Склейки 2–3 подряд идущих слов («рсо пау»→«рсопау») — ловят разнесённую
    # пробелом аббревиатуру, но БЕЗ ложных подстрок (в отличие от глобального
    # среза сжатого текста, где «сопау» протекал из «рсопау»).
    rn_runs = {"".join(rn_toks[i:i + n])
               for n in (2, 3) for i in range(len(rn_toks) - n + 1)}

    # 1) Точное совпадение по короткому имени.
    for e in _INDEX:
        if e["naimk_n"] and e["naimk_n"] == rn:
            return e["full"]

    # 1.5) Каноническое равенство полному/короткому имени (терпит родительный
    #      падеж). Ловит записи из одних родовых слов (МСРО АУ, МСО ПАУ), у
    #      которых нет отличительного токена для слоя 2.
    rc = _canon(rn)
    for e in _INDEX:
        if rc == e["full_c"] or rc == e["naimk_c"]:
            return e["full"]

    # 2) Отличительные токены.
    raw_dist = _dist_tokens(raw)
    if raw_dist:
        scored = []
        for e in _INDEX:
            shared = e["dist"] & raw_dist
            score = len(shared)
            # Сжатая аббревиатура записи (len≥5) == склейка подряд идущих слов `raw`.
            if not score:
                for t in e["dist"]:
                    if len(t) >= 5 and " " not in t and t in rn_runs:
                        score = 1
                        break
            if score:
                scored.append((score, e))
        if scored:
            best = max(scored, key=lambda se: (
                se[0],
                len(set(se[1]["naimk_n"].split()) & rn_words),
                len(se[1]["naimk_n"]),
            ))
            return best[1]["full"]

    # 3) NAIMK — подстрока raw или наоборот.
    cand = [e for e in _INDEX if e["naimk_n"] and (e["naimk_n"] in rn or rn in e["naimk_n"])]
    if len(cand) == 1:
        return cand[0]["full"]
    if cand:
        return max(cand, key=lambda e: len(set(e["naimk_n"].split()) & rn_words))["full"]

    return None

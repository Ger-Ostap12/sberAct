"""Нормализация регистра значений перед подстановкой в акт.

В заявлениях поля приходят капсом или целиком строчными («ИВАНОВ ИВАН
ИВАНОВИЧ», «г. ростов-на-дону»). В акте нужен обычный регистр.
"""

import re

# Правим только однородный регистр: смешанный уже набран человеком.
_СТРОЧНЫЕ = re.compile(r"[а-яёa-z]")
_ЗАГЛАВНЫЕ = re.compile(r"[А-ЯЁA-Z]")
# Слово целиком: буквы с дефисами и апострофами внутри.
_СЛОВО = re.compile(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z'’-]*")

# Организационно-правовые формы и отраслевые аббревиатуры — всегда капсом.
ОПФ = frozenset("""
ООО ОАО ЗАО ПАО АО НАО ПКО МКК МФК МФО КПК НКО НПФ ИП КФХ СРО
МУП ГУП ФГУП ФГБУ ГБУ МБУ АНО НП СПК ТСЖ ТСН ЖСК ГСК ОВД УФК
ФНС ИФНС УФНС МИФНС МРИ ФССП УФССП ПФР СФР ФСС ОПФР ЦБ РФ
ЕФРСБ ЕГРЮЛ ЕГРИП ЕГРН ГК АПК НК ЖК
""".split())

# Служебные слова внутри дефисных топонимов: «Ростов-на-Дону», «Камень-на-Оби».
_СЛУЖЕБНЫЕ_В_ДЕФИСЕ = frozenset("на при под над у из за по от в с без для".split())

# Предлоги и союзы в середине названия организации остаются со строчной.
_СЛУЖЕБНЫЕ_СЛОВА = frozenset("и или на при под над у из за по от в во с со без для".split())

# Фамильные частицы, которые по документам пишутся со строчной.
_ЧАСТИЦЫ_ФИО = frozenset("оглы кызы гызы улы уулу де да ду ван фон дер ла ле бин аль".split())

# Аббревиатуры в названиях организаций: по замеру корпуса их не отличить от
# обычных коротких слов («БАНК» и «АСВ» — обе с одной гласной), поэтому реестр.
_АББРЕВИАТУРЫ_НАЗВАНИЙ = {
    "ГМБХ": "ГмбХ",
    **{a: a for a in """
    СПН ТМД РСВ СКМ АСВ ПСБ ПКБ НФ УФ КБ ВТБ РСХБ СДМ ЭОС МКБ БКС СКБ УБРИР
    МТС РЖД НПО НИИ КБРР ТКБ БЖФ АТБ ХКФ ОТП МФЦ
    """.split()},
}

# Сокращения в адресе — всегда со строчной, падежные формы перечислены явно.
_СОКРАЩЕНИЯ_АДРЕСА = frozenset("""
г гор город города городе с село села сельское ст ст-ца станица станицы
сл слобода х хутор хутора п пос пгт посёлок поселок посёлка поселка
д дом дома деревня деревни дер влд двлд домовл кв квартира квартиры
ком комната комнаты оф офис корп корпус корпуса стр строение строения
лит литер уч участок участка сот
ул улица улицы пер переулок переулка пр пр-кт просп проспект проспекта
пл площадь площади наб набережная набережной ш шоссе туп тупик
б-р бульвар бульвара мкр мкр-н микрорайон микрорайона кв-л квартал квартала
линия линии аллея аллеи тракт тракта
обл область области кр край края краю р-н район района районе
окр округ округа округе тер территория территории
снт днп гск массив промзона вл
""".split())

# «Республика» в реестр выше намеренно не входит: она часть названия субъекта
# («Чеченская Республика», «Респ. Калмыкия») и остаётся с заглавной.

# Аббревиатуры в адресах и местах рождения — капсом (реестр, не эвристика:
# «ОМСК» и «МАГАС» тоже короткие, но это названия).
_АББРЕВИАТУРЫ_АДРЕСА = frozenset("""
РФ СССР РСФСР ССР АССР ЧИАССР ТАССР БАССР ДАССР КАССР УАССР МАССР СОАССР ЧИАССР
ЧР КБР КЧР РСО РД РБ РТ РК РМ РА УР ХМАО ЯНАО ЕАО НАО АО МО ЛО СНГ ГДР ФРГ
""".split())


def _однородный_регистр(значение: str) -> bool:
    """Строка целиком капсом или целиком строчными — её и правим."""
    if not значение:
        return False
    есть_строчные = bool(_СТРОЧНЫЕ.search(значение))
    есть_заглавные = bool(_ЗАГЛАВНЫЕ.search(значение))
    if not (есть_строчные or есть_заглавные):
        return False
    return not (есть_строчные and есть_заглавные)


def _с_заглавной(слово: str) -> str:
    return слово[:1].upper() + слово[1:].lower()


def _по_дефисам(слово: str, служебные_строчными: bool) -> str:
    """«РОСТОВ-НА-ДОНУ» в «Ростов-на-Дону»: служебные части со строчной."""
    части = слово.split("-")
    собрано = []
    for i, часть in enumerate(части):
        if not часть:
            собрано.append(часть)
        elif i and служебные_строчными and часть.lower() in _СЛУЖЕБНЫЕ_В_ДЕФИСЕ:
            собрано.append(часть.lower())
        else:
            собрано.append(_с_заглавной(часть))
    return "-".join(собрано)


def _правка_по_словам(значение: str, правило) -> str:
    счётчик = [0]

    def замена(m):
        счётчик[0] += 1
        return правило(m.group(0), счётчик[0] == 1)

    return _СЛОВО.sub(замена, значение)


def normalize_person_case(значение: str) -> str:
    """ФИО в обычный регистр; инициалы и «ИП» остаются заглавными."""
    if not значение or not _однородный_регистр(значение):
        return значение

    def слово(w: str, первое: bool) -> str:
        if w.upper() in ОПФ:
            return w.upper()
        if w.lower() in _ЧАСТИЦЫ_ФИО:
            return w.lower()
        if "-" in w:
            return _по_дефисам(w, служебные_строчными=False)
        return _с_заглавной(w)

    return _правка_по_словам(значение, слово)


def normalize_org_case(значение: str) -> str:
    """Название организации: ОПФ и короткие аббревиатуры капсом, прочее с заглавной."""
    if not значение or not _однородный_регистр(значение):
        return значение

    def слово(w: str, первое: bool) -> str:
        if w.upper() in ОПФ:
            return w.upper()
        if w.upper() in _АББРЕВИАТУРЫ_НАЗВАНИЙ:
            return _АББРЕВИАТУРЫ_НАЗВАНИЙ[w.upper()]
        # «ЗАВОД ПО ПЕРЕРАБОТКЕ» в «Завод по переработке», а не «По».
        if not первое and w.lower() in _СЛУЖЕБНЫЕ_СЛОВА:
            return w.lower()
        if "-" in w:
            return _по_дефисам(w, служебные_строчными=False)
        return _с_заглавной(w)

    return _правка_по_словам(значение, слово)


def normalize_address_case(значение: str) -> str:
    """Адрес или место рождения: сокращения строчными, аббревиатуры капсом."""
    if not значение or not _однородный_регистр(значение):
        return значение

    def слово(w: str, первое: bool) -> str:
        if w.lower() in _СОКРАЩЕНИЯ_АДРЕСА:
            return w.lower()
        if w.upper() in _АББРЕВИАТУРЫ_АДРЕСА:
            return w.upper()
        if w.upper() in ОПФ:
            return w.upper()
        if "-" in w:
            return _по_дефисам(w, служебные_строчными=True)
        return _с_заглавной(w)

    return _правка_по_словам(значение, слово)


# ОПФ или кавычки в строке — признак организации, а не человека.
_ПРИЗНАК_ОРГАНИЗАЦИИ = re.compile(
    r"[«»\"]|\b(?:%s)\b" % "|".join(sorted(ОПФ - {"ИП", "КФХ"}, key=len, reverse=True)),
    re.IGNORECASE,
)


def normalize_name_case(значение: str, как_организацию: bool = False) -> str:
    """Имя стороны: организация или человек определяется по ОПФ и кавычкам."""
    if not значение:
        return значение
    if как_организацию or _ПРИЗНАК_ОРГАНИЗАЦИИ.search(значение):
        return normalize_org_case(значение)
    return normalize_person_case(значение)

def _норм(x) -> str:
    """Сравниваем по существу: пробелы разрядов, неразрывные пробелы, регистр."""
    s = str(x if x is not None else "")
    s = s.replace(" ", " ").replace("ё", "е").replace("Ё", "Е")
    s = re.sub(r"\s+", " ", s).strip().lower()
    return СИНОНИМЫ.get(s, s)


def достать(r: dict, п: tuple):
    """Значение по пути из label_map — то, что реально видит юрист."""
    вид, аргумент = п[0], п[1]
    f = r.get("fields") or {}
    if вид == "field":
        return f.get(аргумент)
    if вид == "first":
        return next((f.get(k) for k in аргумент if f.get(k)), None)
    if вид == "card":
        # Возвращаем ВСЕ значения поля по карточкам, а не только первую.
        # Причина: у документа бывает пять обязательств, и эталон пишет пять
        # ожиданий с одной подписью «Номер договора». Сравнение с первой
        # карточкой давало бы четыре ложных красных из пяти — прибор врал бы
        # про программу. Ожидание считается сошедшимся, если значение есть
        # ХОТЬ У ОДНОЙ карточки: эталон утверждает «такая сторона/договор
        # в документе есть», а не «он идёт вторым по счёту».
        return [(к or {}).get(п[2]) for к in (r.get(аргумент) or [])]
    if вид == "count":
        return len(r.get(аргумент) or [])
    if вид == "button":
        if аргумент == "entityType":
            return ТИП_ЛИЦА.get(r.get("entityType"), r.get("entityType"))
        if аргумент == "collateralOption":
            return (r.get("recommendedActs") or {}).get("collateralOption")
        if аргумент == "recommendedActIds":
            return (r.get("recommendedActs") or {}).get("recommendedActIds")
        if аргумент == "debtorStatusHint":
            # Форма показывает «обычный», когда подсказки статуса нет вовсе.
            # Без этого приведения эталон краснел бы на КАЖДОМ обычном должнике —
            # то есть врал бы про программу, а не про документ.
            return СТАТУС_КНОПКИ.get(r.get("debtorStatusHint"), "обычный")
        if аргумент == "applicationKind":
            # Вид заявления форма выводит, а не читает: самобанкрот по признаку,
            # иначе — по наличию акта о включении в реестр (DocumentAnalysis.tsx).
            if (r.get("fields") or {}).get("applicationKind") == "self_bankruptcy" \
                    or r.get("applicationKind") == "self_bankruptcy":
                return "Самобанкрот"
            акты = (r.get("recommendedActs") or {}).get("recommendedActIds") or []
            return "Включение в РТК" if "final_rtk_inclusion" in акты else "Инициирование/иное"
        return r.get(аргумент)
    if вид == "flag":
        # Пометки живут в fieldIssues; «любое» — любое предупреждение верхнего уровня.
        if аргумент == "любое":
            return bool(r.get("documentTypeWarning") or r.get("debtorNameWarning")
                        or r.get("entityTypeWarning") or r.get("collateralWarning"))
        претензии = r.get("fieldIssues") or []
        return any(аргумент in str(i.get("field", "")) or аргумент in str(i.get("reason", ""))
                   for i in претензии)
    return None


def сверить(ожидание: dict, r: dict):
    """(сошлось, фактическое) для одного ожидания."""
    вид = ожидание.get("вид", "значение")
    п = ожидание.get("путь_явный") or путь(
        ожидание["подпись"], ИПОТЕКА if r.get("documentType") == "mortgage_claim" else ОБЫЧНЫЙ)
    if п is None:
        return None, "подпись не в карте"
    факт = достать(r, п)
    множество = isinstance(факт, list) and п[0] == "card"
    if вид == "пусто":
        пусто = all(v in (None, "", [], {}) for v in факт) if множество \
            else факт in (None, "", [], {})
        return пусто, факт
    if вид == "без_пометки":
        return факт is False or факт == 0, факт
    if вид == "количество":
        return str(факт) == str(ожидание["ждём"]).strip(), факт
    if множество:
        ждём = _норм(ожидание["ждём"])
        совпало = any(_норм(v) == ждём for v in факт)
        # В отчёт кладём короткий список карточек, иначе строка расхождения
        # разрастается и её невозможно читать.
        return совпало, [v for v in факт if v][:4]
    return _норм(факт) == _норм(ожидание["ждём"]), факт


def загрузить():
    for имя in sorted(glob.glob(os.path.join(ЭТАЛОН, "*.json"))):
        yield json.load(io.open(имя, encoding="utf-8"))


def главное(фильтр_класс=None, фильтр_документ=None):
    from document_analyzer import DocumentAnalyzer
    анализатор = DocumentAnalyzer()
    всего = сошлось = пропущено = 0
    по_классам, по_документам, расхождения = {}, {}, []
    # Подпись вне карты — не «пропущено», а ДЫРА В ПРИБОРЕ: ожидание есть,
    # а сверить его нечем. Молчать об этом нельзя, иначе эталон выглядит
    # меньше, чем он есть, и недосверенное читается как успех.
    без_карты = []

    for блок in загрузить():
        ключ = блок["ключ"]
        if фильтр_документ and ключ != фильтр_документ:
            continue
        часть, номер = ключ.rsplit("-", 1)
        # Ищем документ по ИМЕНИ; номер в ключе остаётся только как подпись.
        путь = путь_по_имени(часть, блок["файл"]) if блок.get("файл") else None
        if путь is None:
            путь = путь_документа(часть, int(номер))
        r = анализатор.analyze(путь)
        зелёных = красных = 0
        for о in блок.get("ожидания", []):
            if фильтр_класс and о.get("класс") != фильтр_класс:
                continue
            if о["подпись"] in ПРАВИЛО_НЕ_ОПРЕДЕЛЕНО:
                пропущено += 1
                continue
            ок, факт = сверить(о, r)
            if ок is None:
                без_карты.append((ключ, о["подпись"]))
                continue
            всего += 1
            клс = о.get("класс", "без класса")
            по_классам.setdefault(клс, [0, 0])
            if ок:
                сошлось += 1
                зелёных += 1
                по_классам[клс][0] += 1
            else:
                красных += 1
                по_классам[клс][1] += 1
                расхождения.append((ключ, о["подпись"], о["ждём"], факт))
        по_документам[ключ] = (зелёных, красных)

    print(f"ожиданий {всего}   сходится {сошлось}   не сходится {всего - сошлось}"
          f"   пропущено (правило не определено) {пропущено}\n")
    if без_карты:
        print(f"!! ПОДПИСЬ ВНЕ КАРТЫ — {len(без_карты)} ожиданий сверить НЕЧЕМ:")
        for ключ, подпись in sorted(set(без_карты)):
            print(f"   {ключ:14s} {подпись!r}")
        print("   добавь их в label_map.КАРТА, иначе эталон недосчитывает себя\n")
    print("ПО КЛАССАМ")
    for клс, (з, к) in sorted(по_классам.items(), key=lambda kv: -kv[1][1]):
        print(f"   {клс:32s} красных {к:3d}   зелёных {з:3d}")
    print("\nПО ДОКУМЕНТАМ (только с красными)")
    for ключ, (з, к) in sorted(по_документам.items(), key=lambda kv: -kv[1][1]):
        if к:
            print(f"   {ключ:14s} {к} из {з + к} красных")
    if "-v" in sys.argv:
        print("\nРАСХОЖДЕНИЯ")
        for ключ, подпись, ждём, факт in расхождения:
            print(f"   {ключ:14s} {подпись:24s} ждём {ждём!r}  факт {факт!r}")
    return всего - сошлось


if __name__ == "__main__":
    арг = sys.argv
    класс = арг[арг.index("--класс") + 1] if "--класс" in арг else None
    документ = арг[арг.index("--документ") + 1] if "--документ" in арг else None
    sys.exit(0 if главное(класс, документ) == 0 else 1)

def путь(подпись: str, режим: str = ОБЫЧНЫЙ):
    """Путь для подписи с учётом режима формы; None — если подпись не поле."""
    подпись = подпись.strip()
    if подпись in НЕ_ПОЛЯ:
        return None
    варианты = КАРТА.get(подпись)
    if варианты is None:
        # Подписи с номером: «Обязательство №1», «Обязательство [1]»
        база = подпись.split("№")[0].split("[")[0].strip()
        варианты = КАРТА.get(база)
    if варианты is None:
        return None
    return варианты.get(режим) or варианты.get(ЛЮБОЙ)

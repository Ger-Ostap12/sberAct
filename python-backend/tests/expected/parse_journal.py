# -*- coding: utf-8 -*-
"""Шаг 2 эталона: журнал сверки -> ЧЕРНОВИК ожиданий.

Читает `СВЕРКА_ДОКУМЕНТОВ.md` и раскладывает строки расхождений на данные.
Ничего не выдумывает: строка, из которой значение не выводится однозначно,
уходит в список «руками», а не в эталон. Выдуманное ожидание опаснее
пропущенного — оно молчит там, где ошибка.

Запуск:  python parse_journal.py            -> expectations_draft.json + отчёт
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from label_map import ИПОТЕКА, ОБЫЧНЫЙ, путь  # noqa: E402

КОРЕНЬ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
ЖУРНАЛ = os.path.join(КОРЕНЬ, "СВЕРКА_ДОКУМЕНТОВ.md")

# Шапка блока: «**[12] имя.docx — 4**», «— всё совпадает», «**[9] имя** — проза»,
# «**[33] a.docx и [34] b.docx — по 8, документы идентичны**».
# Число расхождений может отсутствовать — тогда блок описан словами.
ШАПКА = re.compile(r"^\*\*\[(\d+)\]\s+(.+?)(?:\*\*)?\s*(?:—\s*(.*?))?\*?\*?\s*$")
# «в док.» и «прогр.» встречаются в ОБОИХ порядках: в журнале есть и
# «Поле  в док. X  прогр. Y», и «Поле  прогр. Y  в док. X».
ДОК_ЧАСТЬ = re.compile(r"в\s+док\.\s*")
ПРОГР_ЧАСТЬ = re.compile(r"прогр\.\s*")

# Значение в кавычках-ёлочках: берём ТОЛЬКО его, иначе в эталон попадёт проза
В_КАВЫЧКАХ = re.compile(r"^«(.+)»$")
# «Значение» с хвостом-комментарием: «АС Ростовской области» (дело А53-…)
ПЕРВЫЕ_КАВЫЧКИ = re.compile(r"^«([^»]+)»\s*[(\-—,].*$")
# Голое число/дата/сумма: тоже однозначно
ГОЛОЕ = re.compile(r"^[\d\s.,/№A-Za-zА-Яа-яЁё\-]{1,60}$")

ПРОЗА = ("вместо", "потеряно", "адрес ", "взят ", "мусор", "это ", "надо ",
         "у физлица", "весь блок", "второе ", "не найден", "не извлеч")


def значение(сырое: str):
    """Однозначное значение или None, если это описание словами."""
    s = (сырое or "").strip().rstrip(",;")
    if not s:
        return None
    m = В_КАВЫЧКАХ.match(s)
    if m:
        return m.group(1).strip()
    # «Значение» + пояснение в скобках/через тире: кавычки задают границу
    # значения однозначно, хвост — комментарий сверщика, а не часть данных.
    m = ПЕРВЫЕ_КАВЫЧКИ.match(s)
    if m:
        return m.group(1).strip()
    низ = s.lower()
    if any(p in низ for p in ПРОЗА):
        return None
    if s in ("пусто", "—", "Не указана", "нет"):
        return ""
    if ГОЛОЕ.match(s) and not s.endswith(("(", "…")):
        return s
    return None


def разложить(строка: str):
    """Строка расхождения -> (подпись, что в документе, что показала программа).

    Порядок «в док.»/«прогр.» в журнале не выдержан, поэтому режем по позициям
    маркеров, а не по жёсткому шаблону. Подпись — всё до ПЕРВОГО маркера.
    """
    д = ДОК_ЧАСТЬ.search(строка)
    п = ПРОГР_ЧАСТЬ.search(строка)
    if д or п:
        первый = min(x.start() for x in (д, п) if x)
        подпись = строка[:первый].strip()
        куски = sorted([x for x in (д, п) if x], key=lambda x: x.start())
        значения = {}
        for i, м in enumerate(куски):
            конец = куски[i + 1].start() if i + 1 < len(куски) else len(строка)
            имя = "док" if м is д else "прогр"
            значения[имя] = строка[м.end():конец].strip()
        return подпись, значения.get("док"), значения.get("прогр")
    if "→" in строка:
        левая, правая = строка.split("→", 1)
        м = re.match(r"^(?P<поле>[^\s].{0,33}?)\s{2,}(?P<док>.*)$", левая)
        if м:
            return м.group("поле").strip(), м.group("док").strip(), правая.strip()
    return None, None, None


def разобрать():
    текст = io.open(ЖУРНАЛ, encoding="utf-8").read()
    граница = текст.index("# ЧАСТЬ II") if "# ЧАСТЬ II" in текст else len(текст)

    черновик, руками, пропущено = {}, [], []
    текущий = None
    внутри_блока = False
    позиция = 0

    for сырая in текст.split("\n"):
        позиция += len(сырая) + 1
        ш = ШАПКА.match(сырая) if сырая.startswith("**[") else None
        if ш:
            часть = "корпус" if позиция > граница else "свежие"
            текущий = f"{часть}[{ш.group(1)}]"
            хвост = (ш.group(3) or "").strip()
            черновик.setdefault(текущий, {"имя": ш.group(2).strip(" *"), "часть": часть,
                                          "заявлено": хвост, "ожидания": {}})
            continue
        if сырая.startswith("```"):
            внутри_блока = not внутри_блока
            continue
        if not внутри_блока or текущий is None or not сырая.strip():
            continue
        if сырая.startswith((" ", "\t")):      # продолжение предыдущей строки
            continue

        подпись, док, прогр = разложить(сырая)
        if not подпись:
            continue
        режим = ИПОТЕКА if "ипотек" in черновик[текущий]["имя"].lower() else ОБЫЧНЫЙ
        п = путь(подпись, режим)
        if п is None:
            пропущено.append((текущий, подпись, сырая.strip()[:90]))
            continue
        зн = значение(док)
        запись = {"подпись": подпись, "путь": п,
                  "сырое_док": (док or "")[:120], "сырое_прогр": (прогр or "")[:120]}
        if зн is None:
            руками.append({"документ": текущий, **запись})
        else:
            запись["ждём"] = зн
            черновик[текущий]["ожидания"][подпись] = запись

    return черновик, руками, пропущено


if __name__ == "__main__":
    ч, р, п = разобрать()
    всего = sum(len(d["ожидания"]) for d in ч.values())
    вывод = os.path.join(os.path.dirname(__file__), "expectations_draft.json")
    io.open(вывод, "w", encoding="utf-8").write(
        json.dumps({"черновик": ч, "руками": р, "пропущено": п},
                   ensure_ascii=False, indent=1))
    print(f"документов в журнале : {len(ч)}")
    print(f"ожиданий разобрано   : {всего}")
    print(f"в список «руками»    : {len(р)}   (проза, значение не выводится)")
    print(f"подпись не в карте   : {len(п)}")
    if п:
        print("\nнеопознанные подписи (первые 15):")
        for д, подпись, строка in п[:15]:
            print(f"   {д:12s} {подпись!r:28s} {строка}")

# --- df_v8: та же логика, что df_v7 (§R.10), теперь и для debtor (Андрей,
#     2026-07-22, тот же день) — какие поля должника применимы, зависит от
#     entityType (individual/legal/ip/kfh), а regex УЖЕ надёжно определяет
#     entityType (это давно работающая часть `parties_mixin.py`, мы же
#     используем её как эталон для сверки метрики "entityType верно
#     определён"). Значит regex-entityType — такой же "известный до вызова
#     LLM" сигнал, как documentType/ФНС-кредитор для manager. Схему `debtor`
#     сужаем по нему: individual — без ogrn; legal — без birthDate/
#     birthPlace; ip/kfh — без birthPlace. Шаг 1 (определение entityType
#     самой моделью) СОХРАНЯЕМ как есть — это дешёвая независимая сверка
#     LLM-vs-regex, вдруг regex ошибся на редком случае; узкая схема — риск
#     в обратную сторону (если regex всё же ошибся типом, у модели физически
#     нет слота под поле нужного типа, напр. ogrn для реально legal-документа,
#     который regex принял за individual) — принят сознательно, тот же
#     профиль риска, что уже принят для documentType в df_v7.
#     Сужаем схему ТОЛЬКО для individual/legal — для них есть few-shot,
#     согласованный по форме (текст описывает ИМЕННО такого должника, а не
#     смесь). Для ip/kfh (в нашем корпусе всего 1 ip, kfh нет вовсе) готового
#     согласованного примера пока нет — сознательно НЕ сужаем, безопасный
#     откат к полной схеме (как в df_v7), чтобы не давать модели пример,
#     противоречащий её же декларируемой схеме.
_DF_V8_DEBTOR_FIELDS_BY_TYPE = {
    "individual": ("name", "address", "inn", "birthDate", "birthPlace"),
    "legal": ("name", "address", "inn", "ogrn"),
}
_DF_V8_DEBTOR_FIELDS_ALL = ("name", "address", "inn", "ogrn", "birthDate", "birthPlace")


def _df_v8_debtor_schema(regex_entity_type: str) -> str:
    fields = _DF_V8_DEBTOR_FIELDS_BY_TYPE.get(regex_entity_type, _DF_V8_DEBTOR_FIELDS_ALL)
    return "{" + ", ".join(f'"{f}": ""' for f in fields) + "}"


def _df_v8_schema(need_fio: bool, need_sro: bool, regex_entity_type: str) -> str:
    manager_parts = []
    if need_fio:
        manager_parts.append('"name": "", "address": ""')
    if need_sro:
        manager_parts.append('"sro": ""')
    if not manager_parts:
        raise ValueError("df_v8: need_fio и need_sro одновременно False — не должно случаться")
    manager = "{" + ", ".join(manager_parts) + "}"
    debtor = _df_v8_debtor_schema(regex_entity_type)
    return f'{{"entityType": "individual|legal|ip|kfh", "debtor": {debtor}, "manager": {manager}}}'


def _df_v8_trim_debtor(debtor: dict, regex_entity_type: str) -> dict:
    fields = _DF_V8_DEBTOR_FIELDS_BY_TYPE.get(regex_entity_type, _DF_V8_DEBTOR_FIELDS_ALL)
    return {k: debtor[k] for k in fields}



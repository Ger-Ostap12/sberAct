# -*- coding: utf-8 -*-
"""Правило ISO-даты не портит номер договора (05.10.2026).

Генерация переводит дату «2024-08-10» в «10.08.2024» — правило идёт по ВСЕМУ
тексту акта. Границ у него не было, и оно срабатывало ВНУТРИ номера договора:
у сбербанковской нумерации «6142027489-24-1» внутри лежит «7489-24-1», и в акт
уезжало «61420201.24.7489».

Замер по корпусу на 05.10.2026: искажались номера 17 карточек в 7 документах
(корпус-27, -28, -29, -30, -31, -38). Номер в акте — то, по чему суд опознаёт
требование, так что это не косметика.

Найдено попутно, при сборке актов с разными видами обязательств: вид стал
печататься верно, и стало видно, что номер рядом с ним неверный.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))


@pytest.fixture(scope="module")
def ген():
    from document_generator import DocumentGenerator
    return DocumentGenerator()


def привести(ген, текст: str) -> str:
    """Текст после форматирования акта (то же, что делает генерация)."""
    from docx import Document

    документ = Document()
    документ.add_paragraph(текст)
    ген._postprocess_document_formatting(документ, {})
    return документ.paragraphs[0].text


# --- номера, которые правило ломало --------------------------------------------

@pytest.mark.parametrize("номер", [
    "6142027489-24-1",        # корпус-38
    "6168086464-23-5П02",     # корпус-28, договор поручительства
    "616100070855-24-3П01",   # корпус-29
    "6123013561-23-1",        # корпус-27
    "616506698400-25-2",      # корпус-30
    "616270139617-24-1",      # корпус-31
])
def test_номер_договора_не_переписывается(ген, номер):
    итог = привести(ген, f"задолженность по кредитному договору № {номер} от 20.03.2024")
    assert номер in итог, итог


# --- даты, которые правило обязано переводить -----------------------------------

@pytest.mark.parametrize("было,ждём", [
    ("от 2024-08-10 года", "от 10.08.2024 года"),
    ("дата 2026.04.02 принятия", "дата 02.04.2026 принятия"),
    ("от 2024-8-1,", "от 01.08.2024,"),
])
def test_iso_дата_переводится(ген, было, ждём):
    assert привести(ген, было) == ждём


def test_номер_дела_не_трогается(ген):
    """«А53-41535-2025/121148» — номер дела, а не дата."""
    итог = привести(ген, "Дело № А53-41535-2025/121148 о взыскании")
    assert "А53-41535-2025/121148" in итог


def test_номер_и_дата_рядом(ген):
    """Оба правила в одной строке: номер цел, дата переведена."""
    итог = привести(
        ген, "по кредитному договору № 6142027489-24-1 от 2024-08-10 в размере 1 руб.")
    assert "6142027489-24-1" in итог
    assert "10.08.2024" in итог


def test_правило_сторожит_обе_стороны(ген):
    """Тест обязан падать и на обратной ошибке.

    Если границы сделать слишком строгими и правило перестанет работать
    вообще, покраснеет `test_iso_дата_переводится`; если их убрать —
    покраснеет `test_номер_договора_не_переписывается`. Здесь — обе проверки
    на одной строке, чтобы связь была видна.
    """
    итог = привести(ген, "№ 6142027489-24-1 от 2024-08-10")
    assert re.search(r"№ 6142027489-24-1 от 10\.08\.2024", итог), итог

def test_определение_термина_не_становится_именем_кредитора(analyzer):
    """«(далее — Кредитор) является кредитором» отдавало creditorName «Кредитор)».

    Заявление вводит термин и дальше им пользуется; паттерн
    `([^,\n]+)\s+является кредитором` захватывал определение, а не имя банка.
    Гард общий: ни одно поле не может законно равняться метке из реестра.
    Случай из корпуса — «Заявление о включении в РТК_Рытченко Л.В..docx».
    """
    # Текст из документа дословно: ЗАПЯТАЯ перед «Кредитор)» и решает дело —
    # класс [^,\n]+ через неё не переходит, и в захват попадает одно слово.
    текст = (
        "Конкурсный кредитор: «Газпромбанк» (Акционерное общество)\n"
        "ОГРН 1027700167110, ИНН 7744001497\n"
        "«Газпромбанк» (Акционерное общество) (далее — Банк ГПБ (АО), Кредитор) "
        "является кредитором должника.\n"
    )
    имя = analyzer.extract_fields(текст, "rtk_application").get("creditorName") or ""
    assert "Кредитор)" not in имя
    assert имя == "" or "банк" in имя.lower() or "газпром" in имя.lower()


@pytest.mark.parametrize("метка", ["Кредитор", "Должник", "Заявитель", "Адрес", "ИНН"])
def test_голая_метка_не_проходит_как_значение(analyzer, метка):
    """Проверяем сам гард, а не один паттерн: метка в любом падеже написания
    не может быть значением поля."""
    assert analyzer._BARE_LABEL_VALUE_RE.match(метка)
    assert analyzer._BARE_LABEL_VALUE_RE.match(метка + ")")
    assert analyzer._BARE_LABEL_VALUE_RE.match("«" + метка + "»")
    assert not analyzer._BARE_LABEL_VALUE_RE.match(метка + " Сбербанк")

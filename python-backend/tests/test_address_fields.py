# --- 2б. Сверка адреса кредитора со справочником ------------------------------
#
# Правило (решение Андрея, 02.09.2026): документ главнее справочника, справочник —
# это СВЕРКА. Молча заполняется ровно один случай: юр-адрес из документа совпал
# со справочником. Во всех остальных поле помечается для проверки.

def _advisory(fields):
    return (fields.get("_advisories") or {}).get("creditorAddress")


def test_юр_адрес_совпал_со_справочником_без_пометки(analyzer):
    """Два независимых источника сказали одно и то же — проверять нечего."""
    text = ("Кредитор: ПАО Сбербанк\n"
            "Юридический адрес: 117312, г. Москва, ул. Вавилова, д. 19\n")
    fields = {"creditorName": "ПАО Сбербанк"}
    analyzer._fill_creditor_requisites(fields, text)
    analyzer._verify_creditor_address(fields)
    assert fields["creditorAddress"] == "117312, г. Москва, ул. Вавилова, д. 19"
    assert _advisory(fields) is None


def test_иное_написание_того_же_адреса_не_расхождение(analyzer):
    """Иначе предупреждение зажигалось бы почти на каждом заявлении."""
    text = ("Кредитор: ПАО Сбербанк\n"
            "Юридический адрес: 117312, Москва, Вавилова ул., дом 19\n")
    fields = {"creditorName": "ПАО Сбербанк"}
    analyzer._fill_creditor_requisites(fields, text)
    analyzer._verify_creditor_address(fields)
    assert fields["creditorAddress"] == "117312, Москва, Вавилова ул., дом 19"
    assert _advisory(fields) is None


def test_юр_адрес_разошёлся_со_справочником(analyzer):
    """Побеждает документ, но юрист должен увидеть, с чем именно разошлось."""
    text = ("Кредитор: ПАО Сбербанк\n"
            "Юридический адрес: 344002, г. Ростов-на-Дону, ул. Ленина, д. 5\n")
    fields = {"creditorName": "ПАО Сбербанк"}
    analyzer._fill_creditor_requisites(fields, text)
    analyzer._verify_creditor_address(fields)
    assert fields["creditorAddress"] == "344002, г. Ростов-на-Дону, ул. Ленина, д. 5"
    assert "117312, г. Москва, ул. Вавилова, д. 19" in _advisory(fields)


def test_адреса_в_документе_нет_берём_справочник_с_пометкой(analyzer):
    text = "Кредитор: ПАО Сбербанк ИНН 7707083893\n"
    fields = {"creditorName": "ПАО Сбербанк"}
    analyzer._fill_creditor_requisites(fields, text)
    assert fields["creditorAddress"] == "117312, г. Москва, ул. Вавилова, д. 19"
    assert "из справочника" in _advisory(fields)
    assert fields["_provenance"]["creditorAddress"] == "registry"


def test_кредитора_нет_в_справочнике_пометки_нет(analyzer):
    """Сверять не с чем — это не расхождение. Пометка на каждом небанковском
    кредиторе обесценила бы саму пометку."""
    text = ("Кредитор: ООО «ПКО Ромашка» ИНН 6670056296\n"
            "Юридический адрес: 344002, г. Ростов-на-Дону, ул. Ленина, д. 5\n")
    fields = {"creditorName": "ООО «ПКО Ромашка»"}
    analyzer._fill_creditor_requisites(fields, text)
    analyzer._verify_creditor_address(fields)
    assert fields["creditorAddress"] == "344002, г. Ростов-на-Дону, ул. Ленина, д. 5"
    assert _advisory(fields) is None



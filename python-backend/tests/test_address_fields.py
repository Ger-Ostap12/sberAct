# -*- coding: utf-8 -*-
"""Адреса кредитора и управляющего (01.09.2026).

Четыре правки, каждая — из разбора конкретного класса заявлений:

1. Реквизиты кредитора не извлекались, если `creditorName` на момент вызова ещё
   пуст. Имя нужно ТОЛЬКО для сверки со справочником банков, а выход по пустому
   имени рубил и извлечение из документа: у «Петросян Г.С.» юридический адрес
   «108811, г. Москва, БЦ Comcity…» в поле не попадал вовсе.
2. Адрес кредитора без метки, вклеенный в строку с реквизитами
   («…Банк ГПБ (АО) ОГРН …, ИНН … Дата регистрации 13.11.2001 ул. Наметкина,
   д. 16, к. 1, г. Москва, 117420»).
3. Адрес управляющего сразу за его ФИО, метки может не быть.
   ⚠️ Якорь — ЕДИНСТВЕННОЕ число: «управляющих» это кусок названия СРО, и
   заглавное название организации свободно проходит проверку «похоже на ФИО».
4. Точка в конце адреса — конец предложения, а не часть значения.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from patterns import MANAGER_ADDRESS_AFTER_NAME  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- 1. Реквизиты кредитора без известного имени -----------------------------

_CREDITOR_BLOCK = (
    "Заявитель: НАО ПКО «Первое клиентское бюро»\n"
    "Юридический адрес: 108811, г. Москва, БЦ Comcity, Киевское шоссе, домовл.6\n"
    "ИНН 2723115222, ОГРН 1092723000446\n"
)


def test_адрес_кредитора_берётся_без_имени(analyzer):
    """Имя нужно только справочнику банков — извлечение из документа от него
    зависеть не должно."""
    fields = {}
    analyzer._fill_creditor_requisites(fields, _CREDITOR_BLOCK)
    assert (fields.get("creditorAddress") or "").startswith("108811")


def test_слишком_длинное_имя_по_прежнему_отсекается(analyzer):
    """Гард на длину остаётся: строка в 200+ символов — это не имя, а мусор,
    и сверка со справочником по ней бессмысленна."""
    fields = {"creditorName": "x" * 250}
    analyzer._fill_creditor_requisites(fields, _CREDITOR_BLOCK)
    assert "creditorAddress" not in fields


# --- 2. Адрес кредитора, вклеенный в строку с реквизитами --------------------

def test_адрес_вклеен_в_строку_с_реквизитами(analyzer):
    block = ("кредитор: «Газпромбанк» (Акционерное общество) Банк ГПБ (АО) "
             "ОГРН 1027700167110, ИНН 7744001497 Дата регистрации 13.11.2001 "
             "ул. Наметкина, д. 16, кори. 1, г. Москва, 117420")
    assert analyzer._creditor_address_glued_to_requisites(block) == (
        "ул. Наметкина, д. 16, кори. 1, г. Москва, 117420")


def test_реквизиты_не_уезжают_в_адрес(analyzer):
    """Хвост с ОГРН и ИНН срезает `_clean_creditor_address`. Отдельного гарда
    в самом сегменте НЕТ намеренно: мутационная проверка показала, что он не
    меняет ни одного исхода."""
    block = ("ул. Ленина, д. 1 ОГРН 1027700167110, ИНН 7744001497 "
             "г. Москва, 117420")
    got = analyzer._creditor_address_glued_to_requisites(block) or ""
    assert "ОГРН" not in got and "ИНН" not in got
    assert got.startswith("ул. Ленина")


def test_почтовый_адрес_не_годится_кредитору(analyzer):
    """Продуктовое правило слоёв выше: адрес кредитора — ЮРИДИЧЕСКИЙ."""
    block = "почтовый адрес: ул. Ленина, д. 1, г. Москва, 117420"
    assert analyzer._creditor_address_glued_to_requisites(block) is None


# --- 2а. Запасной адрес кредитора, когда юридического нет --------------------

_NON_LEGAL_BLOCK = (
    "Кредитор: ООО «ПКО Воксис» ИНН 6670056296;\n"
    "ОГРН 1046603500426\n"
    "Фактический адрес: 400050, г. Волгоград, ул. им. Рокоссовского, 62, этаж 9 \n"
    "Адрес для направления корреспонденции: 400050, г.Волгоград, а/я № 1966\n"
)


def test_фактический_адрес_когда_юридического_нет(analyzer):
    """Решение Андрея: пустое поле хуже, чем непрофильный, но верный адрес."""
    assert analyzer._creditor_address_non_legal(_NON_LEGAL_BLOCK) == (
        "400050, г. Волгоград, ул. им. Рокоссовского, 62, этаж 9")


def test_порядок_запасных_видов(analyzer):
    """Фактический предпочтительнее адреса для корреспонденции: там кредитор
    действительно находится, а «для корреспонденции» часто просто а/я."""
    got = analyzer._creditor_address_non_legal(_NON_LEGAL_BLOCK)
    assert "Рокоссовского" in got and "а/я" not in got


def test_почта_не_приклеивается_к_запасному_адресу(analyzer):
    block = ("Почтовый адрес: 620000, г.Екатеринбург,а/я 803 \n"
             "bankruptcy@arsfinance.ru \n")
    assert analyzer._creditor_address_non_legal(block) == "620000, г.Екатеринбург,а/я 803"


def test_запасной_адрес_дочитывается_через_узкую_колонку(analyzer):
    """Узкая колонка рвёт адрес по дефису и по пробелу, и хвост «, ООО "ПКО
    "АСВ"» — повтор названия, а не часть адреса."""
    block = ("Адрес для корреспонденции: 195277, г. Санкт-\n"
             "Петербург, пр. Большой Сампсониевский, д. \n"
             "28, корп.2, Лит. Д, оф. 642, ООО \"ПКО \"АСВ\"\n"
             "Представитель кредитора \n")
    assert analyzer._creditor_address_non_legal(block) == (
        "195277, г. Санкт- Петербург, пр. Большой Сампсониевский, д. 28, корп.2, Лит. Д, оф. 642")


def test_справочник_главнее_запасного_адреса(analyzer):
    """У банка из справочника есть настоящий юр-адрес — подменять его адресом
    для корреспонденции нельзя (замер: так менялись 5 документов корпуса)."""
    text = ("Кредитор: ПАО Сбербанк\n"
            "Почтовый адрес: 344000, г. Ростов-на-Дону, ул. Пушкинская, д. 1\n")
    fields = {"creditorName": "ПАО Сбербанк"}
    analyzer._fill_creditor_requisites(fields, text)
    assert fields["creditorAddress"] == "117997, г. Москва, ул. Вавилова, д. 19"


def test_метка_обязательна_для_запасного_адреса(analyzer):
    """Без метки правило брало бы любую строку с индексом — в блоке кредитора
    это может быть адрес суда или представителя."""
    block = "Кредитор: ООО «Ромашка»\n344002, г. Ростов-на-Дону, ул. Ленина, д. 1\n"
    assert analyzer._creditor_address_non_legal(block) is None


# --- 3. Адрес управляющего сразу за ФИО --------------------------------------

_MGR_RE = re.compile(MANAGER_ADDRESS_AFTER_NAME, re.IGNORECASE)


def test_адрес_управляющего_с_незнакомой_меткой():
    text = ("Финансовым управляющим утвержден(а) Семенов Сергей Станиславович, "
            "адрес для направления корреспонденции: 117418 г. Москва, "
            "ул. Новочерёмушкинская, д.56, к. 1, а/я 4. Согласно положениям главы 10")
    m = _MGR_RE.search(text)
    assert m and m.group(1).startswith("117418")
    assert "Согласно" not in m.group(1)


def test_адрес_управляющего_без_метки_со_следующей_строки():
    text = ("Конкурсный управляющий ООО «УО «Владимирская» Каплиёв Михаил Васильевич\n"
            "344011, г. Ростов-на-Дону, ул. Красноармейская, д. 17, а/я 493\n"
            "Размер требований: 800 293,35 руб.")
    m = _MGR_RE.search(text)
    assert m and m.group(1) == "344011, г. Ростов-на-Дону, ул. Красноармейская, д. 17, а/я 493"


def test_адрес_сро_не_адрес_управляющего():
    """Множественное «управляющих» — часть названия СРО, а заглавное название
    организации проходит проверку «похоже на ФИО». С якорем `управляющ\\w+`
    слой брал адрес СРО на двух документах корпуса."""
    text = ("утвердить арбитражного управляющего Степанову Лидию Дмитриевну "
            "из числа членов СОЮЗ АРБИТРАЖНЫХ УПРАВЛЯЮЩИХ «САМОРЕГУЛИРУЕМАЯ "
            "ОРГАНИЗАЦИЯ ДЕЛО», адрес: 125284, г. Москва, Хорошевское шоссе, 32А")
    assert not _MGR_RE.search(text)


def test_маркер_сро_обрывает_окно():
    """Второй рубеж: даже при единственном числе якоря «из числа членов»
    означает, что дальше идёт адрес организации."""
    text = ("Финансовым управляющим утвержден Иванов Иван Иванович из числа "
            "членов Ассоциации, адрес: 454100, г. Челябинск, ул. Ленина, 1")
    assert not _MGR_RE.search(text)


# --- 4. Точка в конце адреса --------------------------------------------------

def test_точка_в_конце_срезается(analyzer):
    fields = {"managerAddress": "610000, Кировская обл., г. Киров, а/я 99."}
    analyzer._sanitize_address_fields(fields)
    assert fields["managerAddress"] == "610000, Кировская обл., г. Киров, а/я 99"


def test_сокращения_внутри_адреса_не_страдают(analyzer):
    value = "344002, г. Ростов-на-Дону, ул. Б. Садовая, д. 5, стр. 1"
    fields = {"creditorAddress": value}
    analyzer._sanitize_address_fields(fields)
    assert fields["creditorAddress"] == value


# --- 5. Сумма не должна читаться как индекс ------------------------------------

def test_сумма_не_индекс(analyzer):
    """«499999, 53 руб.» выглядит как индекс с продолжением. Проверять надо то,
    что идёт ЗА индексом: сам индекс подтверждением быть не может."""
    block = ("Должник: Иванов Иван Иванович\n"
             "499999, 53 руб., в том числе - просроченный основной долг")
    assert analyzer._collect_block_address(block) is None

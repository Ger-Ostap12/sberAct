# -*- coding: utf-8 -*-
"""Сверка адреса из документа с адресом из справочника (app/address_match.py).

Задача сверки — отличить РАЗНОЕ МЕСТО от разного НАПИСАНИЯ одного места.
Дословное сравнение зажигало бы предупреждение почти на каждом заявлении.
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from address_match import (  # noqa: E402
    address_house,
    address_index,
    address_key,
    address_street,
    same_address,
)

# Юр-адреса банков против того, как их пишут в заявлениях.
СБЕР = "117997, г. Москва, ул. Вавилова, д. 19"
ГПБ = "117420, г. Москва, ул. Наметкина, д. 16, корп. 1"
ВТБ = "190000, г. Санкт-Петербург, ул. Большая Морская, д. 29"


@pytest.mark.parametrize("written", [
    "117997, г. Москва, ул. Вавилова, д. 19",
    "117997, Москва, Вавилова ул., 19",
    "117997, г.Москва, улица Вавилова, дом 19",
    "117997, Российская Федерация, г. Москва, ул. Вавилова, д. 19",
    "г. Москва, ул. Вавилова, д. 19, 117997",
])
def test_одно_место_разные_написания(written):
    assert same_address(СБЕР, written)


@pytest.mark.parametrize("written", [
    "117997, г. Москва, ул. Вавилова, д. 21",       # другой дом
    "117997, г. Москва, ул. Профсоюзная, д. 19",    # другая улица
    "125009, г. Москва, ул. Вавилова, д. 19",       # другой индекс
])
def test_разные_места_расходятся(written):
    assert not same_address(СБЕР, written)


@pytest.mark.parametrize("written,ожидание", [
    ("117420, Москва, Наметкина ул., 16 корп.1", True),
    ("117420, г. Москва, ул. Наметкина, д. 16, к. 1", True),
    ("117420, г. Москва, ул. Наметкина, д. 16, корпус 1", True),
    # Конвертер печатает «корп» как «кори» — это то же здание.
    ("117420, г. Москва, ул. Наметкина, д. 16, кори. 1", True),
    ("117420, г. Москва, ул. Наметкина, д. 16, корп. 2", False),
    # Корпус и строение — РАЗНЫЕ здания в одном владении.
    ("117420, г. Москва, ул. Наметкина, д. 16, стр. 1", False),
])
def test_корпус_и_строение(written, ожидание):
    assert same_address(ГПБ, written) is ожидание


def test_тип_улицы_в_сверку_не_входит():
    """Конвертер и сокращения корёжат именно тип; название и дом решают."""
    assert same_address(ВТБ, "190000, Санкт-Петербург, Большая Морская улица, 29")
    assert same_address(ВТБ, "190000, СПб, Б. Морская ул., д. 29") is False  # имя другое


def test_ё_и_кавычки_не_расхождение():
    assert same_address(
        "107078, г. Москва, ул. Каланчёвская, д. 27",
        "107078, г. Москва, ул. Каланчевская, д. 27",
    )


def test_неразрывный_пробел_не_расхождение():
    assert same_address(СБЕР, "117997,\u00a0г.\u00a0Москва,\u00a0ул.\u00a0Вавилова,\u00a0д.\u00a019")


def test_нечего_сравнить_не_расхождение():
    """Абонентский ящик: улицы и дома нет вовсе. Тревога без основания хуже молчания."""
    assert same_address("344090, г. Ростов-на-Дону, а/я 77", "344090, г. Ростов-на-Дону, ул. Ленина, д. 5")


def test_общий_только_индекс_и_он_разный():
    assert not same_address("344090, а/я 77", "125009, а/я 77")


def test_офис_и_помещение_в_сверку_не_входят():
    assert same_address(
        "344002, г. Ростов-на-Дону, ул. Социалистическая, д. 74, оф. 642",
        "344002, г. Ростов-на-Дону, ул. Социалистическая, д. 74",
    )


def test_составляющие_по_отдельности():
    assert address_index(ГПБ) == "117420"
    assert address_street(ГПБ) == "наметкина"
    assert address_house(ГПБ) == "16к1"
    assert address_key(ГПБ) == ("117420", "наметкина", "16к1")


def test_улица_с_числом_в_названии():
    """«8 Марта» — название, а не номер дома: иначе дом уехал бы в улицу."""
    assert address_street("105066, г. Москва, ул. 8 Марта, д. 1, стр. 12") == "8 марта"
    assert address_house("105066, г. Москва, ул. 8 Марта, д. 1, стр. 12") == "1с12"


def test_дом_без_метки_сразу_за_улицей():
    assert address_house("190000, Санкт-Петербург, Большая Морская ул., 29") == "29"


def test_метка_дома_без_запятой_не_прилипает_к_улице():
    """«ул. Наметкина д. 16» без запятой: «д» не должно стать частью названия."""
    assert address_street("117420, Москва, ул. Наметкина д. 16") == "наметкина"
    assert address_house("117420, Москва, ул. Наметкина д. 16") == "16"


def test_индекс_не_принимается_за_дом():
    assert address_house("117997, г. Москва, ул. Вавилова, д. 19") == "19"


def test_пустая_строка_не_падает():
    assert address_key("") == ("", "", "")
    assert same_address("", СБЕР)


@pytest.mark.parametrize("written,ключ", [
    ("191144, г. Санкт-Петербург, пер. Дегтярный, д. 11-А", "11а"),
    ("191144, г. Санкт-Петербург, пер. Дегтярный, д. 11, лит. А", "11а"),
    ("191144, г. Санкт-Петербург, пер. Дегтярный, д. 11А", "11а"),
    ("191144, г. Санкт-Петербург, пер. Дегтярный, д. 11", "11"),
])
def test_буква_дома_пишется_тремя_способами(written, ключ):
    """«11-А», «11А» и «11, лит. А» — один и тот же дом. Литера не получает
    маркера именно поэтому: иначе ключи разошлись бы на пустом месте."""
    assert address_house(written) == ключ


def test_дом_с_буквой_сверяется_через_дефис_и_литеру():
    assert same_address(
        "191144, г. Санкт-Петербург, пер. Дегтярный, д. 11-А",
        "191144, Санкт-Петербург, Дегтярный пер., д. 11, лит. А",
    )

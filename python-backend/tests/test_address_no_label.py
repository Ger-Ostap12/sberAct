# -*- coding: utf-8 -*-
"""Адрес стороны без подписи «Адрес:» (01.09.2026).

Часть заявлений печатает запись стороны одной строкой и адрес не подписывает:

    Должник: Рудакова Александра Сергеевна, 11.04.2002,
    ИНН 614107678825, 346889, Ростовская обл, Батайск г, Литовская ул, дом

`_collect_block_address` умела стартовать с почтового индекса, но только если
тот стоял в НАЧАЛЕ строки. Здесь индекс в середине — адрес терялся целиком.

Две ловушки, каждая стоила отдельного документа:

1. Голая метка «адрес» цепляла «Адрес электронной почты», и значением адреса
   становилось «электронной почты: asipakova@bk.ru».
2. Порядок правил решал за порядок текста: сначала перебирались ВСЕ начала
   строк, и адрес следующей стороны («344003, …, а/я 44» отдельной строкой)
   выигрывал у адреса должника в середине первой.

Замер: 3 свежих заявления, на корпусе из 66 — ни одного такого случая.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def test_индекс_в_середине_строки(analyzer):
    block = ("Кравцова Алина Викторовна, 08.05.1995, ИНН 616809024129, "
             "344103, Ростовская обл, Ростов-на-Дону г, Белгородская дом 21")
    assert analyzer._collect_block_address(block) == (
        "344103, Ростовская обл, Ростов-на-Дону г, Белгородская дом 21")


def test_почта_не_адрес(analyzer):
    """«Адрес электронной почты» — не почтовый адрес. Иначе метка перебивает
    настоящий адрес, стоящий выше в той же записи."""
    block = ("Суровецёв Сергей Андреевич, ИНН 615010470247, "
             "346536, Ростовская обл, Шахты г, Седова дом 53\n"
             "Адрес электронной почты: asipakova@bk.ru")
    got = analyzer._collect_block_address(block)
    assert got == "346536, Ростовская обл, Шахты г, Седова дом 53"


def test_ранний_индекс_побеждает_поздний(analyzer):
    """За строкой должника идёт строка представителя, начинающаяся с индекса.
    Выигрывать обязан тот, что раньше по тексту, а не тот, что удобнее правилу."""
    block = ("Суровецёв Сергей Андреевич, ИНН 615010470247, "
             "346536, Ростовская обл, Шахты г, Седова дом 53\n"
             "344003, Ростовская обл, Ростов-на-Дону г, а/я 44")
    got = analyzer._collect_block_address(block)
    assert got.startswith("346536")


def test_метка_адреса_по_прежнему_главнее_индекса(analyzer):
    """Подписанный адрес — сильный признак, он и должен побеждать: правило
    индекса задумано как запасное, а не как замена."""
    block = ("Иванов Иван Иванович, ИНН 616809024129, 100000, чужой хвост\n"
             "Адрес регистрации: 344103, Ростовская обл, Ростов-на-Дону г")
    got = analyzer._collect_block_address(block)
    assert got.startswith("344103")


def test_шестизначное_число_без_адреса_не_старт(analyzer):
    """Условие «за индексом запятая и содержимое» отделяет индекс от прочих
    шестизначных чисел записи — номера паспорта, номера договора."""
    block = "Иванов Иван Иванович, паспорт 601706 725500 выдан 09.12.2016"
    assert analyzer._collect_block_address(block) is None


def test_пустой_блок(analyzer):
    assert analyzer._collect_block_address("") is None

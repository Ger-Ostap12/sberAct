# -*- coding: utf-8 -*-
"""Порядковый номер в КОНЦЕ названия улицы (23.09.2026, пункт 6.9).

«2-я Хуторская» и «Хуторская 2-я» — одна улица, а сверка считала их разными.
Дефекта было ДВА сразу, и второй хуже первого:

    ул. Хуторская 2-я, д. 38А, стр. 26
    ключ ДО:  ('127287', 'хуторская', '2я')      <- дом «2я» вместо «38ас26»
    ключ ПОСЛЕ: ('127287', '2 хуторская', '38ас26')

`_NAME` разбирал порядковый номер только В НАЧАЛЕ («8 Марта», «1905 года»), а в
конце продолжение имени обрывалось на цифре — и «2-я» доставалось разбору дома
как номер. Следствие: ложная пометка «юр. адрес расходится со справочником».

Замер по 101 документу: пометка стояла на 14 документах, из них ЛОЖНЫХ две
(корпус-19, корпус-22); после правки 12, и больше ничего не сдвинулось.

⚠️ Окончание у порядкового номера ОБЯЗАТЕЛЬНО — оно отличает его от номера дома
с литерой: «16-а» остаётся домом. И хвостовой номер берётся только через ПРОБЕЛ:
в «ул. Мира, 5-я» запятая отделяет дом, и съесть его нельзя.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from address_match import address_key, address_street, same_address  # noqa: E402

ДОКУМЕНТ = "127287, г. Москва, ул. Хуторская 2-я, д. 38А, стр. 26"
СПРАВОЧНИК = "127287, г. Москва, ул. 2-я Хуторская, д. 38А, стр. 26"


def test_порядковый_в_конце_и_в_начале_одна_улица():
    assert same_address(ДОКУМЕНТ, СПРАВОЧНИК)


def test_ключ_совпадает_целиком():
    assert address_key(ДОКУМЕНТ) == address_key(СПРАВОЧНИК) == (
        "127287", "2 хуторская", "38ас26")


def test_порядковый_не_становится_домом():
    """Главный вред: «2-я» доставалось разбору дома и подменяло номер."""
    from address_match import address_house
    assert address_house(ДОКУМЕНТ) == "38ас26"


@pytest.mark.parametrize("написание", [
    "ул. 2-я Хуторская", "ул. Хуторская 2-я",
    "2-я Хуторская ул.", "Хуторская 2-я ул.",
])
def test_все_четыре_написания_дают_один_ключ(написание):
    assert address_street("127287, г. Москва, " + написание) == "2 хуторская"


# --- чего правило ломать НЕ должно ---------------------------------------------

def test_разные_порядковые_остаются_разными():
    """2-я и 3-я Хуторская — РАЗНЫЕ улицы; правило не имеет права их склеить."""
    assert not same_address("127287, г. Москва, ул. 2-я Хуторская, д. 38",
                            "127287, г. Москва, ул. 3-я Хуторская, д. 38")


def test_литера_дома_не_читается_порядковым():
    """«16-а» — дом с литерой, а не порядковый номер: у него нет окончания."""
    assert address_key("344002, г. Ростов-на-Дону, ул. Наметкина 16-А") == (
        "344002", "наметкина", "16а")


def test_запятая_перед_номером_оставляет_его_домом():
    """В «ул. Мира, 5-я» запятая отделяет дом — в название он не уходит."""
    assert address_key("г. Москва, ул. Мира, 5-я") == ("", "мира", "5я")


def test_числовое_имя_без_окончания_не_переставляется():
    """«8 Марта» и «1905 года» — не порядковые номера, порядок слов сохраняется."""
    assert address_street("620000, г. Екатеринбург, ул. 8 Марта, д. 12") == "8 марта"
    assert address_street("620000, г. Екатеринбург, ул. 1905 года, д. 12") == "1905 года"


def test_разные_дома_на_одной_улице_остаются_разными():
    assert not same_address("117312, г. Москва, ул. Вавилова, д.16",
                            "117312, г. Москва, ул. Вавилова, д. 19")


def test_обычная_улица_без_номера_не_затронута():
    assert same_address("117420, г. Москва, ул. Наметкина, д. 16, корп. 1",
                        "117420, Москва, Наметкина ул., 16 корп.1")

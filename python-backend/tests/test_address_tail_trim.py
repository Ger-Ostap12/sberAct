# -*- coding: utf-8 -*-
"""Обрезка адреса на подписи следующего поля (31.08.2026).

`_sanitize_address_fields` резала хвост адреса по списку из пяти меток
(ИНН/ОГРНИП/ОГРН/СНИЛС/КПП), написанному руками. Всё остальное проходило
насквозь, и в поле оставалась подпись соседнего поля вместе с его значением:

    «…, пр-кт Курортный, д 96Г, кв 70 Дата рождения: 30.12.1984»
    «…, д.62 к.в кв.29 Финансовый управляющий: ОВЧАРЕНКО…»

Метки теперь берутся из реестра (`label_synonyms.all_labels`) — тот же приём,
что в структурном слое (`doc_structure._trim_at_next_label`).

Границы правила заданы замером на 101 документе: срабатывает на 3 свежих
заявлениях, на корпусе из 66 — ни разу (эталон не сдвинулся).
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _clean(analyzer, value, field="applicantAddress"):
    fields = {field: value}
    analyzer._sanitize_address_fields(fields)
    return fields.get(field)


_ADDR = "354024, Краснодарский край, г Сочи, пр-кт Курортный, д 96Г, кв 70"


def test_дата_рождения_обрезается(analyzer):
    assert _clean(analyzer, _ADDR + " Дата рождения: 30.12.1984") == _ADDR


def test_метка_блока_обрезается(analyzer):
    """Подпись стороны — такая же граница, как подпись поля."""
    assert _clean(analyzer, _ADDR + " Финансовый управляющий: ОВЧАРЕНКО И.И.") == _ADDR


@pytest.mark.parametrize("label", [
    "Место рождения:", "Паспорт:", "Дата государственной регистрации:",
    "Должник:", "Третье лицо:", "Взыскатель:", "Размер требований:",
])
def test_любая_метка_реестра_обрезает(analyzer, label):
    """Реестр — единственный источник меток: новое написание закрывается
    правкой данных, а не этой функции."""
    assert _clean(analyzer, f"{_ADDR} {label} что-то") == _ADDR


def test_тире_вместо_двоеточия(analyzer):
    assert _clean(analyzer, _ADDR + " Дата рождения — 30.12.1984") == _ADDR


def test_реквизиты_режутся_как_раньше(analyzer):
    """Старое правило должно продолжать работать: его метки идут без
    двоеточия («… кв 70 ИНН 6162059094»), и разделитель для них не нужен."""
    assert _clean(analyzer, _ADDR + " ИНН 6162059094") == _ADDR


def test_метка_без_разделителя_не_режет(analyzer):
    """Осознанный размен: без двоеточия или тире метка не считается границей.

    Цена — потерянное двоеточие конвертера («… д. 5 Должник Иванов») остаётся в
    поле. Выигрыш — правило не рубит адрес по слову, которое лишь похоже на
    метку. Замер выбрал этот край: с обязательным разделителем ложных обрезок
    на 101 документе нет.

    ⚠️ ОТДЕЛЬНО, не про это правило: `_truncate_glued_address` режет адрес по
    `кредитор\\w*` БЕЗ разделителя, поэтому «ул. Кредиторская» обрубается по
    «Кредитор». Латентный баг старого слоя, здесь не чиним.
    """
    value = "344002, г. Ростов-на-Дону, ул. Ленина, д. 5 Должник Иванов И.И."
    assert _clean(analyzer, value) == value


def test_адрес_без_хвоста_не_меняется(analyzer):
    assert _clean(analyzer, _ADDR) == _ADDR


def test_метка_в_начале_не_обнуляет_поле(analyzer):
    """Режем только ХВОСТ. Значение, начинающееся с метки, — другой случай:
    слева от неё ничего нет, и обрезка оставила бы пустую строку, а поле было
    бы удалено вместе с настоящим адресом."""
    assert _clean(analyzer, "Адрес: " + _ADDR)


def test_мусор_без_букв_удаляется(analyzer):
    """Существующее поведение: если после обрезки букв не осталось — это был
    не адрес."""
    assert _clean(analyzer, "123456 ИНН 6162059094") is None

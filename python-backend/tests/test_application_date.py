# -*- coding: utf-8 -*-
"""Дата заявления (02.09.2026).

Поле бралось первым паттерном `(\\d{1,2}[.,]\\d{1,2}[.,]\\d{4})` — то есть ЛЮБОЙ
первой датой в тексте. Замер на 35 свежих заявлениях: верной она оказывалась
3 раза из 35, в остальных 32 приезжали дата рождения должника, дата
государственной регистрации банка-кредитора, дата закона 127-ФЗ, дата обзора
судебной практики Верховного суда и дата доверенности представителя.

Правило теперь одно: **дата заявления берётся ТОЛЬКО по якорю исходящего
номера, иначе поле остаётся пустым.** Воздержание здесь дешевле догадки —
неверная дата в судебном акте опаснее пустого поля.

Форма прописью («"17" мая 2023 года») в якоря НЕ входит намеренно: на 15
срабатываниях по корпусу и свежим она ни разу не обозначала дату заявления —
это дата договора, срока кредитной линии или свидетельства о рождении.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _date(analyzer, text):
    return analyzer.extract_fields(text, "rtk_application").get("applicationDate")


ШАПКА = "В Арбитражный суд Ростовской области\nКредитор: ПАО Сбербанк\n"


# --- якорь исходящего номера -------------------------------------------------

@pytest.mark.parametrize("строка", [
    "Исх. № 8462384/1 от 30.07.2026 Вн. № CP-RQST-92442",
    "Исх. №14797996 от 14.02.2026 CP-Case-14797996",
    "Исх. №б/н от 14.02.2026",
    "Исх. № _________/_ от 14.02.2026",
    "Исходящий № 12/345 от 14.02.2026",
    "исх. № 8462384/1 от 14.02.2026",
])
def test_дата_по_исходящему_номеру(analyzer, строка):
    """Номер бывает цифровой, «б/н» и вовсе прочерком — дата от этого не зависит."""
    got = _date(analyzer, ШАПКА + строка + "\nДолжник: Иванов Иван Иванович")
    assert got == "14.02.2026" or got == "30.07.2026"


def test_ocr_превратил_исх_в_латиницу(analyzer):
    """Конвертер печатает «Hcx. № … oт» латинскими H и o (ДДУ.docx).

    Ловушка: глазами строка неотличима от кириллической, и якорь молча давал
    ноль на целом документе.
    """
    assert _date(analyzer, ШАПКА + "Hcx. № 8073556/1 oт 25.06.2025") == "25.06.2025"


@pytest.mark.parametrize("токен", ["CP-Case-19444613", "case-19444613", "ase-19469482"])
def test_обезличенная_шапка_без_слова_исх(analyzer, токен):
    """Обезличиватель вырезает «Исх. №», оставляя внутренний номер обращения;
    при конвертации у него теряется ещё и первая буква."""
    assert _date(analyzer, ШАПКА + токен + " от 04.06.2026") == "04.06.2026"


def test_явная_метка_даты(analyzer):
    assert _date(analyzer, ШАПКА + "Дата составления: 14.02.2026") == "14.02.2026"


# --- чего брать НЕЛЬЗЯ -------------------------------------------------------

@pytest.mark.parametrize("строка,что", [
    ("Должник: Рудакова Александра Сергеевна\nДата рождения: 11.04.2002 г.",
     "дата рождения должника"),
    ("ПАО Сбербанк, г. Москва, ул. Вавилова, д. 19\nДата государственной регистрации: 20.06.1991",
     "дата регистрации банка"),
    ("Дата регистрации кредитной организации 17.10.1990г.",
     "дата регистрации кредитной организации"),
    ("Согласно п. 8 ст. 42 Федерального закона № 127-ФЗ от 26.10.2002 «О несостоятельности»",
     "дата закона"),
    ("В Обзоре судебной практики Верховного суда Российской Федерации № 1 от 29.05.2024 года",
     "дата обзора практики"),
    ("Определением Арбитражного суда Ростовской области от 03.10.2025 заявление принято",
     "дата судебного акта"),
    ("Доверенность: № 282/ФЦ от 26.01.2026", "дата доверенности"),
    ("заключен кредитный договор № КЛ-25/1472 от 14.05.2025", "дата договора"),
    ("На основании Договора уступки права требования № 1 от 29.03.2024 г.", "дата цессии"),
    ("Паспорт: серия 60 23 № 278902 Выдан ГУ МВД 21.04.2023 г.", "дата выдачи паспорта"),
])
def test_чужая_дата_не_становится_датой_заявления(analyzer, строка, что):
    assert _date(analyzer, ШАПКА + строка) is None, f"взяли {что}"


def test_деепричастие_исходя_не_якорь(analyzer):
    """«исходя из того, что…» начинается на те же три буквы, что и «Исх.».

    Знак № в якоре обязателен именно поэтому.
    """
    текст = ("госпошлина оплачивается исходя из того, что такие заявления "
             "носят имущественный характер, определение от 14.02.2026")
    assert _date(analyzer, ШАПКА + текст) is None


def test_без_якоря_поле_пустое(analyzer):
    """Дат в документе много, а даты ЗАЯВЛЕНИЯ нет — поле обязано остаться пустым.

    Так выглядят 34 из 35 свежих заявлений.
    """
    текст = ("Должник: Юрцов Ян Анатольевич\nДата рождения: 27.06.1968\n"
             "Решением Арбитражного суда от 22.06.2026 введена процедура\n"
             "Федеральный закон от 26.10.2002 N 127-ФЗ")
    assert _date(analyzer, ШАПКА + текст) is None

# -*- coding: utf-8 -*-
"""Перечень приложений — список ДОКУМЕНТОВ, а не денег должника.

Правило Андрея: из перечня приложений суммы не берём. «1. Квитанция о внесении
денежных средств на депозитный счет АС в размере 25000» — это депозит на
вознаграждение управляющего, а он утекал в `totalDebt` и дальше в текст акта как
«основной долг в размере 25 000 руб.» (`Самобанкрот/Заявление РФЛ1.docx`).

Границы правила измерены по корпусу ДО реализации (приём §K.2) и закреплены здесь:
режем ТОЛЬКО нумерованные пункты перечня после ПОСЛЕДНЕГО якоря «Приложение».
"""
import logging
import os
import sys
import types

logging.disable(logging.CRITICAL)
_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402

# Метод не трогает self — зовём несвязанным, чтобы не поднимать spaCy-модель.
_mask = DocumentAnalyzer._mask_attachment_list_amounts
_stub = types.SimpleNamespace(
    _ATTACH_ANCHOR_RE=DocumentAnalyzer._ATTACH_ANCHOR_RE,
    _ATTACH_ITEM_RE=DocumentAnalyzer._ATTACH_ITEM_RE,
)


def mask(text: str) -> str:
    return _mask(_stub, text)


def test_deposit_receipt_amount_is_masked():
    """Заявление РФЛ1.docx: депозит 25000 из квитанции уезжал в «основной долг»."""
    text = ("Приложение:\n"
            "1. Квитанция о внесении денежных средств на депозитный счет АС в размере 25000; "
            "2. Копия паспорта;\n")
    assert "25000" not in mask(text)


def test_mask_preserves_length():
    """Длина обязана сохраниться: смещения нужны остальным слоям разбора."""
    text = ("Приложение:\n"
            "1. Квитанция о внесении денежных средств на депозитный счет АС в размере 25000;\n")
    assert len(mask(text)) == len(text)


def test_document_names_survive_masking():
    """Маскируем цифры, а не строку целиком — перечень остаётся читаемым."""
    text = "Приложение:\n1. Платежные поручения на 100 000 руб., 1 480 060 руб.;\n"
    masked = mask(text)
    assert "Платежные поручения" in masked
    assert "100 000" not in masked and "1 480 060" not in masked


def test_prayer_items_are_never_masked():
    """АНТИ-РЕГРЕССИЯ (Заявл_Ликвидир_Оргтехника.docx).

    Просительная часть тоже нумерованная. Пока якорь брался ПЕРВЫЙ, «приложение
    № 1 к договору» в теле включало маску, и суммы просительной уничтожались:
    debtAmount становился 7,04. Якорь обязан быть ПОСЛЕДНИМ.
    """
    text = ("Кредитный договор (приложение № 1 к настоящему заявлению) заключён.\n"
            "4. Включить требования ПАО Сбербанк в третью очередь реестра требований "
            "кредиторов должника в размере 501 365 000,9 руб.\n"
            "Приложение:\n"
            "1. Платежные поручения на 100 000 руб.;\n")
    masked = mask(text)
    assert "501 365 000,9" in masked, "сумма просительной части не должна маскироваться"
    assert "100 000" not in masked, "сумма в перечне приложений должна маскироваться"


def test_attached_debt_calculation_table_survives():
    """АНТИ-РЕГРЕССИЯ: у 7 документов корпуса за словом «Приложение» идёт
    приложенный РАСЧЁТ задолженности — их единственный источник финансов.

    Строки таблицы не нумерованы, поэтому под правило не подпадают. Слепая обрезка
    «всё после Приложения» обнулила бы им суммы.
    """
    text = ("Приложение:\n"
            "Остаток основного долга: 52660.75\n"
            "в т.ч. Просроченная ссудная задолженность: 8020.73\n")
    assert mask(text) == text


def test_no_anchor_means_no_change():
    text = "1. Включить требования в размере 100 000 руб.\n"
    assert mask(text) == text


def test_item_without_amount_is_untouched():
    """Пункт без суммы не трогаем: номера пунктов сами по себе не мешают."""
    text = "Приложение:\n1. Копия паспорта;\n2. Копия СНИЛС;\n"
    assert mask(text) == text

# -*- coding: utf-8 -*-
"""Дата рождения должника из ТЕЛА заявления, а не из шапки (§S.9).

Шапка печатает не всё. У части заявлений в записи должника есть ИНН, СНИЛС и
адрес, а дата рождения стоит только в теле:

    В производстве … дело о несостоятельности (банкротстве) гражданина
    ЕПИФАНОВА ЛЮДМИЛА НИКОЛАЕВНА (27.11.1961 года рождения, адрес регистрации …)

Разбор работал строго по записи должника из шапки и такую дату не видел, а
дальше срабатывало правило «дата авторитетна из записи должника» и вычищало
поле окончательно.

Якорь здесь — ИМЯ должника, а не слово «рождения»: в теле заявления хватает
чужих дат рождения (управляющего, поручителя, наследника), и без привязки к
имени поле начало бы врать. Отрицательные проверки ниже — ровно про это.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def test_дата_рождения_из_тела_рядом_с_именем(analyzer):
    fields = {"debtorName": "Епифанова Людмила Николаевна"}
    text = (
        "Должник: ЕПИФАНОВА ЛЮДМИЛА НИКОЛАЕВНА ИНН: 614600107524\n"
        "В производстве суда находится дело о несостоятельности (банкротстве) гражданина "
        "ЕПИФАНОВА ЛЮДМИЛА НИКОЛАЕВНА (27.11.1961 года рождения, адрес регистрации: "
        "346311, РОСТОВСКАЯ ОБЛ.)\n"
    )
    assert analyzer._birthdate_near_debtor_name(fields, text) is True
    assert fields["birthDate"] == "27.11.1961"


def test_чужая_дата_рождения_не_подбирается(analyzer):
    """Дата стоит рядом с УПРАВЛЯЮЩИМ, а не с должником — брать нельзя."""
    fields = {"debtorName": "Епифанова Людмила Николаевна"}
    text = (
        "Должник: ЕПИФАНОВА ЛЮДМИЛА НИКОЛАЕВНА ИНН: 614600107524\n"
        "Финансовый управляющий: Галифинова Татьяна Сергеевна, 05.03.1975 года рождения\n"
    )
    assert analyzer._birthdate_near_debtor_name(fields, text) is False
    assert "birthDate" not in fields


def test_дата_за_пределами_окна_не_подбирается(analyzer):
    """Окно короткое намеренно: чем оно длиннее, тем выше шанс чужой даты."""
    fields = {"debtorName": "Епифанова Людмила Николаевна"}
    text = (
        "Должник: ЕПИФАНОВА ЛЮДМИЛА НИКОЛАЕВНА "
        + "прочий текст заявления по существу требования, " * 6
        + "01.01.1980 года рождения\n"
    )
    assert analyzer._birthdate_near_debtor_name(fields, text) is False


def test_без_имени_должника_ничего_не_ищется(analyzer):
    """Без якоря правило превращается в «первая дата рождения в документе»."""
    fields = {}
    text = "Гражданин (27.11.1961 года рождения) признан банкротом"
    assert analyzer._birthdate_near_debtor_name(fields, text) is False

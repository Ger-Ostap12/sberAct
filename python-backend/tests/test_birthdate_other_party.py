# -*- coding: utf-8 -*-
"""Чужая дата рождения не уезжает должнику.

У «Умерший ким клим» в поле стояла дата дочери, отказавшейся от наследства:
своей даты рождения документ не называет, поле обязано быть пустым. Границу
ставим только поиску даты — ИНН берётся из хвоста той же записи.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

import fio_detector  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402

КОРПУС = os.path.abspath(os.path.join(_THIS, "..", "..", "Заявления"))
КИМ = os.path.join(КОРПУС, "НОвая конвертация", "Умерший ким клим.docx")


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- документ целиком ------------------------------------------------------------


@pytest.mark.skipif(not os.path.exists(КИМ), reason="документ корпуса недоступен")
def test_ким_клим_дата_рождения_пуста(analyzer):
    """Главная проверка: в акт и на форму не должно уехать ничего."""
    r = analyzer.analyze(КИМ)
    assert not (r.get("fields") or {}).get("birthDate")


@pytest.mark.skipif(not os.path.exists(КИМ), reason="документ корпуса недоступен")
def test_ким_клим_инн_и_имя_на_месте(analyzer):
    """Сужаем ТОЛЬКО дату: ИНН из хвоста записи и имя обязаны остаться."""
    f = (analyzer.analyze(КИМ).get("fields") or {})
    assert f.get("inn") == "614104690687"
    assert f.get("debtorName") == "Ким Клим"


# --- граница «чужой метки» в записи должника -------------------------------------


def test_обрезка_по_детям():
    блок = ("Ким Клим 346744, Ростовская обл.\n"
            "после смерти Ким Клим, дети умершего: Ким Инна Климентьевна 02.04.1985 г.р.")
    assert fio_detector._find_birthdate(fio_detector._до_чужой_метки(блок)) is None
    # Без обрезки дата находилась — иначе тест ничего не проверяет.
    assert fio_detector._find_birthdate(блок) == "02.04.1985"


@pytest.mark.parametrize("метка", [
    "Наследник:", "Наследница:", "Наследники:",
    "Поручитель:", "поручителя", "Созаёмщик:", "созаемщик",
    "Представитель:", "Третье лицо:", "Третьи лица:",
    "Финансовый управляющий:", "конкурсный управляющий",
    "дети умершего:", "детей", "супруга", "сын", "дочь",
])
def test_метка_другого_лица_обрывает_запись(метка):
    """Падежи и ё/е проверяются списком: стоп-лист в одной форме бесполезен."""
    блок = "Иванов Иван Иванович ИНН 616809024129\n%s Петров Пётр 01.01.1970 г.р." % метка
    assert fio_detector._find_birthdate(fio_detector._до_чужой_метки(блок)) is None


def test_наследственное_дело_не_граница():
    """«Наследственное дело» — не лицо, и границей быть не должно."""
    блок = "Иванов Иван Иванович 15.03.1970 г.р.\nВ рамках наследственного дела № 254/2015"
    assert fio_detector._find_birthdate(fio_detector._до_чужой_метки(блок)) == "15.03.1970"


def test_своя_дата_в_записи_остаётся():
    """Ворота, а не запрет: дата ДО чужой метки по-прежнему берётся."""
    блок = ("Иванов Иван Иванович, 15.03.1970 г.р., ИНН 616809024129\n"
            "Наследник: Петров Пётр Петрович 01.01.1990 г.р.")
    assert fio_detector._find_birthdate(fio_detector._до_чужой_метки(блок)) == "15.03.1970"


# --- окно рядом с именем в теле --------------------------------------------------


def test_окно_рядом_с_именем_не_берёт_дату_дочери(analyzer):
    fields = {"debtorName": "Ким Клим"}
    text = ("В рамках наследственного дела № 254/2015, после смерти Ким Клим, "
            "дети умершего: Ким Инна Климентьевна 02.04.1985 г.р. и Ким Валерия "
            "Климентьевна 09.03.1990 г.р. отказались от доли на наследство.")
    assert analyzer._birthdate_near_debtor_name(fields, text) is False
    assert "birthDate" not in fields


def test_окно_рядом_с_именем_обрывается_чужим_фио(analyzer):
    """Метки роли нет вовсе — границей служит само чужое ФИО с отчеством."""
    fields = {"debtorName": "Ким Клим"}
    text = "Ким Клим, Ким Инна Климентьевна 02.04.1985 г.р., отказ от наследства."
    assert analyzer._birthdate_near_debtor_name(fields, text) is False


def test_окно_рядом_с_именем_своя_дата_находится(analyzer):
    """Рабочий случай  не задет: без чужих имён и меток дата берётся."""
    fields = {"debtorName": "Епифанова Людмила Николаевна"}
    text = ("дело о несостоятельности (банкротстве) гражданина ЕПИФАНОВА ЛЮДМИЛА "
            "НИКОЛАЕВНА (27.11.1961 года рождения, адрес регистрации: 346311)")
    assert analyzer._birthdate_near_debtor_name(fields, text) is True
    assert fields["birthDate"] == "27.11.1961"


def test_отсечка_по_фио_требует_отчества():
    """Два слова с заглавной — не ФИО: иначе границей станет любая топонимика."""
    from parties_mixin import PartiesMixin

    rx = PartiesMixin._BIRTH_WINDOW_OTHER_FIO_RE
    assert rx.search("Ким Инна Климентьевна 02.04.1985")
    assert rx.search("Петров Пётр Петрович")
    assert not rx.search("Ростовская обл. Азовский район 01.01.1970")
    assert not rx.search("г. Ростов-на-Дону Азов")

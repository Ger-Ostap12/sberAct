# -*- coding: utf-8 -*-
"""Дата рождения без метки, перечислением внутри записи стороны (фаза 3, п. 3.7).

Заявления по РТК пишут запись должника одной строкой:
«Должник: Кравцова Алина Викторовна, 08.05.1995, ИНН 616809024129, 344103, …».
Метки «дата рождения» нет вовсе, а все прежние формы её требовали.

Почему правило живёт в разборщике ЗАПИСИ, а не в общих паттернах: запись
должника авторитетна (`_finalize_debtor_person_requisites`), и дату, найденную
где-то ещё в тексте, она молча вычищает — защита от даты представителя.
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from fio_detector import _find_birthdate  # noqa: E402

# --- ДВЕ КРАСНЫЕ ЗАПИСИ ЭТАЛОНА ----------------------------------------------

@pytest.mark.parametrize("запись,дата", [
    # свежие-24
    ("Кравцова Алина Викторовна, 08.05.1995, ИНН 616809024129, 344103, "
     "Ростовская обл, Ростов-на-Дону г", "08.05.1995"),
    # свежие-25
    ("Суровецёв Сергей Андреевич, 21.08.1992, ИНН 615010470247, 346536, "
     "Ростовская обл, Шахты г", "21.08.1992"),
    # свежие-26 — ожидания в эталоне нет, поле заполняется бонусом
    ("Рудакова Александра Сергеевна, 11.04.2002, ИНН 614107678825, 346889",
     "11.04.2002"),
])
def test_дата_без_метки_между_фио_и_инн(запись, дата):
    assert _find_birthdate(запись) == дата


def test_якорь_принимает_снилс_наравне_с_инн():
    assert _find_birthdate("Петров Иван Ильич, 03.02.1970, СНИЛС 112-233-445 55") == "03.02.1970"


def test_ё_в_фамилии_не_ломает_якорь():
    assert _find_birthdate("Суровецёв Сергей Андреевич, 21.08.1992, ИНН 1") == "21.08.1992"


def test_двойная_фамилия_через_дефис():
    assert _find_birthdate("Петрова-Водкина Анна Ивановна, 01.12.1980, ИНН 2") == "01.12.1980"


def test_фио_из_двух_слов_тоже_запись_стороны():
    assert _find_birthdate("Кравцова Алина, 08.05.1995, ИНН 3") == "08.05.1995"


# --- ГРАНИЦЫ: ЧТО БРАТЬ НЕЛЬЗЯ ----------------------------------------------

def test_голая_дата_без_фио_слева_не_берётся():
    """Без левого якоря это может быть дата договора, а не рождения."""
    assert _find_birthdate("по договору, 08.05.1995, ИНН 616809024129") is None


def test_дата_без_реквизита_справа_не_берётся():
    """Без правого якоря — просто дата рядом с именем."""
    assert _find_birthdate("Кравцова Алина Викторовна, 08.05.1995, адрес: Ростов") is None


def test_строчное_слово_не_считается_фио():
    """Под IGNORECASE класс [А-ЯЁ] ловит и строчные — якорь закрыт (?-i:…)."""
    assert _find_birthdate("выдан кредит заемщику, 08.05.1995, ИНН 1") is None


def test_невозможная_дата_отсекается():
    assert _find_birthdate("Кравцова Алина Викторовна, 45.13.1995, ИНН 1") is None


def test_год_вне_диапазона_отсекается():
    assert _find_birthdate("Кравцова Алина Викторовна, 08.05.1812, ИНН 1") is None


# --- СТАРЫЕ ФОРМЫ НЕ СЛОМАНЫ И ИМЕЮТ ПРИОРИТЕТ -------------------------------

@pytest.mark.parametrize("запись,дата", [
    ("Дата рождения: 01.01.1990", "01.01.1990"),
    ("д.р. 01.01.1990", "01.01.1990"),
    ("д/р: 01.01.1990", "01.01.1990"),
    ("01.01.1990 г.р.", "01.01.1990"),
    ("01.01.1990 года рождения", "01.01.1990"),
])
def test_прежние_формы_с_меткой_работают(запись, дата):
    assert _find_birthdate(запись) == дата


def test_метка_сильнее_перечисления():
    """Новая форма стоит ПОСЛЕДНЕЙ: явная метка обязана выигрывать."""
    запись = ("Иванов Иван Иванович, 08.05.1995, ИНН 1\n"
              "Дата рождения: 02.02.1960")
    assert _find_birthdate(запись) == "02.02.1960"


def test_пустой_блок_не_падает():
    assert _find_birthdate("") is None

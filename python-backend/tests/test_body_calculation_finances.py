# -*- coding: utf-8 -*-
"""Разбивка финансов из тела документа, когда просьба называет только итог.

У «ООО СПОРТ» расчёт лежит в разделе «2. Расчёт задолженности», и запасной
путь брал только первый договор из четырёх. На корпусе слой не срабатывает
ни на одном документе, поэтому правку защищает только этот тест.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from amounts_mixin import AmountsMixin  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402

СПОРТ = os.path.abspath(os.path.join(
    _THIS, "..", "..", "Заявления", "НОвая конвертация",
    "Заявление о включении в РТК - ООО СПОРТ.docx"))

# Скелет СПОРТа: расчёт в теле, просьба с одним итогом и своей пошлиной.
ТЕЛО = """2. Расчёт задолженности
По состоянию на 10.02.2026 задолженность по договорам займа составляет: По договору займа № 89099-317981 от 26.01.2024:
– 1 142 934,17 руб. — основной долг;
– 276 231,53 руб. — проценты;
– 67 575,00 руб. – расходы по оплате государственной пошлине.
– итого: 1 486 740,70 руб.
По договору займа № 89099-373093 от 02.04.2024:
– 1 525 648,67 руб. — основной долг;
– 251 864,86 руб. — проценты;
– 78 325 руб. – расходы по оплате государственной пошлине.
– итого: 1 855 838,53 руб.
По договору займа № 89099-403845 от 06.05.2024:– 399 969,94 руб. — основной долг;
– 56 770,06 руб. — проценты;
– итого: 456 740,00 руб.
По договору займа № 89099-444343 от 19.06.2024:
– 1 457 065,74 руб. — основной долг;
– 198 598,06 руб. — проценты;
– 74 670,00 руб. – расходы по оплате государственной пошлине.
– итого: 1 730 333,80 руб.
Итого ко включению: 5 529 653,03 руб.
3. Правовое обоснование требований
ПРОСИТ СУД:
1. Признать обоснованными требования ООО МКК «Озон Кредит» к ООО «СПОРТ» в общем размере 5 529 653,03 руб.
2. Включить указанные требования в третью очередь реестра требований кредиторов.
Включить расходы по уплате государственной пошлины в размере 13 919,00 руб. в третью очередь реестра с учётом п. 3 ст. 137 Закона о банкротстве.
Приложения (в копиях):
1. Договор займа № 89099-317981 от 26.01.2024 с графиком платежей;
"""


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def разбор(analyzer, text):
    fields = {}
    analyzer._apply_prayer_finances(fields, text)
    return fields


# --- слой на скелете документа ---------------------------------------------------


def test_складываются_все_четыре_договора(analyzer):
    """несколько договоров — складываем ВСЕ."""
    f = разбор(analyzer, ТЕЛО)
    assert f.get("principalDebt") == "4 525 618,52"
    assert f.get("interest") == "783 464,51"
    assert f.get("totalDebt") == "5 529 653,03"


def test_пошлины_расходятся_по_своим_графам(analyzer):
    """Пошлина ВНУТРИ расчёта — ссудная [17]; своя пошлина из просьбы — [16]."""
    f = разбор(analyzer, ТЕЛО)
    assert f.get("loanStateDuty17") == "220 570,00"
    assert f.get("stateDuty16") == "13 919,00"


def test_копейки_не_обязательны(analyzer):
    """«78 325 руб.» без копеек — такое же слагаемое, и подытог обязан сойтись."""
    f = разбор(analyzer, ТЕЛО)
    assert "78 325,00" in (f.get("financeBreakdown") or {}).get("loanStateDuty17", [])


def test_слагаемые_для_тултипа_по_каждому_договору(analyzer):
    """Юрист должен видеть, из чего собрано число, а не только итог."""
    брк = разбор(analyzer, ТЕЛО).get("financeBreakdown") or {}
    assert брк.get("principalDebt") == [
        "1 142 934,17", "1 525 648,67", "399 969,94", "1 457 065,74"]
    assert len(брк.get("interest") or []) == 4


# --- границы, без которых слой опасен --------------------------------------------


def test_без_итого_отрезок_не_берётся(analyzer):
    """Нет «итого» — нечем проверить подытог, и слой обязан молчать."""
    текст = ТЕЛО.replace("– итого:", "– справочно:")
    f = разбор(analyzer, текст)
    assert f.get("principalDebt") != "4 525 618,52"


def test_несходящийся_отрезок_глушит_весь_слой(analyzer):
    """Один битый отрезок — молчит ВСЁ, а не «считаем остальные»."""
    текст = ТЕЛО.replace("– 276 231,53 руб. — проценты;", "– 999 999,99 руб. — проценты;")
    f = разбор(analyzer, текст)
    assert f.get("principalDebt") != "4 525 618,52"
    # Сумма трёх договоров тоже не должна попасть на форму.
    assert f.get("principalDebt") != "3 382 684,35"


def test_неподтверждённый_итог_глушит_слой(analyzer):
    """Сумма отрезков не названа документом — складывать её наше решение, не его."""
    текст = (ТЕЛО.replace("Итого ко включению: 5 529 653,03 руб.", "Итого ко включению: 9 999,00 руб.")
                 .replace("в общем размере 5 529 653,03 руб.", "в общем размере 9 999,00 руб."))
    f = разбор(analyzer, текст)
    assert f.get("principalDebt") != "4 525 618,52"
    assert not (f.get("financeBreakdown") or {}).get("principalDebt")


def test_разбивка_просьбы_имеет_приоритет(analyzer):
    """Финансы берутся из ПРОСИТЕЛЬНОЙ части."""
    текст = ТЕЛО.replace(
        "1. Признать обоснованными требования ООО МКК «Озон Кредит» к ООО «СПОРТ» "
        "в общем размере 5 529 653,03 руб.",
        "1. Включить требования в размере 100 000,00 руб., в том числе: "
        "– 90 000,00 руб. — основной долг; – 10 000,00 руб. — проценты.")
    f = разбор(analyzer, текст)
    assert f.get("principalDebt") == "90 000,00"


# --- якорь отрезка ---------------------------------------------------------------


@pytest.mark.parametrize("строка", [
    "По договору займа № 89099-317981 от 26.01.2024:",
    "По кредитному договору № 123/45 от 01.02.2024:",
    "по договору поручительства № П-7 от 3.4.2024:",
    "По кредитному договору № 123 от 01.02.2024 задолженность составляет:",
])
def test_якорь_опознаёт_отрезок(строка):
    """Уточняющее слово бывает и слева от «договора», и справа."""
    assert AmountsMixin._РАСЧЁТ_ОТРЕЗОК.search(строка), строка


@pytest.mark.parametrize("строка", [
    # Проза: двоеточия нет, перечень не начинается.
    "За взысканием задолженности по договору № 89099-403845 Кредитор в Суд не обращался.",
    "По договору займа № 89099-317981 от 26.01.2024 на сумму 5 000 000 руб.;",
    # Строка ПРИЛОЖЕНИЯ: расчёт приложен отдельным документом, и его чисел в
    # заявлении нет — у семи документов корпуса расчёт именно такой.
    "8. Расчет задолженности по КД № 1221/5221/0890/019/13 от 15.11.2013;",
    "6. Расчёт задолженности по Договорам займа;",
])
def test_якорь_не_ловит_прозу_и_приложения(строка):
    assert not AmountsMixin._РАСЧЁТ_ОТРЕЗОК.search(строка), строка


def test_итого_всего_расчёта_не_путается_с_подытогом(analyzer):
    """«Итого ко включению» лежит ЗА последним отрезком и подытогом быть не может."""
    f = разбор(analyzer, ТЕЛО)
    брк = f.get("financeBreakdown") or {}
    assert "5 529 653,03" not in брк.get("principalDebt", [])
    assert f.get("principalDebt") == "4 525 618,52"


# --- документ целиком ------------------------------------------------------------


@pytest.mark.skipif(not os.path.exists(СПОРТ), reason="документ вне корпуса недоступен")
def test_спорт_целиком(analyzer):
    """Сквозная проверка на реальном файле: все пять чисел сразу."""
    f = (analyzer.analyze(СПОРТ).get("fields") or {})
    assert f.get("principalDebt") == "4 525 618,52"
    assert f.get("interest") == "783 464,51"
    assert f.get("loanStateDuty17") == "220 570,00"
    assert f.get("stateDuty16") == "13 919,00"
    assert f.get("totalDebt") == "5 529 653,03"

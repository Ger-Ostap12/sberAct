# -*- coding: utf-8 -*-
"""Номер дела о банкротстве (08.09.2026).

Две беды с разных сторон: поле брало ЧУЖОЙ номер и теряло СВОЙ.

1. Чужой. Дело о банкротстве ведёт арбитражный суд, и его номер всегда с
   буквой региона — «А53-25457/2026». В поле попадали номера из судов общей
   юрисдикции:

       «на основании судебного приказа № 2-1178/2024»  (самобанкрот: дела
                                                        ещё нет вовсе)
       «Каменским районным судом … в рамках дела №2-1142/2010»

   Ипотечный иск исключён из правила: он и подаётся в суд общей юрисдикции,
   номер без буквы там свой.

2. Свой. Разбор «ранее вынесенного решения» возвращал ОДИН голый номер — тот
   самый номер текущего дела, встреченный второй раз в реквизитах для платежа
   («…погашения задолженности по Делу №А53-43425/2025»). Правило «номер дела
   совпал с ранее вынесенным значит это его контекст» стирало номер, и поле
   уходило на форму пустым. Теперь «ранее вынесенное» должно быть решением:
   с судом, суммой или датой, а не одним номером.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _номер(analyzer, поля, тип="rtk_application"):
    analyzer._postprocess_mortgage_and_case_number(поля, "", тип)
    return поля.get("caseNumber")


# --- чужой номер -------------------------------------------------------------

@pytest.mark.parametrize("чужой", ["2-1178/2024", "2-1142/2010", "2-8961/2018"])
def test_номер_суда_общей_юрисдикции_снимается(analyzer, чужой):
    assert _номер(analyzer, {"caseNumber": чужой}) is None


@pytest.mark.parametrize("свой", ["А53-25457/2026", "А53-43425/2025", "A53-9758/2026"])
def test_арбитражный_номер_остаётся(analyzer, свой):
    assert _номер(analyzer, {"caseNumber": свой}) == свой


def test_у_ипотеки_номер_без_буквы_законен(analyzer):
    """Ипотечный иск идёт в районный суд — там номер и должен быть без буквы."""
    assert _номер(analyzer, {"caseNumber": "2-1178/2024"},
                  тип="mortgage_claim") == "2-1178/2024"


# --- свой номер, стёртый «ранее вынесенным решением» --------------------------

# Кусок взят из документа дословно: реквизиты для платежа плюс перечень
# приложений. Якорем прежнего акта служит слово «взыскание» из приложения,
# а ближайший номер — это номер ТЕКУЩЕГО дела из строки назначения платежа.
ХВОСТ_ЗАЯВЛЕНИЯ = (
    "Счет № 60322810000000001491 Назначениеплатежа: Перечисление средств "
    "в счет погашения задолженности по Делу №А53-43425/2025 Клиента "
    "____________ Приложение: 1. Документ, подтверждающий взыскание "
    "задолженности по договору № 108834095;")


def test_голый_номер_не_считается_прежним_решением(analyzer):
    """Один номер без суда, суммы и даты — это не «ранее вынесенное решение».

    Тест закрепляет УСЛОВИЕ, по которому принимается решение в analyze:
    разбор прежнего акта возвращает единственный ключ. Сам выбор («оставить
    номер дела, снять priorCaseNumber») живёт в analyze и проверяется
    эталоном ожиданий — класс «номер-дела» на свежих 10, 11 и 12.
    """
    решение = analyzer._extract_prior_court_decision(ХВОСТ_ЗАЯВЛЕНИЯ)
    подтверждено = any(решение.get(k) for k in
                       ("priorCourtName", "priorAmount", "priorDecisionDate",
                        "priorStateDuty"))
    assert решение.get("priorCaseNumber") == "А53-43425/2025"
    assert not подтверждено, "решение без суда, суммы и даты — не решение"


def test_настоящее_прежнее_решение_подтверждается(analyzer):
    """Обратная сторона: у реального взыскания есть и суд, и сумма."""
    текст = ("Мировой судья судебного участка №6 Советского района "
             "г. Ростова-на-Дону вынес судебный приказ № 2-1093/2022 от "
             "15.03.2022 о взыскании задолженности в размере 96 525,00 руб.")
    решение = analyzer._extract_prior_court_decision(текст)
    assert any(решение.get(k) for k in
               ("priorCourtName", "priorAmount", "priorDecisionDate")), решение

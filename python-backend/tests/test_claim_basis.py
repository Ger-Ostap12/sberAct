# -*- coding: utf-8 -*-
"""Реестр видов основания требования и общий разбор обязательства (31.08.2026).

Повод — свежие заявления, где блок обязательств оказался пустым у одиннадцати
документов из тридцати пяти. Разбор ждал кредитный договор, а основанием были
судебный приказ, исполнительный документ и соглашение о кредитовании. Это не
другой банк — это другой ВИД требования.

Поэтому виды лежат данными (`claim_basis.CLAIM_BASIS`), а разбор один на все.
Проверки ниже двух родов:

  * форматы, на которых прежний разбор спотыкался (номер с пробелами внутри,
    дата в ISO, скобочный второй номер);
  * границы захвата — где номер ОБЯЗАН остановиться. Ложный номер хуже
    пропущенного: он молча попадает в акт.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from claim_basis import (  # noqa: E402
    CLAIM_BASIS,
    basis_alternation,
    basis_kind,
    general_obligation_pattern,
)


@pytest.fixture(scope="module")
def rx():
    return re.compile(general_obligation_pattern(), re.IGNORECASE)


def _num(rx, text):
    m = rx.search(text)
    return m.group(1) if m else None


def _date(rx, text):
    m = rx.search(text)
    return m.group(2) if m else None


# --- Виды основания ------------------------------------------------------------

@pytest.mark.parametrize("text,expected", [
    ("заключен договор займа № 107977878 от 10.08.2024", "107977878"),
    ("установленные Судебным приказом № 2-253/2026 от 16.03.2026", "2-253/2026"),
    ("исполнительный документ № 2-1-733/2026 о взыскании", "2-1-733/2026"),
    ("Соглашение о кредитовании № M0PIL520S23012600185 от 26.01.2023", "M0PIL520S23012600185"),
    ("Договор потребительского кредита № ВДРСТ-1/С/17 от 01.02.2017", "ВДРСТ-1/С/17"),
    ("договор поручительства № 5730016 от 01.01.2020", "5730016"),
    ("по договору цессии № 12/25 от 03.03.2025", "12/25"),
    ("исполнительный лист № ФС-045678 от 12.12.2024", "ФС-045678"),
])
def test_виды_основания_из_реестра(rx, text, expected):
    assert _num(rx, text) == expected


def test_вид_определяется_по_любой_словоформе():
    """Морфология через `\\w*`: «судебным приказом» — тот же вид, что «судебный приказ»."""
    assert basis_kind("судебным приказом") == "judicial"
    assert basis_kind("кредитного договора") == "credit"
    assert basis_kind("договором залога") == "pledge"


def test_длинные_написания_идут_раньше_коротких(rx):
    """Проверка ПОВЕДЕНИЕМ, а не сравнением строк.

    Первая версия резала альтернативу по «|» и падала: разделитель есть и
    ВНУТРИ группы «(?:независим\\w+|банковск\\w+)». Сама строка альтернативы —
    деталь реализации, а закрепить надо результат: составное написание должно
    совпадать целиком, а не обрываться на общем префиксе «договор».
    """
    alt = basis_alternation()
    assert alt.index(r"договор\w*\s+потребительского\s+кредита") < alt.index(r"договор\w*\s+займа")
    m = rx.search("Договор потребительского кредита № ВДРСТ-1/С/17 от 01.02.2017")
    assert m and "потребительского" in m.group(0)


def test_реестр_покрывает_все_группы():
    """Список намеренно ШИРЕ встреченного — заведён на будущее."""
    assert {"credit", "loan", "surety", "pledge", "judicial", "assignment"} <= set(CLAIM_BASIS)


# --- Форматы номера ---------------------------------------------------------------

def test_номер_с_пробелами_внутри(rx):
    """Конвертация PDF→DOCX разбивает длинный номер, и жёсткий класс терял его."""
    assert _num(rx, "договору займа № 003 83 6 2312250225 от 25.12.2023 г.") == "003 83 6 2312250225"


def test_скобочный_второй_номер(rx):
    assert _num(rx, "по кредитному договору № 2431453618(10551861421) от 17.05.2023") == (
        "2431453618(10551861421)")


def test_номер_не_съедает_русское_слово(rx):
    """Продолжение номера обязано содержать ЦИФРУ.

    Без этого условия из «№ 2-1-733/2026 о взыскании» получался номер
    «2-1-733/2026 о взыскании», а из «№ 2-253/2026 от 16.03.2026» — «… от 16».
    """
    assert _num(rx, "исполнительный документ № 2-1-733/2026 о взыскании") == "2-1-733/2026"
    assert _num(rx, "судебный приказ № 2-253/2026 от 16.03.2026") == "2-253/2026"


# --- Форматы даты ---------------------------------------------------------------------

@pytest.mark.parametrize("text,expected", [
    ("договор займа № 111 от 10.08.2024", "10.08.2024"),
    ("договор займа № 111 от 2024-08-10 года", "2024-08-10"),
    ('кредитный договор № 111 от "22" октября 2025 года', '"22" октября 2025'),
])
def test_форматы_даты(rx, text, expected):
    assert _date(rx, text) == expected


def test_дата_необязательна(rx):
    """Часть заявлений даёт основание без даты — обязательство всё равно есть."""
    assert _num(rx, "судебный приказ № 2-500/2025") == "2-500/2025"


# --- Границы -----------------------------------------------------------------------------

def test_номер_не_берётся_из_соседнего_предложения(rx):
    """Окно между основанием и номером короткое — иначе номер уедет из чужой фразы."""
    text = ("кредитный договор был заключён сторонами в надлежащей форме. "
            "Впоследствии стороны подписали иное соглашение № 999 от 01.01.2020")
    assert _num(rx, text) != "999"


def test_основание_без_номера_не_даёт_обязательства(rx):
    """«В соответствии с условиями договора» — не основание с реквизитами."""
    assert rx.search("взысканием задолженности в соответствии с условиями договора") is None

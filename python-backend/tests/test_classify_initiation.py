# -*- coding: utf-8 -*-
"""Различение ИНИЦИИРОВАНИЯ банкротства и чистого ВКЛ-в-РТК.

Инициирующее заявление (в т.ч. кредиторское «о признании банкротом») просит суд
ПРИЗНАТЬ должника банкротом и/или ВВЕСТИ процедуру. Чистое включение в реестр
просит ТОЛЬКО «включить требование в реестр» (банкротство уже введено). Тип
инициирования — по ДОЛЖНИКУ, а не по реквизитам банка-заявителя.
"""
from classify_mixin import ClassifyMixin

C = ClassifyMixin()

# Чистое ВКЛ-в-РТК: просят только включить. Шапка даёт rtk-слова (арбитражный
# суд, банкротство, реестр требований), чтобы дойти до ветки скоринга.
INCLUSION = (
    "В Арбитражный суд Ростовской области. Дело о банкротстве. Заявление о "
    "включении в реестр требований кредиторов. "
    "ПРОСИТ СУД: 1. Включить требования ПАО Сбербанк в третью очередь "
    "реестра требований кредиторов ИВАНОВА ИВАНА в размере 100000 руб. "
    "2. Взыскать с ИВАНОВА госпошлину."
)
# Инициирование ФЛ: признать + ввести процедуру.
INIT_PHYS = (
    "Текст. ПРОСИТ СУД: 1. Признать гражданина ПЕТРОВА ПЕТРА несостоятельным "
    "(банкротом). 2. Ввести в отношении Должника ПЕТРОВА процедуру "
    "реструктуризации долгов гражданина."
)
# Инициирование ЮЛ кредитором-банком (форма «Признать заявление банка …
# о признании ООО … банкротом» + «Ввести процедуру наблюдения в отношении ООО …»).
INIT_LEGAL = (
    "В Арбитражный суд. Дело о несостоятельности (банкротстве). Реестр "
    "требований кредиторов. "
    "просим суд: 1. Признать заявление АО «Экспобанк» (ИНН 7708397772, "
    "адрес: Москва) о признании общества с ограниченной ответственностью "
    "«Ромашка» (ИНН 1234567890) несостоятельным (банкротом) обоснованным. "
    "2. Ввести процедуру наблюдения в отношении общества с ограниченной "
    "ответственностью «Ромашка»."
)
# Инициирование ФЛ кредитором-банком: должник — гражданин, заявитель — АО.
INIT_PHYS_BANK = (
    "Текст. ПРОСИТ СУД: 1. Признать заявление АО «Сбербанк» о признании "
    "гражданина ПЕТРОВА несостоятельным (банкротом) обоснованным. 2. Ввести в "
    "отношении гражданина ПЕТРОВА процедуру реализации имущества."
)


def test_inclusion_not_initiation():
    assert C._is_initiation_petition(INCLUSION) is False


def test_declare_and_procedure_is_initiation():
    assert C._is_initiation_petition(INIT_PHYS) is True


def test_forte_style_reversed_procedure_order():
    # «Ввести процедуру … в отношении» (обратный порядок) тоже инициирование.
    assert C._is_initiation_petition(INIT_LEGAL) is True


def test_type_physical_debtor():
    assert C._initiation_type_by_entity(INIT_PHYS, False, INIT_PHYS.lower()) == "initiation_physical"


def test_type_legal_by_debtor_not_creditor_bank():
    # Заявитель — АО (банк), должник — ООО → initiation_legal по ДОЛЖНИКУ.
    assert C._initiation_type_by_entity(INIT_LEGAL, False, INIT_LEGAL.lower()) == "initiation_legal"


def test_type_physical_when_creditor_is_ao_bank():
    # Регресс: «АО» банка-заявителя не должно утекать в ЮЛ, должник — гражданин.
    assert C._initiation_type_by_entity(INIT_PHYS_BANK, False, INIT_PHYS_BANK.lower()) == "initiation_physical"


def test_classify_inclusion_stays_rtk():
    assert C.classify_document(INCLUSION) == "rtk_application"


def test_classify_initiation_legal():
    assert C.classify_document(INIT_LEGAL) == "initiation_legal"

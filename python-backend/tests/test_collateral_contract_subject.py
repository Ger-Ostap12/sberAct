# -*- coding: utf-8 -*-
"""Предмет договора одной фразой на несколько объектов (28.09.2026).

корпус-49 («Умерший ким клим») называет залог так:

    …заключены договоры ип № 1221/5221/0890/033/13И01 …, № 1221/5221/0890/034/13И01
    …, предметом которых являлись земельные участки сельскохозяйственного
    назначения, расположенные в Ростовской области, Азовского района
    с кадастровыми номерами: 61:01:0600006:3070, 61:01:0600006:3071.

Ни перечня, ни буллетов: объект назван ОДИН раз во множественном числе, а
различают объекты только кадастровые номера. Сканеры не видели этого вовсе —
карточек было НОЛЬ при живом залоге, и юрист получал пустой блок «Залог»
(документ не ипотечный иск, значит показывается именно `collaterals`).

⚠️ Слово «залог» рядом требовать НЕЛЬЗЯ: конвертер обрезал «договоры ипотеки»
до «договоры ип». Якорь держится на обороте «предметом которых являлись».
Замер по 101 документу: срабатывает на одном — на том, ради которого заведён.

⚠️ Кадастровый номер отдаём КАК В ДОКУМЕНТЕ: у первого участка конвертер
поставил «$» вместо цифры («61:01:0$00006:3070»). Выдумывать пропавшую цифру
нельзя — карточка существует, а номер остаётся таким, каким его напечатали.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import (  # noqa: E402
    DocumentAnalyzer,
    _is_false_collateral_description,
)


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


КОРПУС_49 = (
    "Между Ким Клим и ПАО Сбербанк заключены кредитные договоры № 1221/5221/0890/019/13 "
    "от 15.11.2013.\n"
    "заключены договоры ип № — 1221/5221/0890/033/13И01 от 2111201 3, "
    "№ 1221/5221/0890/034/13И01 от 013, предметом которых являлись земельные участки "
    "сельскохозяйственного назначения, расположенные в Ростовской области, Азовского "
    "района с кадастровыми номерами: 61:01:0600006:3070, 61:01:0600006:3071.\n")


def test_две_карточки_по_числу_кадастровых_номеров(analyzer):
    предметы = analyzer._extract_all_collateral_items(КОРПУС_49)
    assert len(предметы) == 2, предметы
    assert предметы[0].endswith("61:01:0600006:3070")
    assert предметы[1].endswith("61:01:0600006:3071")


def test_объект_из_общей_фразы_попал_в_каждую(analyzer):
    предметы = analyzer._extract_all_collateral_items(КОРПУС_49)
    # Длину проверяем ПЕРВОЙ: `all()` по пустому списку истинно, и без этой
    # строки тест зеленел бы на коде, где предметы не находятся вовсе.
    assert len(предметы) == 2, предметы
    assert all(п.startswith("земельные участки сельскохозяйственного назначения") for п in предметы)
    assert all("Азовского района" in п for п in предметы)
    # висячий предлог «с» от «с кадастровыми номерами» обрезан
    assert " с кадастровый" not in " ".join(предметы)


def test_карточки_недвижимость_с_номером(analyzer):
    карточки = [analyzer._make_collateral_obj(i, d)
                for i, d in enumerate(analyzer._extract_all_collateral_items(КОРПУС_49))]
    assert [c["collateralType"] for c in карточки] == ["real_estate", "real_estate"]
    assert карточки[1]["cadastralNumber"] == "61:01:0600006:3071"


ПОБИТЫЙ_НОМЕР = КОРПУС_49.replace("61:01:0600006:3070", "61:01:0$00006:3070")


def test_побитый_конвертером_номер_не_теряет_карточку(analyzer):
    """«$» вместо цифры — след конвертера; предмет всё равно существует."""
    предметы = analyzer._extract_all_collateral_items(ПОБИТЫЙ_НОМЕР)
    assert len(предметы) == 2, предметы
    assert предметы[0].endswith("61:01:0$00006:3070")


# --- чего правило брать НЕ должно ----------------------------------------------

def test_наследство_без_оборота_не_даёт_предметов(analyzer):
    """Те же участки в другом обороте — это наследство, а не предмет договора."""
    текст = ("В рамках наследственного дела № 254/2015 Ким Эмма Николаевна приняла "
             "в качестве наследства, в том числе земельные участки "
             "сельскохозяйственного назначения, расположенные в Ростовской области, "
             "Азовского района с кадастровыми номерами: 61:01:0600006:3070, "
             "61:01:0600006:3071.\n")
    assert analyzer._extract_all_collateral_items(текст) == []


def test_опись_имущества_должника_не_берётся(analyzer):
    """Перед оборотом стоит заголовок описи — предметом залога это не является."""
    текст = ("Должнику принадлежат на праве собственности: "
             "договоры, предметом которых являлись квартиры, расположенные "
             "в г. Ростове-на-Дону с кадастровыми номерами: 61:44:0011105:1180.\n")
    assert analyzer._extract_all_collateral_items(текст) == []


def test_фраза_без_кадастровых_номеров_не_даёт_карточек(analyzer):
    текст = ("заключены договоры ипотеки, предметом которых являлись земельные "
             "участки сельскохозяйственного назначения в Ростовской области.\n")
    assert analyzer._extract_all_collateral_items(текст) == []


# --- РАЗМАСКИРОВКА: мусор в поле [1221] -----------------------------------------
#
# Пока у корпус-49 не было карточек, поле [1221] вычищалось ЗАОДНО с пустым
# списком залогов — и денежная сумма, попавшая туда вместо описания предмета,
# никому не мешала. Как только карточки появились, крышка ушла и мусор всплыл.
# Замер по корпусу: таких документов ДВА — корпус-49 и корпус-65 (у второго
# мусор жил открыто уже сейчас).


@pytest.mark.parametrize("мусор", [
    "4509 575,34",          # корпус-49
    "2 867 955,21",         # корпус-65
    "1 234 567.89",
    " 12 000 ",
    "Кому выдана Иванову Ивану Ивановичу",
])
def test_мусор_в_описании_предмета_отсеивается(мусор):
    assert _is_false_collateral_description(мусор)


@pytest.mark.parametrize("описание", [
    "Квартира, общей площадью 83,9 кв. м., кадастровый номер: 23:69:9464362:1223",
    "земельные участки сельскохозяйственного назначения, Азовский район",
    "Автомобиль VOLKSWAGEN Jetta 2013 г.в., VIN XW8ZZZ16ZEN900156",
])
def test_настоящее_описание_не_трогается(описание):
    assert not _is_false_collateral_description(описание)


@pytest.mark.parametrize("пусто", [None, "", "   "])
def test_пустое_значение_мусором_не_считается(пусто):
    """Пустое поле — это отсутствие значения, а не ложное значение."""
    assert not _is_false_collateral_description(пусто)

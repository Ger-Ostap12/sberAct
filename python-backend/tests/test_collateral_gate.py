# -*- coding: utf-8 -*-
"""Кнопка «с залогом / без залога»: ворота признания документа залоговым (08.09.2026).

Восемь документов корпуса получали «Без залога» при живом залоге. Причин было
три, и каждая закрыта отдельно — тесты держат все три:

1. Перечислялись только короткие формы причастия (обеспечено/обеспечен/…) и одна
   полная («обеспеченное»). Заявления же написаны остальными: «включить … как
   ОБЕСПЕЧЕННЫЕ залогом», «требование, обеспеченнОГО залогом автомобиля».
2. Разобранный список предметов залога в решении не участвовал: у «Форте Пром
   Стил» четыре предмета на 73,9 млн, а кнопка стояла «Без залога».
3. Фраза сама по себе залогом НЕ является: на шести документах корпуса она
   приходит из цитат ст. 334, 348 ГК РФ и ст. 213.8 закона о банкротстве. Их
   отличает предлог: требование заявителя пишется «КАК обеспеченные залогом».
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from patterns import COLLATERAL_SECURED  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- формы причастия ---------------------------------------------------------

@pytest.mark.parametrize("фраза", [
    "обеспеченное залогом",
    "обеспечено залогом",
    "обеспечен залогом",
    "обеспечена залогом",
    "обеспечены залогом",
    "обеспеченные залогом",     # просительная часть — её и теряли
    "обеспеченного залогом",    # «требование, обеспеченного залогом автомобиля»
    "обеспеченным залогом",
    "обеспеченному залогом",
])
def test_все_формы_причастия_ловятся(фраза):
    assert re.search(COLLATERAL_SECURED, фраза, re.IGNORECASE)


def test_чужое_слово_не_ловится():
    """\\w* не должен превращать паттерн в «любое слово перед залогом»."""
    assert not re.search(COLLATERAL_SECURED, "не обеспечивается залогом", re.IGNORECASE)
    assert not re.search(COLLATERAL_SECURED, "залогом обеспечение", re.IGNORECASE)


# --- ворота целиком ----------------------------------------------------------

ЗАКОН = (
    "На первом собрании кредиторов конкурсные кредиторы, в том числе кредиторы, "
    "требования которых обеспечены залогом имущества гражданина, и уполномоченный "
    "орган участвуют в собрании. В силу залога кредитор по обеспеченному залогом "
    "обязательству (залогодержатель) имеет право получить удовлетворение (ст. 334 ГК РФ)."
)


def _кнопка(analyzer, текст, тип="rtk_application", поля=None, предметы=None):
    рек = analyzer._get_recommended_acts(тип, поля or {}, текст, предметы)
    return рек.get("collateralOption")


def test_цитата_закона_залогом_не_считается(analyzer):
    """Шесть документов корпуса несут эту прозу БЕЗ единого предмета залога."""
    assert _кнопка(analyzer, ЗАКОН) == "no_collateral"


def test_просительная_часть_с_как_считается(analyzer):
    текст = (ЗАКОН + " Прошу включить требования в реестр требований кредиторов "
             "как обеспеченные залогом имущества должника.")
    assert _кнопка(analyzer, текст) == "collateral"


def test_разобранные_предметы_считаются(analyzer):
    """Список предметов приходит аргументом: в extracted_fields его нет."""
    текст = "Требования обеспеченные залогом имущества должника."
    assert _кнопка(analyzer, текст) == "no_collateral", "без предметов и без индикаторов"
    предметы = [{"description": "земельный участок 325 кв.м", "value": "1 547 000,00"}]
    assert _кнопка(analyzer, текст, предметы=предметы) == "collateral"


def test_без_обязательной_фразы_предметы_не_спасают(analyzer):
    """Фраза остаётся обязательной: список без неё залогом не делает."""
    предметы = [{"description": "земельный участок 325 кв.м"}]
    assert _кнопка(analyzer, "Прошу включить требования в реестр.",
                   предметы=предметы) == "no_collateral"


def test_транспорт_даёт_отдельную_кнопку(analyzer):
    """Только транспорт — collateral_auto; на форме это та же «с залогом»."""
    текст = ("Требования, обеспеченные залогом транспортного средства "
             "VOLKSWAGEN Jetta, VIN XW8ZZZ16ZEN900156.")
    предметы = [{"description": "автомобиль VOLKSWAGEN Jetta"}]
    assert _кнопка(analyzer, текст, предметы=предметы) == "collateral_auto"

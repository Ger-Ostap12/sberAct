# -*- coding: utf-8 -*-
"""Предмет залога назван в ЗАГОЛОВКЕ перечня, пункты несут адрес (23.09.2026).

свежие-15 верстает залог так:

    Учитывая, что обязательства Заемщика по Кредитному договору обеспечены
    залогом недвижимого имущества, жилая квартира:
    -   Россия, Краснодарский край, г. Краснодар, ул. Им. Евгении Жигуленко,
        д. 11, к.1, кв. 615, кадастровый номер: 23:43:0129001:39774.

`bullet_re` требует название объекта В САМОМ пункте («- Квартира …»), а здесь
пункт начинается с «Россия…». Такую вёрстку сканер не видел вовсе: предметов 0
при кнопке «с залогом».

Название объекта берётся из заголовка и приписывается КАЖДОМУ пункту — один
заголовок может собирать несколько адресов.

⚠️ Слово «залог»/«ипотека» в заголовке обязательно: без него под правило попал
бы любой перечень адресов, включая опись имущества должника. Замер по 101
документу: якорь срабатывает на ОДНОМ документе — на том, ради которого заведён.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


СВЕЖИЕ_15 = (
    "Учитывая,чтообязательстваЗаемщикапо Кредитному договору обеспечены залогом "
    "недвижимого имущества, жилая квартира:\n"
    "-\tРоссия, Краснодарский край, г. Краснодар, ул. Им. Евгении Жигуленко, "
    "д. 11, к.1, кв. 615, кадастровый номер: 23:43:0129001:39774.\n"
    "требования Банка по Кредитному договору обеспечены залогом имущества Должника.\n")


def test_предмет_из_заголовка_находится(analyzer):
    предметы = analyzer._extract_all_collateral_items(СВЕЖИЕ_15)
    assert len(предметы) == 1, предметы
    assert предметы[0].startswith("жилая квартира: Россия")
    assert предметы[0].endswith("23:43:0129001:39774")


def test_карточка_недвижимость_с_кадастровым(analyzer):
    предметы = analyzer._extract_all_collateral_items(СВЕЖИЕ_15)
    карточка = analyzer._make_collateral_obj(0, предметы[0])
    assert карточка["collateralType"] == "real_estate"
    assert карточка["cadastralNumber"] == "23:43:0129001:39774"
    assert analyzer._collateral_has_substance(карточка)


def test_несколько_адресов_под_одним_заголовком(analyzer):
    """Заголовок называет предмет один раз, а пунктов под ним может быть много."""
    текст = ("обязательства обеспечены залогом недвижимого имущества, "
             "земельный участок:\n"
             "-\tРостовская область, Аксайский район, х. Ленина, участок 12, "
             "кадастровый номер: 61:02:0600009:1234\n"
             "-\tРостовская область, Аксайский район, х. Ленина, участок 14, "
             "кадастровый номер: 61:02:0600009:5678\n")
    предметы = analyzer._extract_all_collateral_items(текст)
    assert len(предметы) == 2, предметы
    assert all(п.startswith("земельный участок: Ростовская") for п in предметы)


# --- чего правило брать НЕ должно ----------------------------------------------

def test_перечень_без_слова_залог_не_берётся(analyzer):
    """Опись имущества должника — не залог; слово «залог» в заголовке обязательно."""
    текст = ("Должнику принадлежит на праве собственности следующее имущество, "
             "квартира:\n"
             "-\tРостовская область, г. Ростов-на-Дону, ул. Мира, д. 5, кв. 7, "
             "кадастровый номер: 61:44:0000000:1111\n")
    assert analyzer._extract_all_collateral_items(текст) == []


def test_заголовок_без_пунктов_ничего_не_даёт(analyzer):
    """Двоеточие без перечня под ним — обычная проза, предмета нет."""
    текст = ("Обязательства обеспечены залогом недвижимого имущества, "
             "жилая квартира:\n"
             "Расчёт задолженности прилагается.\n")
    assert analyzer._extract_all_collateral_items(текст) == []


def test_короткий_пункт_отбрасывается(analyzer):
    """Пункт короче адреса — обрывок вёрстки, а не предмет."""
    текст = ("обеспечены залогом недвижимого имущества, жилая квартира:\n"
             "-\tд. 11\n")
    assert analyzer._extract_all_collateral_items(текст) == []


def test_прежняя_вёрстка_не_сломана(analyzer):
    """Объект В САМОМ пункте — прежний путь `bullet_re`, без дублей."""
    текст = ("В залог переданы объекты:\n"
             "-\tКвартира, общей площадью 33,8 кв.м., расположенная по адресу: "
             "г. Краснодар, ул. Жигуленко, д. 11, кв. 615\n")
    предметы = analyzer._extract_all_collateral_items(текст)
    assert len(предметы) == 1, предметы
    assert предметы[0].startswith("Квартира,")

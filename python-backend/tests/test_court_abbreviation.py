# -*- coding: utf-8 -*-
"""Сокращение «АС ⟨регион⟩» в названии суда (21.09.2026, фаза 6 п.2).

Семь заявлений корпуса адресованы «АС Ростовской области», и шесть из них
полного названия не содержат ВОВСЕ. Среди паттернов `courtName` такой формы
не было — отсюда пять пустых полей, а там, где в теле находилось хоть
что-то, в поле уезжало чужое:

    свежие-2    Судебный участок № 1 … (из исполнительного документа)
    свежие-20   «Решением Арбитражного суда Ростовской области» с приставкой

РЕШЕНИЕ АНДРЕЯ 21.09.2026: раскрывать до полного названия. Причина —
`courtName` идёт в маркер [0], то есть в ЗАГОЛОВОК судебного акта, и
определение с шапкой «АС Ростовской области» это брак. Четыре ожидания
эталона, записанные буквально, приведены к полному виду (поле «правка»).

⚠️ Весь разбор идёт с `re.IGNORECASE`, поэтому «АС» защищено `(?-i:...)`:
без защиты сокращение совпадало бы со строчным «ас» внутри обычной речи.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _суд(analyzer, текст):
    """Название суда так, как его увидит форма (поле courtName)."""
    результат = analyzer.analyze_from_text(текст) or {}
    return (результат.get("fields") or {}).get("courtName")


# --- раскрытие сокращения -----------------------------------------------------

@pytest.mark.parametrize("кратко, полно", [
    ("АС Ростовской области", "Арбитражный суд Ростовской области"),
    ("АС Краснодарского края", "Арбитражный суд Краснодарского края"),
    ("АС города Москвы", "Арбитражный суд города Москвы"),
    ("АС Республики Татарстан", "Арбитражный суд Республики Татарстан"),
])
def test_сокращение_раскрывается(analyzer, кратко, полно):
    assert analyzer._expand_court_abbreviation(кратко) == полно


def test_полное_название_не_трогаем(analyzer):
    полно = "Арбитражный суд Ростовской области"
    assert analyzer._expand_court_abbreviation(полно) == полно


def test_раскрытие_только_в_начале(analyzer):
    """«АС» внутри строки — не сокращение суда, а часть чужого текста."""
    значение = "Отдел АС Ростовской области"
    assert analyzer._expand_court_abbreviation(значение) == значение


def test_пустое_значение(analyzer):
    assert analyzer._expand_court_abbreviation("") == ""


# --- паттерн на тексте заявления ---------------------------------------------

ШАПКА_СОКРАЩЁННО = (
    "АС Ростовской области\n"
    "344082, Ростовская обл, г Ростов-на-Дону, ул Станиславского, д 10/11-13\n"
    "Кредитор: ООО «ПКО Воксис» ИНН 6670056296;\n"
    "Должник: Епифановский Владислав Михайлович\n"
    "Дело № А53-39783/2025\n"
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
)


def test_суд_из_шапки_сокращённо(analyzer):
    assert _суд(analyzer, ШАПКА_СОКРАЩЁННО) == "Арбитражный суд Ростовской области"


def test_мировой_участок_не_перебивает_шапку(analyzer):
    """свежие-2: участок назван в теле, арбитражный суд — в шапке."""
    текст = ШАПКА_СОКРАЩЁННО + (
        "21.04.2026 по гражданскому делу № 2-1-733/2026 Судебный участок № 1 "
        "Аксайского судебного района Ростовской области был выдан "
        "исполнительный документ.\n")
    assert _суд(analyzer, текст) == "Арбитражный суд Ростовской области"


def test_приставка_решением_не_попадает_в_название(analyzer):
    """свежие-20: в теле «Решением Арбитражного суда …» с приставкой и в падеже."""
    текст = "В " + ШАПКА_СОКРАЩЁННО + (
        "Решением Арбитражного суда Ростовской области от 04.08.2026 г. "
        "по делу № А53-19435/2026 должник признан банкротом.\n")
    assert _суд(analyzer, текст) == "Арбитражный суд Ростовской области"


# --- чего паттерн брать НЕ должен ---------------------------------------------

def test_строчное_ас_не_считается_судом(analyzer):
    """Разбор идёт с IGNORECASE: без защиты «ас» совпало бы в обычной речи."""
    текст = ("Заявление подано в суд.\n"
             "Передача ас ростовской области в тексте прозой не считается.\n")
    assert _суд(analyzer, текст) != "Арбитражный суд ростовской области"


def test_хвост_слова_не_считается_сокращением(analyzer):
    текст = "КЛАСС Ростовской области упомянут в тексте заявления.\n"
    значение = _суд(analyzer, текст) or ""
    assert "КЛАСС" not in значение


# --- прежнее поведение --------------------------------------------------------

def test_полное_название_в_шапке_по_прежнему(analyzer):
    текст = ("Арбитражный суд Ростовской области\n"
             "344082, г Ростов-на-Дону, ул Станиславского, д 10/11-13\n"
             "Должник: Иванов Иван Иванович\n")
    assert _суд(analyzer, текст) == "Арбитражный суд Ростовской области"

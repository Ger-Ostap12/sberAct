# --- справочник ПОДТВЕРЖДАЕТ документ ----------------------------------------

def test_подтверждение_снимает_пометку(а):
    """§S.16: справочник — СВЕРКА, а не источник.

    У инспекции «Адрес для корреспонденции» и есть её адрес. Пометка
    «юридического адреса в документе нет» была ложной: адрес там есть, и
    справочник его подтверждает.
    """
    поля = {"creditorAddress": "ул. Мясникова, 52/32, г. Ростов-на-Дону, 344019"}
    а._advise(поля, "creditorAddress", а._ADDR_NON_LEGAL.format("адрес для корреспонденции"))
    а._reconcile_fns_address(поля, "344019, Ростов-на-Дону г, Мясникова ул, 52/32")
    assert "creditorAddress" not in (поля.get(а._ADVISORY_KEY) or {})


def test_настоящее_расхождение_помечается(а):
    поля = {"creditorAddress": "344019, г. Ростов-на-Дону, ул. Мясникова, 52/32"}
    а._reconcile_fns_address(поля, "450075, Уфа г, Октября проспект, 95")
    assert "creditorAddress" in (поля.get(а._ADVISORY_KEY) or {})


def test_снятие_пометки_не_трогает_чужие_поля(а):
    поля = {}
    а._advise(поля, "creditorInn", "проверьте")
    а._unadvise(поля, "creditorAddress")
    assert поля[а._ADVISORY_KEY] == {"creditorInn": "проверьте"}



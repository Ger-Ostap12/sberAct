# --- метка юр-адреса ---------------------------------------------------------

def test_местонахождения_одним_словом(а):
    """свежие-23: «Адрес местонахождения:» — половина банков печатает слитно,
    а паттерн требовал пробела («место нахождения») и терял адрес целиком."""
    текст = ("Кредитор:\tАкционерное общество «ТБанк»\n"
             "\tАдрес местонахождения: 127287, г. Москва, Ул. 2-я Хуторская, "
             "д.38А, стр. 26\tТелефон:\n 8-(800)-511-96-21\n"
             "Должник:\tЮРЦОВ ЯН АНАТОЛЬЕВИЧ\n")
    assert а._extract_creditor_address(текст) == (
        "127287, г. Москва, Ул. 2-я Хуторская, д.38А, стр. 26")


def test_место_нахождения_через_пробел_работает_как_прежде(а):
    текст = ("Истец:\n          ПАО Сбербанк\n"
             "          Место нахождения: 117997, г. Москва, ул. Вавилова, д. 24\n"
             "          ОГРН: 1027700132195\n")
    assert а._extract_creditor_address(текст) == "117997, г. Москва, ул. Вавилова, д. 24"


def test_битая_распознаванием_метка_истца(а):
    """корпус-7: «Истеп:» — в этом начертании «ц» читается как «п».

    Блок кредитора не находился вовсе, и адрес, ИНН и ОГРН брались из
    справочника с пометкой «в документе их нет».
    """
    текст = ("Истеп:\n          ПАО Сбербанк\n"
             "          Место нахождения: 117997, г. Москва, ул. Вавилова, д. 24\n"
             "          ОГРН: 1027700132195\n")
    assert а._extract_creditor_block(текст) is not None
    assert а._extract_creditor_address(текст) == "117997, г. Москва, ул. Вавилова, д. 24"


def test_истек_и_истечение_метками_не_считаются(а):
    """Пара букв закрыта явно, чтобы не ловить однокоренные слова прозы."""
    текст = "Срок исполнения истек: обязательство не исполнено.\nОГРН: 1027700132195\n"
    assert а._extract_creditor_block(текст) is None



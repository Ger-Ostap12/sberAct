# -*- coding: utf-8 -*-
"""ИНН должника не должен попадать в реквизиты кредитора (22.09.2026, ф.6 п.4).

свежие-3: шапка свёрстана в ДВЕ КОЛОНКИ. После склейки метка должника
оказывается на одной строке с хвостом колонки кредитора:

    …bankruptcy@gkcdu.ru<TAB>Должник: Андрей Виталий Семенович
     Место рождения: … ИНН: 616506982877

Рез блока кредитора ищет метку с НАЧАЛА СТРОКИ, поэтому не срабатывает, блок
перехлёстывает в запись должника, и первый «ИНН:» внутри него — уже
должников. Верные реквизиты из платёжного блока при этом ОТБРАСЫВАЛИСЬ
защитой «блок описывает другое лицо»: неверный ИНН приехал раньше.
ОГРН уцелел лишь потому, что в блоке его нет вовсе.

⚠️ Чинится НЕ граница блока. Попытка резать и по табуляции укорачивает блок
так, что в юр-адрес кредитора уезжает адрес СУДА («Куда: Арбитражный суд …»),
а собственный адрес кредитора приклеен к строке «Заявитель:» табуляцией и не
находится ни одним слоем. Вместо этого отсекается сам ЧУЖОЙ реквизит:
кредитор и должник одним лицом быть не могут. Обратное направление той же
защиты — `_dedup_cross_block_ids`.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# Шапка в две колонки: метка должника за ТАБУЛЯЦИЕЙ, а не с новой строки.
ШАПКА_В_ДВЕ_КОЛОНКИ = (
    "Заявитель: АО ПКО «ЦДУ»\t117420, г. Москва, ул. Намёткина, д. 15\n"
    "эл. почта:\n"
    "bankruptcy@gkcdu.ru\tДолжник: Андрей Виталий Семенович\n"
    " Адрес: 354024, Краснодарский край, г Сочи, пр-кт Курортный, д 96Г\n"
    " Место рождения: Венгерская республика ИНН: 616506982877\n"
    " СНИЛС: 06191450650\n"
)
ПЛАТЁЖНЫЙ_БЛОК = (
    "Реквизиты для перечисления денежных средств в случае удовлетворения "
    "требований АО ПКО «ЦДУ»:\n"
    "ИНН: 7730592401, ОГРН: 5087746390353\n"
    "КПП: 772701001, БИК: 044525225\n"
)


def _реквизиты(analyzer, текст, должников_инн=None):
    """Что положит слой реквизитов, когда ИНН должника уже известен."""
    поля = {}
    if должников_инн:
        поля["inn"] = должников_инн
    analyzer._fill_creditor_requisites(поля, текст)
    return поля


# --- протечка ИНН должника ----------------------------------------------------

def test_инн_должника_не_становится_кредиторским(analyzer):
    поля = _реквизиты(analyzer, ШАПКА_В_ДВЕ_КОЛОНКИ + ПЛАТЁЖНЫЙ_БЛОК,
                      должников_инн="616506982877")
    assert поля.get("creditorInn") == "7730592401"


def test_огрн_кредитора_не_пострадал(analyzer):
    поля = _реквизиты(analyzer, ШАПКА_В_ДВЕ_КОЛОНКИ + ПЛАТЁЖНЫЙ_БЛОК,
                      должников_инн="616506982877")
    assert поля.get("creditorOgrn") == "5087746390353"


def test_поле_companyInn_тоже_считается_должниковым(analyzer):
    """ИНН должника-организации живёт в companyInn — защита обязана его видеть."""
    поля = {}
    поля["companyInn"] = "616506982877"
    analyzer._fill_creditor_requisites(поля, ШАПКА_В_ДВЕ_КОЛОНКИ + ПЛАТЁЖНЫЙ_БЛОК)
    assert поля.get("creditorInn") == "7730592401"


# --- обычный путь не сломан ---------------------------------------------------

ОБЫЧНАЯ_ШАПКА = (
    "Кредитор: АО «ТБанк»\n"
    "Юридический адрес: 127287, г. Москва, ул. 2-я Хуторская, д. 38А, стр. 26\n"
    "ИНН: 7710140679, ОГРН: 1027739642281\n"
    "Должник: Петров Пётр Петрович\n"
    " ИНН: 616506982877\n"
)


def test_свой_инн_из_блока_берётся(analyzer):
    поля = _реквизиты(analyzer, ОБЫЧНАЯ_ШАПКА, должников_инн="616506982877")
    assert поля.get("creditorInn") == "7710140679"


def test_без_известного_инн_должника_поведение_прежнее(analyzer):
    """Защите не на что опереться — берём то же, что и раньше."""
    поля = _реквизиты(analyzer, ОБЫЧНАЯ_ШАПКА)
    assert поля.get("creditorInn") == "7710140679"


# --- сквозная проверка --------------------------------------------------------

ЗАЯВЛЕНИЕ = (
    "Куда: Арбитражный суд Ростовской области\n"
    + ШАПКА_В_ДВЕ_КОЛОНКИ +
    "Дело № А53-23431/2025\n"
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
    "10.02.2026 г. Арбитражный суд Ростовской области вынес Определение "
    "по делу № А53-23431/2025, которым в отношении Андрей Виталий Семенович "
    "введена процедура реструктуризации долгов гражданина.\n"
    + ПЛАТЁЖНЫЙ_БЛОК
)


def test_разбор_целиком_не_путает_стороны(analyzer):
    поля = (analyzer.analyze_from_text(ЗАЯВЛЕНИЕ) or {}).get("fields") or {}
    assert поля.get("creditorInn") != поля.get("inn"), (
        f"ИНН кредитора и должника совпали: {поля.get('creditorInn')}")

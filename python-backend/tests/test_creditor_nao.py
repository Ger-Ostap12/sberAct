"""Кредитор в форме НАО — непубличное акционерное общество (фаза 3, п. 3.8).

свежие-16: «Заявитель: НАО ПКО «Первое клиентское бюро»». Ни один из одиннадцати
паттернов кредитора не срабатывал — в перечне организационно-правовых форм не
было «НАО», хотя остальной код (classify_mixin, document_analyzer) его знает.
Значение добиралось фолбэком и захватывало соседнюю колонку двухколоночной шапки.
"""
import os
import re
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from patterns import build_patterns  # noqa: E402


def _паттерны_кредитора():
    for группа in build_patterns().values():
        for поле in группа:
            if поле["name"] == "creditorName":
                return поле["patterns"]
    raise AssertionError("поле creditorName не найдено в реестре паттернов")


def _первое_совпадение(текст):
    """Повторяет цикл разбора: рвётся на ПЕРВОМ совпавшем паттерне."""
    for пат in _паттерны_кредитора():
        m = re.search(пат, текст, re.IGNORECASE | re.MULTILINE)
        if m:
            return m.group(1).strip()
    return None


# --- КРАСНОЕ ЭТАЛОНА ---------------------------------------------------------

def test_нао_с_меткой_заявитель():
    """Строка склеена из двух колонок шапки — берём то, что после метки."""
    текст = ("НАО ПКО «ПКБ» Заявитель: НАО ПКО «Первое клиентское бюро»\n"
             "108811, г. Москва, БЦ Comcity, ИНН 2723115222, ОГРН 1092723000446")
    assert _первое_совпадение(текст) == "НАО ПКО «Первое клиентское бюро»"


@pytest.mark.parametrize("метка", ["Заявитель", "Кредитор", "Взыскатель"])
def test_нао_по_всем_меткам_стороны(метка):
    текст = f"{метка}: НАО «Первое клиентское бюро»\nИНН 2723115222"
    assert _первое_совпадение(текст) == "НАО «Первое клиентское бюро»"


# --- ПРЕЖНИЕ ФОРМЫ НЕ СЛОМАНЫ ------------------------------------------------

@pytest.mark.parametrize("строка,ожидание", [
    ("Заявитель: АО «АЛЬФА-БАНК»\nИНН 1", "АО «АЛЬФА-БАНК»"),
    ("Заявитель: ПАО Сбербанк\nИНН 1", "ПАО Сбербанк"),
    ("Заявитель: ООО «Феникс»\nИНН 1", "ООО «Феникс»"),
    ("Заявитель: ЗАО «Тест»\nИНН 1", "ЗАО «Тест»"),
    ("Заявитель: ОАО «Тест»\nИНН 1", "ОАО «Тест»"),
])
def test_прежние_опф_работают(строка, ожидание):
    assert _первое_совпадение(строка) == ожидание


def test_оао_не_разбирается_как_ао():
    """«АО» стоит в перечне раньше «ОАО»/«НАО» — проверяем, что префикс цел."""
    assert _первое_совпадение("Заявитель: ОАО «Тест»\nИНН 1").startswith("ОАО")
    assert _первое_совпадение("Заявитель: НАО «Тест»\nИНН 1").startswith("НАО")


def test_значение_обрывается_на_переводе_строки():
    """Хвост следующей строки в название кредитора попадать не должен."""
    текст = "Заявитель: НАО «ПКБ»\nАдрес: 108811, г. Москва"
    assert _первое_совпадение(текст) == "НАО «ПКБ»"

# -*- coding: utf-8 -*-
"""Адрес должника: хвосты, чужой адрес, метки в значении (13-14.09.2026).

Двенадцать красных в эталоне разложились на ТРИ корня, и каждый потребовал
своего правила. Тексты — дословные куски заявлений корпуса: вся сложность
именно в том, как конвертер ломает вёрстку, и выдуманные строки её не
воспроизводят.

ГЛАВНЫЙ УРОК ЗАДАЧИ — граница блока стороны важнее любой чистки значения.
Якорь «Должник» без границы срабатывал на косвенный падеж внутри прозы
(«…и ИНН должника), по согласованию…»), и «записью должника» становился хвост
просительной части, где рядом лежит адрес представителя банка.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from patterns import DEBTOR_BLOCK, RESPONDENT_BLOCK  # noqa: E402


@pytest.fixture(scope="module")
def а():
    return DocumentAnalyzer()


def блок(текст, паттерн=DEBTOR_BLOCK):
    m = re.search(паттерн, текст, re.IGNORECASE | re.DOTALL)
    return m.group(1) if m else None


# --- граница записи стороны --------------------------------------------------

def test_косвенный_падеж_в_прозе_не_якорь():
    """свежие-6/31/32: «…и ИНН должника), по согласованию с финансовым
    управляющим» — и блоком должника становилась просительная часть."""
    текст = ("«…(ФИО и ИНН должника), по согласованию с финансовым управляющим»\n"
             "Адрес представителя по доверенности: 443001, г. Самара, ул. Галактионовская, д. 157\n"
             "\n"
             "Должник: ХЛИЯН ЕЛЕНА ОГАНОВНА\n"
             "Адрес: г. Ростов-на-Дону, Буденновский пр-кт, д. 102А, кв. 10\n")
    assert "ХЛИЯН" in блок(текст)


def test_склейка_метки_с_названием_не_отбраковывается():
    """Форте Хоум: конвертер съел двоеточие — «ДолжникОбщество с ограниченной…».

    Проверка границы применяется под re.IGNORECASE, и без снятия флага класс
    [а-яё] ловил заглавную «О». Запись должника уходила в мусор целиком, а
    должником становился банк из строки выше.
    """
    текст = ('ДолжникОбщество с ограниченной ответственностью «Форте Хоум ГмбХ»\n'
             'ОГРН: 1066163001222, ИНН: 6163076960\n')
    assert "Форте Хоум" in блок(текст)


def test_запись_стороны_обрывается_на_подписи_следующей():
    """Ипотека: за записью ответчика-физлица идёт «Третье лицо: <учреждение>»
    с его ОГРН — и гражданин объявлялся юрлицом."""
    текст = ("Ответчик:\nЖЕВНИН МАГОМЕД ТИМУРОВИЧ\nИНН: 201233777777\n"
             "Третье лицо: Федеральное государственное казенное учреждение\n"
             "ОГРН: 1067781337095\n")
    b = блок(текст, RESPONDENT_BLOCK)
    assert "ЖЕВНИН" in b
    assert "1067781337095" not in b


# --- хвосты ------------------------------------------------------------------

def test_склеенная_подпись_следующей_секции_обрезается(а):
    """свежие-13: «Финансовыйуправляющий» без пробела — подстрока не находилась."""
    b = ("Давтян Вартан Оганович\n"
         "344030 Ростовская г Ростов-на-Дону ул Коммунаровд.д 33 кв.кв 64\n"
         "Финансовыйуправляющий: СЕРГИЕНКО ИВАН ГЕННАДЬЕВИЧ\n")
    assert а._collect_block_address(b) == (
        "344030 Ростовская г Ростов-на-Дону ул Коммунаровд.д 33 кв.кв 64")


def test_подпись_разорванная_колонками_обрезается(а):
    """свежие-4: «ФИНАНСОВЫЙ  Селина Ольга Олеговна» — слово «УПРАВЛЯЮЩИЙ»
    уехало в соседний столбец, и целиком подпись не ищется."""
    b = ("Адрес регистрации: Ростовская область, г. Азов, ул.\n"
         "Ленинградская, д. 86, кв. 53\n"
         "ФИНАНСОВЫЙ \tСелина Ольга Олеговна (ИНН 431202681065\n")
    assert а._collect_block_address(b) == (
        "Ростовская область, г. Азов, ул. Ленинградская, д. 86, кв. 53")


def test_исходящий_номер_письма_не_продолжение_адреса(а):
    """свежие-18: «кв. 1 / №007.28.7-3/918/26 от 09.07.2026»."""
    b = ("адрес: 346480, Россия, обл Ростовская, р-н Октябрьский, рп Каменоломни,\n"
         "ул Красноармейская, д. 12, кв. 1\n"
         "№007.28.7-3/918/26 от 09.07.2026\n")

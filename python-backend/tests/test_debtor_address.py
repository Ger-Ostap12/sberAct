# --- адрес под меткой «Место рождения» ---------------------------------------

def test_место_рождения_с_улицей_это_адрес(а):
    """свежие-1: вёрстка слила строки шапки, настоящее место рождения пусто.

    Замер по корпусу: из 44 заполненных мест рождения улицу содержит РОВНО
    ОДНО — это. Место рождения — населённый пункт, улицы в нём не бывает.
    """
    b = ("Рудакова Александра Сергеевна\n"
         "Дата рождения: 11.04.2002 г.\n"
         "Место рождения: Ростовская область, г. Батайск, ул. Литовская,\n"
         "д. 180 \nИНН: 614107678825\n")
    assert а._collect_block_address(b) == (
        "Ростовская область, г. Батайск, ул. Литовская, д. 180")


def test_настоящее_место_рождения_адресом_не_считается(а):
    b = ("Иванов Иван Иванович\n"
         "Место рождения: гор. Мирный Архангельская обл.\n"
         "ИНН: 614107678825\n")
    assert а._collect_block_address(b) is None


def test_улица_вычищается_из_поля_место_рождения(а):
    """Иначе юрист увидит улицу в графе «Место рождения»."""
    поля = {"birthPlace": "Ростовская область, г. Батайск, ул. Литовская"}
    а._resolve_debtor_address(поля, "", None)
    assert "birthPlace" not in поля


def test_обычное_место_рождения_остаётся(а):
    поля = {"birthPlace": "гор. Мирный Архангельская обл."}
    а._resolve_debtor_address(поля, "", None)
    assert поля["birthPlace"] == "гор. Мирный Архангельская обл."



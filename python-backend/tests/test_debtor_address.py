# --- расширение адреса до строки ---------------------------------------------

def test_расширение_не_возвращает_отрезанный_хвост(а):
    """ДДУ: «…КВАРТИРА 68 Иной известный адрес проживания: 350011, …».

    Расширение берёт строку целиком и возвращало обратно ровно тот хвост,
    который сборка только что отрезала.
    """
    текст = ("675014. АМУРСКАЯ ОБЛАСТЬ. Г БЛАГОВЕЩЕНСК, УЛ. ТЕКСТИЛЬНАЯ, ДОМ 86/2, "
             "КВАРТИРА 68 Иной  известный адрес проживания: 350011. Краснодарский край\n")
    адрес = "675014. АМУРСКАЯ ОБЛАСТЬ. Г БЛАГОВЕЩЕНСК, УЛ. ТЕКСТИЛЬНАЯ, ДОМ 86/2, КВАРТИРА 68"
    assert а._extend_address_from_text(текст, адрес) is None


def test_расширение_работает_когда_адрес_действительно_длиннее(а):
    текст = "Адрес: 344002, г. Ростов-на-Дону, ул. Ленина, д. 5, кв. 10\n"
    assert а._extend_address_from_text(текст, "344002, г. Ростов-на-Дону") == (
        "344002, г. Ростов-на-Дону, ул. Ленина, д. 5, кв. 10")

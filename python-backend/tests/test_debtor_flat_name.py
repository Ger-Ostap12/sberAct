# -*- coding: utf-8 -*-
"""Плоское имя должника и краткое наименование ЮЛ (08.09.2026).

Форма показывает ПЛОСКОЕ поле `debtorName`, а разбор блока «Должник:/Ответчик:»
кладёт имя ещё и в КАРТОЧКУ должника. На шести документах карточка была верна,
а плоское поле несло мусор:

    «ФИНАНСОВЫЙ»                    первое слово соседней колонки шапки
                                    «ФИНАНСОВЫЙ УПРАВЛЯЮЩИЙ:»
    «имеет неисполненные денежные»  кусок прозы из текста
    «КОЛОР« (заемщик)»»             имя ООО «КОЛОР» с осколками вёрстки
    «ДЖАИЕВ ФИРУДДИН ИКРАМ»         имя без «ОГЛЫ»

Отсюда правило: плоское имя обязано СОГЛАСОВЫВАТЬСЯ с карточкой. Не «всегда
брать карточку» — замер по корпусу показал, что из 8 расхождений на 69
документов четыре ЗАКОННЫХ: ипотека с несколькими должниками склеивает имена
через запятую, а у юрлица плоское поле — краткая форма против полной.

`legalShortName` заполнялось из того же сырого имени и у ФИЗЛИЦ несло то их
ФИО, то кусок прозы. У физлица краткого наименования юрлица не бывает.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _свести(analyzer, плоское, карточка, тип="individual", краткое=None):
    поля = {"debtorName": плоское, "entityType": тип}
    if краткое is not None:
        поля["legalShortName"] = краткое
    analyzer._reconcile_flat_debtor_name(поля, [{"name": карточка}])
    return поля


# --- имена не связаны: мусор -------------------------------------------------

def test_колонка_шапки_вытесняется_карточкой(analyzer):
    """«ФИНАНСОВЫЙ» — соседняя колонка шапки, а не имя должника."""
    поля = _свести(analyzer, "ФИНАНСОВЫЙ", "Горина Юлия Игоревна")
    assert поля["debtorName"] == "Горина Юлия Игоревна"


def test_кусок_прозы_вытесняется_карточкой(analyzer):
    поля = _свести(analyzer, "имеет неисполненные денежные", "Форте Хоум ГмбХ",
                   тип="legal")
    assert поля["debtorName"] == "Форте Хоум ГмбХ"


# --- плоское ⊂ карточки ------------------------------------------------------

def test_обрубленное_имя_физлица_чинится(analyzer):
    """«ОГЛЫ» — часть имени, а не приставка: у физлица обрезка это дефект."""
    поля = _свести(analyzer, "ДЖАИЕВ ФИРУДДИН ИКРАМ", "ДЖАИЕВ ФИРУДДИН ИКРАМ ОГЛЫ")
    assert поля["debtorName"] == "ДЖАИЕВ ФИРУДДИН ИКРАМ ОГЛЫ"


def test_краткая_форма_юрлица_остаётся(analyzer):
    """У ЮЛ плоское поле НАМЕРЕННО короче карточки — это не дефект."""
    поля = _свести(analyzer, "ООО «Форте Пром Стил ГмбХ»",
                   "Общество с ограниченной ответственностью ООО «Форте Пром Стил ГмбХ»",
                   тип="legal")
    assert поля["debtorName"] == "ООО «Форте Пром Стил ГмбХ»"


# --- карточка ⊂ плоского -----------------------------------------------------

def test_несколько_должников_склеены_и_остаются(analyzer):
    """Ипотека: плоское поле — список должников через запятую, карточка первая."""
    склейка = "Ёлкин Денис Александрович, Елкина Наталия Сергеевна"
    поля = _свести(analyzer, склейка, "Ёлкин Денис Александрович")
    assert поля["debtorName"] == склейка


def test_осколки_вёрстки_вытесняются(analyzer):
    """«КОЛОР« (заемщик)»» формально СОДЕРЖИТ имя из карточки.

    Отличить его от законной склейки нескольких должников можно только по
    следам вёрстки: кавычка вплотную к скобке и роль в скобках.
    """
    поля = _свести(analyzer, 'КОЛОР« (заемщик)»', 'ООО "КОЛОР"', тип="legal",
                   краткое='КОЛОР« (заемщик)»')
    assert поля["debtorName"] == 'ООО "КОЛОР"'
    assert поля["legalShortName"] == "КОЛОР", "краткое пересобирается без ОПФ"


# --- краткое наименование юрлица ---------------------------------------------

@pytest.mark.parametrize("мусор", [
    "Медведев Максим Юрьевич",       # ФИО самого должника
    "не имеет возможности",          # кусок прозы
    "владеет недвижимым имуществом",
])
def test_у_физлица_краткого_наименования_нет(analyzer, мусор):
    поля = {"entityType": "individual", "legalShortName": мусор}
    analyzer._drop_legal_short_name_for_person(поля)
    assert "legalShortName" not in поля


def test_у_юрлица_краткое_наименование_сохраняется(analyzer):
    поля = {"entityType": "legal", "legalShortName": "Форте Хоум ГмбХ"}
    analyzer._drop_legal_short_name_for_person(поля)
    assert поля["legalShortName"] == "Форте Хоум ГмбХ"


# --- границы -----------------------------------------------------------------

def test_совпадающие_имена_не_трогаются(analyzer):
    поля = _свести(analyzer, "Медведев Максим Юрьевич", "Медведев Максим Юрьевич",
                   краткое="что-то")
    assert поля["debtorName"] == "Медведев Максим Юрьевич"
    assert поля["legalShortName"] == "что-то", "равные имена не повод чистить"


def test_без_карточки_ничего_не_ломается(analyzer):
    поля = {"debtorName": "ФИНАНСОВЫЙ", "entityType": "individual"}
    analyzer._reconcile_flat_debtor_name(поля, [])
    assert поля["debtorName"] == "ФИНАНСОВЫЙ", "выдумывать имя не из чего"


def test_пустое_плоское_поле_не_заполняется_молча(analyzer):
    """Пустое поле — отдельный случай: его заполняет другой слой, не этот."""
    поля = {"debtorName": "", "entityType": "individual"}
    analyzer._reconcile_flat_debtor_name(поля, [{"name": "Горина Юлия Игоревна"}])
    assert поля["debtorName"] == ""

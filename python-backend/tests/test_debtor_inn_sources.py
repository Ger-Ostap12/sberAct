# -*- coding: utf-8 -*-
"""ИНН должника: заголовок заявления и границы числа (08.09.2026).

Две независимые причины пустого и кривого ИНН.

1. Блок «Должник:» обрывается на слове «ЗАЯВЛЕНИЕ» — и это ПРАВИЛЬНО: иначе
   в него утекают реквизиты кредитора. Но ИНН стоит ровно ЗА этим словом:

       Должник: Воробьева Светлана Михайловна
       Адрес: ул. Орбитальная, д.90, к.67, г. Ростов-на-Дону, 344114
       ЗАЯВЛЕНИЕ о включении требований кредитора в реестр требований
       кредиторов Воробьевой Светланы Михайловны ИНН 611000587986.

   Семь заявлений оставались без ИНН, хотя он напечатан в первой строке.
   Формула сама называет должника по имени, поэтому чужой ИНН по ней прийти
   не может.

2. Класс числа `[0-9\\s]{9,12}` глотал пробел и первую цифру ПОЧТОВОГО ИНДЕКСА
   со следующей строки: «ИНН 6162059094 344002, Ростовская область…» давало
   одиннадцатизначное «61620590943». Та же болезнь, что когда-то лечили у
   СНИЛСа границами по цифрам.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from fio_detector import _inn_candidates  # noqa: E402
from parties_mixin import PartiesMixin  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- заголовок заявления -----------------------------------------------------

ЗАГОЛОВОК = ("ЗАЯВЛЕНИЕ о включении требований кредитора в реестр требований "
             "кредиторов Воробьевой Светланы Михайловны ИНН 611000587986. "
             "Определением Арбитражного суда")


def test_инн_из_заголовка():
    assert PartiesMixin._debtor_inn_from_title(ЗАГОЛОВОК) == "611000587986"


def test_имя_в_именительном_падеже_тоже():
    """Половина заявлений не склоняет ФИО: «…кредиторов Мурадьян Максим Евгеньевич ИНН»."""
    текст = ("о включении требований кредитора в реестр требований кредиторов "
             "Мурадьян Максим Евгеньевич ИНН 616402764553 ПАО «Сбербанк»")
    assert PartiesMixin._debtor_inn_from_title(текст) == "616402764553"


def test_далёкий_инн_не_берётся():
    """Окно в 80 знаков: дальше начинается уже другое предложение."""
    текст = ("в реестр требований кредиторов Воробьевой Светланы Михайловны. "
             "Определением суда утверждён управляющий, состоящий в организации, "
             "адрес которой указан ниже, ИНН 7730309884")
    assert PartiesMixin._debtor_inn_from_title(текст) is None


def test_без_формулы_ничего_не_выдумывается():
    assert PartiesMixin._debtor_inn_from_title("Должник: Иванов Иван Иванович") is None


def test_предпочитается_валидный_по_контрольной_сумме():
    текст = ("в реестр требований кредиторов Иванова И.И. ИНН 611000587980 "
             "в реестр требований кредиторов Иванова И.И. ИНН 611000587986")
    assert PartiesMixin._debtor_inn_from_title(текст) == "611000587986"


# --- границы числа -----------------------------------------------------------

def test_почтовый_индекс_не_приклеивается():
    запись = ("ООО «УО «Владимирская» ИНН 6162059094 344002, Ростовская область, "
              "город Ростов-на-Дону, ул. Баумана, д. 20/12/13")
    assert _inn_candidates(запись) == ["6162059094"]


def test_двенадцать_цифр_предпочтительнее_десяти():
    """У гражданина ИНН длиннее; обрезать его до десяти нельзя."""
    assert _inn_candidates("Должник: Иванов И.И. ИНН 611000587986") == ["611000587986"]


def test_один_разрыв_вёрстки_ловится_запасным():
    """Конвертер рвёт номер пробелом — строгий молчит, терпимый склеивает.

    Терпимость невелика и осознанно: окно в 12 знаков вмещает ОДИН лишний
    пробел. Номер, разорванный на пять групп («61 62 05 90 94»), не берётся
    ни тем, ни другим — такого в корпусе нет, а расширение окна открыло бы
    дорогу соседним числам.
    """
    assert _inn_candidates("ИНН 616205 9094") == ["6162059094"]
    assert _inn_candidates("ИНН 61 62 05 90 94") == []


def test_без_инн_кандидатов_нет():
    assert _inn_candidates("Должник: Иванов Иван Иванович, адрес: Ростов") == []

# -*- coding: utf-8 -*-
"""Реквизиты в скобках сразу за ФИО должника не должны съедать фамилию.

Найдено на реальном заявлении вне корпуса (ООО ПКО «АйДи Коллект»), которое
принёс Андрей. Строка должника там выглядит так:

    Должник:
    Буниатян Алина Генриковна (дата рождения: 28.03.2001 г., место рождения: …,
    СНИЛС 158-801-520 75, ИНН 612504512780, адрес регистрации …)

Позиционный разбор резал кандидата по первой ЦИФРЕ и получал
«Буниатян Алина Генриковна (дата рождения:» — не ФИО. Кандидат отклонялся, имя
доставал Natasha-фолбэк, и в акт уходило «Алина Генриковна» — БЕЗ ФАМИЛИИ,
вместе со всеми падежами.

Отрицательные проверки здесь не менее важны: обрезка по скобке, сделанная
без разбора, ломала эталон (`ИП БАЗОВ ГЕОРГИЙ НИКОЛАЕВИЧ (ДОЛЖНИК)` начинал
разбираться позиционно и титлкейситься в «Ип Базов …», а склонение — в
«Базового»). Поэтому режется ТОЛЬКО скобка с реквизитами.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from fio_detector import extract_debtor_name  # noqa: E402


class TestРеквизитыВСкобках:
    @pytest.mark.parametrize(
        "block, expected",
        [
            (
                "Должник:\nБуниатян Алина Генриковна (дата рождения: 28.03.2001 г., "
                "место рождения: гор. Новочеркасск, СНИЛС 158-801-520 75, ИНН 612504512780)",
                "Буниатян Алина Генриковна",
            ),
            (
                "Должник:\nИванова Мария Петровна (ИНН 612504512780)",
                "Иванова Мария Петровна",
            ),
            (
                "Ответчик:\nСидоров Пётр Иванович (паспорт 6012 123456)",
                "Сидоров Пётр Иванович",
            ),
            (
                "Должник:\nКузнецов Иван Иванович (место рождения: г. Ростов-на-Дону)",
                "Кузнецов Иван Иванович",
            ),
        ],
    )
    def test_фамилия_не_теряется(self, block, expected):
        assert extract_debtor_name(block) == expected

    def test_без_скобок_поведение_прежнее(self):
        assert extract_debtor_name("Должник:\nИванов Иван Иванович, ИНН 612504512780") == (
            "Иванов Иван Иванович"
        )


class TestНеРеквизитныеСкобкиНеТрогаем:
    def test_девичья_фамилия_остаётся_в_имени(self):
        """«(Кулемзина)» — часть имени, а не приписка. Резать нельзя."""
        got = extract_debtor_name("Должник:\nПетрова Мария (Кулемзина) Сергеевна")
        assert got == "Петрова Мария (Кулемзина) Сергеевна"

    def test_скобка_с_ролью_не_делает_кандидата_валидным(self):
        """Регрессия: обрезка по ЛЮБОЙ скобке ломала эталон.

        «ИП БАЗОВ ГЕОРГИЙ НИКОЛАЕВИЧ (ДОЛЖНИК)» — в скобке РОЛЬ, а не реквизиты.
        Позиционный разбор на такой строке осознанно отказывается, и имя даёт
        паттерн — в том регистре, как в документе. Стоит обрезке сработать, и
        имя титлкейсится в «Ип Базов …», а родительный падеж — в «Базового».
        Здесь проверяем главное: фамилия и регистр НЕ превращаются в титлкейс
        через путь «обрезали скобку -> кандидат стал валиден».
        """
        got = extract_debtor_name("Должник:\nИП БАЗОВ ГЕОРГИЙ НИКОЛАЕВИЧ (ДОЛЖНИК)")
        assert got != "Ип Базов Георгий Николаевич", (
            "скобка с ролью обрезана — эталон БАЗОВ поедет"
        )

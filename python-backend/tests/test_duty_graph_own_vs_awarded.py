# -*- coding: utf-8 -*-
"""Графы госпошлины: своя пошлина кредитора [16] против взысканной [17].

Лексика путала графы: «включить расходы по уплате пошлины» попадало под
маркер ссудной. Различитель структурный — число, объявленное меткой в шапке
реквизитов, принадлежит банкротной графе.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from amounts_mixin import AmountsMixin  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402

ШАПКА = """В Арбитражный суд Ростовской области
Заявитель (кредитор): ООО МКК «Озон Кредит»
Должник: ООО «СПОРТ»
Размер требования: 456 740,00 руб.
Государственная пошлина: 13 919,00 руб.
ЗАЯВЛЕНИЕ
"""
ПРОСЬБА = """ПРОСИТ СУД:
Включить расходы ООО МКК «Озон Кредит» по уплате государственной пошлины в размере 13 919,00 руб. в третью очередь реестра требований кредиторов ООО «СПОРТ» с учётом п. 3 ст. 137 Закона о банкротстве.
"""


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def test_своя_пошлина_из_шапки_идёт_в_банкротную(analyzer):
    fields = {"stateDuty16": "13 919,00", "stateDuty": "13 919,00"}
    analyzer._normalize_financial_block(fields, ШАПКА + ПРОСЬБА)
    assert fields.get("stateDuty16") == "13 919,00"
    assert not fields.get("loanStateDuty17")


def test_без_метки_в_шапке_прежняя_лексика_работает(analyzer):
    """Ворота, а не запрет: нет метки — классификация по формулировке, как была."""
    fields = {"stateDuty16": "13 919,00", "stateDuty": "13 919,00"}
    текст = ШАПКА.replace("Государственная пошлина: 13 919,00 руб.\n", "") + ПРОСЬБА
    analyzer._normalize_financial_block(fields, текст)
    assert fields.get("loanStateDuty17") == "13 919,00"
    assert not fields.get("stateDuty16")


def test_чужое_число_метка_не_прикрывает(analyzer):
    """Переопределение привязано к ЗНАЧЕНИЮ: другая сумма остаётся ссудной."""
    fields = {}
    текст = ШАПКА + ПРОСЬБА.replace("13 919,00 руб.", "67 575,00 руб.")
    analyzer._normalize_financial_block(fields, текст)
    assert fields.get("loanStateDuty17") == "67 575,00"


# --- метка шапки ------------------------------------------------------------------


@pytest.mark.parametrize("строка,ожидание", [
    ("Государственная пошлина: 13 919,00 руб.", ["13 919,00"]),
    ("Госпошлина: 6 000 руб.", ["6 000"]),
    ("  Государственной пошлины: 44 007 руб.", ["44 007"]),
    # Две пошлины подряд: Альфа-Банк объявляет 100 000 руб. за вступление в
    # дело и 5 000 000 руб. за требование (пп. 9 п. 1 ст. 333.21 НК).
    ("Государственная пошлина: 100 000 руб.,\nГоспошлина: 5 000 000 руб.",
     ["100 000", "5 000 000"]),
])
def test_метка_шапки_находится(строка, ожидание):
    assert [m.group(1).strip() for m in AmountsMixin._ГП_ШАПКА.finditer(строка)] == ожидание


@pytest.mark.parametrize("строка", [
    # В ПРОЗЕ то же слово означает уже другое — метка только с начала строки.
    "Включить расходы по уплате государственной пошлины в размере 13 919,00 руб.",
    "взысканы расходы по государственной пошлине: 67 575,00 руб.",
    "Согласно пп. 9 п. 1 ст. 333.21 НК РФ государственная пошлина уплачивается",
])
def test_метка_шапки_не_ловит_прозу(строка):
    assert not AmountsMixin._ГП_ШАПКА.search(строка), строка


# --- документ целиком -------------------------------------------------------------

СПОРТ = os.path.abspath(os.path.join(
    _THIS, "..", "..", "Заявления", "НОвая конвертация",
    "Заявление о включении в РТК - ООО СПОРТ.docx"))


@pytest.mark.skipif(not os.path.exists(СПОРТ), reason="документ вне корпуса недоступен")
def test_спорт_обе_графы(analyzer):
    """Сквозная проверка: своя пошлина в [16], три взысканные судом — в [17]."""
    f = (analyzer.analyze(СПОРТ).get("fields") or {})
    assert f.get("stateDuty16") == "13 919,00"
    assert f.get("loanStateDuty17") == "220 570,00"

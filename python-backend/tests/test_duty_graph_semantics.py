"""Графа госпошлины — по СМЫСЛУ, а не по порядку в тексте (07.10.2026).

Решение Андрея: «нужно проверять по смыслу, а не по порядку». До этого графа
выбиралась позицией в блоке «ПРОСИТ СУД» (`nonzero_duties[0]` -> банкротная,
`[1]` -> ссудная), и у свежие-9 обе графы вставали РОВНО НАОБОРОТ:

```
шапка, п.3 просительной   «Госпошлина: 23 542 руб.» / «Взыскать … расходы
                          по уплате государственной пошлины 23 542» -> БАНКРОТНАЯ
п.1, состав требования    «- 10 906,00 руб. – госпошлина» -> ССУДНАЯ
                          (взыскана судом по кредиту, часть требования)
```

Смысловые признаки (handoff §S.43):
    банкротная  отдельный пункт «Взыскать … расходы по уплате ГП», шапка
                «Госпошлина: N руб»
    ссудная     ГП внутри перечня слагаемых требования
    пусто       «исполнительные документы освобождают Банк от оплаты ГП»

⚠️ Два теста внизу — сторожа на ошибки, допущенные при самой этой правке:
первая редакция выбирала категорию по слову, ближайшему к числу, и уводила
«неустойку/штраф» в штраф; значит нужны оба сторожа, а не один.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def поля(analyzer, текст):
    return analyzer.analyze_from_text(текст)["fields"]


ШАПКА = (
    "Арбитражный суд Ростовской области\n"
    "Заявитель: ПАО Сбербанк, ИНН 7707083893\n"
    "Должник: ИВАНОВ ИВАН ИВАНОВИЧ\n"
    "ЗАЯВЛЕНИЕ о включении требований в реестр требований кредиторов\n"
)


# --- банкротная: отдельный пункт «Взыскать …» -----------------------------------

# Порядок частей повторяет свежие-9 НАМЕРЕННО: «Банк просит суд» стоит ВЫШЕ
# просительной, а «прошу суд» — ниже её, в последнем пункте. На этом ломался
# разбор: якорь просительной выбирался по порядку в СПИСКЕ якорей, а не по
# самому раннему в тексте, область обрезалась до 56 знаков, и банкротную
# госпошлину искать было уже негде.
ВЗЫСКАТЬ = ШАПКА + (
    "Сумма требований: 1 426 188,65 руб. Госпошлина: 23 542 руб.\n"
    "В части уплаты государственной пошлины Банк просит суд учесть следующее.\n"
    "ПРОШУ:\n"
    "1. Включить требования ПАО Сбербанк в третью очередь реестра требований "
    "кредиторов ИВАНОВА ИВАНА ИВАНОВИЧА в размере 1 426 188,65 рублей, из которых: "
    "- 1 039 411,92 руб. – просроченный основной долг "
    "- 361 413,26 руб. – просроченные проценты "
    "- 14 457,47 руб. – неустойка "
    "- 10 906,00 руб. – госпошлина\n"
    "2. Задолженность по неустойке в размере 14 457,47 рублей учесть в третьей "
    "очереди требований кредиторов после удовлетворения требований кредитора "
    "по основному долгу.\n"
    "3. Взыскать с ИВАНОВА ИВАНА ИВАНОВИЧА в пользу ПАО Сбербанк расходы по "
    "уплате государственной пошлины в размере 23 542 рублей.\n"
    "4. В соответствии с ч. 2 ст. 156 АПК РФ прошу суд рассмотреть дело "
    "в отсутствие представителя Банка.\n"
    "Приложения:\n"
    "1. Платёжное поручение об уплате государственной пошлины.\n"
)


def test_банкротная_из_пункта_взыскать(analyzer):
    assert поля(analyzer, ВЗЫСКАТЬ).get("stateDuty") == "23 542,00"


def test_ссудная_из_состава_требования(analyzer):
    assert поля(analyzer, ВЗЫСКАТЬ).get("loanStateDuty17") == "10 906,00"


def test_госпошлина_не_попадает_в_неустойку(analyzer):
    """Сторож на окно подписи, залезающее в СЛЕДУЮЩИЙ пункт.

    «- 10 906,00 руб. – госпошлина 2. Задолженность по неустойке …»: ведущим
    словом окна становилась «неустойка», и неустойка вырастала до 25 363,47
    (14 457,47 + 10 906,00), а ссудная госпошлина пропадала.
    """
    ф = поля(analyzer, ВЗЫСКАТЬ)
    assert ф.get("forfeit") == "14 457,47", "госпошлина снова приклеилась к неустойке"


def test_составная_подпись_решается_ведущим_словом(analyzer):
    """Сторож на обратную ошибку: в «неустойку/штраф» решает ПЕРВОЕ слово.

    Первая редакция правки брала слово, ближайшее к числу, и 384 руб. уходили
    в штрафы, а неустойка обнулялась (свежие-24, свежие-25 покраснели).
    """
    текст = ШАПКА + (
        "ПРОШУ: Включить в реестр требований кредиторов Должника требование "
        "ООО ПКО «Вернём» в размере 20 304 руб. из которых: сумма основного "
        "долга 8 000 руб., задолженность по процентам 9 920 руб., судебные "
        "расходы в размере 2 000 руб., неустойку/штраф в размере 384 руб.\n"
    )
    ф = поля(analyzer, текст)
    assert ф.get("forfeit") == "384,00", "ведущее слово подписи перестало решать"


# --- банкротная из шапки --------------------------------------------------------

def test_банкротная_из_шапки(analyzer):
    текст = (
        "Арбитражный суд Ростовской области\n"
        "Заявитель: Банк ВТБ (ПАО)\n"
        "Должник: ПЕТРОВ ПЁТР ПЕТРОВИЧ\n"
        "РАЗМЕР ТРЕБОВАНИЙ: 10 182.19 рублей\n"
        "ГОСПОШЛИНА: 5 000.00 рублей\n"
        "ЗАЯВЛЕНИЕ о включении требований в реестр требований кредиторов\n"
        "ПРОШУ:\n"
        "1. Включить требования Банка ВТБ (ПАО) в третью очередь в размере "
        "10 182.19 рублей, из которых: 8 624,19 руб. – основной долг, "
        "1 558,00 руб. – госпошлина.\n"
        "2. Взыскать с должника в пользу Банка ВТБ (публичное акционерное "
        "общество) расходы по уплате государственной пошлины за подачу "
        "настоящего заявления в размере 5 000.00 рублей.\n"
    )
    ф = поля(analyzer, текст)
    assert ф.get("stateDuty") == "5 000,00"
    assert ф.get("loanStateDuty17") == "1 558,00"



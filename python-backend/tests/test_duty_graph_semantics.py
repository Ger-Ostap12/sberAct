# --- ворота: заполненную графу не пересчитываем ---------------------------------

def test_заполненную_графу_не_пересчитываем(analyzer):
    """Ворота, а не запрет.

    Банкротная, собранная из двух слагаемых («1 490 913 руб.+ 100 000 руб.»),
    должна остаться суммой: смысловой слой не имеет права её переписать
    одним слагаемым, иначе ломаются зелёные ожидания класса «госпошлина».
    """
    ф = {"stateDuty16": "1 590 913,00", "stateDuty": "1 590 913,00",
         "totalDebt": "501 365 000,90"}
    analyzer._resolve_duty_graphs(
        ф,
        "Сумма требования: 501 365 000,9 руб., Госпошлина: 1 490 913 руб.+ "
        "100 000 руб.\nВзыскать с должника расходы по уплате государственной "
        "пошлины в размере 1 490 913 рублей.\n",
    )
    assert ф["stateDuty"] == "1 590 913,00"


def test_мелочь_не_считается_пошлиной(analyzer):
    """Меньше сотни — это номер пункта или мусор, а не пошлина."""
    ф = {}
    analyzer._resolve_duty_graphs(
        ф, "Взыскать расходы по уплате государственной пошлины в размере 2 рублей.\n")
    assert not ф.get("stateDuty")


def test_без_признаков_ничего_не_меняем(analyzer):
    """Нет смысловых признаков — поля остаются как были."""
    ф = {"stateDuty": "7 777,00", "loanStateDuty17": "1 111,00"}
    analyzer._resolve_duty_graphs(ф, "Текст без упоминания пошлины вовсе.\n")
    assert ф == {"stateDuty": "7 777,00", "loanStateDuty17": "1 111,00"}

# -*- coding: utf-8 -*-
"""Дата публикации на ЕФРСБ через «от» и номер сообщения (22.09.2026, ф.6 п.3).

Все пять паттернов поля `efirsbPublicationDate` требовали дату ВПЛОТНУЮ к
слову «ЕФРСБ». Пять заявлений корпуса уходили с пустым полем, и две пары
документов различались ровно ОДНИМ СЛОВОМ:

    корпус-51  …опубликовано на сайте ЕФРСБ ОТ 02.12.2025   -> пусто
    корпус-53  …опубликовано на сайте ЕФРСБ 02.02.2026      -> верно

Это одна и та же форма ФНС. Остальные три документа вставляют между «ЕФРСБ»
и датой номер сообщения: «ЕФРСБ № 365421146 от …», «ЕФРСБ - Сообщение
№ 22660261 от …», «ЕФРСБ имеется сообщение №35315847 от …».

⚠️ Слово «закон» в разрыв не пускается: «опубликовано на ЕФРСБ согласно
Закона от 26.10.2002 № 127-ФЗ» иначе положило бы в поле дату закона.
В корпусе такой записи НЕТ — защита проверяется только здесь.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _дата(analyzer, текст):
    """Дата публикации так, как её увидит форма."""
    результат = analyzer.analyze_from_text(текст) or {}
    return (результат.get("fields") or {}).get("efirsbPublicationDate")


ШАПКА = (
    "Арбитражный суд Ростовской области\n"
    "Кредитор: ПАО «Сбербанк России»\n"
    "Должник: Иванов Иван Иванович\n"
    "Дело № А53-11111/2026\n"
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
)


# --- предлог «от» между «ЕФРСБ» и датой ---------------------------------------

@pytest.mark.parametrize("фраза, ждём", [
    # корпус-51 и корпус-54: форма ФНС, отличается от зелёной одним словом
    ("Сообщение о введении процедуры реструктуризации долгов гражданина "
     "опубликовано на сайте ЕФРСБ от 02.12.2025.", "02.12.2025"),
    # корпус-0: номер сообщения без слова «Сообщение»
    ("Сообщением на ЕФРСБ № 365421146 от 05.06.2026 ликвидатор уведомил "
     "о намерении обратиться в арбитражный суд.", "05.06.2026"),
    # корпус-25: тире и слово «Сообщение» перед номером
    ("Сообщение о введении процедуры реализации имущества опубликовано "
     "на ЕФРСБ - Сообщение № 22660261 от 28.04.2026 г.", "28.04.2026"),
    # корпус-31: «имеется сообщение», после даты время и часовой пояс
    ("По данным сайта ЕФРСБ имеется сообщение №35315847 от 15.04.2026 "
     "11:01 МСК.", "15.04.2026"),
])
def test_дата_через_предлог_и_номер(analyzer, фраза, ждём):
    assert _дата(analyzer, ШАПКА + фраза + "\n") == ждём


# --- формы без предлога сохраняют приоритет -----------------------------------

@pytest.mark.parametrize("фраза, ждём", [
    ("Сообщение о введении процедуры реструктуризация долгов гражданина, "
     "опубликовано на сайте ЕФРСБ 02.02.2026.", "02.02.2026"),
    ("Сообщение опубликовано на сайте ЕФРСБ 05.02.2026.", "05.02.2026"),
])
def test_дата_вплотную_не_сломана(analyzer, фраза, ждём):
    assert _дата(analyzer, ШАПКА + фраза + "\n") == ждём


def test_форма_без_предлога_побеждает(analyzer):
    """Новый паттерн стоит последним: дата вплотную важнее более поздней «от»."""
    текст = ШАПКА + (
        "Сообщение опубликовано на сайте ЕФРСБ 02.02.2026 по требованию "
        "кредитора от 15.03.2026 в установленном порядке.\n")
    assert _дата(analyzer, текст) == "02.02.2026"


# --- чего брать НЕ должен -----------------------------------------------------

def test_дата_закона_не_подставляется(analyzer):
    """«ЕФРСБ согласно Закона от 26.10.2002» — это дата закона, не публикации."""
    текст = ШАПКА + ("Сведения размещаются на ЕФРСБ согласно Закона "
                     "от 26.10.2002 № 127-ФЗ о несостоятельности.\n")
    assert _дата(analyzer, текст) != "26.10.2002"


def test_дата_за_точкой_не_берётся(analyzer):
    """Разрыв не пересекает точку: за ней уже другое предложение."""
    текст = ШАПКА + ("Сведения размещены на ЕФРСБ. Договор заключен "
                     "от 26.10.2002 между сторонами.\n")
    assert _дата(analyzer, текст) != "26.10.2002"


def test_без_упоминания_ефрсб_поля_нет(analyzer):
    текст = ШАПКА + "Требование заявлено от 02.12.2025 в установленный срок.\n"
    assert _дата(analyzer, текст) != "02.12.2025"

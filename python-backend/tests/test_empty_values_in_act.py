"""Пустые значения в акте банкротства: полное название сторон, вырезание необязательных
реквизитов и нулевых сумм, звёздочки на месте остальных пустых маркеров."""

import os
import sys

import pytest
from docx import Document
from docx.oxml.ns import qn

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from document_generator import DocumentGenerator  # noqa: E402
from org_normalizer import abbreviate_org_name, has_own_legal_form  # noqa: E402
from text_case import normalize_org_case  # noqa: E402


@pytest.fixture
def gen():
    return DocumentGenerator()


def акт(gen, абзацы, **поля):
    doc = Document()
    for текст in абзацы:
        doc.add_paragraph(текст)
    данные = {
        "caseNumber": "А53-1234/2026",
        "judge": "Ерёмин Ф.Ф.",
        "date": "17.07.2026",
        "creditorName": "ООО ПКО «ФИЛБЕРТ»",
        "applicantName": "Сафина Рушания Ильдаровна",
        "applicantNameGenitive": "Сафиной Рушании Ильдаровны",
        "entityType": "individual",
        "obligations": [],
    }
    данные.update(поля)
    gen.replace_document_data(doc, данные)
    return doc


def текст(doc):
    return "\n".join(p.text for p in doc.paragraphs)


def выделенные(doc):
    return [
        "".join(t.text for t in r.iter(qn("w:t")))
        for r in doc.element.body.iter(qn("w:r"))
        if r.find(qn("w:rPr") + "/" + qn("w:highlight")) is not None
    ]


class TestНазваниеОрганизации:
    @pytest.mark.parametrize("было, стало", [
        ("Общество с ограниченной ответственностью «ОРГТЕХНИКА»", "ООО «ОРГТЕХНИКА»"),
        ("Общество с ограниченной ответственностью Профессиональная коллекторская организация «ФИЛБЕРТ»",
         "ООО ПКО «ФИЛБЕРТ»"),
        ("Публичное акционерное общество «Сбербанк России»", "ПАО «Сбербанк России»"),
        ("ООО ПКО «ФИЛБЕРТ»", "ООО ПКО «ФИЛБЕРТ»"),
        ("ПАО Сбербанк", "ПАО Сбербанк"),
    ])
    def test_сокращение_правовой_формы(self, было, стало):
        assert abbreviate_org_name(было) == стало

    def test_признак_своей_правовой_формы(self):
        assert has_own_legal_form("ООО ПКО «ФИЛБЕРТ»")
        assert has_own_legal_form("ПАО Сбербанк")
        assert not has_own_legal_form("Сбербанк")

    def test_правовая_форма_остаётся_при_правке_регистра(self):
        assert normalize_org_case("ООО ПКО «ФИЛБЕРТ»") == "ООО ПКО «Филберт»"

    def test_кредитор_полностью_и_без_двойных_кавычек(self, gen):
        doc = акт(gen, ["ознакомившись с заявлением «[989]» (ИНН 1).",
                        "[989] обратилось с заявлением.",
                        "в пользу публичного акционерного общества «[989]» судебные расходы."])
        t = текст(doc)
        assert "заявлением ООО ПКО «Филберт» (ИНН 1)" in t
        assert "ООО ПКО «Филберт» обратилось" in t
        assert "в пользу ООО ПКО «Филберт» судебные" in t
        assert "«ООО" not in t and "общества «" not in t

    def test_должник_юл_полностью(self, gen):
        doc = акт(gen, ["в отношении общества с ограниченной ответственностью «[2]» введена процедура.",
                        "должника [2] (ОГРН [3])."],
                  entityType="legal",
                  debtorName="Общество с ограниченной ответственностью «ОРГТЕХНИКА»",
                  applicantName="Общество с ограниченной ответственностью «ОРГТЕХНИКА»",
                  birthDate="1026100000001")
        t = текст(doc)
        assert "в отношении ООО «Оргтехника» введена" in t
        assert "должника ООО «Оргтехника» (ОГРН 1026100000001)" in t

    def test_сро_с_заглавной_и_без_кавычек_шаблона(self, gen):
        doc = акт(gen, ["Заявитель просил утвердить финансового управляющего из числа членов «[987]»."],
                  sroName="саморегулируемой организации арбитражных управляющих Союз АУ «Созидание»")
        assert ("из числа членов Саморегулируемой организации арбитражных управляющих "
                "Союз АУ «Созидание».") in текст(doc)


class TestРеквизитыДолжника:
    def test_пустая_дата_рождения_уходит_с_подписью(self, gen):
        doc = акт(gen, ["о банкротстве [2.1] ([3] года рождения, место рождения: [3.1], ИНН [4], "
                        "адрес регистрации: [6])."],
                  inn="616100000001", applicantAddress="г. Ростов-на-Дону")
        assert "Сафиной Рушании Ильдаровны (ИНН 616100000001, адрес регистрации: г. Ростов-на-Дону)" in текст(doc)

    def test_пустые_скобки_не_остаются(self, gen):
        doc = акт(gen, ["в отношении должника - [2.1] ([3] года рождения) сведения."])
        assert "Сафиной Рушании Ильдаровны сведения" in текст(doc)

    def test_пустой_огрн_юл_помечается(self, gen):
        doc = акт(gen, ["должника [2] (ОГРН [3], ИНН [4])."], entityType="legal",
                  debtorName="ООО «Ромашка»", applicantName="ООО «Ромашка»", inn="6161")
        assert "******" in выделенные(doc)


class TestСуммы:
    ПЕРЕЧЕНЬ = ("задолженности в размере [12] руб., из них: [13] руб. – основной долг, [14] руб. – проценты, "
                "[15] руб. – штрафы, пени, неустойки, [35] руб. – дополнительные услуги.")

    def test_нулевые_и_пустые_статьи_вырезаются(self, gen):
        doc = акт(gen, [self.ПЕРЕЧЕНЬ], totalDebt="1 782 415,10", principalDebt="729 102,73",
                  interest="1 036 285,43", forfeit="0", other35="")
        assert ("задолженности в размере 1 782 415,10 руб., из них: 729 102,73 руб. – основной долг, "
                "1 036 285,43 руб. – проценты.") in текст(doc)

    def test_первая_статья_нулевая(self, gen):
        doc = акт(gen, [self.ПЕРЕЧЕНЬ], totalDebt="100", principalDebt="0",
                  interest="60", forfeit="40", other35="0")
        assert "из них: 60 руб. – проценты, 40 руб. – штрафы, пени, неустойки." in текст(doc)

    def test_родительный_падеж_после_суммы(self, gen):
        doc = акт(gen, ["Требование в размере [13] руб. основного долга, [14] руб. процентов, "
                        "[15] руб. неустойки следует включить в реестр."],
                  principalDebt="100", interest="0", forfeit="5")
        assert "Требование в размере 100 руб. основного долга, 5 руб. неустойки следует включить" in текст(doc)

    def test_предложение_о_неустойке_уходит_целиком(self, gen):
        doc = акт(gen, ["Первое. В соответствии с п. 3 ст. 137 Федерального закона от 26.10.2002 № 127-ФЗ "
                        "требования об установлении [15] руб. неустойки учесть отдельно в реестре. Последнее."],
                  forfeit="0")
        assert текст(doc).strip() == "Первое. Последнее."

    def test_госпошлина_в_перечне_и_отдельно(self, gen):
        doc = акт(gen, ["из них: [13] руб. – основной долг, [14] руб. – проценты; о взыскании с должника "
                        "государственной пошлины в размере [16] руб.",
                        "Начало. Судебные расходы по уплате государственной пошлины в размере [16] рубля "
                        "учесть в реестре."],
                  principalDebt="10", interest="5")
        t = текст(doc)
        assert "из них: 10 руб. – основной долг, 5 руб. – проценты." in t
        assert "Судебные расходы" not in t and "Начало." in t


class TestЗвёздочки:
    def test_пустой_обязательный_маркер_выделен(self, gen):
        doc = акт(gen, ["Установить срок для рассмотрения заявления до [19] включительно."])
        assert "до ****** включительно" in текст(doc)
        assert выделенные(doc) == ["******"]
        hl = next(doc.element.body.iter(qn("w:highlight")))
        assert hl.get(qn("w:val")) == "brightGreen"

    def test_публикация_пустая_целиком_помечается(self, gen):
        doc = акт(gen, ["опубликованы [на сайте ЕФРСБ №[9] от [11]] в газете «Коммерсантъ» № [67] от [68]."])
        assert len(выделенные(doc)) == 2

    def test_публикация_есть_в_коммерсанте(self, gen):
        doc = акт(gen, ["опубликованы [на сайте ЕФРСБ №[9] от [11]] в газете «Коммерсантъ» № [67] от [68]."],
                  kommersantNumber="77", kommersantDate="01.02.2026")
        assert выделенные(doc) == []
        assert "«Коммерсантъ» № 77 от 01.02.2026" in текст(doc)

    def test_номер_дела_без_повторной_приставки(self, gen):
        doc = акт(gen, ["Дело № А53-[1]/[22]"])
        assert "Дело № А53-1234/2026" in текст(doc)
        assert выделенные(doc) == []

    def test_точка_после_инициалов_судьи(self, gen):
        doc = акт(gen, ["в составе судьи [415]., ознакомившись"])
        assert "судьи Ерёмина Ф.Ф., ознакомившись" in текст(doc)

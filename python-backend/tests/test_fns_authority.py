# -*- coding: utf-8 -*-
"""Тесты ФНС-детекта уполномоченного органа и определения должника (_apply_fns_authority).

Покрывают дефекты OCR-копий заявлений «о включении в РТК»:
  • шапка обобщённая (бланк ФНС ушёл в тело/подвал) → детект по ТЕЛУ (ИФНС +
    «обязательных платежей»);
  • позиционный парсер берёт арбитражного управляющего/мусор как должника →
    надёжный должник по якорю «<ФИО> обратился в суд» / «Должник: <ФИО> ИНН»;
  • правило Андрея: ФИО должника ≠ ФИО арбитражного управляющего (дедуп).
"""
import pytest
from document_analyzer import DocumentAnalyzer


@pytest.fixture(scope="module")
def da():
    return DocumentAnalyzer()


def test_body_detection_and_debtor_anchor_and_dedup(da):
    # Шапка «ЗАЯВЛЕНИЕ о включении в РТК ФИО» — БЕЗ бланка ФНС в первых 400 символах.
    # ФНС опознаётся по телу (ИФНС + обязательные платежи). Должник берётся по якорю
    # «<ФИО> обратился», а не позиционный «Колос» (= арбитражный управляющий).
    text = (
        "ЗАЯВЛЕНИЕ\nо включении требований кредитора в реестр требований кредиторов "
        "Артемова Игоря Геннадьевича ИНН 615004049577\n"
        "Артемов Игорь Геннадьевич обратился в Арбитражный суд Ростовской области с "
        "заявлением о признании несостоятельным (банкротом). Решением суда в отношении "
        "должника введена процедура реализации имущества. Финансовым управляющим "
        "утверждена Колос Екатерина Александровна.\n"
        "Межрайонной ИФНС России № 13 по Ростовской области за должником числится "
        "задолженность по уплате обязательных платежей."
    )
    fields = {
        "debtorName": "Колос Екатерина Александровна",
        "applicantName": "Колос Екатерина Александровна",
        "managerName": "Колос Екатерина Александровна",
    }
    da._apply_fns_authority(fields, text)
    assert "фнс" in (fields.get("creditorName") or "").lower()      # детект по телу
    assert fields["debtorName"] == "Артемов Игорь Геннадьевич"      # якорь > управляющего
    assert fields["managerName"] == "Колос Екатерина Александровна"  # управляющий цел
    assert fields["debtorName"] != fields["managerName"]            # дедуп


def test_debtor_anchor_dolzhnik_label_caps(da):
    # Заявление уполномоченного органа: должник — в метке «Должник: <ФИО CAPS> ИНН»,
    # а позиционный парсер дал мусор «А И Кредиторов». Берём метку, снимаем CAPS.
    text = (
        "Заявление уполномоченного органа о признании ЗАЙЦЕВА ВИТАЛИЯ ВЛАДИМИРОВИЧА "
        "несостоятельным (банкротом)\nФедеральная налоговая служба ... по уплате "
        "обязательных платежей ... Межрайонная ИФНС России № 13 по Ростовской области.\n"
        "Должник: ЗАЙЦЕВ ВИТАЛИЙ ВЛАДИМИРОВИЧ ИНН 613205503003 ОГРНИП 318619600012345"
    )
    fields = {"debtorName": "А И Кредиторов", "applicantName": "А И Кредиторов"}
    da._apply_fns_authority(fields, text)
    assert fields["debtorName"] == "Зайцев Виталий Владимирович"


def test_dedup_without_anchor_clears_duplicate(da):
    # Якоря должника нет, но должник == управляющий → это заведомо ошибка: дубль
    # убирается, чтобы ФИО управляющего не ушло в акт как должник.
    text = (
        "МИНФИН РОССИИ ФЕДЕРАЛЬНАЯ НАЛОГОВАЯ СЛУЖБА\nМежрайонная ИФНС России № 13 по "
        "Ростовской области ... задолженность по уплате обязательных платежей ..."
    )
    fields = {
        "debtorName": "Иванов Иван Иванович",
        "managerName": "Иванов Иван Иванович",
    }
    da._apply_fns_authority(fields, text)
    assert not fields.get("debtorName")  # дубль управляющего очищен


def test_manager_anchor_and_address(da):
    # ФИО управляющего теряется общим парсером из-за OCR-артефакта «На №» и строчной
    # «утверждён»; берём по якорю «управляющим утверждён <ФИО>». Адрес управляющего —
    # с меткой «Адрес для корреспонденции» и хвостом «а/я N» (не обрезаем).
    text = (
        "ЗАЯВЛЕНИЕ\nо включении требований кредитора в реестр требований кредиторов "
        "Мишунина Ивана Александровича ИНН 366517949240\n"
        "Мишунин Иван Александрович обратился в Арбитражный суд. Финансовым управляющим "
        "утвержден Котова Елена Сергеевна.\nМежрайонная ИФНС России № 26 по Ростовской "
        "области по уплате обязательных платежей.\n"
        "Финансовый управляющий: На № Котова Елена Сергеевна Адрес для корреспонденции: "
        "350075, г.Краснодар, а/я 4426 Должник: Мишунин Иван Александрович"
    )
    fields = {"managerName": None}
    da._apply_fns_authority(fields, text)
    assert fields["managerName"] == "Котова Елена Сергеевна"        # якорь «утверждён»
    assert fields["managerAddress"] == "350075, г.Краснодар, а/я 4426"  # хвост «а/я» цел
    assert fields["debtorName"] == "Мишунин Иван Александрович"     # должник ≠ управляющий


def test_non_fns_not_touched(da):
    # Нет ни бланка в шапке, ни связки «ИФНС + обязательные платежи» → не ФНС.
    text = ("ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов должника. "
            "ПАО Сбербанк, кредитный договор, задолженность по кредиту.")
    fields = {"creditorName": "ПАО Сбербанк", "debtorName": "Петров Пётр Петрович"}
    da._apply_fns_authority(fields, text)
    assert fields["creditorName"] == "ПАО Сбербанк"      # не перезаписан на ФНС
    assert fields["debtorName"] == "Петров Пётр Петрович"

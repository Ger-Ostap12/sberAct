# -*- coding: utf-8 -*-
"""Тесты ФНС-финансов по ОЧЕРЕДЯМ реестра требований (парсер _apply_fns_queue_finances).

Пиновка поведения на представительных фрагментах реального корпуса
(`Заявления/Заявления на проверку/`), чтобы будущие правки не сломали разводку по
очередям и маппинг категорий. Схема полей и маппинг — память fns-queue-finances.

Краевые случаи: OCR «py6.» вместо «руб.»; знак взносов игнорируем; очередь-по-умолчанию=3;
«налог» и «основной долг» → одно поле LoanDebt; госпошлина внутри очереди → LoanDuty;
недоимка (явное слово) → отдельное поле Arrears; гейт (не-ФНС не трогаем).
"""
import pytest
from document_analyzer import DocumentAnalyzer

FNS_CRED = "ФНС России в лице Межрайонной ИФНС России № 13 по Ростовской области"


@pytest.fixture(scope="module")
def da():
    return DocumentAnalyzer()


def _run(da, text, creditor=FNS_CRED, **extra):
    """Прогоняет ФНС-парсер финансов; возвращает fields с нормализованными
    неразрывными пробелами (для наглядных ассертов)."""
    fields = {"creditorName": creditor}
    fields.update(extra)
    da._apply_fns_queue_finances(fields, text)
    return {k: (v.replace(" ", " ") if isinstance(v, str) else v)
            for k, v in fields.items()}


# --- Очередь не указана → 3-я; OCR «py6.»; разделитель-дефис «штраф -0,00» --------
def test_default_queue_three_and_ocr_and_dash(da):
    text = ("признать требование ФНС России обоснованным, включить в реестр требований "
            "кредиторов Артемова Игоря Геннадьевича сумму задолженности по уплате "
            "обязательных платежей в сумме 855,35py6., пени - 24,35руб., штраф -0,00руб.")
    f = _run(da, text)
    assert f["fnsQ3Total"] == "855,35"
    assert f["fnsQ3Forfeit"] == "24,35"       # пени
    assert f["fnsQ3Penalties"] == "0,00"      # штраф; ведущий «-» — разделитель, не минус
    assert f["totalDebt"] == "855,35"
    # других очередей нет
    assert not any(k.startswith("fnsQ1") or k.startswith("fnsQ2") for k in f)


# --- НДФЛ + страховые взносы (2 очередь) + осн.долг/пени/штраф (3 очередь) ---
def test_ndfl_insurance_and_queue3(da):
    text = ("Установить требования ФНС России в размере 71145066,58руб., в том числе: "
            "- во вторую очередь реестра требования кредиторов задолженность в размере "
            "104786,66 руб., в т.ч. по НДФЛ – 8390,27 руб., по страховым взносам – "
            "-96396,39 руб.; - в третью очередь реестра требований кредиторов "
            "задолженность в размере 71040279,92 руб., в том числе основной долг – "
            "50811691,40 руб., пени – 16242223,52 руб., штраф – 3986365,00 руб.")
    f = _run(da, text)
    assert f["totalDebt"] == "71 145 066,58"
    assert f["fnsQ2Total"] == "104 786,66"
    assert f["fnsQ2Ndfl"] == "8 390,27"
    # Минус — артефакт разделителя «– -96396,39»; суммы ФНС всегда положительны
    # (правило Андрея). С плюсом очередь сходится: 8 390,27 + 96 396,39 = 104 786,66.
    assert f["fnsQ2Insurance"] == "96 396,39"
    assert f["fnsQ3Total"] == "71 040 279,92"
    assert f["fnsQ3LoanDebt"] == "50 811 691,40"  # «основной долг»
    assert f["fnsQ3Forfeit"] == "16 242 223,52"   # пени
    assert f["fnsQ3Penalties"] == "3 986 365,00"  # штраф


# --- «налог» → тоже LoanDebt; порядок очередей в тексте 3→2 ------------------------
def test_nalog_maps_to_loan_debt(da):
    text = ("включить в реестр требований -в третью очередь – 4 270 589,08 руб., "
            "из них: налог - 2 045 779,00 руб., пени - 224 810,08 руб. "
            "-во вторую очередь - 3 131 130,79 руб., из них: налог 3 131 130,79 руб.;")
    f = _run(da, text)
    assert f["fnsQ3Total"] == "4 270 589,08"
    assert f["fnsQ3LoanDebt"] == "2 045 779,00"   # «налог» → ссудная задолженность
    assert f["fnsQ3Forfeit"] == "224 810,08"
    assert f["fnsQ2Total"] == "3 131 130,79"
    assert f["fnsQ2LoanDebt"] == "3 131 130,79"


# --- Цифровая форма очереди «3-ой очереди» + госпошлина → LoanDuty -----------------
def test_digit_queue_and_gosposhlina(da):
    text = ("включить как кредитора 3-ой очереди по уплате обязательных платежей в "
            "размере 1503756.77py6., в том числе налог 745735.35 руб., пени 684091.42 "
            "руб., штраф 71322.00 руб., госпошлина - 2608.00 руб.")
    f = _run(da, text)
    assert f["fnsQ3Total"] == "1 503 756,77"
    assert f["fnsQ3LoanDebt"] == "745 735,35"
    assert f["fnsQ3Forfeit"] == "684 091,42"
    assert f["fnsQ3Penalties"] == "71 322,00"
    assert f["fnsQ3LoanDuty"] == "2 608,00"       # госпошлина внутри очереди


# --- Недоимка (явное слово) → отдельное поле Arrears -------------------------------
def test_nedoimka_arrears(da):
    text = ("включить в реестр требований в третью очередь в размере 1020,12 руб., "
            "в том числе: недоимка – 1020,12 руб.")
    f = _run(da, text)
    assert f["fnsQ3Total"] == "1 020,12"
    assert f["fnsQ3Arrears"] == "1 020,12"
    assert "fnsQ3LoanDebt" not in f            # «недоимка» ≠ «налог/осн.долг»


# --- Гейт: не-ФНС кредитор не трогаем (никаких fnsQ*, общий блок сохранён) ---------
def test_gate_non_fns_untouched(da):
    text = ("включить в реестр требований в третью очередь в размере 1020,12 руб., "
            "в том числе: основной долг – 1020,12 руб.")
    f = _run(da, text, creditor="ПАО Сбербанк", principalDebt="1 020,12")
    assert not any(k.startswith("fnsQ") for k in f)
    assert f["principalDebt"] == "1 020,12"    # общий блок НЕ очищен на не-ФНС


# --- Грандтотал «в общей сумме N» → берём из документа, НЕ помечаем computed --------
def test_grandtotal_obshchey_summe(da):
    text = ("включить в реестр требований в общей сумме 187 348,68 руб., в том числе "
            "во вторую очередь в сумме 153 398,37 руб., в третью очередь в сумме "
            "33 950,31 руб., в том числе: основной долг – 1 312,40 руб., пени – "
            "27 087,91 руб., штрафы- 5 550,00 рублей.")
    f = _run(da, text)
    assert f["totalDebt"] == "187 348,68"          # «в общей сумме» распознан
    assert "fnsTotalComputed" not in f             # взято из документа, не вычислено
    assert f["fnsQ2Total"] == "153 398,37"
    assert f["fnsQ3Total"] == "33 950,31"


# --- Грандтотал «N руб., в том числе» без «в размере/сумме» + OCR-разрыв тысяч точкой
def test_grandtotal_v_tom_chisle_ocr(da):
    text = ("ПРОСИТ: ... 7. 267 312,82 рублей, в том числе.\n"
            "-во вторую очередь - 3 131 130,79 руб., из них: налог 3 131 130,79 руб.;\n"
            "-в третью очередь – 4 270 589,08 руб., из них: налог - 2 045 779,00 руб., "
            "пени - 2 118 547,65 руб., штрафы – 105 555,43 руб., госпошлина 707,00 руб.;")
    f = _run(da, text)
    assert f["totalDebt"] == "7 267 312,82"        # OCR «7. 267 312,82» → 7 267 312,82
    assert "fnsTotalComputed" not in f
    # сумма очередей (7 401 719,87) ≠ тоталу из документа — это ловит сверка (⚠), но
    # значение берётся из документа как есть (приоритет документа над вычислением).


# --- ФНС-режим чистит скрытый общий блок финансов ---------------------------------
def test_fns_clears_general_fields(da):
    text = ("включить в реестр требований в третью очередь в размере 1020,12 руб., "
            "в том числе: основной долг – 1020,12 руб.")
    f = _run(da, text, principalDebt="999,99", interest="1,00", stateDuty16="7,00")
    assert "principalDebt" not in f
    assert "interest" not in f
    assert "stateDuty16" not in f              # банкротной ГП у ФНС нет
    assert f["fnsQ3LoanDebt"] == "1 020,12"

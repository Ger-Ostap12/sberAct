# -*- coding: utf-8 -*-
"""Чужие ОГРН и ИНН у должника (08.09.2026).

Два источника протечки, и первый опаснее, чем кажется.

1. Саморегулируемая организация управляющего. Её реквизиты стоят вплотную к
   его ФИО: «член САУ «Авангард» (ИНН 7705479434 ОГРН 1027705031320 …)».
   Дело не только в лишнем поле: `detect_entity_type` считает тринадцать цифр
   ОГРН доказательством юрлица и перебивает ФИО — четыре свежих заявления
   объявляли гражданина организацией.

2. Третье лицо. В военной ипотеке ОГРН ФГКУ «Росвоенипотека», в ДДУ — ИНН
   Управления Росреестра.

Оба якоря пришлось сузить дважды, и оба раза из-за реальных документов:

    «член» без метки СРО    в просительной части стоит «из числа членОВ
                            которой будет утвержден управляющий Общества …
                            «Перспектива» ОГРН: …, ИНН: …» — и это реквизиты
                            САМОГО ДОЛЖНИКА
    окно без обрезки        перепрыгивало в следующий пункт: «…оф.14;
                            5. взыскать с Общества … ОГРН …»
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from parties_mixin import PartiesMixin  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- реквизиты СРО -----------------------------------------------------------

@pytest.mark.parametrize("текст, ждём", [
    ("Финансовым управляющим утвержден Ширшов Дмитрий Игоревич член САУ "
     "«Авангард» (ИНН 7705479434 ОГРН 1027705031320 рег.номер 005, адрес: Москва)",
     {"7705479434", "1027705031320"}),
    ("-член Ассоциации «Дальневосточная межрегиональная саморегулируемая "
     "организация профессиональных арбитражных управляющих» ОГРН 1032700295099, "
     "ИНН 2721099166, адрес",
     {"1032700295099", "2721099166"}),
    ("член Ассоциации профессиональных арбитражных управляющих «Гарант» "
     "(ОГРН 1237700565332, ИНН 7730309884, адрес)",
     {"1237700565332", "7730309884"}),
])
def test_реквизиты_сро_опознаются(текст, ждём):
    assert PartiesMixin._sro_requisites(текст) == ждём


def test_членов_которой_это_не_членство():
    """Просительная часть: за «членов» идут реквизиты САМОГО ДОЛЖНИКА."""
    текст = ("3. утвердить саморегулируемую организацию, из числа членов которой "
             "будет утвержден временный управляющий Общества с ограниченной "
             "ответственностью «Перспектива» ОГРН: 1107746649625, ИНН: 7701887506 "
             "посредством случайного выбора;")
    assert PartiesMixin._sro_requisites(текст) == set()


def test_окно_обрывается_на_границе_пункта():
    """За реквизитами СРО идёт следующий пункт — его реквизиты не наши."""
    текст = ("утвердить из числа членов Ассоциации МСРО «Содействие» "
             "ОГРН: 1025700780071, ИНН: 5752030226, 302004, Орловская область, "
             "г. Орел, ул. 3-я Курская, д.15, оф.14; "
             "5. взыскать с Общества с ограниченной ответственностью «Форте Пром» "
             "ОГРН 1103461000455, ИНН 3448049188 расходы")
    найдено = PartiesMixin._sro_requisites(текст)
    assert "1025700780071" in найдено and "5752030226" in найдено
    assert "3448049188" not in найдено, "ИНН должника объявлен чужим"
    assert "1103461000455" not in найдено, "ОГРН должника объявлен чужим"


def test_реквизит_сро_снимается_с_должника(analyzer):
    поля = {"ogrn": "1237700565332", "inn": "612504512780"}
    текст = ("член Ассоциации профессиональных арбитражных управляющих «Гарант» "
             "(ОГРН 1237700565332, ИНН 7730309884)")
    analyzer._drop_sro_requisites_from_debtor(поля, текст)
    assert "ogrn" not in поля
    assert поля["inn"] == "612504512780", "свой ИНН трогать нельзя"


# --- ОГРН у гражданина -------------------------------------------------------

def test_у_гражданина_огрн_не_бывает(analyzer):
    поля = {"entityType": "individual", "ogrn": "1067781337095"}
    карточки = [{"name": "Жевнин Магомед Тимурович", "ogrn": "1067781337095"}]
    analyzer._drop_ogrn_for_person(поля, карточки)
    assert "ogrn" not in поля
    assert not карточки[0]["ogrn"], "в карточке ОГРН тоже чужой"


def test_у_юрлица_огрн_остаётся(analyzer):
    поля = {"entityType": "legal", "ogrn": "1103461000455"}
    analyzer._drop_ogrn_for_person(поля, [{"ogrn": "1103461000455"}])
    assert поля["ogrn"] == "1103461000455"


# --- ИНН гражданина ----------------------------------------------------------

def test_инн_организации_у_гражданина_меняется_на_свой(analyzer):
    """ДДУ: в плоском поле ИНН Управления Росреестра, в карточке — свой."""
    поля = {"entityType": "individual", "inn": "2309090540",
            "companyInn": "2309090540"}
    analyzer._drop_ogrn_for_person(поля, [{"inn": "280111111111"}])
    assert поля["inn"] == "280111111111"
    assert поля["companyInn"] == "280111111111"


def test_склейка_инн_нескольких_должников_остаётся(analyzer):
    """Ипотека: плоское поле — список созаёмщиков, а карточка только первая."""
    склейка = "644986285759, 644122681613"
    поля = {"entityType": "individual", "inn": склейка, "companyInn": склейка}
    analyzer._drop_ogrn_for_person(поля, [{"inn": "644986285759"}])
    assert поля["inn"] == склейка, "созаёмщик затёрт первой карточкой"


def test_без_карточки_инн_не_трогается(analyzer):
    поля = {"entityType": "individual", "inn": "2309090540"}
    analyzer._drop_ogrn_for_person(поля, [])
    assert поля["inn"] == "2309090540", "заменять не на что"

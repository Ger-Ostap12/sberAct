# Пары «документ × мутация», ломающиеся СЕЙЧАС. Снимаются фазами нормализации:
# double_spaces/nbsp — фазой 2a, quotes — 2b, yo — 2c. В комментарии — поля,
# которые поехали, чтобы при снятии было видно, что именно чинится.
#
# Фаза 1 (контракт поля) сняла две пары: РФЛ1×double_spaces и Медведев×label_case
# ломались ТОЛЬКО через loanDebt, куда мутация переносила кусок другого текста.
# Как только поле перестало принимать не-суммы, мутация на него влиять перестала.
#
# Фаза 2a (нормализация горизонтальных пробелов) сняла ВСЕ пары double_spaces и
# nbsp — по корпусу 42/79 и 5/71 обратились в ноль.
#
# ⚠️ ОСЬ «КАВЫЧКИ» ОСТАЁТСЯ ХРУПКОЙ ОСОЗНАННО (решение Андрея, июль-2026).
# Канонизация кавычек в тексте чинит устойчивость (21/75 -> 0..1 в обе стороны:
# и к «ёлочкам», и к прямым), но ПОРТИТ ИМЯ ДОЛЖНИКА в реальных заявлениях:
# «АО "КОНЦЕРН "САРМАТ" (заемщик)» разбирается как «АО «КОНЦЕРН «САРМАТ»
# (заемщик)»» — паттерны используют символ кавычки как ГРАНИЦУ значения, и подмена
# символа границу ломает. Испорченное имя уезжает в акт, поэтому цена выше выгоды:
# документов с прямыми кавычками, которые бы выиграли, в корпусе нет.
# Правильное лечение — сделать паттерны безразличными к виду кавычек (граница =
# «любая кавычка»); это работа по паттернам, она вне текущего плана.
#
# Ось «ё/е» остаётся хрупкой по той же причине: нормализация вернула бы в поле
# «Петров» вместо «Пётров», а правило Андрея — «текст в поля как в документе».
# Чинится только через span ownership (значение из оригинала по позиции) — фаза 4.
#
# 01.09.2026: пара «умерший сос»×quotes УБРАНА — она никогда не была хрупкостью.
# Расходилось единственное поле `creditorName`, и расходилось РОВНО символом
# кавычки, который переписала сама мутация. Сверка по оси «quotes» теперь идёт с
# приведёнными кавычками (`_canon_quotes`), и такие пары отсеиваются сами.
# Настоящая хрупкость приведение переживает: у «отсутствующий заявление» едут
# `entityType` и падежи имени — там кавычка служит ГРАНИЦЕЙ значения.
KNOWN_BRITTLE = {
    ("НОвая конвертация/Остальные/main_Заявление о включении в РТК - 2 л.docx", "yo"),  # creditorAddress
    ("НОвая конвертация/отсутствующий заявление.docx", "quotes"),  # entityType, applicantName + падежи
}

_analyzer = DocumentAnalyzer()
_base_cache = {}

_QUOTE_CHARS = re.compile(r"[«»“”„‟‘’\"']")


def _canon_quotes(flat: dict) -> dict:
    """Все виды кавычек к одному символу — для сверки по оси «quotes»."""
    return {k: _QUOTE_CHARS.sub('"', v) for k, v in flat.items()}


def _baseline(rel: str):
    """Разбор исходника (кешируется: analyze ~0.7 с, а мутаций на файл шесть)."""
    if rel not in _base_cache:
        path = os.path.join(CORPUS_DIR, rel)
        if not os.path.exists(path):
            pytest.skip(f"нет файла корпуса: {rel}")
        text = _analyzer.extract_text(path)
        _base_cache[rel] = (text, significant_result(_analyzer.analyze_from_text(text, 2)))
    return _base_cache[rel]


@pytest.mark.parametrize("rel", SAMPLE, ids=lambda p: os.path.basename(p)[:40])
@pytest.mark.parametrize("mutation", [m[0] for m in MUTATIONS])
def test_result_survives_cosmetic_mutation(rel: str, mutation: str):
    """Косметика не должна менять извлечённые данные."""
    text, base = _baseline(rel)
    mutate = dict(MUTATIONS)[mutation]
    mutated_text = mutate(text)
    if mutated_text == text:
        pytest.skip("мутация неприменима к этому документу")

    known = (rel, mutation) in KNOWN_BRITTLE
    mutated = significant_result(_analyzer.analyze_from_text(mutated_text, 2))
    if mutation == "quotes":
        # Мутация переписывает САМ СИМВОЛ кавычки, в том числе внутри законных
        # значений: адрес «Автомагистраль «Дон», 9 км» отличается до и после
        # ровно этим — и разбор тут ни при чём. Сверяем поля с приведёнными
        # кавычками, иначе тест ловит собственную мутацию, а не хрупкость.
        # Настоящая хрупкость переживает приведение: там паттерн использует
        # кавычку как ГРАНИЦУ значения, и меняется длина, а не только символ.
        base, mutated = _canon_quotes(base), _canon_quotes(mutated)
    changed = diff_fields(base, mutated)

    if known:
        assert changed, (
            f"Хрупкость «{mutation}» на {rel} ИСЧЕЗЛА — похоже, починено. "
            f"Убери пару из KNOWN_BRITTLE, иначе список перестанет отражать реальность."
        )
    else:
        assert not changed, (
            f"НОВАЯ хрупкость к формату: мутация «{mutation}» изменила поля {changed} "
            f"на {rel}. Документ не изменился по смыслу — значит, разбор зацепился "
            f"за типографику."
        )

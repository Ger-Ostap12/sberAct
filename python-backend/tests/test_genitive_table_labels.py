# -*- coding: utf-8 -*-
"""Метки таблицы в РОДИТЕЛЬНОМ падеже: пункт 6 фазы 4 (09.10.2026), §S.49.

Свежие-1 («0_Заявление ООО ПКО АСВ о включении требования в РТК.docx») печатает
разбивку отдельной таблицей в конце документа, подпись и значение — в разных
строках, подписи в родительном падеже:

```
Основного долга:        Процентов:        Штрафов:
3 950 руб.              5 480,92 руб.     244,08 руб.
```

Почему форму потеряли: паттерны вида «процент[^,\\n]*([0-9\\s,]+)\\s*руб» раньше
перепрыгивали перевод строки, потому что класс `[0-9\\s,]+` включал \\s. Когда
денежный класс ужесточили до MONEY_NUM (начинается с цифры), запись осталась
без читателя вовсе — а табличный читатель знал только именительный падеж.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# Структура повторяет свежие-1: названный итог в теле, разбивка — таблицей
# в конце, и между ними страница прозы.
РОДИТЕЛЬНЫЙ = (
    "Судебным актом от 29.03.2024 г. по делу № 2-1-1248/2024 с Рудаковой "
    "Александры Сергеевны в пользу Кредитора взыскана задолженность по договору "
    "потребительского займа № 1903965846 от 05.05.2023 г. в размере 9 875 "
    "рублей, из них сумма:\n"
    "ПРОШУ:\n"
    "1. Включить в реестр требований кредиторов должника денежное требование "
    "в размере 9 875 руб.\n"
    "Основного долга:\n"
    "3 950 руб.\n"
    "Процентов:\n"
    "5 480,92 руб.\n"
    "Штрафов:\n"
    "244,08 руб.\n"
    "Пени:\n"
    "0 руб.\n"
    "Госпошлины:\n"
    "200 руб.\n"
    "Основного долга просроченного:\n"
    "0 руб.\n"
    "Процентов просроченных:\n"
    "0 руб.\n"
)


@pytest.fixture(scope="module")
def поля(analyzer):
    return analyzer.extract_fields(РОДИТЕЛЬНЫЙ, "rtk_application")


def test_основного_долга_в_родительном(поля):
    assert поля.get("principalDebt") == "3 950,00"


def test_процентов_в_родительном(поля):
    assert поля.get("interest") == "5 480,92"


def test_штрафов_в_родительном(поля):
    assert поля.get("penalties") == "244,08"


def test_названный_итог_не_пересчитан(поля):
    """Разбивка из ПЯТИ граф сходится с итогом — пересчёт по трём занизил бы его.

    3 950,00 + 5 480,92 + 0,00 + 244,08 + 200,00 = 9 875,00

    ⚠️ На СТАРОМ коде этот тест проходит по другой причине: слагаемые там не
    находились вовсе, и сверке было нечего пересчитывать. Сами ворота
    доказывает `test_полная_разбивка_закрывает_пересчёт` — он вызывает сверку
    на готовых полях и на старом коде краснеет.
    """
    assert поля.get("totalDebt") == "9 875,00"


def test_просроченное_не_перебивает_основное(поля):
    """«Основного долга просроченного: 0 руб.» идёт ниже и не должно победить."""
    assert поля.get("principalDebt") != "0,00"


# --- ворота сверки «части = целое» вызываются напрямую ----------------------------

def сверить(analyzer, поля):
    поля = dict(поля)
    analyzer._reconcile_debt_amounts(поля, "", "rtk_application")
    return поля


def test_полная_разбивка_закрывает_пересчёт(analyzer):
    р = сверить(analyzer, {
        "totalDebt": "9 875,00",
        "principalDebt": "3 950,00",
        "interest": "5 480,92",
        "forfeit": "0,00",
        "penalties": "244,08",
        "stateDuty": "200,00",
    })
    assert р.get("totalDebt") == "9 875,00"


def test_пересчёт_работает_когда_разбивка_не_сходится(analyzer):
    """Ворота узкие: мусор в слагаемом по-прежнему ловится сверкой.

    Это защита §S.46 (свежие-18): номер пункта договора попадал в проценты,
    и ЗАКОННАЯ сверка переписывала общий долг. Ломать её нельзя.
    """
    р = сверить(analyzer, {
        "totalDebt": "494 190,08",
        "principalDebt": "400 000,00",
        "interest": "4,50",
        "forfeit": "0,00",
    })
    assert р.get("totalDebt") == "400 004,50"


def test_итог_много_больше_частей_по_прежнему_пересчитывается(analyzer):
    """Сумма ВЫДАЧИ кредита вместо суммы требований — старое правило 1.15."""
    р = сверить(analyzer, {
        "totalDebt": "5 000 000,00",
        "principalDebt": "100 000,00",
        "interest": "0",
        "forfeit": "0",
    })
    assert р.get("totalDebt") == "100 000,00"


# --- ворота табличного читателя: проза не становится суммой -----------------------

def test_проза_с_номером_пункта_не_даёт_процентов(analyzer):
    """Защита §S.46: «п. 4.5 … проценты за пользование» — строка С ЦИФРАМИ."""
    текст = (
        "Задолженность по договору составляет 494 190,08 руб.\n"
        "В соответствии с п. 4.5 Общих условий проценты за пользование кредитом "
        "уплачиваются ежемесячно.\n"
    )
    assert not analyzer.extract_fields(текст, "rtk_application").get("interest")

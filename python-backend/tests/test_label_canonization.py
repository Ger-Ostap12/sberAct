"""Канонизация написания метки перед сопоставлением (§S.2.D).

`label_synonyms` обещает: поддержка нового банка = добавить строку в реестр, без
правки логики. Обещание было ложным — паттерны держат написание метки в себе и
реестр не читают (замер: подмена метки на её же синоним ломала 42 документа из
47). `_normalize_labels_for_matching` делает обещание правдой для той части
реестра, которой в корпусе нет.

Ключевое свойство, которое стерегут эти тесты: карта содержит ТОЛЬКО написания,
отсутствующие в корпусе, поэтому на корпусе преобразование тождественное и
эталон не двигает. Отрицательные проверки тут важнее положительных: канонизация,
задевшая лишнее, тихо испортит разбор реальных заявлений.
"""

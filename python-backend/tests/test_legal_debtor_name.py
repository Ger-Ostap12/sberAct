"""Имя должника-юрлица: ОПФ остаётся в поле «Должник» (фаза 3, п. 3.8).

корпус-63: программа показывала юристу «СМТ 40», хотя документ пишет
«ООО «СМТ 40»». ОПФ срезалась у ВСЕХ трёх полей сразу, хотя без неё должно
жить только `legalShortName` — оно для того и заведено; `debtorName` это поле
формы, `applicantName` несёт ОПФ для маркеров [2], [2.1], [2.2].

Два края, на которых первая редакция правки сломалась:
  * ОПФ записана ДВАЖДЫ («Общество с ограниченной ответственностью ООО «…»»);
  * роль-суффикс «(заемщик)» попадал в краткое имя и там окаменевал.
"""
import os
import re
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from parties_mixin import PartiesMixin  # noqa: E402

# --- ДВОЙНАЯ ОПФ -------------------------------------------------------------

@pytest.mark.parametrize("строка,есть_опф", [
    ("ООО «Форте Пром Стил ГмбХ»", True),
    ("АО \"КОНЦЕРН \"САРМАТ\"", True),
    ("Общество с ограниченной ответственностью «ОРГТЕХНИКА»", True),
    ("НАО «ПКБ»", True),
    # Это и есть признак ДВОЙНОЙ записи: остаток после снятия одной ОПФ
    # снова начинается с ОПФ.
    ("ООО «Форте Пром Стил ГмбХ»", True),
    ("Форте Пром Стил ГмбХ", False),
    ("СМТ 40", False),
    ("КОЛОР", False),
])
def test_опф_в_начале_опознаётся(строка, есть_опф):
    assert bool(PartiesMixin._OPF_HEAD_RE.match(строка)) is есть_опф


def test_опф_head_не_ловит_имя_человека():
    assert PartiesMixin._OPF_HEAD_RE.match("Кравцова Алина Викторовна") is None


def test_опф_head_не_ловит_слово_начинающееся_на_ао():
    """Граница слова обязательна, иначе «Аорта» прошла бы за «АО»."""
    assert PartiesMixin._OPF_HEAD_RE.match("Аорта плюс") is None


# --- РОЛЬ-СУФФИКС ------------------------------------------------------------

@pytest.mark.parametrize("сырое,чистое", [
    ('ООО "КОЛОР" (заемщик)', 'ООО "КОЛОР"'),
    ("ООО «ТМД» (должник)", "ООО «ТМД»"),
    ("Иванов Иван Иванович (ответчик)", "Иванов Иван Иванович"),
    ("ПАО Сбербанк (кредитор)", "ПАО Сбербанк"),
    ("ООО «Без роли»", "ООО «Без роли»"),
])
def test_роль_суффикс_снимается(сырое, чистое):
    assert PartiesMixin._ROLE_SUFFIX_RE.sub("", сырое).strip() == чистое


def test_роль_суффикс_только_в_конце():
    """«(заемщик)» в середине — часть прозы, а не хвост наименования."""
    строка = "ООО «КОЛОР» (заемщик) по договору"
    assert PartiesMixin._ROLE_SUFFIX_RE.sub("", строка).strip() == строка


def test_роль_суффикс_не_трогает_скобку_с_инн():
    строка = "ООО «КОЛОР» (ИНН 6123013561)"
    assert PartiesMixin._ROLE_SUFFIX_RE.sub("", строка).strip() == строка


# --- ПОРЯДОК ЧИСТКИ ----------------------------------------------------------

def test_роль_снимается_до_срезания_опф():
    """Иначе краткое имя получается «КОЛОР« (заемщик)»» и больше не чинится.

    Поздний чистильщик его не достаёт: мусор оканчивается кавычкой, а не
    закрывающей скобкой, на которую он рассчитан.
    """
    сырое = 'ООО "КОЛОР" (заемщик)'
    без_роли = PartiesMixin._ROLE_SUFFIX_RE.sub("", сырое).strip()
    assert без_роли == 'ООО "КОЛОР"'
    # После снятия роли ОПФ срезается начисто, без хвоста в кавычках.
    ядро = re.sub(r'^\s*ООО\s*[«"]?|[»"]\s*$', "", без_роли).strip()
    assert ядро == "КОЛОР"

# -*- coding: utf-8 -*-
"""Тесты детекции ликвидации должника-ЮЛ и извлечения наименования ликвидатора.

Покрывают:
  • детект по сильным сигналам (ликвидатор / ликвидационная комиссия / ликвидируемый
    должник) и слабым (решение/стадия/процесс … ликвидации), veto на «ликвидацию
    задолженности/последствий/аварии»;
  • все паттерны извлечения ликвидатора: один / комиссия / универсальные / ЮЛ.
"""
import pytest
from document_analyzer import DocumentAnalyzer


@pytest.fixture(scope="module")
def da():
    return DocumentAnalyzer()


# ── Детекция ────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("text", [
    "В лице ликвидатора: Оленченко Олег Игоревич",
    "должник находится в стадии ликвидации",
    "принято решение о ликвидации Общества",
    "в лице председателя ликвидационной комиссии Иванова Ивана Ивановича",
    "заявление о признании ликвидируемого должника банкротом",
    "Ликвидатором назначен Петров Пётр Петрович",
])
def test_detect_liquidation_positive(da, text):
    assert da._detect_liquidation(text) is True


@pytest.mark.parametrize("text", [
    "требуется ликвидация задолженности перед банком",
    "меры по ликвидации последствий аварии",
    "обычное заявление о признании должника банкротом",
])
def test_detect_liquidation_negative(da, text):
    assert da._detect_liquidation(text) is False


# ── Извлечение ──────────────────────────────────────────────────────────────
@pytest.mark.parametrize("text,expected", [
    ("В лице ликвидатора: Оленченко Олег Игоревич", "Оленченко Олег Игоревич"),
    ("в лице ликвидатора Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице единственного ликвидатора Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице председателя ликвидационной комиссии Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице руководителя ликвидационной комиссии Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице ликвидационной комиссии в составе председателя Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице лица, ответственного за ликвидацию, Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице органа, осуществляющего ликвидацию, в лице Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("в лице лица, имеющего право без доверенности действовать от имени юридического лица "
     "(ликвидатора), Иванова Ивана Ивановича", "Иванов Иван Иванович"),
    ("Ликвидатором назначен Петров Пётр Петрович", "Петров Пётр Петрович"),
])
def test_extract_liquidator_person(da, text, expected):
    assert da._extract_liquidator(text) == expected


def test_extract_liquidator_org(da):
    # Ликвидатор — управляющая организация: наименование = организация.
    text = 'в лице ликвидатора — ООО «Вектор» в лице генерального директора Иванова Ивана Ивановича'
    assert da._extract_liquidator(text) == 'ООО «Вектор»'


def test_extract_liquidator_none(da):
    assert da._extract_liquidator("обычный текст без ликвидатора") is None

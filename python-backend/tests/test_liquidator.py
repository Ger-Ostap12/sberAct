# ── Кандидат в управляющие (_extract_manager_candidate) ─────────────────────
# В инициирующем заявлении управляющего ПРОСЯТ утвердить («утвердить <ФИО>»), а не
# «управляющим утверждён <ФИО>» — существующие якоря такую форму не ловили.
def test_manager_candidate_nominative(da):
    # Форма ФНС: ФИО после блока СРО, именительный падеж.
    text = ("3. конкурсным управляющим ООО «СМТ 40» утвердить члена Ассоциация СРО "
            "«Эгида» (адрес: 170100, обл. Тверская, г. Тверь) Белов Иван Алексеевич "
            "(ИНН 632127553358, регистрационный номер 22962), выбранного случайным образом")
    assert da._extract_manager_candidate(text) == "Белов Иван Алексеевич"


def test_manager_candidate_genitive_to_nominative(da):
    # Форма банка: родительный падеж → приводим к именительному.
    text = ("Заявитель просит в качестве кандидатуры арбитражного управляющего утвердить "
            "Панина Александра Владимировича (ИНН 644923704326, СНИЛС 143-211-094 04), "
            "члена саморегулируемой организации – Ассоциации «Содействие»")
    assert da._extract_manager_candidate(text) == "Панин Александр Владимирович"


def test_manager_candidate_ignores_organization_inn(da):
    # У СРО в такой же скобке ИНН 10-значный — организация кандидатом стать не должна.
    text = ("утвердить члена саморегулируемой организации – Ассоциации «Межрегиональная "
            "саморегулируемая организация арбитражных управляющих «Содействие» "
            "(ИНН 5752030226, ОГРН 1025700780071)")
    assert da._extract_manager_candidate(text) is None


def test_manager_candidate_requires_context(da):
    # ФИО с 12-значным ИНН без контекста утверждения — это должник/иное лицо, не кандидат.
    text = "Должник: Иванов Иван Иванович (ИНН 616270139617) зарегистрирован по адресу"
    assert da._extract_manager_candidate(text) is None

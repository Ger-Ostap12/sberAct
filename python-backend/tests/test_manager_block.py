@pytest.mark.parametrize("проза,падежная_форма", [
    ("Прошу утвердить арбитражным управляющим Теплова Алексея Сергеевича из числа "
     "членов Ассоциации.\n", "Теплова Алексея Сергеевича"),
    ("Прошу утвердить арбитражным управляющим Колесникова Сергея Владимировича.\n",
     "Колесникова Сергея Владимировича"),
    ("Утвердить арбитражным управляющим Степанову Лидию Дмитриевну.\n",
     "Степанову Лидию Дмитриевну"),
])
def test_косвенный_падеж_из_просительной_не_становится_именем(проза, падежная_форма):
    """Сторож регрессии: слой «роль + юрлицо + ФИО» без ОБЯЗАТЕЛЬНОГО юрлица
    вырождается в «роль + три слова с заглавной» и хватает падежную форму из
    просительной части. На golden это стоило четырёх документов ФНС."""
    assert _имя(проза) != падежная_форма



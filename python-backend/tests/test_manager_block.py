def test_утверждён_без_скобки_работает_как_прежде():
    текст = ("Финансовым управляющим утвержден Селина Ольга Олеговна "
             "(ИНН 431202681065, СНИЛС 125-151-221 05)\n")
    assert _имя(текст) == "Селина Ольга Олеговна"



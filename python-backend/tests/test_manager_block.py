"""Блок управляющего: ФИО и адрес (14.09.2026).

Восемь красных эталона на восьми документах, шесть разных форм записи. Общее
у них одно: слои разбора знают ОДНУ раскладку блока — «роль: ФИО \\n адрес», —
а заявления пишут ещё пять.

  свежие-24/30  «Финансовый управляющий: ФУ Ярошевич Виктор Юрьевич» —
                аббревиатура роли занимала первый из трёх токенов ФИО, и
                отчество отваливалось.
  свежие-16     «Финансовым управляющим утвержден(а) Семенов Сергей
                Станиславович, адрес…» — общий паттерн хватал подпись
                СЛЕДУЮЩЕГО поля, цикл обрывался, поле оставалось пустым.
  свежие-28     «Конкурсный управляющий ООО «УО «Владимирская» Каплиёв Михаил
                Васильевич» — между ролью и ФИО стоит управляемое юрлицо.
  свежие-13     «Финансовыйуправляющий:» без пробела — конвертер съел пробел,
                и адрес следующей строкой терялся целиком.
  свежие-32     «Адрес для корреспонденции: 400137, г. Волгоград, а/я 29» на
                одной строке с ролью — многочастный паттерн обрывал значение
                на запятой и терял абонентский ящик.
  свежие-4      двухколоночная шапка ВТБ: метка разорвана значением, а адрес
                стоит ЗА строкой-разделителем из дефисов.

Тексты — дословные куски заявлений корпуса.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from patterns import MANAGER_ROLE, build_patterns  # noqa: E402


@pytest.fixture(scope="module")
def а():
    return DocumentAnalyzer()


def _имя(текст):
    """Первый сработавший паттерн managerName — как в разборе (цикл до первого)."""
    for группа in build_patterns().values():
        for info in группа:
            if info.get("name") != "managerName":
                continue
            for p in info["patterns"]:
                m = re.search(p, текст, re.IGNORECASE)
                if m:
                    return m.group(1).strip().rstrip(",;")
    return None


# --- аббревиатура роли перед именем -------------------------------------------

@pytest.mark.parametrize("строка,ожидаем", [
    ("Финансовый управляющий: ФУ Ярошевич Виктор Юрьевич \n",
     "Ярошевич Виктор Юрьевич"),
    ("Финансовый управляющий: ФУ Бесчастнова Олеся Владимировна,\n",
     "Бесчастнова Олеся Владимировна"),
    ("Арбитражный управляющий: АУ Эфендиева Амина Агаевна\n",
     "Эфендиева Амина Агаевна"),
])
def test_аббревиатура_роли_не_съедает_отчество(строка, ожидаем):
    """`[а-яё]` под IGNORECASE ловит и ЗАГЛАВНЫЕ, поэтому «ФУ» проходило как
    первый токен ФИО — в поле уезжало «ФУ Ярошевич Виктор»."""
    assert _имя(строка) == ожидаем


def test_имя_без_аббревиатуры_разбирается_как_прежде():
    assert _имя("Финансовый управляющий: Сипакова Алина Олеговна, адрес:\n") == (
        "Сипакова Алина Олеговна")


# --- «утверждён(а) <ФИО>» ------------------------------------------------------


# --- абонентский ящик ----------------------------------------------------------

def _адрес_паттернами(текст):
    """Первый сработавший паттерн managerAddress — как в разборе."""
    for группа in build_patterns().values():
        for info in группа:
            if info.get("name") != "managerAddress":
                continue
            for p in info["patterns"]:
                m = re.search(p, текст, re.IGNORECASE)
                if m:
                    return m.group(1).strip().rstrip(" ,;")
    return None


def test_абонентский_ящик_остаётся_в_адресе():
    """свежие-32: «а/я 29» — это и есть адрес, по которому управляющему шлют
    корреспонденцию. Многочастный паттерн обрывал значение на ЛЮБОЙ запятой и
    отдавал «400137, г. Волгоград»."""
    текст = ("346720, Ростовская область, г. Аксай, ул. Коминтерна, д.\n72\n"
             "Финансовый управляющий: Андреева Оксана Георгиевна "
             "Адрес для корреспонденции: 400137, г. Волгоград, а/я 29\n"
             "ЗАЯВЛЕНИЕ\n")
    assert _адрес_паттернами(текст) == "400137, г. Волгоград, а/я 29"


def test_реквизиты_после_адреса_в_него_не_утекают():
    текст = ("Финансовый управляющий: Андреева Оксана Георгиевна "
             "Адрес: 400137, г. Волгоград, а/я 29 ИНН 344400112233\n")
    assert _адрес_паттернами(текст) == "400137, г. Волгоград, а/я 29"


def test_адрес_сро_за_адрес_управляющего_не_выдаётся():
    """Сторож регрессии: та же метка «адрес:» стоит и у САМОРЕГУЛИРУЕМОЙ
    организации, из членов которой просят утвердить управляющего. Без гарда на
    маркеры СРО и без требования ФИО между ролью и меткой пять документов
    golden получали чужой адрес."""
    текст = ("Прошу утвердить арбитражного управляющего из числа членов "
             "Ассоциации «Меркурий», адрес: 125047, город Москва, "
             "4-Я Тверская-Ямская ул., д.2/11 к.2\n")
    assert _адрес_паттернами(текст) is None



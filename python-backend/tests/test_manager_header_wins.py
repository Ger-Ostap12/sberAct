# -*- coding: utf-8 -*-
"""Управляющих названо больше одного — верен тот, что в шапке (01.09.2026).

Заявление может назвать двух разных управляющих: в мотивировке — того, кого
утвердил суд, в блоке сторон — действующего. Поля извлекаются независимо,
поэтому имя бралось из одного места, а ИНН и СНИЛС — из другого:

    managerName     Потапов Дмитрий Викторович (ИНН 614211646210)   ← имя и ИНН
    managerInn      614211646210                                      разных лиц
    managerSnils    144-099-696-91
    managerAddress  101000, Москва                                  ← адрес СРО

Правило Андрея: верен тот, кто в ШАПКЕ. Признак шапки — ПАДЕЖ метки:
именительный с двоеточием открывает блок стороны, творительный
(«финансовым управляющим утвержден») — проза мотивировки.

Замер на 101 документе: двух управляющих называют два документа, и во втором
это ОДИН человек с разночтением OCR («Теслёлкин» / «Тесёлкин»). Отсюда сверка
по похожести, а не по равенству.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# Проза мотивировки: суд утвердил Ширшова, все его реквизиты рядом.
_PROSE = ("Финансовым управляющим утвержден Ширшов Дмитрий Игоревич "
          "(ИНН 614211646210 СНИЛС 144-099-696-91) член САУ «Авангард» "
          "(ИНН 7705479434, адрес:101000, Москва, вн. тер. г. Басманный).\n")

# Блок сторон: действующий управляющий — Потапов.
_HEADER = ("АРБИТРАЖНЫЙ УПРАВЛЯЮЩИЙ:\n"
           "Потапов Дмитрий Викторович\n"
           "344090, г.Ростов-на-Дону, а/я 77\n")

# Что дал бы независимый разбор до правила.
_FROM_PROSE = {
    "managerName": "Потапов Дмитрий Викторович",
    "managerInn": "614211646210",
    "managerSnils": "144-099-696-91",
    "managerAddress": "101000, Москва",
}


def test_шапка_побеждает(analyzer):
    fields = dict(_FROM_PROSE)
    analyzer._prefer_header_manager(fields, _PROSE + _HEADER)
    assert fields["managerName"] == "Потапов Дмитрий Викторович"
    assert fields["managerAddress"] == "344090, г.Ростов-на-Дону, а/я 77"


def test_чужие_реквизиты_вычищаются(analyzer):
    """Пусто лучше чужого значения в акте: ИНН и СНИЛС принадлежат Ширшову,
    а в шапке их нет — значит поля должны опустеть, а не остаться чужими."""
    fields = dict(_FROM_PROSE)
    analyzer._prefer_header_manager(fields, _PROSE + _HEADER)
    assert "managerInn" not in fields
    assert "managerSnils" not in fields


def test_один_управляющий_ничего_не_трогает(analyzer):
    """Подавляющее большинство заявлений называет одного управляющего —
    там правило обязано быть тождественным."""
    text = ("Финансовым управляющим утвержден Потапов Дмитрий Викторович "
            "(ИНН 614211646210 СНИЛС 144-099-696-91).\n" + _HEADER)
    fields = dict(_FROM_PROSE)
    analyzer._prefer_header_manager(fields, text)
    assert fields == _FROM_PROSE


def test_разночтение_фамилии_это_одно_лицо(analyzer):
    """«Теслёлкин» в шапке и «Тесёлкин» в прозе — один человек, чью фамилию
    OCR прочёл двояко. Правило не должно принимать это за спор и вычищать
    реквизиты."""
    text = ("Финансовым управляющим утвержден Тесёлкин Дмитрий Сергеевич.\n"
            "Финансовый управляющий:\nТеслёлкин Дмитрий Сергеевич\n"
            "Адрес для корреспонденции:\n344082, Ростовская область, а/я 2717\n")
    fields = {"managerName": "Теслёлкин Дмитрий Сергеевич",
              "managerInn": "615519848330"}
    before = dict(fields)
    analyzer._prefer_header_manager(fields, text)
    assert fields == before


def test_разные_люди_с_общим_именем_это_спор(analyzer):
    """Порог похожести не должен склеивать разных людей: у «Иванова Ивана
    Ивановича» и «Иванова Ивана Петровича» совпадает две трети ФИО."""
    text = ("Финансовым управляющим утвержден Иванов Иван Петрович "
            "(ИНН 614211646210).\n"
            "Финансовый управляющий:\nИванов Иван Иванович\n"
            "344090, г.Ростов-на-Дону, а/я 77\n")
    fields = {"managerName": "Иванов Иван Иванович", "managerInn": "614211646210"}
    analyzer._prefer_header_manager(fields, text)
    assert fields["managerName"] == "Иванов Иван Иванович"
    assert "managerInn" not in fields


def test_метки_стопкой_не_блок_управляющего(analyzer):
    """Раскладка ВТБ: метки идут списком, значения — отдельным столбцом, и за
    меткой управляющего стоит значение КРЕДИТОРА. Первое попавшееся ФИО там —
    сотрудник банка; принять его за управляющего значит вычистить верные
    реквизиты (так и случилось на двух документах корпуса)."""
    text = ("КРЕДИТОР:\nДОЛЖНИК:\nФИНАНСОВЫЙ\nУПРАВЛЯЮЩИЙ:\n"
            "Банк ВТБ (публичное акционерное общество) ОГРН 1027739609391 "
            "ИНН 7702070139. Начальник отдела Горина Юлия Игоревна.\n"
            "Финансовым управляющим утвержден Удодов Сергей Александрович "
            "(ИНН 615519848330, СНИЛС 118-781-995 07).\n")
    fields = {"managerName": "Удодов Сергей Александрович",
              "managerInn": "615519848330", "managerSnils": "118-781-995 07"}
    before = dict(fields)
    analyzer._prefer_header_manager(fields, text)
    assert fields == before


def test_без_шапки_ничего_не_меняется(analyzer):
    fields = dict(_FROM_PROSE)
    before = dict(fields)
    analyzer._prefer_header_manager(fields, _PROSE)
    assert fields == before


def test_блок_отдаёт_снилс_и_инн_когда_они_в_шапке(analyzer):
    """Если реквизиты стоят в самой шапке — берём их оттуда, а не обнуляем."""
    text = (_PROSE +
            "Финансовый управляющий:\nПотапов Дмитрий Викторович\n"
            "344090, г.Ростов-на-Дону, а/я 77\n"
            "ИНН: 616302225639 СНИЛС: 055-053-091 30\n")
    fields = dict(_FROM_PROSE)
    analyzer._prefer_header_manager(fields, text)
    assert fields["managerInn"] == "616302225639"
    assert fields["managerSnils"] == "055-053-091 30"

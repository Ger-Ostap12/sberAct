# -*- coding: utf-8 -*-
"""Реквизиты арбитражного управляющего: ИНН, ФИО, адрес (§S.8).

Разбор потерь из отчёта покрытия показал, что «managerInn потеряно у 23
документов» — почти целиком ШУМ ЗОНДА. Рядом со словом «управляющий» ИНН стоит
у 21 документа корпуса, но у 16 он ЧУЖОЙ: это ИНН СРО («из числа членов
Ассоциации … ИНН …») или должника-ЮЛ. Настоящих потерь было пять.

Разделяющий признак нашёлся простой и надёжный: **управляющий — физлицо, его ИНН
ВСЕГДА 12 знаков**. Все 16 чужих — десятизначные (СРО и ЮЛ), все 8 работавших в
эталоне — двенадцатизначные. Второе условие — ИНН стоит СРАЗУ ЗА ФИО.

Отрицательные проверки тут — главное: послабление морфологии («управляющим»,
«управляющего») открывает поле для ИНН саморегулируемой организации, и без
ограничения на длину и на порядок «ФИО → ИНН» поле начало бы молча врать.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

import patterns as pattern_exec  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _field_patterns(analyzer, name):
    return next(p for p in analyzer.patterns["rtk_application"] if p["name"] == name)["patterns"]


def _first_match(patterns, text):
    """Первое совпадение по списку паттернов — так же, как в `extract_fields`."""
    for pattern in patterns:
        m = pattern_exec.search(pattern, text)
        if m:
            return m.group(1).strip() if m.groups() else m.group(0).strip()
    return None


# --- ИНН управляющего --------------------------------------------------------

def test_инн_управляющего_за_фио(analyzer):
    """«арбитражным управляющим <ФИО> ИНН …» — форма заявлений ФНС.

    Слои выше требуют именительный падеж («финансовый управляющий») и на ней
    молчали.
    """
    text = "утвердить арбитражным управляющим Теплова Алексея Сергеевича ИНН 582704406654"
    assert _first_match(_field_patterns(analyzer, "managerInn"), text) == "582704406654"


def test_инн_сро_не_становится_инн_управляющего(analyzer):
    """Десятизначный ИНН — это ЮЛ, а управляющий физлицо. Так на корпусе
    отсекаются 16 ложных срабатываний из 21."""
    text = (
        "прошу утвердить финансового управляющего из числа членов саморегулируемой "
        "организации СРО ААУ «Евросиб» — Ассоциация Евросибирская саморегулируемая "
        "организация арбитражных управляющих (ИНН 0274107073)"
    )
    assert _first_match(_field_patterns(analyzer, "managerInn"), text) is None


def test_нельзя_перепрыгнуть_через_чужой_инн(analyzer):
    """Взять можно только ПЕРВЫЙ ИНН после слова «управляющий».

    Иначе выражение перескочит ИНН СРО и подберёт двенадцатизначный ИНН,
    стоящий дальше и принадлежащий кому угодно.
    """
    text = (
        "финансового управляющего из числа членов Ассоциации «Гарант» (ИНН 7730309884), "
        "должник Буниатян Алина Генриковна ИНН 612504512780"
    )
    assert _first_match(_field_patterns(analyzer, "managerInn"), text) is None


def test_управляющим_должника_это_обычная_речь(analyzer):
    """«управляющим ДОЛЖНИКА утверждён …» — не граница блока должника.

    Стоп-слово должно требовать двоеточия («Должник:»), иначе теряется
    самая обычная формулировка.
    """
    text = (
        "Финансовым управляющим должника утвержден(-а) "
        "Рябинина Екатерина Сергеевна (ИНН 645100186818)"
    )
    assert _first_match(_field_patterns(analyzer, "managerInn"), text) == "645100186818"


# --- ФИО управляющего --------------------------------------------------------

def test_фио_управляющего_без_скобок_и_в_родительном(analyzer):
    """ФНС пишет ИНН без скобок и ФИО в косвенном падеже."""
    text = (
        "Уполномоченный орган просит утвердить арбитражным управляющим "
        "Колесникова Сергея Владимировича ИНН 362600914260"
    )
    assert analyzer._extract_manager_candidate(text) == "Колесников Сергей Владимирович"


def test_фио_управляющего_требует_контекста_утверждения(analyzer):
    """Без «утвердить/кандидатура/управляющий» слева это чьё-то чужое ФИО+ИНН."""
    text = "Поручитель Колесникова Сергея Владимировича ИНН 362600914260"
    assert analyzer._extract_manager_candidate(text) is None


def test_фио_управляющего_разорванное_переносом(analyzer):
    """Узкая шапка рвёт ФИО посреди имени, и БЕЗ пробела в конце строки.

    Общий паттерн `управляющий[:\\s]+(…)` обрывается на переносе, отдаёт одну
    фамилию и ЗАВЕРШАЕТ перебор — значение потом отбраковывается, а поле
    остаётся пустым. Точный паттерн обязан стоять выше него.
    """
    text = "Арбитражный управляющий: Эфендиева\nАмина Агаевна\nАдрес АУ: 101000, г. Москва"
    assert _first_match(_field_patterns(analyzer, "managerName"), text) == "Эфендиева\nАмина Агаевна"


def test_захват_фио_не_утаскивает_следующее_поле(analyzer):
    """Ровно три токена: иначе двухсловное имя утащило бы слово из «Адрес АУ:»."""
    text = "Арбитражный управляющий: Эфендиева\nАмина Агаевна\nАдрес АУ: 101000, г. Москва"
    got = _first_match(_field_patterns(analyzer, "managerName"), text)
    assert "Адрес" not in got


# --- Адрес управляющего ------------------------------------------------------

def test_адрес_управляющего_дочитывается_за_перенос(analyzer):
    """`$` в этом паттерне — конец СТРОКИ (MULTILINE), и адрес обрывался на нём."""
    fields = {"managerName": "Эфендиева Амина Агаевна"}
    text = (
        "Арбитражный управляющий: Эфендиева Амина Агаевна\n"
        "Адрес АУ: 101000,г. Москва, Мясницкая \n"
        "улица д. 26А стр 1 а\\я, 564\n"
        "Дело№ А53-2848/2026\n"
    )
    analyzer._fill_manager_address(fields, text)
    assert fields["managerAddress"] == "101000,г. Москва, Мясницкая улица д. 26А стр 1 а\\я, 564"


def test_строка_метка_обрывает_адрес_управляющего(analyzer):
    """Мягкий перенос не должен утаскивать в адрес соседнее поле."""
    fields = {"managerName": "Эфендиева Амина Агаевна"}
    text = (
        "Арбитражный управляющий: Эфендиева Амина Агаевна\n"
        "Адрес АУ: 101000,г. Москва, Мясницкая \n"
        "ИНН: 632127553358\n"
        "Дело№ А53-2848/2026\n"
    )
    analyzer._fill_manager_address(fields, text)
    assert "632127553358" not in fields.get("managerAddress", "")

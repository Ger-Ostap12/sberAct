# -*- coding: utf-8 -*-
"""СНИЛС финансового управляющего (31.08.2026).

Поле `managerSnils` объявлено во фронте (`types.ts`), в генерации (подстановка
в шаблон) и в кросс-блочном дедупе, но извлекателя не было НИ ОДНОГО: замер дал
0 значений на 35 свежих заявлениях и 0 на корпусе из 66.

Замер же определил форму паттерна:
  * якорь — вид управляющего («финансовым управляющим», «арбитражного
    управляющего»); голое «управляющ» не добавляет ни одного значения, зато
    открывает дорогу к СНИЛС должника в самобанкротных заявлениях;
  * разделитель групп — до ДВУХ символов: конвертер таблиц печатает пробел и
    табуляцию сразу («125-151-221 \\t05»);
  * границы по цифрам — иначе к номеру приклеивается почтовый индекс со
    следующей строки («07725793102 \\n350012»).

Все 14 найденных на корпусе значений проходят контрольную сумму ПФР — поэтому
она здесь работает как признак качества, а не как источник ложных тревог.
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

import field_contract  # noqa: E402
from patterns import SNILS_VALUE  # noqa: E402
from requisites_validation import is_valid_snils  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _manager_snils(analyzer, text):
    return analyzer.extract_fields(text, "rtk_application").get("managerSnils")


# --- контрольная сумма ПФР ---------------------------------------------------

@pytest.mark.parametrize("value", [
    "14358739389", "055-053-091 30", "134-904-808 62", "15466571489",
    "144-099-696-91", "180-696-413 94", "14986438627", "13726672779",
    "118-781-995 07", "07725793102", "13517430235", "112-979-523 77",
    "143-211-094 04", "125-151-221 05",
])
def test_реальные_снилс_проходят_проверку(value):
    """Все значения, найденные на корпусе. Если проверка их отбраковывает —
    ошибка в алгоритме, а не в документах."""
    assert is_valid_snils(value)


def test_битая_цифра_не_проходит():
    """Одна изменённая цифра ломает контрольную сумму — иначе проверка бесполезна."""
    assert not is_valid_snils("14358739380")


def test_неверная_длина_не_проходит():
    assert not is_valid_snils("1435873938")     # 10
    assert not is_valid_snils("143587393891")   # 12


def test_старый_номер_без_контрольного_разряда():
    """Номера до 001-001-998 выданы без контрольного разряда — не отбраковываем."""
    assert is_valid_snils("00100199800")


# --- форма значения ----------------------------------------------------------

_VALUE_RE = re.compile(SNILS_VALUE)


@pytest.mark.parametrize("raw,expected", [
    ("125-151-221 \t05", "125-151-221 \t05"),  # пробел И табуляция сразу
    ("144-099-696-91", "144-099-696-91"),
    ("118-781-995 07", "118-781-995 07"),
    ("14358739389", "14358739389"),
])
def test_разделители_групп(raw, expected):
    m = _VALUE_RE.search(raw)
    assert m and m.group(1) == expected


def test_приклеенный_индекс_не_попадает_в_номер():
    """«07725793102 \\n350012» — за номером без разделителя идёт почтовый индекс
    следующей строки. Берём ровно одиннадцать цифр."""
    m = _VALUE_RE.search("07725793102 \n350012, г. Краснодар")
    assert m and m.group(1) == "07725793102"


def test_перенос_строки_не_разделитель_внутри_номера():
    """Между группами номера переноса не бывает; пустить его — значит склеить
    номер со следующей строкой."""
    assert not _VALUE_RE.search("123-456-789\n01")


def test_длинное_число_не_снилс():
    """Двенадцатизначный ИНН не должен читаться как СНИЛС по первым одиннадцати."""
    assert not _VALUE_RE.search("ИНН 614211646210 ")


# --- извлечение с якорем роли -------------------------------------------------

def test_снилс_управляющего_извлекается(analyzer):
    text = ("Финансовым управляющим утвержден Хомяков Дмитрий Владимирович "
            "(ИНН 301100767956, СНИЛС 055-053-091 30) член СРО «Авангард».")
    assert _manager_snils(analyzer, text) == "055-053-091 30"


def test_метка_на_отдельной_строке(analyzer):
    text = ("Финансовый управляющий: Галифинова Татьяна Сергеевна\n"
            "ИНН: 740706331908\nСНИЛС: 15466571489\n")
    assert _manager_snils(analyzer, text) == "15466571489"


def test_табуляция_внутри_номера(analyzer):
    """Реальная раскладка ВТБ: конвертер таблицы вставил пробел и табуляцию."""
    text = ("Финансовым управляющим утвержден Селина Ольга Олеговна "
            "(ИНН 431202681065, СНИЛС 125-151-221 \t05) - Ассоциация.")
    assert _manager_snils(analyzer, text) == "125-151-221 05"


def test_снилс_должника_не_берётся(analyzer):
    """Самобанкротное заявление: СНИЛС есть только у должника, управляющий
    упомянут без реквизитов. Пусто лучше чужого значения."""
    text = ("Заявитель (Должник): Федоренко Алексей Алексеевич "
            "СНИЛС 157-887-524-35 ИНН 616118814199. "
            "Прошу утвердить финансового управляющего из числа членов "
            "Ассоциации арбитражных управляющих «Созидание».")
    assert not _manager_snils(analyzer, text)


def test_метка_без_значения(analyzer):
    """«СНИЛС: ЗАЯВЛЕНИЕ о включении…» — метка есть, значения нет."""
    text = ("Финансовый управляющий: Галифинова Татьяна Сергеевна "
            "ИНН: 740706331908 СНИЛС: ЗАЯВЛЕНИЕ о включении требований.")
    assert not _manager_snils(analyzer, text)


def test_битый_ocr_не_берётся(analyzer):
    """«СНИЛС 050706-170 2 -» — десять цифр, номер распознан с потерей."""
    text = ("Финансовый управляющий: Татьков Максим Эдуардович "
            "ИНН 616302225639, СНИЛС 050706-170 2 -член Ассоциации.")
    assert not _manager_snils(analyzer, text)


def test_голое_слово_управляющий_не_якорь(analyzer):
    """Якорь обязан называть ВИД управляющего. Слово «управляющему» встречается
    в описи приложений («копия направлена управляющему и должнику»), и от него
    до чужого СНИЛС бывает меньше двухсот символов без единой метки роли."""
    text = ("Копия заявления направлена управляющему. Поручитель "
            "Петров Петр Петрович, СНИЛС 157-887-524-35, извещен.")
    assert not _manager_snils(analyzer, text)


def test_чужая_метка_роли_обрывает_окно(analyzer):
    """Гард на будущее: окно в 200 символов не должно перепрыгивать в блок
    должника, даже если управляющий упомянут рядом без своих реквизитов."""
    text = ("Прошу утвердить финансового управляющего из числа членов СРО. "
            "Должник: Иванов Иван Иванович СНИЛС 157-887-524-35.")
    assert not _manager_snils(analyzer, text)


# --- контракт поля -------------------------------------------------------------

def test_плохой_снилс_помечается_но_не_чистится():
    """Правило §K.1: реквизит с битой цифрой — «свой, но с опечаткой», а не
    чужое значение. Чистить его дороже, чем поправить глазами."""
    fields = {"managerSnils": "14358739380"}
    issues = field_contract.apply_contract(fields)
    assert fields["managerSnils"] == "14358739380", "значение чистить нельзя"
    assert any(i.field == "managerSnils" and not i.cleared for i in issues)


def test_причина_на_русском():
    reason = field_contract.check_value("managerSnils", "14358739380")
    assert reason and reason.startswith("СНИЛС"), reason


def test_верный_снилс_претензий_не_вызывает():
    assert field_contract.check_value("managerSnils", "055-053-091 30") is None


def test_верный_снилс_повышает_уверенность():
    quality = field_contract.assess_quality({"managerSnils": "055-053-091 30"}, {})
    assert quality.get("managerSnils", {}).get("level") == field_contract.HIGH

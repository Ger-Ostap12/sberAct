# -*- coding: utf-8 -*-
"""СНИЛС управляющего в карточке должника (08.09.2026).

В шапке реквизиты управляющего идут СРАЗУ за блоком должника:

    Адрес регистрации: 346884, Ростовская обл., г. Батайск, ул. Янтарная, д. 7
    Удодов Сергей Александрович (ИНН 615519848330, СНИЛС 118-781-995 07)

Разбор блока «Должник:» дотягивался до следующей строки и клал чужой СНИЛС
в КАРТОЧКУ должника — пять документов корпуса.

Кросс-блочный дедуп этого не ловил, и причина поучительная: он сверяет плоское
поле со списком чужих реквизитов, а «своими» считает то, что стоит в карточке.
Когда чужое значение уже попало в карточку, дедуп сам себя ослеплял — защита
объявляла протечку собственностью должника. Поэтому чистка идёт ДО дедупа.

Само поле `managerSnils` из данных приложения убрано (решение 08.09.2026), но
извлечение оставлено живым именно ради этой защиты — см. test_manager_snils.py.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def test_снилс_управляющего_снимается_с_карточки(analyzer):
    поля = {"managerSnils": "118-781-995 07", "managerInn": "615519848330",
            "snils": "118-781-995 07"}
    карточки = [{"name": "Горина Юлия Игоревна", "snils": "118-781-995 07"}]
    детали = {"snils": "118-781-995 07"}
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, детали)
    assert not карточки[0]["snils"]
    assert not детали["snils"]


def test_разное_написание_снилса_всё_равно_ловится(analyzer):
    """В карточку СНИЛС попадает то с дефисами, то слитно — сверяем по цифрам."""
    поля = {"managerSnils": "118-781-995 07"}
    карточки = [{"snils": "11878199507"}]
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, {})
    assert not карточки[0]["snils"]


def test_инн_управляющего_тоже_снимается(analyzer):
    поля = {"managerInn": "745111378257"}
    карточки = [{"inn": "745111378257"}]
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, {})
    assert not карточки[0]["inn"]


def test_свой_снилс_должника_не_трогается(analyzer):
    поля = {"managerSnils": "118-781-995 07"}
    карточки = [{"snils": "158-801-520 75"}]
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, {})
    assert карточки[0]["snils"] == "158-801-520 75"


def test_без_реквизитов_управляющего_ничего_не_чистится(analyzer):
    поля = {}
    карточки = [{"snils": "158-801-520 75", "inn": "612504512780"}]
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, {})
    assert карточки[0]["snils"] == "158-801-520 75"
    assert карточки[0]["inn"] == "612504512780"


def test_чистятся_все_карточки_а_не_первая(analyzer):
    """Должников бывает несколько, и протечка может попасть в любую карточку."""
    поля = {"managerSnils": "118-781-995 07"}
    карточки = [{"snils": "158-801-520 75"}, {"snils": "118-781-995 07"}]
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, {})
    assert карточки[0]["snils"] == "158-801-520 75"
    assert not карточки[1]["snils"]


def test_дедуп_после_чистки_снимает_и_плоское_поле(analyzer):
    """Порядок и есть суть правки: до чистки дедуп считал чужое своим.

    Карточка несёт чужой СНИЛС -> дедуп видит его в «собственных» -> плоское
    поле остаётся. После чистки карточка пуста, и дедуп срабатывает.
    """
    поля = {"managerSnils": "118-781-995 07", "snils": "118-781-995 07"}
    карточки = [{"snils": "118-781-995 07"}]
    детали = {"snils": "118-781-995 07"}

    # Как было ДО правки: сразу дедуп, без чистки карточки.
    analyzer._dedup_cross_block_ids(dict(поля), dict(детали), [])
    осталось = dict(поля)
    analyzer._dedup_cross_block_ids(осталось, dict(детали), [])
    assert осталось.get("snils") == "118-781-995 07", "дедуп сам себя ослеплял"

    # Как стало: сначала чистка карточки и деталей, потом дедуп.
    analyzer._drop_manager_requisites_from_debtor(поля, карточки, детали)
    analyzer._dedup_cross_block_ids(поля, детали, [])
    assert not поля.get("snils")

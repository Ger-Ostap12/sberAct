# -*- coding: utf-8 -*-
"""Много сторон в одном заявлении: 10 должников и 10 третьих лиц (02.09.2026).

В корпусе максимум — 4 должника (`АРУТЮНЯН_Солидарное_4_ипотека.docx`), поэтому
поведение на длинных списках раньше никем не проверялось. Документы здесь
собираются на лету в раскладке того самого заявления: строка-ФИО, затем
подписанные поля лица, затем следующая строка-ФИО.

Главный риск повторяющихся блоков — не количество, а ДЫРА: если у одного лица
поля нет, границу записи легко потерять, и тогда значения соседей уезжают на
чужую карточку. Замер до правки: у восьмого из десяти нет даты рождения —
9 карточек вместо 10, у четверых перепутаны все поля.

ИНН генерируются с верной контрольной суммой: иначе контракт пометит их сам, и
проверка сцепки утонет в чужих претензиях.
"""
import os
import sys

import pytest
from docx import Document

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from requisites_validation import is_valid_inn  # noqa: E402

ФАМИЛИИ = ["АНТОНОВ", "БОРИСОВ", "ВЛАСОВ", "ГРИГОРЬЕВ", "ДЕМИДОВ",
           "ЕРШОВ", "ЖУКОВ", "ЗАЙЦЕВ", "ИГНАТОВ", "КАРПОВ"]
ИМЕНА = ["АЛЕКСЕЙ", "БОРИС", "ВИКТОР", "ГЕННАДИЙ", "ДМИТРИЙ",
         "ЕВГЕНИЙ", "ЖОРЖ", "ЗАХАР", "ИГОРЬ", "КИРИЛЛ"]
ОТЧЕСТВА = ["АЛЕКСЕЕВИЧ", "БОРИСОВИЧ", "ВИКТОРОВИЧ", "ГЕННАДЬЕВИЧ", "ДМИТРИЕВИЧ",
            "ЕВГЕНЬЕВИЧ", "ЖОРЖЕВИЧ", "ЗАХАРОВИЧ", "ИГОРЕВИЧ", "КИРИЛЛОВИЧ"]
ТРЕТЬИ = ["Смирнова Анна Павловна", "Кузнецов Пётр Ильич", "Попова Мария Львовна",
          "Соколов Илья Романович", "Лебедева Вера Олеговна", "Козлов Артём Юрьевич",
          "Новикова Дарья Сергеевна", "Морозов Роман Русланович",
          "Волкова Ольга Тимофеевна", "Алексеев Тимур Маратович"]


def _инн12(seed: int) -> str:
    """12-значный ИНН физлица с верной контрольной суммой."""
    for хвост in range(100):
        кандидат = f"61{seed:08d}{хвост:02d}"
        if is_valid_inn(кандидат):
            return кандидат
    raise AssertionError(f"не подобрался ИНН для {seed}")


def _норм(s: str) -> str:
    return " ".join(str(s or "").upper().split())


def _собрать(tmp_path, сколько_должников=10, сколько_третьих=0,
             без_инн=None, без_даты=None, без_места=None):
    """Заявление с заданным числом сторон и, при желании, с дырами в полях."""
    doc = Document()
    for строка in ["Арбитражный суд Ростовской области",
                   "Исх. № 12345/7 от 15.08.2026",
                   "Истец:", "ПАО Сбербанк", "ИНН: 7707083893", "Ответчики:"]:
        doc.add_paragraph(строка)

    ожидаемое = []
    for i in range(сколько_должников):
        фио = f"{ФАМИЛИИ[i]} {ИМЕНА[i]} {ОТЧЕСТВА[i]}"
        инн = None if i == без_инн else _инн12(i + 1)
        др = None if i == без_даты else f"{(i % 28) + 1:02d}.{(i % 12) + 1:02d}.19{70 + i}"
        мр = None if i == без_места else f"ГОР. ГОРОД{i + 1} РОСТОВСКАЯ ОБЛАСТЬ"
        адрес = f"3440{i + 10:02d}, г. Ростов-на-Дону, ул. Улица{i + 1}, д. {i + 1}, кв. {i + 11}"
        ожидаемое.append({"name": фио, "inn": инн, "birthDate": др,
                          "birthPlace": мр, "address": адрес})
        doc.add_paragraph(фио)
        if инн:
            doc.add_paragraph(f"ИНН: {инн},")
        if др:
            doc.add_paragraph(f"Дата рождения: {др},")
        if мр:
            doc.add_paragraph(f"Место рождения:  {мр},")
        doc.add_paragraph(f"Адрес регистрации:  {адрес}")

    третьи = []
    if сколько_третьих:
        doc.add_paragraph("Третьи лица:")
        for i in range(сколько_третьих):
            адрес = f"3441{i + 20:02d}, г. Таганрог, пер. Переулок{i + 1}, д. {i + 2}"
            третьи.append({"name": ТРЕТЬИ[i], "address": адрес})
            doc.add_paragraph(ТРЕТЬИ[i])
            doc.add_paragraph(f"Адрес регистрации: {адрес}")

    doc.add_paragraph("ЗАЯВЛЕНИЕ")
    doc.add_paragraph("Решением Арбитражного суда Ростовской области от 04.08.2026 "
                      "по делу № А53-11111/2026 должники признаны несостоятельными.")
    path = str(tmp_path / "многосторонний.docx")
    doc.save(path)
    return path, ожидаемое, третьи


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def test_десять_должников_и_десять_третьих_лиц(analyzer, tmp_path):
    """Каждая карточка собирается из СВОИХ полей, роли не смешиваются."""
    path, ожидаемое, третьи = _собрать(tmp_path, 10, 10)
    r = analyzer.analyze(path)

    должники = r.get("debtors") or []
    лица = r.get("thirdParties") or []
    assert len(должники) == 10, f"карточек должников {len(должники)}"
    assert len(лица) == 10, f"карточек третьих лиц {len(лица)}"

    for i, ждём in enumerate(ожидаемое):
        факт = должники[i]
        for поле in ("name", "inn", "birthDate", "birthPlace", "address"):
            assert _норм(факт.get(поле)) == _норм(ждём[поле]), (
                f"должник #{i + 1}, поле {поле}")

    имена_должников = {_норм(e.get("name")) for e in должники}
    имена_третьих = {_норм(e.get("name")) for e in лица}
    assert not (имена_должников & имена_третьих), "одно лицо попало в две роли"
    for ждём in третьи:
        assert _норм(ждём["name"]) in имена_третьих, f"потеряно третье лицо {ждём['name']}"


def test_контракт_не_придирается_к_сторонам(analyzer, tmp_path):
    """Десять сторон с верными реквизитами не должны рождать претензий О СТОРОНАХ.

    Претензия к `creditorAddress` тут законна и в счёт не идёт: адреса кредитора
    в этом документе нет вовсе, и значение подставлено из справочника банков —
    ровно тот случай, который помечается для проверки юристом.
    """
    path, _, _ = _собрать(tmp_path, 10, 10)
    претензии = analyzer.analyze(path).get("fieldIssues") or []
    о_сторонах = [i for i in претензии
                  if i.get("field", "").startswith(("debtors", "thirdParties"))
                  or i.get("field") in ("debtorName", "inn", "birthDate",
                                        "birthPlace", "applicantAddress")]
    assert о_сторонах == [], f"претензии к сторонам: {о_сторонах}"


def test_дыры_в_полях_не_сдвигают_карточки(analyzer, tmp_path):
    """Пропуск поля у одного лица не должен смещать всех следующих.

    До правки признаком начала записи была ТОЛЬКО дата рождения: должник без
    неё записи не открывал, предыдущая карточка заглатывала его имя в свой
    адрес, а список сокращался на одного.
    """
    path, ожидаемое, _ = _собрать(tmp_path, 10, без_инн=4, без_даты=7, без_места=2)
    должники = analyzer.analyze(path).get("debtors") or []

    assert len(должники) == 10, "лицо без даты рождения потеряло карточку"
    for i, ждём in enumerate(ожидаемое):
        for поле in ("name", "inn", "birthDate", "birthPlace", "address"):
            assert _норм(должники[i].get(поле)) == _норм(ждём[поле]), (
                f"должник #{i + 1}, поле {поле}: значение соседа уехало в дыру")


def test_имя_соседа_не_прилипает_к_адресу(analyzer, tmp_path):
    """Точный симптом потерянной границы: адрес заканчивается ЧУЖИМ ФИО."""
    path, _, _ = _собрать(tmp_path, 10, без_даты=7)
    for i, карточка in enumerate(analyzer.analyze(path).get("debtors") or []):
        адрес = _норм(карточка.get("address"))
        for фамилия in ФАМИЛИИ:
            if фамилия != ФАМИЛИИ[i]:
                assert фамилия not in адрес, f"в адресе #{i + 1} чужая фамилия {фамилия}"


def test_один_должник_разбирается_как_прежде(analyzer, tmp_path):
    """Расширенный признак начала записи не должен ломать одиночный случай."""
    path, ожидаемое, _ = _собрать(tmp_path, 1)
    должники = analyzer.analyze(path).get("debtors") or []
    assert len(должники) == 1
    assert _норм(должники[0].get("name")) == _норм(ожидаемое[0]["name"])

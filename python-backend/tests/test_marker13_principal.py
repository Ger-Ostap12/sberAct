# -*- coding: utf-8 -*-
"""Маркер [13] «Основной долг»: одно значение, то же что на форме (§S.50).

Решение Андрея 09.10.2026: «есть поле для введения основного долга, та сумма
из поля должна быть на месте 13 маркера».

Почему это вообще могло расходиться: на [13] мапятся ТРИ поля
(`principalDebt13`, `principalDebt`, `loanDebt`), а подстановка в документ идёт
циклом по данным, поэтому маркер занимало поле, которое раньше попало в
СЛОВАРЬ. Замер по корпусу: [13] брал principalDebt у 66 документов, loanDebt
у 10, principalDebt13 у 3 — и у трёх это расходилось с формой:

```
корпус-11/-12  в графу основного долга уезжала ОБЩАЯ сумма 1 871 897 982,82
               (эталон записал её как «Общая сумма долга»)
корпус-45      самобанкрот: principalDebt13 держал 158 434,00 — сумму ОДНОГО
               кредитора при итоге 2 126 507,25 — и печатал её при ПУСТОМ
               поле формы
```

⚠️ Ссудная ГП [17] (`loanStateDuty17`) — ДРУГОЕ поле со своим маркером, здесь
не затрагивается. Сторож на это стоит ниже (требование Андрея: «в некоторых
актах есть ссудная ГП, исключать её нельзя»).
"""
import os
import sys

import pytest
from docx import Document

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_generator import DocumentGenerator  # noqa: E402


@pytest.fixture(scope="module")
def generator():
    return DocumentGenerator()


def подготовить(generator, поля):
    """Те же данные, что генератор готовит перед подстановкой в маркеры."""
    return generator._prepare_replacement_data(Document(), dict(поля))


def что_в_13(данные):
    """Первое непустое поле маркера [13] в порядке вставки ключей — его и берёт
    подстановка, потому что после замены маркера в документе уже нет."""
    for ключ in данные:
        if ключ in ("principalDebt13", "principalDebt", "loanDebt"):
            значение = str(данные.get(ключ) or "").strip()
            if значение:
                return значение
    return ""


def test_форма_побеждает_ссудную_задолженность(generator):
    """principalDebt — это то, что показывает форма; loanDebt не должен его обойти.

    ⚠️ Порядок ключей здесь ЗНАЧИМ: `loanDebt` стоит ПЕРВЫМ, как у корпус-11
    и корпус-12. Именно это и ломало акт — подстановка берёт первое непустое
    поле в порядке вставки. С `principalDebt` впереди тест зеленел бы и на
    старом коде, то есть не проверял бы ничего (ср.
    [[test-fakes-must-lie-like-prod]]).
    """
    д = подготовить(generator, {
        "loanDebt": "1 871 897 982,82",
        "principalDebt": "1 465 013 605,99",
        "totalDebt": "1 871 897 982,82",
    })
    assert что_в_13(д) == "1 465 013 605,99"


def test_все_три_поля_несут_одно_значение(generator):
    """Иначе порядок словаря снова начнёт решать, какое число уедет в акт."""
    д = подготовить(generator, {
        "loanDebt": "1 871 897 982,82",
        "principalDebt": "1 465 013 605,99",
    })
    значения = {str(д.get(k) or "").strip()
                for k in ("principalDebt", "principalDebt13", "loanDebt")}
    assert значения == {"1 465 013 605,99"}


def test_пустое_поле_формы_гасит_маркер(generator):
    """У самобанкрота единого основного долга нет — есть список кредиторов.

    principalDebt13 с суммой одного кредитора не должен печататься как
    основной долг всего требования (корпус-45).
    """
    д = подготовить(generator, {
        "principalDebt13": "158 434,00",
        "totalDebt": "2 126 507,25",
    })
    assert что_в_13(д) == ""


def test_ссудная_задолженность_заполняет_пустое(generator):
    """Ворота, а не запрет: когда principalDebt пуст, годится loanDebt."""
    д = подготовить(generator, {"loanDebt": "100 000,00"})
    # Генератор срезает нулевые копейки — в акте «100 000 руб.»
    assert что_в_13(д) == "100 000"


def test_одно_число_в_обоих_полях_не_меняется(generator):
    д = подготовить(generator, {
        "principalDebt": "65 677,56",
        "loanDebt": "65 677,56",
    })
    assert что_в_13(д) == "65 677,56"


# --- сторож: ссудная ГП [17] не затронута -----------------------------------------

def test_ссудная_гп_не_исключается(generator):
    """Требование Андрея: в некоторых актах ссудная ГП есть, убирать её нельзя."""
    д = подготовить(generator, {
        "principalDebt": "1 465 013 605,99",
        "loanDebt": "1 871 897 982,82",
        "loanStateDuty17": "5 017 245,00",
        "stateDuty": "5 017 245,00",
    })
    assert str(д.get("loanStateDuty17") or "").strip() == "5 017 245"


def test_ссудная_гп_живёт_и_без_основного_долга(generator):
    д = подготовить(generator, {"loanStateDuty17": "2 000,00"})
    assert str(д.get("loanStateDuty17") or "").strip() == "2 000"
    assert что_в_13(д) == ""

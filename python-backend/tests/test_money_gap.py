# -*- coding: utf-8 -*-
"""Зазор между суммой и ярлыком в паттернах «с запасом» (MONEY_GAP).

Паттерны «(СУММА) руб <зазор> ЯРЛЫК» и «ЯРЛЫК <зазор> (СУММА) руб» — последний
слой разбора финансов: он срабатывает, когда метка не нашлась. Зазор [^,\n]*
давал два дефекта сразу, и оба найдены на настоящем заявлении
(Заявл_Ликвидир_Оргтехника.docx, снято из корпуса 11.10.2026):

  А. зазор перескакивал «;» и дотягивался от суммы ОДНОГО слагаемого до ярлыка
     СЛЕДУЮЩЕГО — ссудная задолженность выдавалась за проценты, и общая сумма
     долга удваивалась (988 342 671,34 вместо 501 365 000,90);
  Б. зазор съедал часть самого числа, потому что останавливался только на
     запятой — а запятая стоит ВНУТРИ суммы: «2 852 638,84» -> «638,84».
     Ошибка в 4500 раз, и число выглядит правдоподобно.

Проверяем на РЕАЛЬНОМ реестре паттернов (build_patterns), а не на копии: иначе
тест проверял бы выдуманную регулярку, а не ту, по которой идёт разбор.

⚠️ На текущем корпусе правка НЕ меняет вывод ни одного поля (замер 11.10.2026:
98 документов, 0 изменений) — до этих паттернов всегда доходит более точный
слой. Поэтому защита возможна ТОЛЬКО здесь, на уровне паттерна.
"""
import os
import re
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from patterns import build_patterns  # noqa: E402


def _паттерны(поле: str):
    for группа in build_patterns().values():
        for описание in группа:
            if описание["name"] == поле:
                return описание["patterns"]
    raise AssertionError("поле %s не найдено в реестре паттернов" % поле)


def _первое(поле: str, текст: str):
    """Повторяет цикл разбора: рвётся на ПЕРВОМ совпавшем паттерне."""
    for пат in _паттерны(поле):
        m = re.search(пат, текст, re.IGNORECASE | re.MULTILINE)
        if m:
            return m.group(1).strip()
    return None


# Фраза из настоящего заявления: два слагаемых одного перечня через «;».
ПЕРЕЧЕНЬ = ("просроченная ссудная задолженность – 494 171 335,67 рублей; "
            "просроченные проценты за кредит - 2 852 638,84 руб.")


def test_zazor_ne_pereskakivaet_tochku_s_zapyatoy():
    """Дефект А: проценты не должны получить сумму ПРЕДЫДУЩЕГО слагаемого."""
    assert _первое("interest", ПЕРЕЧЕНЬ) != "494 171 335,67", (
        "зазор перескочил «;» и выдал ссудную задолженность за проценты")


def test_procenty_iz_perechnya_berutsya_celikom():
    """Дефекты А и Б вместе: из того же перечня берётся ВЕРНОЕ число целиком."""
    assert _первое("interest", ПЕРЕЧЕНЬ) == "2 852 638,84"


def test_zazor_ne_sedaet_tysyachi():
    """Дефект Б: зазор не имеет права остановиться на запятой ВНУТРИ суммы."""
    факт = _первое("interest", "проценты за кредит - 2 852 638,84 руб.")
    assert факт == "2 852 638,84", "потеряны тысячи: %r" % факт


@pytest.mark.parametrize(("поле", "ярлык", "сумма"), [
    ("principalDebt", "основной долг", "1 234 567,89"),
    ("loanDebt", "ссудная задолженность", "2 345 678,90"),
    ("penalties", "штраф", "3 456 789,01"),
    ("forfeit", "неустойка", "4 567 890,12"),
    # «пени» — не отдельное поле: их паттерны лежат в том же forfeit.
    ("forfeit", "пени", "5 678 901,23"),
    ("totalDebt", "общая сумма долга", "6 789 012,34"),
])
def test_tysyachi_cely_u_vseh_polej_s_zapasom(поле, ярлык, сумма):
    """Дефект Б был ОДИН на все поля «с запасом» — правили общей константой."""
    факт = _первое(поле, "%s за период - %s руб." % (ярлык, сумма))
    assert факт == сумма, "%s: потеряны тысячи, получено %r" % (поле, факт)


@pytest.mark.parametrize(("поле", "ярлык"), [
    ("principalDebt", "основной долг"),
    ("interest", "просроченные проценты"),
    ("forfeit", "неустойка"),
])
def test_obychnaya_zapis_tire_ne_slomana(поле, ярлык):
    """Цена правки: обычная запись «СУММА руб — ЯРЛЫК» обязана работать.

    Зазор сузили, и если сузили лишком — сломались бы все тире-перечни,
    на которых держится разбор просительной части.
    """
    assert _первое(поле, "7 654 321,00 руб. – %s" % ярлык) == "7 654 321,00"


def test_zazor_ne_pereskakivaet_u_neustojki():
    """Дефект А был общим: запрет «;» обязан действовать и у неустойки."""
    текст = ("основной долг – 100 000,00 рублей; "
             "неустойка за просрочку - 2 500,00 руб.")
    assert _первое("forfeit", текст) == "2 500,00"

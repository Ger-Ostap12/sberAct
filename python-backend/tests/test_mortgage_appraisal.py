# -*- coding: utf-8 -*-
"""Отчёт об оценке и рыночная стоимость залога в ипотечных заявлениях (08.09.2026).

Оба поля пустовали или несли мусор на пяти документах корпуса, и по одной
причине: разбор был написан под ОДНУ вёрстку, а их две.

    вёрстка A   «…(отчет об оценке №3782800 от 12.12.2022), которая составила
                7166525 руб.» — номер отчёта есть, слов «рыночная стоимость»
                рядом со значением НЕТ
    вёрстка B   «Согласно заключению о стоимости имущества от 14.05.2026
                рыночная стоимость объекта недвижимости составляет 1 787 000
                руб.» — номера отчёта нет вовсе, значение по прежнему якорю

Ловушка вёрстки A: абзацем выше стоит «обеспечено отчетом об оценке стоимости
объекта недвижимости» — без номера. Прежний паттерн `(/?Отчет[^\\s,\\n]+)`
брал оттуда одно слово и клал в поле «отчетом».
"""
import os
import re
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _поля(analyzer, текст):
    return analyzer.extract_fields(текст, "mortgage_claim")


ВЁРСТКА_A = (
    "Исполнение обязательств обеспечено отчетом об оценке стоимости объекта "
    "недвижимости. При заключении кредитного договора банком была проведена "
    "оценка по определению рыночной стоимости объекта недвижимости "
    "(отчет об оценке №3782800 от 12.12.2022), которая составила 7166525 руб., "
    "в том числе жилого дома - 4 069 525 руб., земельный участок - 3 097 000 руб."
)

ВЁРСТКА_B = (
    "Согласно заключению о стоимости имущества от 14.05.2026 рыночная стоимость "
    "объекта недвижимости составляет 1 787 000 руб. Следовательно, начальная "
    "продажная цена должна быть установлена в размере 1429600 руб."
)


# --- номер отчёта ------------------------------------------------------------

def test_номер_и_дата_отчёта(analyzer):
    assert _поля(analyzer, ВЁРСТКА_A)["mortgageAppraisalReport1223"] == \
        "№3782800 от 12.12.2022"


def test_соседняя_фраза_без_номера_не_подменяет(analyzer):
    """Главная ловушка: «отчетом об оценке стоимости объекта» идёт РАНЬШЕ."""
    поля = _поля(analyzer, ВЁРСТКА_A)
    assert поля["mortgageAppraisalReport1223"] != "отчетом"


@pytest.mark.parametrize("текст, ждём", [
    ("отчет об оценке № 1877 от 15.03.2023", "№ 1877 от 15.03.2023"),
    ("отчет об оценке № 170/59-1204", "№ 170/59-1204"),          # без даты
    ("отчет об оценке № Н-243/2024 от 22.08.2024 г.", "№ Н-243/2024 от 22.08.2024"),
])
def test_варианты_номера(analyzer, текст, ждём):
    """Буква в номере, дробь, отсутствие даты, хвост «г.» после даты."""
    assert _поля(analyzer, текст)["mortgageAppraisalReport1223"] == ждём


def test_без_номера_поле_пустое(analyzer):
    """Вёрстка B: отчёта с номером в документе нет — выдумывать нечего."""
    assert not _поля(analyzer, ВЁРСТКА_B).get("mortgageAppraisalReport1223")


# --- рыночная стоимость ------------------------------------------------------

def test_стоимость_придаточным(analyzer):
    """Вёрстка A: значение висит на обороте «которая составила»."""
    assert _поля(analyzer, ВЁРСТКА_A)["mortgageCollateralValue1224"] == "7166525"


def test_стоимость_прежним_якорем_не_сломана(analyzer):
    """Вёрстка B работала и обязана работать дальше."""
    assert _поля(analyzer, ВЁРСТКА_B)["mortgageCollateralValue1224"] == "1 787 000"


def test_слагаемые_не_попадают_в_итог(analyzer):
    """За итогом идёт «в том числе …» — разбивка не должна вытеснить сумму."""
    поля = _поля(analyzer, ВЁРСТКА_A)
    assert поля["mortgageCollateralValue1224"] == "7166525"
    assert "4 069 525" not in (поля.get("mortgageCollateralValue1224") or "")


def test_паттерн_не_ловит_чужое_составила(analyzer):
    """«которая составила» без числа рядом значения не даёт."""
    поля = _поля(analyzer, "Задолженность, которая составила существенный размер.")
    assert not поля.get("mortgageCollateralValue1224")


def test_регулярка_номера_требует_решётку():
    """Ни один паттерн не смеет срабатывать на фразе БЕЗ номера.

    Строка взята из документа дословно — именно на ней прежний
    `(/?Отчет[^\s,\n]+)` давал «отчетом».
    """
    from patterns import build_patterns

    правило = next(p for p in build_patterns()["mortgage_claim"]
                   if p["name"] == "mortgageAppraisalReport1223")
    ловушка = "обеспечено отчетом об оценке стоимости объекта недвижимости"
    сработали = [pat for pat in правило["patterns"]
                 if re.search(pat, ловушка, re.IGNORECASE)]
    assert not сработали, сработали

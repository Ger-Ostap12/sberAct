# --- ворота: точка-конец-предложения по-прежнему обрывает зазор -------------------

def test_зазор_терпит_сокращение_и_дату_но_не_конец_фразы(analyzer):
    """Проверка САМОГО зазора, а не слоя целиком.

    ⚠️ Первая редакция этого сторожа проверяла слой через
    `_apply_prayer_finances` и краснела: когда верб-блок не найден, слой
    уходит в ЗАПАСНОЙ путь и берёт сумму по якорю «в том числе» — поведение
    прежнее и к зазору отношения не имеющее. Тест обязан смотреть на то,
    что менялось.
    """
    зазор = re.compile(analyzer._ЗАЗОР_ДО_СУММЫ + r"ЦЕЛЬ", re.IGNORECASE)
    assert зазор.match("модель Jetta 2013 г.в.\nVIN-номер ЦЕЛЬ"), "сокращение"
    assert зазор.match("по договору № 186410 от 11.10.2010 ЦЕЛЬ"), "дата"
    assert not зазор.match("обязательным для исполнения. По договору ЦЕЛЬ"), \
        "зазор перешагнул границу предложения"


def test_один_договор_разбирается_как_прежде(analyzer):
    """Ворота, а не запрет: обычная просьба с одним договором не задета."""
    текст = (
        "ПРОШУ:\n"
        "1. Включить требование в реестр требований кредиторов должника "
        "в размере 100 000,00 рублей, в том числе: 90 000,00 рублей - "
        "основной долг, 10 000,00 рублей - проценты.\n"
    )
    п = просьба(analyzer, текст)
    assert п.get("totalDebt") == "100 000,00"
    assert п.get("principalDebt") == "90 000,00"


def test_продолжение_без_разбивки_не_берётся(analyzer):
    """Продолжение перечня обязано нести СВОЮ разбивку, сходящуюся с подытогом."""
    текст = (
        "ПРОШУ:\n"
        "1. Включить требование по договору № 1 в размере 100 000,00 рублей, "
        "в том числе: 90 000,00 рублей - основной долг, 10 000,00 рублей - "
        "проценты; по договору № 2 в размере 50 000,00 рублей.\n"
    )
    assert просьба(analyzer, текст).get("totalDebt") == "100 000,00"

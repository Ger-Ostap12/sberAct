# --- свежие-17: перенос внутри слова-якоря ----------------------------------------

# ⚠️ ТЕЛО ДОКУМЕНТА ОБЯЗАТЕЛЬНО. Без него тест зеленел и на СТАРОМ коде:
# запасной путь слоя не находил ни «из которых», ни «в том числе», падал на
# якорь «просит суд» и разбирал ту же самую просительную часть — то есть
# приходил к верному ответу СЛУЧАЙНО. У настоящего документа первым идёт
# «из которых» ТЕЛА, и запасной путь брал один договор из двух
# (ср. test-fakes-must-lie-like-prod — пятый случай за фазу).
ЯКОРЬ_С_ПЕРЕНОСОМ = (
    "Должником в настоящее время нарушаются обязательства, принятые по "
    "договору. По состо-янию на 22.06.2026 образовалась задолженность "
    "в размере 213 301,56 руб., из которых:\n"
    "- 165 316,04 руб. – просроченный основной долг\n"
    "- 37 055,64 руб. – просроченные проценты\n"
    "- 3 987.77 руб. – просроченные проценты на просроченный основной долг "
    "- 3 304,60 руб. – неустойка за просроченный основной долг\n"
    "- 3 637,51 руб. – неустойка за просроченные проценты\n"
    "ПРОСИТ СУД:\n"
    "1. Включить требования ПАО Сбербанк в третью очередь реестра требований "
    "кредиторов ЕПИФАНОВСКОГО ВЛАДИСЛАВА МИХАЙЛОВИЧА в размере "
    "388 812,32рублей.,из ко-торых:\n"
    "- 292 603,97 руб. – просроченный основной долг\n"
    "- 74 417,09 руб. – просроченные проценты\n"
    "- 8 011.52 руб. – просроченные проценты на просроченный основной долг "
    "- 5 996,07 руб. – неустойка за просроченный основной долг\n"
    "- 7 783,67 руб. – неустойка за просроченные проценты\n"
)


def test_перенос_внутри_якоря_не_мешает(analyzer):
    """«из ко-торых» — запёкшаяся расстановка переносов из PDF."""
    п = просьба(analyzer, ЯКОРЬ_С_ПЕРЕНОСОМ)
    assert п.get("totalDebt") == "388 812,32"
    assert п.get("principalDebt") == "292 603,97"


def test_разбивка_с_переносом_сходится_до_копейки(analyzer):
    """292 603,97 + 74 417,09 + 8 011,52 + 5 996,07 + 7 783,67 = 388 812,32."""
    п = просьба(analyzer, ЯКОРЬ_С_ПЕРЕНОСОМ)
    assert п.get("interest") == "82 428,61"
    assert п.get("forfeit") == "13 779,74"



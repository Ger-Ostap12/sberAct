# -*- coding: utf-8 -*-
"""Склонение ФИО в анализаторе (фаза 3, пункт 3.6 — падежи).

Три красных эталона имели ОДИН корень: анализатор склонял ФИО своим пословным
методом через `parse[0]`, минуя унаследованный InflectionMixin, который знает
про род и про предпочтение Surn-разбора. Тесты закрывают и корень, и обе
формы дефекта, которые он давал.
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from inflection_mixin import InflectionMixin  # noqa: E402
from morph_utils import detect_gender, inflect_given_name, inflect_surname  # noqa: E402

# Метод анализатора вызывается НЕСВЯЗАННЫМ: так проверяется именно делегирование
# в миксин, без подъёма тяжёлого DocumentAnalyzer (spaCy, справочники).
склонить = DocumentAnalyzer._convert_full_name_case


@pytest.fixture(scope="module")
def морф():
    pymorphy3 = pytest.importorskip("pymorphy3")
    return pymorphy3.MorphAnalyzer()


@pytest.fixture(scope="module")
def склонятель():
    """Голый носитель миксина — тот же путь, которым идёт анализатор."""
    pytest.importorskip("pymorphy3")

    class _Склонятель(InflectionMixin):
        def __init__(self):
            self.morph = None

    return _Склонятель()


# --- РОД ПО ОТЧЕСТВУ ---------------------------------------------------------

@pytest.mark.parametrize("фио,ожидаемый_род", [
    (["Нуриева", "Елена", "Валидиновна"], "femn"),
    (["Путова", "Совдаш", "Ромзановна"], "femn"),
    (["Налибаев", "Андрей", "Михайлович"], "masc"),
    (["Сипакова", "Алина", "Олеговна"], "femn"),
])
def test_род_определяется_по_отчеству(фио, ожидаемый_род):
    assert detect_gender(фио) == ожидаемый_род


# --- ТРИ КРАСНЫХ ЭТАЛОНА -----------------------------------------------------

@pytest.mark.parametrize("имя,дательный", [
    # корпус-2: сам документ пишет «выдало кредит НУРИЕВОЙ ЕЛЕНЕ ВАЛИДИНОВНЕ»
    ("Нуриева Елена Валидиновна", "Нуриевой Елене Валидиновне"),
    # корпус-3: «Совдаш» не склоняется — документ в родительном тоже оставляет
    # его как есть («ПУТОВОЙ СОВДАШ РОМЗАНОВНЫ»)
    ("Путова Совдаш Ромзановна", "Путовой Совдаш Ромзановне"),
    # корпус-8: мужская фамилия на -ев, которую pymorphy читал как род.мн.
    ("Налибаев Андрей Михайлович", "Налибаеву Андрею Михайловичу"),
])
def test_дательный_падеж_трёх_красных(склонятель, имя, дательный):
    assert склонить(склонятель, имя, "datv") == дательный


# --- ДЕФЕКТ 1: ЖЕНСКАЯ ФАМИЛИЯ ПО МУЖСКОМУ ТИПУ ------------------------------

@pytest.mark.parametrize("фамилия,падеж,ожидание", [
    ("Нуриева", "datv", "Нуриевой"),
    ("Нуриева", "gent", "Нуриевой"),
    ("Путова", "datv", "Путовой"),
    ("Кузнецова", "datv", "Кузнецовой"),
    ("Сипакова", "datv", "Сипаковой"),
])
def test_женская_фамилия_не_уходит_в_мужской_род(морф, фамилия, падеж, ожидание):
    assert inflect_surname(морф, фамилия, падеж, "femn") == ожидание


def test_мужская_фамилия_склоняется_по_мужскому(морф):
    assert inflect_surname(морф, "Нуриев", "datv", "masc") == "Нуриеву"
    assert inflect_surname(морф, "Налибаев", "datv", "masc") == "Налибаеву"


# --- ДЕФЕКТ 2: ЧУЖАЯ ПАРАДИГМА У РЕДКОГО ИМЕНИ -------------------------------

def test_редкое_имя_не_склоняется_вместо_выдумки(морф):
    """«Совдаш» разбирается как род.мн. (Name,plur,gent) — отсюда «Совдашам».

    Разбора «имя, ед.ч., им.п., женский род» у него нет, значит склонять нечем.
    """
    assert inflect_given_name(морф, "Совдаш", "datv", "femn") == "Совдаш"
    assert inflect_given_name(морф, "Совдаш", "gent", "femn") == "Совдаш"


def test_инициал_не_склоняется(морф):
    """У «А.» нет разбора имени — раньше parse[0] мог отдать что угодно."""
    assert inflect_given_name(морф, "А.", "datv", "masc") == "А."


@pytest.mark.parametrize("имя,род,падеж,ожидание", [
    ("Елена", "femn", "datv", "Елене"),
    ("Мария", "femn", "gent", "Марии"),
    ("Андрей", "masc", "datv", "Андрею"),
    ("Тимур", "masc", "datv", "Тимуру"),
    ("Валидиновна", "femn", "datv", "Валидиновне"),
    ("Михайлович", "masc", "datv", "Михайловичу"),
    ("Ромзановна", "femn", "gent", "Ромзановны"),
])
def test_обычные_имена_и_отчества_склоняются(морф, имя, род, падеж, ожидание):
    assert inflect_given_name(морф, имя, падеж, род) == ожидание


def test_имя_любовь_склоняется_как_имя_а_не_как_чувство(морф):
    """Разбор ИМЕНИ (Name) сильнее нарицательного: «Любови», не «Любви»."""
    assert inflect_given_name(морф, "Любовь", "datv", "femn") == "Любови"


# --- ПОЛНЫЕ ФИО, ОСТАЛЬНЫЕ ПАДЕЖИ --------------------------------------------

@pytest.mark.parametrize("падеж,ожидание", [
    ("gent", "Нуриевой Елены Валидиновны"),
    ("datv", "Нуриевой Елене Валидиновне"),
    ("accs", "Нуриеву Елену Валидиновну"),
])
def test_женское_фио_во_всех_падежах(склонятель, падеж, ожидание):
    assert склонить(склонятель, "Нуриева Елена Валидиновна", падеж) == ожидание


@pytest.mark.parametrize("падеж,ожидание", [
    ("gent", "Налибаева Андрея Михайловича"),
    ("datv", "Налибаеву Андрею Михайловичу"),
    ("accs", "Налибаева Андрея Михайловича"),
])
def test_мужское_фио_во_всех_падежах(склонятель, падеж, ожидание):
    assert склонить(склонятель, "Налибаев Андрей Михайлович", падеж) == ожидание


def test_регистр_исходника_сохраняется(склонятель):
    assert склонить(склонятель, "НУРИЕВА ЕЛЕНА ВАЛИДИНОВНА", "datv") == \
        "НУРИЕВОЙ ЕЛЕНЕ ВАЛИДИНОВНЕ"


def test_двойная_фамилия_склоняется_по_частям(склонятель):
    assert склонить(склонятель, 
        "Петрова-Водкина Анна Ивановна", "datv") == "Петровой-Водкиной Анне Ивановне"


def test_пустое_имя_не_падает(склонятель):
    assert склонить(склонятель, "", "datv") is None
    assert склонить(склонятель, "   ", "datv") is None


def test_именительный_возвращается_как_есть(морф):
    assert inflect_given_name(морф, "Елена", "nomn", "femn") == "Елена"
    assert inflect_surname(морф, "Нуриева", "nomn", "femn") == "Нуриева"

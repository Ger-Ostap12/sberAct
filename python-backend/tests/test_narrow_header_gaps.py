# -*- coding: utf-8 -*-
"""Четыре дыры разбора узкой шапки, найденные на живых заявлениях (§S.6.12).

Часть заявлений печатает шапку колонкой в 30-45 символов, и значение поля рвётся
переносом посреди фразы. Признак разрыва — ПРОБЕЛ в конце строки (мягкий перенос
абзаца) или обрыв на сокращении, которым значение кончиться не может («… вн. тер.
г.»). Жёсткий разрыв (новое поле с новой строки) ни того ни другого не даёт —
именно поэтому склейку строк по МЕДИАНЕ ДЛИНЫ пришлось откатить: она эти два
случая не различала и портила ипотечные заявления, где каждая строка шапки —
отдельное поле.

Закрытые здесь дыры (каждая проявилась на реальном документе):
  1. дата рождения в форме «30.08.1985 года р.»;
  2. «уроженец(ка)» как метка места рождения;
  3. адрес кредитора БЕЗ почтового индекса («Адрес: г. Санкт-Петербург, …»);
  4. реквизиты кредитора во ВТОРОМ блоке, за окном блока кредитора в шапке.

Отрицательные проверки здесь не менее важны положительных: каждое послабление
разбора — это ещё и риск утащить в поле соседнее значение.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from fio_detector import _find_birthdate, extract_debtor_details  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- 1. Дата рождения «года р.» ---------------------------------------------

@pytest.mark.parametrize("text,expected", [
    ("Должник: Медведев Максим Юрьевич\n30.08.1985 года р.,", "30.08.1985"),
    ("Должник: Иванов Иван Иванович\n01.02.1970 год р.", "01.02.1970"),
    # Уже поддержанные формы не должны сломаться.
    ("Должник: Петров Пётр\n05.06.1980 г.р.", "05.06.1980"),
    ("Должник: Сидоров С.С.\n07.08.1990 года рождения", "07.08.1990"),
    ("Должник: Кузнецов К.К.\nДата рождения: 09.10.1995", "09.10.1995"),
])
def test_дата_рождения_распознаётся(text, expected):
    assert _find_birthdate(text) == expected


def test_года_без_точки_после_р_не_считается_датой_рождения():
    """«… 19.12.2025 года районным судом» — не дата рождения.

    Точка после «р» — единственное, что отличает сокращение «года р.» от начала
    обычного слова, поэтому она обязательна.
    """
    assert _find_birthdate("Судебный приказ от 19.12.2025 года районным судом") is None


# --- 2. «уроженец(ка)» как метка места рождения ------------------------------

def test_уроженец_ка_это_метка_места_рождения():
    block = (
        "Должник: Медведев Максим Юрьевич\n"
        "30.08.1985 года р.,\n"
        "уроженец(ка) Пос. Шолоховский\n"
        "Паспорт: 6005 561928\n"
    )
    assert extract_debtor_details(block)["birthPlace"] == "Пос. Шолоховский"


def test_значение_склеивается_через_мягкий_перенос():
    """Строка оборвалась ПРОБЕЛОМ — значит, значение продолжается следующей."""
    block = (
        "Должник: Медведев Максим Юрьевич\n"
        "уроженец(ка) Пос. Шолоховский г. Белая \n"
        "Калитва Ростовской обл.\n"
        "Паспорт: 6005 561928\n"
    )
    assert (extract_debtor_details(block)["birthPlace"]
            == "Пос. Шолоховский г. Белая Калитва Ростовской обл.")


def test_строка_метка_не_утягивается_в_значение():
    """Пробел в конце строки не должен утаскивать в значение соседнее ПОЛЕ."""
    block = (
        "Должник: Медведев Максим Юрьевич\n"
        "уроженец(ка) Пос. Шолоховский \n"
        "Паспорт: 6005 561928\n"
    )
    assert extract_debtor_details(block)["birthPlace"] == "Пос. Шолоховский"


def test_место_рождения_обрывается_на_первом_реквизите():
    """Реквизиты идут ОДНОЙ строкой — иначе в поле уезжает вся запись должника."""
    block = (
        "Должник:\n"
        "Буниатян Алина Генриковна (дата рождения: 28.03.2001 г., "
        "место рождения: гор. Новочеркасск Ростовская область, "
        "СНИЛС 158-801-520 75, ИНН 612504512780, адрес регистрации: 346496)\n"
    )
    assert (extract_debtor_details(block)["birthPlace"]
            == "гор. Новочеркасск Ростовская область")


# --- 3. Адрес кредитора без почтового индекса --------------------------------

_COLLECTOR_HEADER = (
    "Взыскатель: Общество с ограниченной \n"
    "ответственностью ПКО Юнона\n"
    "Адрес: г. Санкт-Петербург, вн. тер. г.\n"
    "Муниципальный округ Большая Охта, ул. \n"
    "Магнитогорская, д.23, к.1, литера А, офис \n"
    "332, ком. 43-Н\n"
    "ИНН: 7806253521\n"
)


def test_адрес_без_индекса_извлекается(analyzer):
    """Слои выше требуют `[0-9]{6}`, а адрес может начинаться прямо с города."""
    addr = analyzer._extract_creditor_address(_COLLECTOR_HEADER)
    assert addr == ("г. Санкт-Петербург, вн. тер. г. Муниципальный округ Большая Охта, "
                    "ул. Магнитогорская, д.23, к.1, литера А, офис 332, ком. 43-Н")


def test_почтовый_адрес_не_считается_юридическим(analyzer):
    block = (
        "Взыскатель: ООО ПКО Юнона\n"
        "Почтовый адрес: г. Санкт-Петербург, ул. Магнитогорская, д. 23\n"
        "ИНН: 7806253521\n"
    )
    assert analyzer._creditor_address_without_index(block) is None


def test_метка_адрес_без_географии_не_даёт_значения(analyzer):
    block = (
        "Взыскатель: ООО ПКО Юнона\n"
        "Адрес: см. приложение № 1 к настоящему заявлению\n"
        "ИНН: 7806253521\n"
    )
    assert analyzer._creditor_address_without_index(block) is None


def test_вн_тер_г_не_считается_вторым_городом(analyzer):
    """«вн. тер. г. …» — часть ОДНОГО адреса в формате ФИАС, а не склейка двух."""
    addr = ("г. Санкт-Петербург, вн. тер. г. Муниципальный округ Большая Охта, "
            "ул. Магнитогорская, д.23")
    assert analyzer._truncate_glued_address(addr) == addr


def test_литера_офиса_не_считается_вторым_домом(analyzer):
    """«оф. Д13» — не второй дом: без разделителя это литера офиса."""
    addr = "121096, г. Москва, ул. Василисы Кожиной, д. 1, оф. Д13"
    assert analyzer._truncate_glued_address(addr) == addr


def test_склейка_двух_адресов_по_прежнему_режется(analyzer):
    """Гард на настоящую склейку должен остаться рабочим."""
    glued = "г. Москва, ул. Тверская, д. 1 г. Казань, ул. Баумана, д. 5"
    assert analyzer._truncate_glued_address(glued) == "г. Москва, ул. Тверская, д. 1"


# --- 4. Реквизиты кредитора во втором блоке ----------------------------------

_PAY_TAIL = (
    "сообщаю наименование, место нахождения и банковские реквизиты Организации:\n"
    "Наименование организации: ООО ПКО Юнона\n"
    "Юридический адрес: 121096, г. Москва, ул. Василисы Кожиной, д. 1\n"
    "ИНН: 7806253521\n"
    "КПП: 780601001\n"
    "ОГРН: 1167847404053\n"
)


def test_реквизиты_из_платёжного_блока(analyzer):
    req = analyzer._extract_payment_requisites(_PAY_TAIL)
    assert req["inn"] == "7806253521"
    assert req["ogrn"] == "1167847404053"
    assert req["address"] == "121096, г. Москва, ул. Василисы Кожиной, д. 1"


def test_депозитный_счёт_суда_не_реквизиты_кредитора(analyzer):
    """Депозит АС — счёт СУДА, приписывать его кредитору нельзя."""
    text = (
        "Платежные реквизиты для внесения средств на депозитный счет суда:\n"
        "ИНН: 7706562710\nОГРН: 1047796991550\n"
    )
    assert analyzer._extract_payment_requisites(text) == {}


def test_чужой_инн_в_платёжном_блоке_не_даёт_огрн(analyzer):
    """Блок с ДРУГИМ ИНН описывает другое лицо — его ОГРН брать нельзя.

    Платёжный блок отнесён в конец документа намеренно: только там он лежит вне
    окна блока кредитора, и единственный путь к нему — новый фолбэк.
    """
    fields = {"creditorName": "ООО ПКО Юнона"}
    text = (
        "Взыскатель: ООО ПКО Юнона\n"
        "ИНН: 7806253521\n"
        "Адрес: г. Санкт-Петербург, ул. Магнитогорская, д. 23\n"
        "Должник: Медведев Максим Юрьевич\n"
        + "Текст заявления по существу требования. " * 40
        + "\nБанковские реквизиты:\n"
        "ИНН: 7730233723\n"
        "ОГРН: 1177746355225\n"
    )
    analyzer._fill_creditor_requisites(fields, text)
    assert fields.get("creditorInn") == "7806253521"
    assert not fields.get("creditorOgrn")

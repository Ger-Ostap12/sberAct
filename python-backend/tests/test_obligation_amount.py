# -*- coding: utf-8 -*-
"""Сумма долга в карточке обязательства (08.09.2026).

Семь документов корпуса несли в карточке неправду, и причин три:

1. Класс числа `[0-9\\s,]+` обрывался на ТОЧКЕ. Банки пишут копейки и через
   запятую («2789060,93»), и через точку («7371840.35») — во втором случае
   карточка получала «7 371 840,00».
2. Копейки бывают оторваны пробелом — «138 909, 16 руб.» (артефакт
   конвертера). Прежний класс их склеивал случайно, потому что жадно глотал
   и пробелы, и запятые; строгий класс обязан это уметь осознанно.
3. Фраза-якорь была одна («образовалась задолженность в размере»), а вёрстки
   две: на трёх документах сумма названа как «…задолженности по кредитному
   договору от 26.10.2023 №… составляет X руб.», и карточка получала
   выдуманный «0,00».

Отдельно: сборщик, который находит только НОМЕРА договоров, суммы не искал
вовсе — карточка уходила на форму без суммы. Теперь ищет, но якорем служит
сам номер договора, поэтому чужая сумма подставиться не может.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _карточки(analyzer, текст):
    поля = {}
    return analyzer.extract_obligations(текст, поля)


def _блок(тело: str) -> str:
    """Заявление с одним блоком «Обязательство 1:» — минимум, который нужен."""
    return ("Должник имеет неисполненные обязательства.\n"
            "Обязательство 1: Банк и должник заключили кредитный договор №1271058 "
            "от 28.10.2022. " + тело)


# --- копейки -----------------------------------------------------------------

@pytest.mark.parametrize("тело, ждём", [
    ("образовалась задолженность в размере 7371840.35 руб.", "7 371 840,35"),
    ("образовалась задолженность в размере 2789060,93 руб.", "2 789 060,93"),
    ("образовалась задолженность в размере 1 249 122,53 руб.", "1 249 122,53"),
    # Копейки оторваны пробелом — так печатает конвертер таблиц
    ("образовалась задолженность в размере 138 909, 16 руб.", "138 909,16"),
])
def test_копейки_не_теряются(analyzer, тело, ждём):
    карточки = _карточки(analyzer, _блок(тело))
    assert карточки[0]["amount"] == ждём


def test_точка_с_пробелом_не_копейки(analyzer):
    """«500000. 15 марта» — точка тут конец предложения, а не разделитель."""
    карточки = _карточки(analyzer, _блок(
        "образовалась задолженность в размере 500000. 15 марта направлено требование."))
    assert карточки[0]["amount"] == "500 000,00", "копейки «15» приехали из даты"


# --- вторая вёрстка фразы ----------------------------------------------------

def test_вёрстка_составляет(analyzer):
    """Трёх документов корпуса фраза «образовалась» не касается вовсе."""
    карточки = _карточки(analyzer, _блок(
        "Размер и состав требования. В соответствии с расчетом задолженности по "
        "состоянию на 29.05.2026 размер просроченной задолженности по кредитному "
        "договору от 26.10.2023 №6123013561-23-1 составляет 2789060,93 руб. "
        "в том числе: - просроченный основной долг 2294779,03 руб."))
    assert карточки[0]["amount"] == "2 789 060,93"


def test_дата_и_номер_в_разрыве_не_мешают(analyzer):
    """Между «договору» и «составляет» стоят дата и номер — оба с точками.

    Из-за них окно задано как [\\s\\S]{0,140}, а не [^.]: класс «всё, кроме
    точки» разрывался бы на дате договора.
    """
    карточки = _карточки(analyzer, _блок(
        "По состоянию на 19.05.2025 задолженность по кредитному договору "
        "№1271058 от 28.10.2022 составляет 1 249 122,53 руб. из которых: "
        "- 1 241 195,88 руб. просроченный основной долг"))
    assert карточки[0]["amount"] == "1 249 122,53"


def test_слагаемые_разбивки_не_вытесняют_итог(analyzer):
    """За итогом идёт «в том числе …» — итог обязан остаться итогом."""
    карточки = _карточки(analyzer, _блок(
        "образовалась задолженность в размере 437176.96 руб., из которых: "
        "- 295330.43 руб. просроченный основной долг, "
        "- 141846.53 руб. просроченные проценты."))
    assert карточки[0]["amount"] == "437 176,96"


# --- сумма по якорю на номер договора ----------------------------------------

ДВА_ДОГОВОРА = (
    "Должник имеет следующие не исполненные денежные обязательства перед "
    "Кредитором.\n"
    "Банк и должник заключили кредитный договор №332552560 от 02.08.2011. "
    "Итого, общая сумма задолженности по договору №332552560: 679023.89 руб.\n"
    "Банк и должник заключили кредитный договор №12434716027 от 02.04.2025. "
    "Итого, общая сумма задолженности по договору №12434716027: 65835.14 руб."
)


def _по_номерам(analyzer, текст):
    """Сборщик, который находит только НОМЕРА договоров.

    Он срабатывает, когда блоков «Обязательство N:» в заявлении нет, и до
    08.09.2026 суммы не искал вовсе — карточка уходила на форму без суммы.
    """
    карточки = []
    analyzer._parse_obligations_fallback({}, текст, карточки)
    return {к.get("contractNumber"): к.get("amount") for к in карточки}


def test_сумма_по_номеру_договора(analyzer):
    по_номеру = _по_номерам(analyzer, ДВА_ДОГОВОРА)
    assert по_номеру.get("332552560") == "679 023,89"


def test_чужая_сумма_не_приезжает(analyzer):
    """Главная защита: якорь — сам номер, а обязательств в деле бывает десяток."""
    по_номеру = _по_номерам(analyzer, ДВА_ДОГОВОРА)
    assert по_номеру.get("12434716027") == "65 835,14"
    assert по_номеру.get("332552560") != по_номеру.get("12434716027")


def test_без_суммы_поле_не_появляется(analyzer):
    """Пусто лучше выдуманного нуля: ключа amount просто нет."""
    карточки = []
    analyzer._parse_obligations_fallback(
        {}, "Банк и должник заключили кредитный договор №332552560 от 02.08.2011.",
        карточки)
    assert карточки, "карточка обязательства должна найтись"
    assert "amount" not in карточки[0]

# -*- coding: utf-8 -*-
"""Сумма в карточке канонического сборщика (21.09.2026, фаза 6 п.1).

Канон `_extract_obligations_primary` клал в карточку только номер, дату и
тип — суммы он не искал ВОВСЕ, и юрист видел на форме договор без долга.
Девять документов корпуса уходили так.

Отдельно: «сумма по ЭТОМУ договору» знала две вёрстки, а Совкомбанк и ЦДУ
Инвест пишут третью:

    По кредитному договору № 10050033429 от "22" апреля 2024 года -
    в размере 218574.56 руб.

Между номером и суммой стоит дата ПРОПИСЬЮ, поэтому разрыв здесь — окно в
строке, а не «всё, кроме цифр», как в двух прежних формах.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _карточки(analyzer, текст):
    return analyzer.extract_obligations(текст, {})


ДВА_ДОГОВОРА = (
    '1. "22" апреля 2024 года между Банком и Должником был заключен кредитный '
    'договор (в виде акцептованного заявления оферты) № 10050033429. '
    'По кредитному договору № 10050033429 от "22" апреля 2024 года - '
    'в размере 218574.56 руб., что подтверждается расчетом задолженности:\n'
    '2. "28" сентября 2023 года между Банком и Должником был заключен кредитный '
    'договор (в виде акцептованного заявления оферты) № 8963411620. '
    'По кредитному договору № 8963411620 от "28" сентября 2023 года - '
    'в размере 66849.19 руб., что подтверждается расчетом задолженности:\n'
)


def test_сумма_появляется_в_карточке(analyzer):
    суммы = [к.get("amount") for к in _карточки(analyzer, ДВА_ДОГОВОРА)]
    assert суммы == ["218 574,56", "66 849,19"]


def test_сумма_привязана_к_своему_договору(analyzer):
    """Якорь — сам номер, поэтому сумма соседа подставиться не может."""
    пары = [(к.get("contractNumber"), к.get("amount"))
            for к in _карточки(analyzer, ДВА_ДОГОВОРА)]
    assert пары == [("10050033429", "218 574,56"), ("8963411620", "66 849,19")]


def test_дата_прописью_в_разрыве_не_мешает(analyzer):
    """Между номером и суммой стоит «от "22" апреля 2024 года»."""
    текст = ('По договору займа: № 14162667052 от "22" октября 2025 года - '
             'в размере 130571.88, из которых: 111190.48 руб. - основной долг.\n')
    assert _карточки(analyzer, текст)[0]["amount"] == "130 571,88"


def test_без_фразы_сумма_не_выдумывается(analyzer):
    """Нет фразы — поля нет; выдуманный «0,00» хуже пустого места."""
    текст = "Банк и Должник заключили кредитный договор № 1271058 от 28.10.2022.\n"
    карточка = _карточки(analyzer, текст)[0]
    assert карточка.get("amount") is None


def test_чужая_сумма_не_подставляется(analyzer):
    """У второго договора своей суммы нет — и она не должна приехать от первого."""
    текст = ('По кредитному договору № 10050033429 от "22" апреля 2024 года - '
             'в размере 218574.56 руб.\n'
             'Также заключен кредитный договор № 8963411620 от 28.09.2023.\n')
    пары = [(к.get("contractNumber"), к.get("amount"))
            for к in _карточки(analyzer, текст)]
    assert пары == [("10050033429", "218 574,56"), ("8963411620", None)]

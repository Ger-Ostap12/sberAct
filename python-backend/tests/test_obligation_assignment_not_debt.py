def test_уступка_в_общий_паттерн_обязательств_не_входит():
    assert "assignment" in NOT_DEBTOR_OBLIGATION
    паттерн = general_obligation_pattern()
    assert "цессии" not in паттерн
    assert "уступки" not in паттерн
    # Остальные виды на месте — правило отнимает ровно один вид.
    for слово in ("поручительства", "займа", "приказ"):
        assert слово in паттерн


@pytest.mark.parametrize("текст,номер", [
    # Точка остаётся границей там, где за ней НЕ цифра.
    ("Должник имеет задолженность по договору займа № 186410. Далее по тексту.",
     "186410"),
    # Скобка с цифрой — часть номера (Совкомбанк), её рвать нельзя.
    ("По кредитному договору № 2431453618(10551861421) от 17.05.2023 - в размере 1 руб.",
     "2431453618(10551861421)"),
])
def test_границы_номера(analyzer, текст, номер):
    import re

    m = re.search(general_obligation_pattern(), текст, re.IGNORECASE)
    assert m and m.group(1) == номер

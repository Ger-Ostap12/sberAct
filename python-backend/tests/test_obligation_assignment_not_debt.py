"""Уступка — не обязательство должника; точка внутри номера (03.10.2026).

свежие-30 («Жуменко И.А.», МКК «Джет Мани Микрофинанс») дал сразу три дефекта
на одной фразе:

    «…заключили Договор потребительского кредита № ВДРСТ-1/С/17.644, …
     На основании Договора уступки права требования № О/66-91/2018
     от 31.10.2018 г. задолженность … была уступлена ООО ПКО «АРС ФИНАНС».»

    1. карточек ДВЕ: вторая — на номер договора УСТУПКИ. Уступка это сделка
       МЕЖДУ КРЕДИТОРАМИ, должник по ней никому ничего не должен (то же
       правило уже разобрано на свежие-33 и свежие-34);
    2. номер кредита обрезан на точке: «ВДРСТ-1/С/17» вместо «…/17.644»;
    3. дата кредита взята от УСТУПКИ (31.10.2018) — своей даты документ не
       называет вовсе.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from claim_basis import NOT_DEBTOR_OBLIGATION, general_obligation_pattern  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


СВЕЖИЕ_30 = (
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
    "ООО МКК «Джет Мани Микрофинанс» и Жуменко Ирина Александровна заключили "
    "Договор потребительского кредита № ВДРСТ-1/С/17.644, в соответствии с "
    "которым Кредитор передает Заёмщику денежные средства.\n"
    "На основании Договора уступки права требования № О/66-91/2018 от 31.10.2018 г. "
    "задолженность в отношении Жуменко Ирины Александровны была уступлена "
    "ООО ПКО «АРС ФИНАНС».\n"
    "*МС СУ №6 Советского района г.Ростова-на-Дону вынес судебный акт о взыскании "
    "задолженности с Жуменко Ирины Александровны в размере 96525 руб.\n"
    "Жуменко Ирина Александровна имеет задолженность по договору "
    "№ ВДРСТ-1/С/17.644 в размере 96525,00 руб.\n")


def карточки(analyzer, текст):
    return (analyzer.analyze_from_text(текст)["fields"].get("obligations") or [])


def test_уступка_не_становится_обязательством(analyzer):
    номера = [к.get("contractNumber") for к in карточки(analyzer, СВЕЖИЕ_30)]
    assert "О/66-91/2018" not in номера
    assert номера == ["ВДРСТ-1/С/17.644"]


def test_точка_внутри_номера_сохраняется(analyzer):
    assert карточки(analyzer, СВЕЖИЕ_30)[0]["contractNumber"] == "ВДРСТ-1/С/17.644"


def test_чужая_дата_не_прилипает(analyzer):
    """31.10.2018 — дата УСТУПКИ: между ней и номером стоит чужой «№».

    ⚠️ Текст взят из документа ЦЕЛИКОМ, вместе с фразой про мирового судью:
    правило смотрит на чужой «№» в промежутке, и укороченный пересказ (без
    «МС СУ №6») вёл бы себя иначе, чем прод. Граница правила именно такая —
    соседнее предложение БЕЗ чужого номера дату отдаст.
    """
    assert карточки(analyzer, СВЕЖИЕ_30)[0]["contractDate"] == "Не указана"


def test_своя_дата_за_своим_номером_остаётся(analyzer):
    """Обратная сторона: «№» прямо перед номером — свой, он границей не считается.

    Альфа-Банк (свежие-6/31) пишет «14.02.2023 … заключили Соглашение …
    Данному Соглашению был присвоен номер № SRSRS510S23021400327». Первая
    редакция правила убивала эту ВЕРНУЮ дату.
    """
    текст = ("14.02.2023 г. Банк и ХЛИЯН ЕЛЕНА ОГАНОВНА заключили Соглашение о "
             "кредитовании на получение Персонального кредита. Данному Соглашению "
             "был присвоен номер № SRSRS510S23021400327.\n")
    assert analyzer.find_date_near_contract(текст, "SRSRS510S23021400327") == "14.02.2023"


def test_дата_закона_не_берётся_за_дату_договора(analyzer):
    """«Федерального закона от 26.10.2002 N 127-ФЗ» стоит в каждом заявлении."""
    текст = ("В соответствии со ст. 213.5 Федерального закона от 26.10.2002 N 127-ФЗ "
             "«О несостоятельности (банкротстве)» кредитор обратился по договору "
             "займа № 77889900.\n")
    assert analyzer.find_date_near_contract(текст, "77889900") == ""



# -*- coding: utf-8 -*-
"""Банковский счёт — не номер договора (03.10.2026).

свежие-18 («Рытченко Л.В.», Газпромбанк) называет ОДИН кредитный договор, но
карточек было две: вторую дала фраза

    «В соответствии с Кредитным договором 1 сумма кредита перечислена Банком
     на счет Рытченко Ларисы Васильевны № 40817810164071245613»

— это счёт заёмщика, а не второе обязательство.

⚠️ ПРОВЕРЯЕМ ДЛИНОЙ, А НЕ СЛОВОМ «СЧЁТ». Первое правило было «номер, перед
которым стоит счет/р.с/л.с» — и замер его ОТВЕРГ: подстрока «счет» живёт внутри
«Ра-счет задолженности по карте», и правило убивало законный номер кредитной
КАРТЫ у свежие-9 («выдана кредитная карта № 220220XXXXXX4210»).

Двадцать цифр подряд — длина счёта по правилам ЦБ. Замер по 101 документу:
таких номеров среди 178 карточек ровно один — тот самый.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def номера(поля):
    return [о.get("contractNumber") for о in (поля.get("obligations") or [])]


СВЕЖИЕ_18 = (
    "«Газпромбанк» (Акционерное общество) является кредитором Рытченко Ларисы "
    "Васильевны по денежному обязательству, возникающему из кредитного договора: "
    "№ 16469-ПБ/О07/2026/21 от 21.05.2021 (Далее — Кредитный договор-1).\n"
    "В соответствии с Кредитным договором 1 сумма кредита перечислена Банком на "
    "счет Рытченко Ларисы Васильевны № 40817810164071245613. Факт предоставления "
    "кредита подтверждается выпиской по счету.\n")


def test_счёт_заёмщика_не_становится_обязательством(analyzer):
    assert номера(analyzer.analyze_from_text(СВЕЖИЕ_18)["fields"]) == ["16469-ПБ/О07/2026/21"]


@pytest.mark.parametrize("счёт", [
    "40817810164071245613",   # свежие-18, счёт физлица
    "40702810500000012345",   # расчётный счёт организации
    "30101810150040000763",   # корсчёт
])
def test_двадцать_цифр_подряд_не_номер_договора(analyzer, счёт):
    assert not analyzer._is_valid_contract_number(счёт)


# --- чего правило ломать НЕ должно ---------------------------------------------

@pytest.mark.parametrize("номер", [
    "220220XXXXXX4210",        # свежие-9: номер кредитной КАРТЫ
    "16469-ПБ/О07/2026/21",
    "003 83 6 2312250225",     # номер с пробелами (корпус-5)
    "1903965846",
    "99ТКПР24061300419782",    # 20 знаков, но не только цифры
    "4081781016407124561",     # 19 цифр — не длина счёта
    "408178101640712456134",   # 21 цифра — тоже не счёт
])
def test_настоящие_номера_не_отсекаются(analyzer, номер):
    assert analyzer._is_valid_contract_number(номер)


def test_правило_не_смотрит_на_слово_счёт(analyzer):
    """Сторож отвергнутого правила.

    Первая редакция отсеивала номер, перед которым стоит «счет/р.с/л.с». Замер
    показал, что «счет» встречается ВНУТРИ слова «Ра-счет» («Расчет
    задолженности по карте 220220XXXXXX4210»), и номер кредитной карты у
    свежие-9 пропадал. Поэтому правило работает ТОЛЬКО по длине: если кто-то
    вернётся к проверке по слову, этот тест покраснеет.
    """
    # Номер карты остаётся номером, в каком бы соседстве он ни стоял.
    assert analyzer._is_valid_contract_number("220220XXXXXX4210")
    # А счёт отсекается независимо от того, есть ли рядом слово «счёт».
    assert not analyzer._is_valid_contract_number("40817810164071245613")

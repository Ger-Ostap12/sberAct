# -*- coding: utf-8 -*-
"""Номер договора внутри блока «Обязательство N» (21.09.2026, фаза 6 п.1).

Блоки разбирались верно по датам и суммам, но номер терялся, и карточка
получала заглушку «Договор_N». Позже в заглушку подставлялся номер из
ПЛОСКОГО списка номеров документа — по индексу, то есть номер СОСЕДНЕГО
обязательства. В свежие-16 обе карточки получили один и тот же номер.

Три причины потери:

1. `договор` в паттерне стоял без окончания, а блок пишет «взыскана
   задолженность по кредитному договорУ № 186410»: класс номера строчную
   кириллицу не берёт, и поиск не совпадал НИГДЕ в блоке.
2. Номер карты печатают с УДВОЕННЫМ «№» («выдана кредитная карта № №
   220220XXXXXX4210») — ветка договора обрывалась на втором «№».
3. Найденный номер блочный путь не проверял вовсе, и окончание слова
   открыло доступ к огрызкам: «исполнение заключенного договора⇥Должнику»
   даёт номер «Д».
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _карточки(analyzer, текст):
    return analyzer.extract_obligations(текст, {})


def _номера(analyzer, текст):
    return [к.get("contractNumber") for к in _карточки(analyzer, текст)]


ДВА_БЛОКА = (
    "Кредитор является кредитором должника по следующим договорам.\n"
    "Обязательство № 1\n"
    "Судебным актом мирового судьи по Делу № 8-2-3913/2025 с должника "
    "взыскана задолженность по кредитному договору № 186410 от 11.10.2010.\n"
    "По состоянию на день введения процедуры задолженность по кредитному "
    "договору № 186410 от 11.10.2010 составляет 47 500,00 рублей.\n"
    "Обязательство № 2\n"
    "АО «ТБанк» и должник заключили кредитный договор № 0198544409 "
    "от 07.10.2023.\n"
    "По состоянию на день введения процедуры задолженность по кредитному "
    "договору № 0198544409 от 07.10.2023 составляет 210 779,74 рублей.\n"
)


def test_номер_после_окончания_слова(analyzer):
    """«по кредитному договорУ № 186410» — окончание не должно мешать."""
    assert _номера(analyzer, ДВА_БЛОКА) == ["186410", "0198544409"]


def test_соседний_номер_не_подставляется(analyzer):
    """Оба блока получали 0198544409: заглушку заполняли по индексу."""
    номера = _номера(analyzer, ДВА_БЛОКА)
    assert len(номера) == len(set(номера)), f"номер задвоился: {номера}"


def test_даты_блоков_свои(analyzer):
    даты = [к.get("contractDate") for к in _карточки(analyzer, ДВА_БЛОКА)]
    assert даты == ["11.10.2010", "07.10.2023"]


# --- кредитная карта с удвоенным «№» ------------------------------------------

БЛОК_КАРТЫ = (
    "Кредитор является кредитором должника по следующим договорам.\n"
    "Обязательство № 1\n"
    "03.02.2023 стороны заключили договор на предоставление возобновляемой "
    "кредитной линии посредством выдачи международной кредитной карты.\n"
    "Во исполнение заключенного договора\tДолжнику\tбыла\tвыдана\tкредитная"
    "\tкарта\t№ № 220220XXXXXX4210, условия изложены в Условиях.\n"
    "образовалась задолженность в размере 146429.92 руб.\n"
)


def test_номер_карты_с_удвоенной_решёткой(analyzer):
    assert _номера(analyzer, БЛОК_КАРТЫ) == ["220220XXXXXX4210"]


def test_тип_карты_опознан(analyzer):
    карточки = _карточки(analyzer, БЛОК_КАРТЫ)
    assert карточки[0]["obligationType"] == "Кредитная карта"


def test_огрызок_не_становится_номером(analyzer):
    """«заключенного договора⇥Должнику» давало номер «Д»."""
    assert "Д" not in _номера(analyzer, БЛОК_КАРТЫ)


# --- заглушка честнее выдуманного номера --------------------------------------

БЛОК_БЕЗ_НОМЕРА = (
    "Кредитор является кредитором должника по следующим договорам.\n"
    "Обязательство № 1\n"
    "03.03.2022 стороны заключили договор\tДолжнику предоставлены средства "
    "без указания номера.\n"
    "образовалась задолженность в размере 207356.52 руб.\n"
)


def test_блок_без_номера_остаётся_заглушкой(analyzer):
    """Номера в блоке нет — выдумывать его нельзя, заглушку видно на форме."""
    assert _номера(analyzer, БЛОК_БЕЗ_НОМЕРА) == ["Договор_1"]


def test_сумма_блока_без_номера_сохранена(analyzer):
    """Заглушка не должна стоить блоку его суммы."""
    карточки = _карточки(analyzer, БЛОК_БЕЗ_НОМЕРА)
    assert карточки[0]["amount"] == "207 356,52"


# --- прежнее поведение --------------------------------------------------------

def test_форма_заключили_кредитный_договор(analyzer):
    текст = ("Кредитор является кредитором должника.\n"
             "Обязательство № 1\n"
             "15.05.2023 Банк и Заемщик заключили кредитный договор №1041428.\n"
             "образовалась задолженность в размере 198017.98 руб.\n")
    assert _номера(analyzer, текст) == ["1041428"]


def test_эмиссионный_контракт_не_перебит_картой(analyzer):
    """Ветка карты стоит ПОСЛЕ эмиссионного контракта и не отнимает его."""
    текст = ("Кредитор является кредитором должника.\n"
             "Обязательство № 1\n"
             "01.02.2015 путем подписания эмиссионного контракта №99ТКПР15 "
             "должнику выдана кредитная карта.\n"
             "образовалась задолженность в размере 10000.00 руб.\n")
    assert _номера(analyzer, текст) == ["99ТКПР15"]

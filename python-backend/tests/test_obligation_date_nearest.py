# -*- coding: utf-8 -*-
"""Дата обязательства: ближайшая к номеру, а не первая в окне (21.09.2026).

Фолбэк `find_date_near_contract` брал ПЕРВУЮ подходящую дату в окне ±300
знаков вокруг номера. Первая — значит самая левая, то есть отстоящая почти
на треть окна влево, и туда попадала чужая дата:

    свежие-6, свежие-31   дата публикации в ЕФРСБ вместо даты соглашения
    свежие-2, корпус-64   дата решения о банкротстве вместо даты выдачи
                          исполнительного документа

Своя дата у номера стоит вплотную, поэтому побеждать должна близость.
Шаг 1 лесенки («DATE … заключен договор № N») правило не трогает: он точнее
и стоит раньше.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- сам поиск даты -----------------------------------------------------------

def test_ефрсб_не_перебивает_дату_соглашения(analyzer):
    текст = (
        "Сведения о признании гражданина банкротом опубликованы в Едином "
        "федеральном реестре сведений о банкротстве 13.01.2026 г.\n"
        "Обоснованность требований Банка подтверждается нижеследующим.\n"
        "14.02.2023 г. Банк и ХЛИЯН ЕЛЕНА ОГАНОВНА заключили Соглашение о "
        "кредитовании на получение Персонального кредита. Данному Соглашению "
        "был присвоен номер № SRSRS510S23021400327.\n")
    assert analyzer.find_date_near_contract(текст, "SRSRS510S23021400327") \
        == "14.02.2023"


def test_решение_о_банкротстве_не_перебивает_выдачу(analyzer):
    текст = (
        "Решением АС Ростовской области от 22.06.2026 Епифановский Владислав "
        "Михайлович признан банкротом.\n"
        "В обоснование заявленных требований сообщаем следующее:\n"
        "21.04.2026 по гражданскому делу № 2-1-733/2026 Судебный участок № 1 "
        "Аксайского судебного района был выдан исполнительный документ "
        "№ 2-1-733/2026 о взыскании задолженности.\n")
    assert analyzer.find_date_near_contract(текст, "2-1-733/2026") == "21.04.2026"


def test_дата_справа_от_номера_тоже_считается(analyzer):
    """Близость меряется в обе стороны, а не только влево."""
    текст = ("Решением суда от 22.06.2026 должник признан банкротом. "
             "Длинная вставка без дат, чтобы левая дата была дальше правой, "
             "тянется и тянется и ещё немного тянется дальше по строке.\n"
             "Взыскание по договору № 0437689812 от 06.10.2025 г.\n")
    assert analyzer.find_date_near_contract(текст, "0437689812") == "06.10.2025"


def test_прямая_форма_остаётся_первой(analyzer):
    """«DATE … заключен договор № N» точнее близости и стоит раньше неё."""
    текст = ("01.02.2020 между Банком и Должником заключен договор № 1271058 "
             "о предоставлении кредита. Расчет составлен на 28.10.2022.\n")
    assert analyzer.find_date_near_contract(текст, "1271058") == "01.02.2020"


def test_дат_нет_вовсе(analyzer):
    assert analyzer.find_date_near_contract("договор № 1271058 без дат", "1271058") == ""


# --- карточка целиком ---------------------------------------------------------

def test_карточка_получает_свою_дату(analyzer):
    текст = (
        "Решением АС Ростовской области от 22.06.2026 должник признан банкротом.\n"
        "В обоснование заявленных требований сообщаем следующее:\n"
        "21.04.2026 по гражданскому делу № 2-1-733/2026 Судебный участок № 1 "
        "был выдан исполнительный документ № 2-1-733/2026 о взыскании "
        "задолженности в размере 105517.78 руб.\n")
    карточки = analyzer.extract_obligations(текст, {})
    assert карточки[0]["contractDate"] == "21.04.2026"

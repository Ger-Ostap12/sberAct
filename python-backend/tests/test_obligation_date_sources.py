# -*- coding: utf-8 -*-
"""Откуда берётся дата обязательства (06.10.2026).

Найдено покрытием: номер и дата стерёгись эталоном на 11 документах из 77,
и когда покрытие довели до конца, вскрылись три карточки, у которых дата в
документе ЕСТЬ, а на форме стояло «Не указана».

```
свежие-33, -34  «заключен договор займа № 107977878 ОТ 2024-08-10 года» —
                ISO-вид. Паттерн основания его ловит, а нормализация даты
                обязательства этот вид не знала
свежие-32       «25.01.2022 г. Банк и ДЖАИЕВ … заключили Соглашение о
                кредитовании на получение Кредитной карты. Данному
                Соглашению был присвоен номер № PILCAUEJ0C2201251822» —
                дата в НАЧАЛЕ своего предложения, номер в следующем
```

У свежие-6 и свежие-31 та же форма Альфа-Банка дату отдавала: там карточку
строит другой проход, который дату перед номером искать умеет. Поэтому
канонический проход теперь спрашивает ту же `find_date_near_contract` —
своих правил «кто ближе» не изобретаем, у неё они уже есть (и уже защищены
от даты закона и от даты за чужим «№»).
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def карточки(analyzer, текст):
    return analyzer.analyze_from_text(текст)["fields"].get("obligations") or []


# --- ISO-дата -------------------------------------------------------------------

СВЕЖИЕ_33 = (
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
    "Между ООО МФК «Быстроденьги» (г. Ульяновск, ул. К. Маркса, д. 13а, корп.1, "
    "ОГРН: 1087325005899, ИНН: 7325081622) и должником заключен договор займа "
    "№ 107977878 от 2024-08-10 года (далее – Договор) путем направления "
    "Обществом Оферты и ее акцепта должником.\n")


def test_iso_дата_доезжает_до_карточки(analyzer):
    o = карточки(analyzer, СВЕЖИЕ_33)
    assert [(к["contractNumber"], к["contractDate"]) for к in o] == \
        [("107977878", "10.08.2024")]


@pytest.mark.parametrize("строка,ждём", [
    ("2024-08-10", "10.08.2024"),
    ("2024-8-1", "01.08.2024"),
    ("17.02.2023", "17.02.2023"),
    ("21 сентября 2023", "21.09.2023"),
])
def test_нормализация_даты(analyzer, строка, ждём):
    assert analyzer._normalize_obl_date(строка) == ждём


@pytest.mark.parametrize("мусор", [
    "2024-13-45",     # месяц 13, день 45
    "1899-01-01",     # до 1900
    "",
    "от",
])
def test_нормализация_отвергает_мусор(analyzer, мусор):
    assert analyzer._normalize_obl_date(мусор) is None


# --- дата в начале предложения, номер в следующем -------------------------------

СВЕЖИЕ_32 = (
    "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
    "Обоснованность требований Банка (далее - Заявителя, Кредитора) "
    "подтверждается нижеследующим.\n"
    "25.01.2022 г. Банк и ДЖАИЕВ ФИРУДДИН ИКРАМ ОГЛЫ заключили Соглашение о "
    "кредитовании на получение Кредитной карты. Данному Соглашению был присвоен "
    "номер № PILCAUEJ0C2201251822. Соглашение о кредитовании заключено в "
    "офертно-акцептной форме.\n")


def test_дата_из_предыдущего_предложения(analyzer):
    o = карточки(analyzer, СВЕЖИЕ_32)
    assert [(к["contractNumber"], к["contractDate"]) for к in o] == \
        [("PILCAUEJ0C2201251822", "25.01.2022")]


def test_дата_закона_не_становится_датой_договора(analyzer):
    """Обратная сторона: новая лесенка не должна тащить что попало.

    «Федерального закона от 26.10.2002 N 127-ФЗ» стоит в каждом заявлении, и
    без защиты она стала бы датой договора у любой карточки без своей даты.
    Защита живёт в find_date_near_contract, здесь — сторож на неё.
    """
    текст = ("ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов\n"
             "В соответствии со ст. 213.5 Федерального закона от 26.10.2002 "
             "N 127-ФЗ «О несостоятельности (банкротстве)» Банк обратился с "
             "требованием.\n"
             "Между Банком и должником заключен договор займа № 77889900.\n")
    o = карточки(analyzer, текст)
    assert o, "карточка не создалась — проверять нечего"
    assert o[0]["contractDate"] == "Не указана", o[0]

# -*- coding: utf-8 -*-
"""Судебный акт о взыскании по договору — не второе обязательство (22.09.2026).

свежие-3 называет ОДИН долг двумя номерами в одном предложении: «вынесен
судебный приказ № 2-5481/2024 о взыскании … задолженности по договору займа
№ 003 83 6 2312250225 от 25.12.2023». Приказ — акт о взыскании ПО договору,
и карточек получалось две вместо одной.

⚠️ Широкий запрет судебных актов недопустим. Замер по 101 документу: у
корпус-62, корпус-64, корпус-65, свежие-2, свежие-10, свежие-11, свежие-12 и
свежие-13 судебный акт — ЕДИНСТВЕННАЯ карточка обязательства, а корпус-43
состоит из трёх таких. Поэтому правило требует ОБА признака: договор назван в
ТОМ ЖЕ предложении и его номер уже стал отдельной карточкой.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def номера(поля):
    return [о.get("contractNumber") for о in (поля.get("obligations") or [])]


# --- ради чего заведено --------------------------------------------------------

СВЕЖИЕ_3 = (
    "Мировым судьей Судебный участок № 98 Хостинского района г. Сочи 20.09.2024 "
    "вынесен судебный приказ № 2-5481/2024 о взыскании с должника в пользу "
    "АО ПКО «ЦДУ» задолженности по договору займа № 003 83 6 2312250225 "
    "от 25.12.2023 г. по состоянию на 29.07.2024 в размере 161 000,00 руб., "
    "а также 2 210,00 руб. – расходов по оплате государственной пошлины, "
    "а всего 163 210,00 руб.\n")


def test_приказ_про_договор_не_даёт_второй_карточки(analyzer):
    поля = analyzer.analyze_from_text(СВЕЖИЕ_3)["fields"]
    assert номера(поля) == ["003 83 6 2312250225"]


# --- чего правило ломать НЕ должно ---------------------------------------------

ТОЛЬКО_ПРИКАЗ = (
    "Мировым судьей судебного участка № 4 12.05.2025 вынесен судебный приказ "
    "№ 2-4-436/2025 о взыскании с должника в пользу взыскателя задолженности "
    "в размере 84 120,00 руб.\n")


def test_приказ_без_договора_остаётся_обязательством(analyzer):
    """У восьми документов корпуса судебный акт — единственное основание."""
    assert номера(analyzer.analyze_from_text(ТОЛЬКО_ПРИКАЗ)["fields"]) == ["2-4-436/2025"]


# Тот же текст свежие-3, но долг назван ОТДЕЛЬНЫМ предложением: связи «приказ
# вынесен по этому договору» в нём уже нет, и обе карточки законны.
ПРИКАЗ_И_ДОГОВОР_ПОРОЗНЬ = (
    "Мировым судьей Судебный участок № 98 Хостинского района г. Сочи 20.09.2024 "
    "вынесен судебный приказ № 2-5481/2024 о взыскании с должника в пользу "
    "АО ПКО «ЦДУ» задолженности в размере 161 000,00 руб.\n"
    "Задолженность возникла по договору займа № 003 83 6 2312250225 "
    "от 25.12.2023 г. в размере 161 000,00 руб.\n")


def test_договор_в_другом_предложении_приказ_не_отменяет(analyzer):
    """Одно предложение — обязательное условие: иначе приказ съедал бы соседа."""
    assert set(номера(analyzer.analyze_from_text(ПРИКАЗ_И_ДОГОВОР_ПОРОЗНЬ)["fields"])) == {
        "2-5481/2024", "003 83 6 2312250225"}


ТРИ_ПРИКАЗА = (
    "1. Судебный приказ № 2-1178/2024 от 15.03.2024 о взыскании 12 000,00 руб.\n"
    "2. Судебный приказ № 2-1535/2024 от 20.05.2024 о взыскании 18 500,00 руб.\n"
    "3. Судебный приказ № 2-1387/2025 от 11.02.2025 о взыскании 9 300,00 руб.\n")


def test_перечень_приказов_не_вычищается(analyzer):
    """корпус-43 состоит ТОЛЬКО из судебных актов — акт с актом не сравниваем."""
    assert set(номера(analyzer.analyze_from_text(ТРИ_ПРИКАЗА)["fields"])) == {
        "2-1178/2024", "2-1535/2024", "2-1387/2025"}


def test_единственная_карточка_не_трогается(analyzer):
    """Правило молчит, пока карточка одна: пустой блок хуже лишней карточки."""
    одна = [{"contractNumber": "2-5481/2024", "obligationType": "Судебный приказ"}]
    assert analyzer._drop_judicial_about_contract(СВЕЖИЕ_3, одна) == одна


def test_правило_не_выносит_блок_целиком(analyzer):
    """Даже если отсев забрал бы всё, возвращается прежний список."""
    обе = [{"contractNumber": "2-5481/2024"}, {"contractNumber": "2-5481/2024"}]
    assert len(analyzer._drop_judicial_about_contract(СВЕЖИЕ_3, обе)) == 2

# -*- coding: utf-8 -*-
"""Якорь номера договора в каноне обязательств (21.09.2026, фаза 6 п.1).

Три заявления Банка Русский Стандарт несли в карточке номер СУДЕБНОГО ДЕЛА
вместо номера договора:

    По кредитному договору 108834095, в отношении Должника выдан
    исполнительный документ № 2-102/2018 на сумму 90330,47 рублей

Свой номер стоит БЕЗ «№», а ветка с «№» разрешала разрыв до 80 знаков — и
потому перепрыгивала через безномерной номер к «№» ЧУЖОГО документа. Дата
договора в таких заявлениях названа один раз прозой («06.09.2013 года между
… были заключены Кредитные договоры»), своего «от DATE» у номера нет нигде,
и карточка уходила с «Не указана».

Попутно закрыт скрытый дефект: `займ\\w*` совпадал ВНУТРИ названий МФО
(«ЭкваЗАЙМ», «ТурбоЗАЙМ»), и голый номер за ними — это почтовый индекс из
адреса кредитора.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _карточки(analyzer, текст):
    return analyzer.extract_obligations(текст, {})


def _номера(analyzer, текст):
    return [к.get("contractNumber") for к in _карточки(analyzer, текст)]


# --- номер без «№» перед чужим «№» -------------------------------------------

РУССКИЙ_СТАНДАРТ = (
    "06.09.2013 года между АО «Банк Русский Стандарт» (далее – Кредитор, Банк) "
    "и Должником были заключены Кредитные договоры.\n"
    "Задолженность подтверждается вступившим в силу судебным актом и "
    "исполнительным документом.\n"
    "По кредитному договору 108834095, в отношении Должника выдан "
    "исполнительный документ № 2-102/2018 на сумму 90330,47 рублей, который "
    "впоследствии был предъявлен в службу судебных приставов-исполнителей.\n"
)


def test_номер_без_решётки_вместо_чужого(analyzer):
    """Берём свой безномерной номер, а не «№» исполнительного документа."""
    assert _номера(analyzer, РУССКИЙ_СТАНДАРТ) == ["108834095"]


def test_номер_дела_не_попадает_в_карточку(analyzer):
    assert "2-102/2018" not in _номера(analyzer, РУССКИЙ_СТАНДАРТ)


@pytest.mark.parametrize("номер, дело", [
    ("108834095", "2-102/2018"),
    ("102190389", "2-8961/2018"),
    ("110793065", "2-1093/2022"),
])
def test_три_заявления_одной_формы(analyzer, номер, дело):
    текст = (
        "05.12.2012 года между АО «Банк Русский Стандарт» и Должником были "
        "заключены Кредитные договоры.\n"
        f"По кредитному договору {номер}, в отношении Должника выдан "
        f"исполнительный документ № {дело} на сумму 143498,84 рублей.\n")
    assert _номера(analyzer, текст) == [номер]


def test_свой_номер_с_решёткой_раньше_чужого(analyzer):
    """Когда «№» есть у своего номера, чужой номер дела не должен перебивать."""
    текст = ("Задолженность по кредитному договору № 108834095 подтверждена "
             "исполнительным документом № 2-102/2018.\n")
    assert _номера(analyzer, текст) == ["108834095"]


# --- дата заключения прозой ---------------------------------------------------

def test_дата_прозой_подставляется(analyzer):
    карточки = _карточки(analyzer, РУССКИЙ_СТАНДАРТ)
    assert карточки[0]["contractDate"] == "06.09.2013"


def test_дата_прозой_при_нескольких_фразах_не_гадаем(analyzer):
    """Две разные даты заключения — выбор был бы гаданием, оставляем пусто."""
    текст = (
        "06.09.2013 года между Банком и Должником были заключены договоры.\n"
        "14.02.2023 года между Банком и Должником заключен ещё один договор.\n"
        "По кредитному договору 108834095, в отношении Должника выдан "
        "исполнительный документ № 2-102/2018.\n")
    карточки = _карточки(analyzer, текст)
    assert карточки[0]["contractDate"] == "Не указана"


def test_повтор_одной_даты_гаданием_не_считается(analyzer):
    """Одна и та же дата, названная дважды, единственности не отменяет."""
    текст = (
        "06.09.2013 года между Банком и Должником были заключены договоры.\n"
        "Напоминаем: 06.09.2013 года между Банком и Должником заключен договор.\n"
        "По кредитному договору 108834095, в отношении Должника выдан "
        "исполнительный документ № 2-102/2018.\n")
    карточки = _карточки(analyzer, текст)
    assert карточки[0]["contractDate"] == "06.09.2013"


def test_своя_дата_прозу_вытесняет(analyzer):
    """Когда у номера есть «от DATE», прозовая дата не должна её перебивать."""
    текст = (
        "06.09.2013 года между Банком и Должником были заключены договоры.\n"
        "По кредитному договору № 108834095 от 28.10.2022 имеется задолженность.\n")
    карточки = _карточки(analyzer, текст)
    assert карточки[0]["contractDate"] == "28.10.2022"


# --- граница слова: «займ» внутри названия МФО --------------------------------

СПИСОК_КРЕДИТОРОВ = (
    "Кредиторы:\n"
    "ООО МКК Эквазайм\n"
    "432071, Ульяновская область, г Ульяновск, ул Карла Маркса, д. 13а к. 1\n"
    "ООО МКК Турбозайм\n"
    "121087, город Москва, Барклая ул, д. 6 стр. 5, помещ. 23п/4\n"
)


@pytest.mark.parametrize("индекс", ["432071", "121087"])
def test_почтовый_индекс_не_номер_договора(analyzer, индекс):
    """«…займ» внутри названия МФО не открывает договор — дальше идёт индекс."""
    assert индекс not in _номера(analyzer, СПИСОК_КРЕДИТОРОВ)


def test_настоящий_займ_по_прежнему_виден(analyzer):
    """Граница слова не должна отнимать законный «договор займа»."""
    текст = ("Между ООО МФК «Совком Экспресс» и Должником заключен "
             "договор займа № 14162667052 от 22.10.2025.\n")
    assert _номера(analyzer, текст) == ["14162667052"]


# --- прежнее поведение --------------------------------------------------------

@pytest.mark.parametrize("текст, ждём", [
    ("Банк и Должник заключили кредитный договор № 1271058 от 28.10.2022.",
     ["1271058"]),
    ("Банк и Должник заключили договор поручительства № 7M-520CPIS-BV0 "
     "от 30.06.2025.", ["7M-520CPIS-BV0"]),
    ("Банк и Должник заключили эмиссионный контракт № 99ТКПР15 от 01.02.2015.",
     ["99ТКПР15"]),
])
def test_канон_не_сломан(analyzer, текст, ждём):
    assert _номера(analyzer, текст) == ждём


def test_голая_ветка_требует_цифру(analyzer):
    """«кредитный договор заключен» — за типом слово, а не номер: карточки нет."""
    текст = "Между Банком и Должником кредитный договор заключен в офертной форме."
    assert _номера(analyzer, текст) == []

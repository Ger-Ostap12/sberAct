# -*- coding: utf-8 -*-
"""Поручительство, названное без номера (21.09.2026, фаза 6 п.1).

корпус-0 заявляет два поручительства, и у второго номера нет вовсе:

    В обеспечение обязательств ООО Парадигма по Генеральному соглашению
    между Банком и ООО Оргтехника заключен договор поручительства
    от 26.06.2025

Канон требовал «№» и такую запись не видел, хотя дедуп безномерные
обязательства (ключ дата + тип) уже пропускал — не хватало только сборщика.
Поручительство на должника, поэтому проверки стороны к нему не применяются.

Опасность правки — задвоение: тот же договор бывает назван и с номером.
Дата, уже занятая нумерованной карточкой поручительства, пропускается.
Замер по корпусу: безномерная запись одна на 101 документ.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _карточки(analyzer, текст):
    return analyzer.extract_obligations(текст, {})


ДВА_ПОРУЧИТЕЛЬСТВА = (
    "У Должника имеется задолженность, возникшая при следующих обязательствах:\n"
    "I. 30.06.2025 между Кредитором и Должником заключен договор поручительства "
    "№ 7M-520CPIS-BV0-П1 в обеспечение исполнения обязательств ООО «ПАРАДИГМА».\n"
    "II. В обеспечение обязательств ООО Парадигма по Генеральному соглашению "
    "между Банком и ООО Оргтехника заключен договор поручительства "
    "от 26.06.2025, в соответствии с которым ООО Оргтехника согласилось "
    "отвечать за исполнение всех обязательств Должника.\n"
)


def test_безномерное_поручительство_даёт_карточку(analyzer):
    карточки = _карточки(analyzer, ДВА_ПОРУЧИТЕЛЬСТВА)
    assert len(карточки) == 2, [к.get("contractNumber") for к in карточки]


def test_у_безномерной_карточки_своя_дата_и_тип(analyzer):
    безномерная = [к for к in _карточки(analyzer, ДВА_ПОРУЧИТЕЛЬСТВА)
                   if not (к.get("contractNumber") or "").strip()]
    assert len(безномерная) == 1
    assert безномерная[0]["contractDate"] == "26.06.2025"
    assert безномерная[0]["obligationType"] == "Договор поручительства"


def test_нумерованное_поручительство_не_задваивается(analyzer):
    """«договор поручительства от 30.06.2025 № X» — одна запись, не две."""
    текст = ("У Должника имеется задолженность.\n"
             "Между Кредитором и Должником заключен договор поручительства "
             "от 30.06.2025 № 7M-520CPIS-BV0-П1 в обеспечение обязательств.\n")
    карточки = _карточки(analyzer, текст)
    assert len(карточки) == 1, [к.get("contractNumber") for к in карточки]
    assert карточки[0]["contractNumber"] == "7M-520CPIS-BV0-П1"


def test_та_же_дата_карточку_не_добавляет(analyzer):
    """Один договор, названный дважды — с номером и без, — остаётся одним."""
    текст = ("У Должника имеется задолженность.\n"
             "30.06.2025 между Кредитором и Должником заключен договор "
             "поручительства № 7M-520CPIS-BV0-П1.\n"
             "Согласно п. 1.4 заключен договор поручительства от 30.06.2025 "
             "с пределом ответственности 26 500 000 рублей.\n")
    карточки = _карточки(analyzer, текст)
    assert len(карточки) == 1, [(к.get("contractNumber"), к.get("contractDate"))
                                for к in карточки]


def test_без_даты_карточки_нет(analyzer):
    """«Согласно п 1.4. Договора поручительства…» — ни номера, ни даты."""
    текст = ("У Должника имеется задолженность.\n"
             "Согласно п 1.4. Договора поручительства предел общей "
             "ответственности Поручителя ограничивается суммой 26 500 000 руб.\n")
    assert _карточки(analyzer, текст) == []

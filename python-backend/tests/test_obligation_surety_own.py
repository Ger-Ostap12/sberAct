# -*- coding: utf-8 -*-
"""Поручителю — ЕГО договор поручительства, а не чужой кредит (03.10.2026).

корпус-28 («ФЛ ОМЕЛЯНЧУК»): кредит в 10 000 000 руб. выдан ДРУГОМУ лицу
(ООО ТЕХНОПАКДОН), ОМЕЛЯНЧУК назван «Поручитель/Должник», и его обязательство —
договор поручительства № 6168086464-23-5П02. Карточка несла номер КРЕДИТНОГО
договора № 6168086464-23-5 и вид «Кредитный договор»: нарушено правило ролей
(заёмщик -> кредитные, поручитель -> поручительства).

Корень ОДИН: НОМЕР СКЛЕЕН СО СКОБКОЙ — «№6168086464-23-5П02(далее – Договор
поручительства)». Скобка не была границей номера, совпадения не было вовсе,
канонический проход возвращал ПУСТО — и работу подхватывал блочный разбор
«Обязательство №1», который про роли не знает.

⚠️ Второе напрашивавшееся правило — «брать поручительство, в объявлении
которого стоит должник» (по тому же кредиту есть второй поручитель ТРУЩЕНКО,
№ …-5П01) — ОТВЕРГНУТО ЗАМЕРОМ: на всех 101 документе оно не меняет ни одной
карточки. Чужое П01 не попадает в разбор и без него, потому что его номер
стоит на следующей строке, а окно до «№» перенос не пересекает. Поэтому здесь
проверяется НЕ роль, а итог: карточка ровно одна и она своя.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


КОРПУС_28 = (
    "29.11.2023 ПАО Сбербанк (далее – Банк/Кредитор) и ООО ТЕХНОПАКДОН (далее –\n"
    "Заемщик) заключили кредитный договор№6168086464-23-5(далее – «Договор»), по "
    "которому Банк предоставил кредит в сумме 10 000 000,00 руб.\n"
    "В качестве обеспечения исполнения обязательств по Договору ПАО Сбербанк и\n"
    "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ (далее – Поручитель/Должник) заключили договор\n"
    "поручительства №6168086464-23-5П02(далее – Договор поручительства).\n"
    "В качестве обеспечения исполнения обязательств по Договору ПАО Сбербанк и ТРУЩЕНКО\n"
    "АНДРЕЙ ЮРЬЕВИЧ (далее – Поручитель/Должник) заключили договор поручительства\n"
    "№6168086464-23-5П01(далее – Договор поручительства).\n"
    "В настоящее время обязательства, принятые по Договору и Договору поручительства,\n"
    "Заемщиком и Поручителем нарушаются. По состоянию на 20,04,2026 образовалась "
    "задолженность в размере 7371840.35 руб.\n")


def карточки(analyzer, текст, должник):
    return analyzer._extract_obligations_primary(текст, должник, debtor_is_borrower=False)


def test_берётся_поручительство_должника(analyzer):
    o = карточки(analyzer, КОРПУС_28, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert [(к["contractNumber"], к["obligationType"]) for к in o] == [
        ("6168086464-23-5П02", "Договор поручительства")]


def test_чужое_поручительство_в_карточки_не_попадает(analyzer):
    """П01 — договор ВТОРОГО поручителя (ТРУЩЕНКО), у него своё дело.

    ⚠️ Он отсекается НЕ проверкой стороны (её нет, см. шапку модуля), а
    переносом строки: «заключили договор поручительства\\n№…П01» — окно между
    словом-типом и «№» перенос не пересекает. Вёрстка взята из документа
    один-в-один, поэтому тест сторожит именно то поведение, что в проде.
    """
    o = карточки(analyzer, КОРПУС_28, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert "6168086464-23-5П01" not in [к["contractNumber"] for к in o]


def test_чужой_кредит_не_берётся(analyzer):
    """Кредит выдан ООО ТЕХНОПАКДОН — должник по нему только поручитель."""
    o = карточки(analyzer, КОРПУС_28, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert "6168086464-23-5" not in [к["contractNumber"] for к in o]


def test_тест_падает_и_на_обратной_стороне(analyzer):
    """Сторож самого теста: без границы-скобки карточки нет вовсе.

    Если «(» перестанет заканчивать номер, канонический проход вернёт пусто —
    а пустой список молча прошёл бы проверки «такого номера нет».
    """
    склеено = КОРПУС_28.replace("№6168086464-23-5П02(далее",
                                "№6168086464-23-5П02 (далее")
    o = карточки(analyzer, склеено, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert [к["contractNumber"] for к in o] == ["6168086464-23-5П02"]


def test_сумма_долга_доезжает_до_единственной_карточки(analyzer):
    """Поручитель отвечает за весь долг заёмщика, и сумма названа общей фразой.

    По номеру поручительства суммы в документе нет — без этого правила
    карточка уходила на форму вообще без долга.
    """
    o = карточки(analyzer, КОРПУС_28, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert o[0].get("amount") == "7 371 840,35"


def test_сумма_не_угадывается_когда_карточек_несколько(analyzer):
    """Две карточки и одна общая сумма — это выбор наугад, он запрещён."""
    текст = КОРПУС_28.replace(
        "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ (далее – Поручитель/Должник) заключили договор\n"
        "поручительства №6168086464-23-5П02",
        "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ (далее – Поручитель/Должник) заключили договор\n"
        "поручительства №6168086464-23-5П03(далее – Договор поручительства).\n"
        "В качестве обеспечения ПАО Сбербанк и ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ "
        "(далее – Поручитель/Должник) заключили договор поручительства "
        "№6168086464-23-5П02")
    o = карточки(analyzer, текст, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert len(o) == 2
    assert all("amount" not in к for к in o)


# --- скобка как граница номера ---------------------------------------------------

def test_номер_склеенный_со_скобкой(analyzer):
    """«№…П02(далее» — скобка заканчивает номер."""
    o = карточки(analyzer, КОРПУС_28, "ОМЕЛЯНЧУК ЕВГЕНИЙ АЛЕКСЕЕВИЧ")
    assert o[0]["contractNumber"] == "6168086464-23-5П02"


def test_скобка_с_цифрой_номер_не_заканчивает(analyzer):
    """Сторож: «№ 2431453618(10551861421)» — ОДИН договор двумя номерами.

    Совкомбанк пишет внутренний номер в скобках сразу за договорным. Если
    сделать скобку безусловной границей, у свежие-19 и свежие-21 появятся
    задвоенные карточки на тот же долг.
    """
    текст = ('"17" мая 2023 года между Банком и Должником был заключен кредитный '
             "договор (в виде акцептованного заявления оферты) № 10551861421.\n"
             "По кредитному договору № 2431453618(10551861421) от \"17\" мая 2023 года "
             "- в размере 300347.55 руб.\n")
    номера = [к["contractNumber"]
              for к in analyzer._extract_obligations_primary(текст, "БУЯНИНА СВЕТЛАНА ЮРЬЕВНА")]
    assert "2431453618" not in номера

# -*- coding: utf-8 -*-
"""Номер, встречающийся только в хвосте документа (21.09.2026, фаза 6 п.1).

корпус-5 называет ОДИН долг двумя номерами:

    тело        на основании кредитного договора № 67177 (далее по тексту -
                Кредитный договор) от 14.01.2023 выдан ипотечный кредит
    приложение  Справка о зачислении … по договору №67164 от 16.01.2023
    реквизиты   Счет - по кредитному договору № 67164 - 45507810121831476507

Вторая карточка — тот же долг под внутренним номером банка.

⚠️ ОБЩЕЕ правило «не брать обязательства из хвоста» ОПРОВЕРГНУТО замером:
корпус-23, корпус-24 и корпус-49 остались бы вовсе без обязательств, а
корпус-38 потерял бы четыре настоящих договора — они перечислены ТОЛЬКО в
приложении. Поэтому правило требует ДВУХ условий сразу: договор найден и в
теле, и тело объявило его оборотом «(далее … Кредитный договор)».
Срабатывает на одном документе из 101.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def _номера(analyzer, текст):
    return [к.get("contractNumber") for к in analyzer.extract_obligations(текст, {})]


def _заявление(тело: str, хвост: str) -> str:
    """Тело + хвост, разведённые набивкой: метка хвоста должна лечь за 55%."""
    набивка = ("В соответствии со ст. 309 ГК РФ обязательства должны "
               "исполняться надлежащим образом.\n") * 6
    return тело + набивка + хвост


ТЕЛО_С_ОПРЕДЕЛЕНИЕМ = (
    "Банк на основании кредитного договора № 67177 (далее по тексту - "
    "Кредитный договор) от 14.01.2023 выдал ипотечный кредит созаемщикам "
    "в сумме 1106855,90 руб.\n")
ХВОСТ_С_ЧУЖИМ_НОМЕРОМ = (
    "Приложения:\n"
    "16. Справка о зачислении по договору №67164 от 16.01.2023\n"
    "Счет - по кредитному договору № 67164 - 45507810121831476507\n")


def test_номер_из_хвоста_не_заводит_карточку(analyzer):
    текст = _заявление(ТЕЛО_С_ОПРЕДЕЛЕНИЕМ, ХВОСТ_С_ЧУЖИМ_НОМЕРОМ)
    assert _номера(analyzer, текст) == ["67177"]


def test_без_определения_в_теле_номер_остаётся(analyzer):
    """Нет оборота «(далее … Кредитный договор)» — правило не включается."""
    тело = ("Банк на основании кредитного договора № 67177 от 14.01.2023 "
            "выдал ипотечный кредит созаемщикам.\n")
    номера = _номера(analyzer, _заявление(тело, ХВОСТ_С_ЧУЖИМ_НОМЕРОМ))
    assert "67164" in номера, номера


def test_договор_только_в_приложении_сохраняется(analyzer):
    """Часть заявлений называет договор ТОЛЬКО в перечне приложений."""
    тело = "Должник имеет неисполненные денежные обязательства перед Банком.\n"
    хвост = ("Приложения:\n"
             "13. Копия кредитного договора №6142027489-24-2 от 30.09.2024;\n"
             "14. Общие условия;\n")
    assert _номера(analyzer, _заявление(тело, хвост)) == ["6142027489-24-2"]


def test_правило_не_съедает_документ_целиком(analyzer):
    """Если в хвосте ВСЕ номера, прежнее поведение вернее любой догадки."""
    тело = ("Банк выдал кредит на основании кредитного договора "
            "(далее по тексту - Кредитный договор).\n")
    хвост = ("Приложения:\n"
             "13. Копия кредитного договора №6142027489-24-2 от 30.09.2024;\n"
             "14. Копия кредитного договора №6142027489-25-1 от 04.04.2025;\n")
    номера = _номера(analyzer, _заявление(тело, хвост))
    assert номера == ["6142027489-24-2", "6142027489-25-1"], номера


def test_одна_карточка_правило_не_трогает(analyzer):
    """Отсекать нечего, когда обязательство одно — проверка дешевле догадки."""
    текст = _заявление(ТЕЛО_С_ОПРЕДЕЛЕНИЕМ, "Приложения:\n1. Расчет задолженности\n")
    assert _номера(analyzer, текст) == ["67177"]

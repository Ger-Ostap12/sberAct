def test_слово_без_слота_не_правится_НИГДЕ(ген):
    """Гейт проверяется по ВСЕМУ каталогу, а не на одном файле.

    Слово «кредитный договор» встречается в актах и не как вид требования:
    цитата закона, ссылка на приложения, «кредитными организациями». Такие
    места отличает отсутствие слота обязательства рядом — и их количество
    после подстановки обязано остаться прежним.
    """
    from pathlib import Path

    from obligation_wording import ШАБЛОННОЕ_СЛОВО

    СЛОТ = re.compile(r"\[1[01]\d\]")

    def без_слота(документ):
        сколько = 0
        for абзац in документ.paragraphs:
            текст = абзац.text
            for m in ШАБЛОННОЕ_СЛОВО.finditer(текст):
                if not СЛОТ.search(текст[m.end():m.end() + 60]):
                    сколько += 1
        return сколько

    карточки = [карточка("111", "01.01.2021", "Судебный приказ"),
                карточка("222", "02.02.2022", "Кредитная карта")]
    расхождения = []
    for путь in sorted(Path(ШАБЛОНЫ).rglob("*.docx")):
        if путь.name.startswith("~$"):
            continue
        до = без_слота(Document(str(путь)))
        if not до:
            continue
        документ = Document(str(путь))
        ген._apply_obligation_type_wording(документ, карточки)
        после = без_слота(документ)
        if до != после:
            расхождения.append(f"{путь.name}: {до} -> {после}")
    assert not расхождения, расхождения



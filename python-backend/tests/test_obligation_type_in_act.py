# -*- coding: utf-8 -*-
"""Вид обязательства доезжает до АКТА (05.10.2026).

Замер до правки, на живом шаблоне «Реализация ВКЛ несколько договоров.docx»:

```
вид в карточке          что печаталось в акте
Судебный приказ         …заключили: кредитный договор от 28.10.2022 № 1271058
Кредитная карта         …заключили: кредитный договор от 28.10.2022 № 1271058
Договор поручительства  …заключили: кредитный договор от 28.10.2022
                           № договор поручительства № 1271058
Договор залога          …заключили: .      ← обязательство ИСЧЕЗЛО
```

Три причины, все закрыты:
  * слово «кредитный договор» стоит в шаблонах готовым текстом (298 мест в
    57 актах), и замена его на настоящий вид была МЁРТВОЙ: искала фразу
    вместе с квадратными скобками уже после того, как маркеры заполнены;
  * у поручительства вид приклеивался К НОМЕРУ («№ договор поручительства
    № X») — в корпусе 53 такие карточки в 11 документах;
  * карточка с «залог» в виде выбрасывалась из перечня, и чистка пустых
    слотов съедала кусок фразы вместе с суммой.
"""
import os
import re
import sys

import pytest
from docx import Document

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))
ШАБЛОНЫ = os.path.abspath(os.path.join(_THIS, "..", "..", "Templates"))

pytestmark = pytest.mark.skipif(
    not os.path.isdir(ШАБЛОНЫ), reason="папка Templates недоступна")

# Два разных устройства фразы — проверяем на обоих.
ПЕРЕЧИСЛЕНИЕ = os.path.join(
    ШАБЛОНЫ, "шаблоны актов без залогов", "физ реализация ВКЛ в РТК",
    "Реализация ВКЛ несколько договоров.docx")   # «заключили: кредитный договор от [100] № [110], …»
МНОЖЕСТВЕННОЕ = os.path.join(
    ШАБЛОНЫ, "шаблоны актов без залогов", "физ реализация ВКЛ в РТК",
    "Реализация принятие РТК.docx")              # «по кредитным договорам № [110] от [100], …»
# Цитата ст. 213.5 Закона о банкротстве — трогать нельзя.
С_ЦИТАТОЙ = os.path.join(ШАБЛОНЫ, "умерший", "Решение Умерший старый.docx")


@pytest.fixture(scope="module")
def ген():
    from document_generator import DocumentGenerator
    return DocumentGenerator()


def карточка(номер, дата, вид):
    return {"contractNumber": номер, "contractDate": дата, "obligationType": вид}


def собрать(ген, шаблон, карточки):
    """Текст акта после подстановки обязательств, в одну строку."""
    doc = Document(шаблон)
    ген.replace_obligations_data(doc, {"obligations": карточки})
    return re.sub(r"\s+", " ", " ".join(p.text for p in doc.paragraphs))


# --- один вид -------------------------------------------------------------------

@pytest.mark.parametrize("вид,ждём", [
    ("Кредитный договор", "заключили: кредитный договор от 28.10.2022 № 1271058"),
    ("Судебный приказ", "заключили: судебный приказ от 28.10.2022 № 1271058"),
    ("Исполнительный документ",
     "заключили: исполнительный документ от 28.10.2022 № 1271058"),
    ("Соглашение о кредитовании",
     "заключили: соглашение о кредитовании от 28.10.2022 № 1271058"),
    ("Договор займа", "заключили: договор займа от 28.10.2022 № 1271058"),
    # Винительный падеж: «заключили кредитнУЮ картУ».
    ("Кредитная карта", "заключили: кредитную карту от 28.10.2022 № 1271058"),
    # Вид больше не приклеивается к номеру.
    ("Договор поручительства",
     "заключили: договор поручительства от 28.10.2022 № 1271058"),
])
def test_вид_печатается_свой(ген, вид, ждём):
    текст = собрать(ген, ПЕРЕЧИСЛЕНИЕ, [карточка("1271058", "28.10.2022", вид)])
    assert ждём in текст


def test_залог_не_уничтожает_обязательство(ген):
    """Было «…заключили: .» — обязательство исчезало из акта целиком."""
    текст = собрать(ген, ПЕРЕЧИСЛЕНИЕ,
                    [карточка("1271058", "28.10.2022", "Договор залога")])
    assert "заключили: договор залога от 28.10.2022 № 1271058" in текст
    assert "заключили: ." not in текст


def test_поручительство_без_двойного_номера(ген):
    """Было «№ договор поручительства № 1271058»."""
    текст = собрать(ген, ПЕРЕЧИСЛЕНИЕ,
                    [карточка("1271058", "28.10.2022", "Договор поручительства")])
    assert "№ договор поручительства №" not in текст
    assert текст.count("№ 1271058") == 1



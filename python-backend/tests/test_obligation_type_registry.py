    (СВЕЖИЕ_27, "21030267-1", "Кредитный договор"),
    (СВЕЖИЕ_6, "SRSRS510S23021400327", "Соглашение о кредитовании"),
    (КОРПУС_43, "2-1178/2024", "Судебный приказ"),

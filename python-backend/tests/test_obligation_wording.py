# -*- coding: utf-8 -*-
"""Вид обязательства в тексте акта: склонение и форма по шаблону (05.10.2026).

Было: слово «кредитный договор» стоит в шаблонах готовым текстом — 298 мест в
57 актах, — и акт называл кредитным договором что угодно: судебный приказ
самобанкрота, соглашение о кредитовании Альфа-Банка, кредитную карту.

Маркер вместо слова не годится: шаблон требует свою форму («по кредитному
договору», «расторгнуть кредитный договор», «по кредитным договорам»), а в
карточке вид лежит в именительном. Поэтому форма берётся ИЗ ШАБЛОНА.

Здесь проверяется чистая часть — склонение и разбор формы. Подстановка в
живые шаблоны — в tests/test_obligation_type_in_act.py.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from claim_basis import BASIS_TITLE, KIND_TITLE  # noqa: E402
from obligation_wording import (  # noqa: E402
    ШАБЛОННОЕ_СЛОВО,
    как_в_шаблоне,
    склонить,
    форма_шаблона,
)

ВСЕ_ВИДЫ = sorted(set(list(KIND_TITLE.values()) + list(BASIS_TITLE.values())))


# --- склонение ------------------------------------------------------------------

@pytest.mark.parametrize("вид,падеж,число,ждём", [
    # ⚠️ ГЛАВНАЯ ЛОВУШКА: склоняется только ГОЛОВА. Зависимое слово в
    # родительном падеже остаётся: «договору поручительства», а не
    # «договору поручительству» — именно так ломается наивный разбор по словам.
    ("Договор поручительства", "datv", "sing", "Договору поручительства"),
    ("Договор поручительства", "gent", "plur", "Договоров поручительства"),
    ("Договор займа", "datv", "sing", "Договору займа"),
    ("Договор цессии", "ablt", "sing", "Договором цессии"),
    # Предложная группа тоже неизменна: «по соглашению О КРЕДИТОВАНИИ».
    ("Соглашение о кредитовании", "datv", "sing", "Соглашению о кредитовании"),
    ("Соглашение о кредитовании", "gent", "plur", "Соглашений о кредитовании"),
    # Прилагательное согласуется с головой.
    ("Судебный приказ", "datv", "sing", "Судебному приказу"),
    ("Судебный приказ", "datv", "plur", "Судебным приказам"),
    ("Исполнительный документ", "gent", "sing", "Исполнительного документа"),
    ("Мировое соглашение", "datv", "sing", "Мировому соглашению"),
    # ⚠️ ВТОРАЯ ЛОВУШКА: винительный у женского рода. pymorphy на
    # inflect({'accs','sing','inan'}) теряет род и отдаёт мужскую форму —
    # выходило «заключили кредитный карту».
    ("Кредитная карта", "accs", "sing", "Кредитную карту"),
    ("Кредитная карта", "datv", "sing", "Кредитной карте"),
    # ⚠️ ТРЕТЬЯ ЛОВУШКА: винительный множественного. Без пометки
    # неодушевлённости выходило «кредитных карты».
    ("Кредитная карта", "accs", "plur", "Кредитные карты"),
    ("Судебный приказ", "accs", "plur", "Судебные приказы"),
])
def test_склонение(вид, падеж, число, ждём):
    assert склонить(вид, падеж, число) == ждём


def test_все_виды_реестра_склоняются():
    """Ни один вид не теряет слов и не выходит пустым: 32 вида × 6 × 2."""
    сломано = []
    for вид in ВСЕ_ВИДЫ:
        for падеж in ("nomn", "gent", "datv", "accs", "ablt", "loct"):
            for число in ("sing", "plur"):
                итог = склонить(вид, падеж, число)
                if not итог or итог.count(" ") != вид.count(" "):
                    сломано.append((вид, падеж, число, итог))
    assert not сломано, сломано[:5]


# --- форма шаблонного слова -----------------------------------------------------

@pytest.mark.parametrize("слово,слева,падеж,число", [
    ("кредитному договору", "задолженность по ", "datv", "sing"),
    ("кредитным договорам", "задолженности по ", "datv", "plur"),
    ("кредитного договора", "во исполнение ", "gent", "sing"),
    ("кредитных договоров", "на основании ", "gent", "plur"),
    ("кредитном договоре", "в ", "loct", "sing"),
    # Именительный и винительный у «договор» совпадают — решает глагол слева.
    ("кредитный договор", "банк и должник заключили ", "accs", "sing"),
    ("кредитный договор", "расторгнуть ", "accs", "sing"),
    ("кредитные договоры", "«[2]» заключили ", "accs", "plur"),
    ("кредитный договор", "", "nomn", "sing"),
])
def test_форма_шаблона(слово, слева, падеж, число):
    assert форма_шаблона(слово, слева) == (падеж, число)


def test_все_написания_шаблонов_разбираются():
    """17 написаний, найденных в каталоге Templates, — все до единого.

    Если в акты придёт новая форма слова, тест не поможет; зато он стережёт
    то, что уже есть: любое из этих написаний обязано давать падеж и число.
    """
    написания = [
        "кредитному договору", "кредитным договорам", "кредитный договор",
        "кредитные договоры", "кредитных договоров", "кредитного договора",
        "кредитными договорами", "кредитных договорах", "кредитном договоре",
    ]
    for слово in написания:
        падеж, число = форма_шаблона(слово, "по ")
        assert падеж in ("nomn", "gent", "datv", "accs", "ablt", "loct")
        assert число in ("sing", "plur")


# --- вид в форме шаблона --------------------------------------------------------

@pytest.mark.parametrize("вид,слово,слева,ждём", [
    ("Судебный приказ", "кредитному договору", "по ", "судебному приказу"),
    ("Исполнительный документ", "кредитным договорам", "по ",
     "исполнительным документам"),
    ("Кредитная карта", "кредитный договор", "заключили ", "кредитную карту"),
    ("Договор займа", "кредитный договор", "расторгнуть ", "договор займа"),
    ("Соглашение о кредитовании", "кредитного договора", "во исполнение ",
     "соглашения о кредитовании"),
])
def test_как_в_шаблоне(вид, слово, слева, ждём):
    assert как_в_шаблоне(вид, слово, слева) == ждём


def test_регистр_берётся_от_шаблона():
    """Реестр пишет вид с заглавной, шаблон — со строчной внутри фразы."""
    assert как_в_шаблоне("Судебный приказ", "кредитному договору", "по ") \
        == "судебному приказу"
    assert как_в_шаблоне("Судебный приказ", "Кредитный договор", "") \
        == "Судебный приказ"


def test_число_можно_переопределить():
    """Смешанный случай: фраза множественная, а подпись — по одному виду."""
    assert как_в_шаблоне("Судебный приказ", "кредитным договорам", "по ",
                         число="sing") == "судебному приказу"


def test_пустой_вид_не_подменяется():
    """Лучше прежний текст шаблона, чем сломанная фраза."""
    assert как_в_шаблоне("", "кредитному договору", "по ") is None
    assert как_в_шаблоне(None, "кредитному договору", "по ") is None


# --- само шаблонное слово -------------------------------------------------------

@pytest.mark.parametrize("текст,ждём", [
    ("задолженность по кредитному договору от [100]", "кредитному договору"),
    ("заключили кредитные договоры № [110]", "кредитные договоры"),
    ("Кредитный договор № [110]", "Кредитный договор"),
])
def test_слово_находится(текст, ждём):
    найдено = ШАБЛОННОЕ_СЛОВО.search(текст)
    assert найдено and найдено.group(0) == ждём


def test_слово_не_цепляет_лишнего():
    """«кредитной организации» видом требования не является."""
    assert not ШАБЛОННОЕ_СЛОВО.search("с кредитными организациями")
    assert not ШАБЛОННОЕ_СЛОВО.search("кредитор указал")

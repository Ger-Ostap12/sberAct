# -*- coding: utf-8 -*-
"""Падежи наименования ЮЛ: склонятель ФИО не берётся за организации.

Он считает первый токен фамилией, и «ООО «СПН ТРАК»» в родительном падеже
становилось «ООО «СПН ТРАКА»». Закавыченное название и аббревиатура правовой
формы не склоняются, полная правовая форма склоняется по таблице.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from org_normalizer import is_org_name, org_case_form  # noqa: E402

КОРПУС = os.path.abspath(os.path.join(_THIS, "..", "..", "Заявления", "НОвая конвертация"))


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- чистая функция склонения -----------------------------------------------------


@pytest.mark.parametrize("имя,ожидание", [
    # Аббревиатура и закавыченное название неизменны ЦЕЛИКОМ.
    ("ООО «СПН ТРАК»", "ООО «СПН ТРАК»"),
    ("ООО «ТМД»", "ООО «ТМД»"),
    ("ООО «Форте Пром Стил ГМБХ»", "ООО «Форте Пром Стил ГМБХ»"),
    ("ООО МКК «Озон Кредит»", "ООО МКК «Озон Кредит»"),
    ('ООО "КОЛОР"', 'ООО "КОЛОР"'),
    # Полная правовая форма склоняется, предложный хвост и название — нет.
    ("Общество с ограниченной ответственностью «Перспектива»",
     "Общества с ограниченной ответственностью «Перспектива»"),
    ("Публичное акционерное общество «Сбербанк России»",
     "Публичного акционерного общества «Сбербанк России»"),
    ("Акционерное общество «Альфа-Банк»", "Акционерного общества «Альфа-Банк»"),
    ("Микрофинансовая компания «Быстроденьги»",
     "Микрофинансовой компании «Быстроденьги»"),
    ("Сельскохозяйственный производственный кооператив «Колос»",
     "Сельскохозяйственного производственного кооператива «Колос»"),
])
def test_родительный_падеж(имя, ожидание):
    assert org_case_form(имя, "gent") == ожидание


def test_все_четыре_падежа():
    имя = "Общество с ограниченной ответственностью «Перспектива»"
    assert org_case_form(имя, "datv") == "Обществу с ограниченной ответственностью «Перспектива»"
    assert org_case_form(имя, "ablt") == "Обществом с ограниченной ответственностью «Перспектива»"
    # Винительный НЕОДУШЕВЛЁННЫЙ: организация — не лицо, форма как именительный.
    assert org_case_form(имя, "accs") == имя


def test_незнакомая_форма_остаётся_как_есть():
    """Воздержание лучше догадки: нет головного существительного в таблице —
    отдаём именительный падеж, а не выдуманную форму."""
    имя = "Хозяйствующий субъект «Нечто»"
    assert org_case_form(имя, "gent") == имя


@pytest.mark.parametrize("значение,это_юл", [
    ("ООО «СПН ТРАК»", True),
    ("Общество с ограниченной ответственностью «Перспектива»", True),
    # Иностранная правовая форма стоит в КОНЦЕ имени; без неё падежные поля
    # оставались пустыми, то есть пустое место в акте.
    ("Форте Хоум ГмбХ", True),
    ("Иванов Иван Иванович", False),
    ("ЕЛИСЕЕНКО СЕРГЕЙ ВАСИЛЬЕВИЧ", False),
])
def test_опознание_организации(значение, это_юл):
    assert is_org_name(значение) is это_юл


def test_фио_через_склонятель_фио_не_задето(analyzer):
    """Запрет узкий: человеческие имена по-прежнему склоняются морфологией."""
    assert analyzer._convert_name_to_genitive(
        "Елисеенко Сергей Васильевич") == "Елисеенко Сергея Васильевича"
    assert analyzer._convert_name_to_dative(
        "Иванова Мария Петровна") == "Ивановой Марии Петровне"


# --- пересборка по окончательному имени -------------------------------------------


def test_пересборка_добавляет_потерянное_название(analyzer):
    """Форма без названия — негодна: имя должника обязано быть в акте."""
    fields = {"applicantName": "Общество с ограниченной ответственностью «Перспектива»",
              "applicantNameGenitive": "Общества с ограниченной ответственностью"}
    analyzer._fix_org_case_forms(fields)
    assert fields["applicantNameGenitive"] == (
        "Общества с ограниченной ответственностью «Перспектива»")


def test_пересборка_выбрасывает_чужое_фио(analyzer):
    """В поле падежа ЮЛ стояло ФИО подписанта — это чужое значение, не неточное."""
    fields = {"applicantName": "ООО «Форте Пром Стил ГМБХ»",
              "applicantNameGenitive": "Панина Александра Владимировича"}
    analyzer._fix_org_case_forms(fields)
    assert fields["applicantNameGenitive"] == "ООО «Форте Пром Стил ГМБХ»"


def test_пересборка_убирает_роль_в_скобках(analyzer):
    """«(заемщик)» — проза договора, а не часть имени."""
    fields = {"applicantName": 'АО "КОНЦЕРН "САРМАТ"',
              "applicantNameGenitive": 'АО "КОНЦЕРНА "САРМАТ" (заемщик)'}
    analyzer._fix_org_case_forms(fields)
    assert fields["applicantNameGenitive"] == 'АО "КОНЦЕРН "САРМАТ"'


def test_пересборка_не_трогает_годную_форму(analyzer):
    """Ворота, а не запрет: документ назвал форму полно — она и остаётся."""
    fields = {"applicantName": "Общество с ограниченной ответственностью «Перспектива»",
              "applicantNameGenitive": "Общества с ограниченной ответственностью «Перспектива»"}
    analyzer._fix_org_case_forms(fields)
    assert fields["applicantNameGenitive"] == (
        "Общества с ограниченной ответственностью «Перспектива»")


def test_пересборка_не_трогает_физлицо(analyzer):
    fields = {"applicantName": "Елисеенко Сергей Васильевич",
              "applicantNameGenitive": "Елисеенко Сергея Васильевича"}
    analyzer._fix_org_case_forms(fields)
    assert fields["applicantNameGenitive"] == "Елисеенко Сергея Васильевича"



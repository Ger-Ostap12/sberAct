# --- документы корпуса -------------------------------------------------------------


@pytest.mark.parametrize("файл,ожидание", [
    ("Остальные/набл Заявление о признании должника банкротом ООО  СПН ТРАК.docx",
     "ООО «СПН ТРАК»"),
    ("Остальные/Заявление о признании должника несостоятельным (банкротом) Перспектива.docx",
     "Общества с ограниченной ответственностью «Перспектива»"),
    ("Остальные/заявление о банкротстве Форте Пром Стил ГМБХ.docx",
     "ООО «Форте Пром Стил ГМБХ»"),
    ("Остальные/Заявление о признании должника несостоятельным (банкротом) Форте Хоум.docx",
     "Форте Хоум ГмбХ"),
])
def test_родительный_падеж_на_документе(analyzer, файл, ожидание):
    путь = os.path.join(КОРПУС, файл.replace("/", os.sep))
    if not os.path.exists(путь):
        pytest.skip("документ корпуса недоступен")
    f = (analyzer.analyze(путь).get("fields") or {})
    assert f.get("applicantNameGenitive") == ожидание

# -*- coding: utf-8 -*-
"""Паспорт должника: десяток написаний, один разборщик (§S.9).

Отчёт покрытия говорил «passport заполнено 0 из 66» — и это оказалось правдой
лишь формально: витринное поле `passport` объявлено в `patterns.py` и
`label_synonyms.py`, но НЕ ЧИТАЕТСЯ ни генератором, ни фронтом. Настоящие поля —
`debtors[].passportSeries` / `debtors[].passportNumber`, их и рисует форма
(`DebtorsSection.tsx`), их же берут ипотечные акты.

По ним потери были настоящие: у 17 документов корпуса паспорт в тексте есть, а
в карточке должника пусто. Причин ДВЕ, и главная — не та, что кажется:

  • ПРОВОДКА (15 документов). Разбор паспорта жил только в одной ветке и в
    `fields`/карточку должника не попадал вовсе — ни у самобанкротных заявлений,
    ни у ФНС. Формат тут был ни при чём.
  • НАПИСАНИЕ (4 написания). Прежний паттерн понимал 8 форм из 12 и спотыкался
    на запятой, двоеточии после «серия», точке вместо пробела и пробеле ВНУТРИ
    номера.

Отрицательные проверки закрывают главный риск послабления: не откусить кусок
более длинного числа (ИНН, СНИЛС, номер счёта).
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from fio_detector import extract_debtor_details, find_passport  # noqa: E402


@pytest.mark.parametrize("text,expected", [
    # Написания, которые работали и раньше.
    ("Паспорт: 6005 561928", ("6005", "561928")),
    ("Паспорт: серия 1111 № 111111", ("1111", "111111")),
    # Написания из корпуса, на которых поле молчало.
    ("Паспорт: серия 60 24, №940297", ("6024", "940297")),
    ("паспорт 60 17 067255", ("6017", "067255")),
    ("Паспорт: 6002 № 465076", ("6002", "465076")),
    ("паспорт: серия: 60 14 номер: 691850", ("6014", "691850")),
    ("паспорт: серия 60 23.№278902", ("6023", "278902")),
    ("Паспорт 6019 513897", ("6019", "513897")),
    ("Паспорт: 60 14 737042", ("6014", "737042")),
    ("Паспорт: серия 6018 № 402670", ("6018", "402670")),
    ("паспортные данные: серия 60 25 номер 029979", ("6025", "029979")),
    ("паспортные данные: серия 60 05 номер 286525", ("6005", "286525")),
])
def test_написания_паспорта(text, expected):
    assert find_passport(text) == expected


def test_без_паспорта_ничего_не_выдумывается():
    assert find_passport("ИНН 612504512780, СНИЛС 158-801-520 75") is None


def test_не_откусывает_кусок_длинного_числа():
    """`(?<!\\d)`/`(?!\\d)` — единственное, что отделяет серию+номер от ИНН.

    Без них «паспорт … 612504512780» разбирался бы как серия 6125 номер 045127.
    """
    assert find_passport("паспортные данные отсутствуют, ИНН 612504512780") is None


def test_серия_и_номер_не_путаются_местами():
    """Серия — 4 цифры, номер — 6, и порядок в документе всегда такой."""
    assert find_passport("Паспорт: серия 60 05 № 561 928") == ("6005", "561928")


def test_паспорт_попадает_в_реквизиты_должника():
    block = (
        "Должник: Медведев Максим Юрьевич\n"
        "30.08.1985 года р.,\n"
        "Паспорт: серия 60 05 № 561 928\n"
    )
    details = extract_debtor_details(block)
    assert details["passportSeries"] == "6005"
    assert details["passportNumber"] == "561928"

# -*- coding: utf-8 -*-
"""Требование целиком из пеней: пункт 8 фазы 4 (09.10.2026), разбор — handoff §S.48.

Два красных на свежие-28 («Заявление по делу №А53-24404-2018.docx») имели общий
повод — всё требование состоит из пеней, — но РАЗНЫЕ корни в двух файлах:

```
осн. долг        затычка `_reconcile_debt_amounts` копирует общую сумму в осн.
                 долг, когда он не найден явно. Здесь 800 293,35 — это пени,
                 они уже стоят в своей графе, и копия удваивает требование
взысканная сумма поиск суммы прежнего акта берёт первую «в размере N» после
                 акта, а фраза звучит «взысканы пени, НАЧИСЛЕННЫЕ НА СУММУ
                 ДОЛГА в размере 237 743,56 руб.» — это БАЗА начисления.
                 Единой взысканной суммы такой акт не называет вовсе
```
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def сверить(analyzer, поля):
    """Прогон согласования сумм на готовом наборе полей."""
    поля = dict(поля)
    analyzer._reconcile_debt_amounts(поля, "", "rtk")
    return поля


# --- ворота затычки: пени не становятся основным долгом ---------------------------

def test_требование_из_пеней_не_даёт_основного_долга(analyzer):
    """800 293,35 уже стоит в неустойке — копия в осн. долг удваивала бы требование."""
    поля = сверить(analyzer, {
        "debtAmount": "800 293,35",
        "totalDebt": "800 293,35",
        "forfeit": "800 293,35",
    })
    assert not поля.get("loanDebt"), "осн. долг заполнен тем же числом, что неустойка"


def test_штрафы_закрывают_затычку_так_же_как_неустойка(analyzer):
    поля = сверить(analyzer, {
        "debtAmount": "45 000,00",
        "totalDebt": "45 000,00",
        "penalties": "45 000,00",
    })
    assert not поля.get("loanDebt")


def test_совпадение_нулей_ворота_не_открывает(analyzer):
    """«0,00» в обеих графах — случайность, а не требование из пеней.

    У свежие-10 и свежие-12 пусты как «0,00» и общая сумма, и неустойка.
    Первая редакция ворот на этом срабатывала и уводила осн. долг к ОБЩЕЙ
    сумме (90 330,47), тогда как настоящий стоит в таблице — 88 897,01.
    Поймано ручной сверкой: эталон этого не видит, потому что подпись
    «Основной долг» читает первым непустым `principalDebt`.
    """
    поля = сверить(analyzer, {
        "debtAmount": "0,00",
        "totalDebt": "90 330,47",
        "penalties": "0,00",
    })
    assert поля.get("loanDebt") == "0,00", "ворота открылись на совпадении нулей"


# --- ворота, а не запрет: обычная затычка обязана работать ------------------------

def test_затычка_работает_когда_своей_графы_нет(analyzer):
    поля = сверить(analyzer, {"debtAmount": "123 456,78", "totalDebt": "123 456,78"})
    assert поля.get("loanDebt") == "123 456,78"


def test_затычка_работает_когда_неустойка_другая(analyzer):
    """Неустойка есть, но это ЧАСТЬ требования, а не всё оно."""
    поля = сверить(analyzer, {
        "debtAmount": "500 000,00",
        "totalDebt": "500 000,00",
        "forfeit": "12 345,00",
    })
    assert поля.get("loanDebt") == "500 000,00"


# --- ворота в блоке взыскания: база начисления не взысканная сумма ----------------

БАЗА_НАЧИСЛЕНИЯ = (
    "По настоящее время за ООО «УО «Владимирская» числится задолженность по "
    "оплате пени в размере 800 293,35 руб., подтвержденная судебными актами:\n"
    "Решением Арбитражного суда Ростовской области от 07.06.2019 г. по делу "
    "№ А53-12167/2019 с ООО «УО «Владимирская» в пользу ПАО «ТНС энерго "
    "Ростов-на-Дону» взысканы пени, начисленные на сумму долга в размере "
    "237 743,56 руб. на основании абзаца 10 пункта 2 статьи 37 ФЗ "
    "«Об электроэнергетике», начиная с 01.02.2019 г. по день фактической "
    "оплаты задолженности.\n"
    "Кредитором произведено начисление длящихся пеней на сумму 237 743,56 руб. "
    "за период с 01.02.2019 г. по 25.06.2019 г. в размере 19 888,16 руб.\n"
)


def test_база_начисления_не_становится_взысканной_суммой(analyzer):
    r = analyzer._extract_prior_court_decision(БАЗА_НАЧИСЛЕНИЯ)
    assert "priorAmount" not in r, "взята база начисления пеней, а не взысканное"


def test_суд_и_дело_берутся_и_без_суммы(analyzer):
    """Отказ от суммы не должен гасить остальные поля акта."""
    r = analyzer._extract_prior_court_decision(БАЗА_НАЧИСЛЕНИЯ)
    assert r.get("priorCaseNumber") == "А53-12167/2019"
    assert r.get("priorCourtName") == "Арбитражный суд Ростовской области"


def test_обычная_взысканная_сумма_по_прежнему_берётся(analyzer):
    """Ворота узкие: без оборота «начисленные на сумму» сумма берётся как раньше."""
    текст = (
        "Решением Арбитражного суда Ростовской области от 07.06.2019 г. по делу "
        "№ А53-12167/2019 с должника взыскана задолженность по договору "
        "в размере 237 743,56 руб.\n"
    )
    assert analyzer._extract_prior_court_decision(текст).get("priorAmount") == "237 743,56"


def test_форма_на_сумму_не_задета_воротами(analyzer):
    """Исполнительный документ «НА СУММУ N» — своя форма записи (свежие-13)."""
    текст = (
        "По кредитному договору 3199309 в отношении Должника выдан исполнительный "
        "документ № 61MS0046#2-95/2025#1 на сумму 17738,40 рублей, который "
        "впоследствии был предъявлен на принудительное исполнение.\n"
    )
    assert analyzer._extract_prior_court_decision(текст).get("priorAmount") == "17 738,40"

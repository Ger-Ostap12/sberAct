# -*- coding: utf-8 -*-
"""Финансы из ПРОСИТЕЛЬНОЙ части: какой блок берём и что в нём слагаемое.

Решения Андрея (handoff §S.43): «все финансы берём из просительной части»,
«если в документе больше одного договора — все финансы складываем».
Шаг 2 фазы 4, разбор — §S.45.

Четыре причины, по которым слой просительной части молчал или ошибался:

```
изкоторых      конвертер склеивает слова, якорь разбивки требовал пробел —
               свежие-13 терял блок целиком, итог брался из прозы про уступку
прописью       «936 023,39 руб. (Девятьсот тридцать шесть тысяч двадцать три
               рубля 39 копеек), в том числе:» — зазор между суммой и
               разбивкой больше 40 знаков, блок не опознавался (свежие-31, -6)
судебные       «судебные расходы в размере 2 000 руб.» — подписи не было
расходы        в реестре категорий, слагаемое выпадало из ИТОГА
слитный итог   «17738,40 руб. – сумма основной задолженности, КОТОРАЯ ВКЛЮЧАЕТ
               В СЕБЯ основной долг, проценты, комиссии и госпошлину» — это
               итог под составной подписью, а не основной долг
```
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def финансы(analyzer, текст):
    ф = {}
    analyzer._apply_prayer_finances(ф, текст)
    return ф


# --- склеенное «изкоторых» ------------------------------------------------------

# Подписи ПЕРЕД суммами с двоеточием — так пишет Альфа-Банк (свежие-31).
# Важно для сторожа: при склеенном якоре старый код уходил в ветку «тире-
# категории», а она такую запись не видит, и слой молчал целиком.
СКЛЕЙКА = (
    "ПРОШУ:\n"
    "1. Включить в реестр требований кредиторов Должника требование "
    "АО «БанкРусскийСтандарт» в состав третьей очереди в размере 17738,40 руб., "
    "изкоторых: основной долг: 7237,60 руб.; проценты: 8500,80 руб.; "
    "государственная пошлина: 2000,00 руб.\n"
)


def test_склеенное_изкоторых_не_ломает_блок(analyzer):
    ф = финансы(analyzer, СКЛЕЙКА)
    assert ф.get("totalDebt") == "17 738,40"
    assert ф.get("principalDebt") == "7 237,60"
    assert ф.get("loanStateDuty17") == "2 000,00"


# --- сумма прописью в скобках перед разбивкой -----------------------------------

ПРОПИСЬЮ = (
    "ПРОШУ:\n"
    "1. Включить требования АО «АЛЬФА-БАНК» в реестр требований кредиторов "
    "гражданина-должника ХЛИЯН ЕЛЕНЫ ОГАНОВНЫ в третью очередь с общей суммой "
    "требований в размере 936 023,39 руб. (Девятьсот тридцать шесть тысяч "
    "двадцать три рубля 39 копеек), в том числе: - просроченный основной долг: "
    "873 306,77 руб. (Восемьсот семьдесят три тысячи триста шесть рублей "
    "77 копеек); - начисленные проценты: 55 699,59 руб. (Пятьдесят пять тысяч "
    "шестьсот девяносто девять рублей 59 копеек); - государственная пошлина: "
    "7 017,03руб. (Семь тысяч семнадцать рублей 03 копейки).\n"
)


def test_сумма_прописью_не_мешает_опознать_блок(analyzer):
    """Зазор между суммой и разбивкой больше 40 знаков из-за прописи."""
    ф = финансы(analyzer, ПРОПИСЬЮ)
    assert ф.get("totalDebt") == "936 023,39", "блок просительной не опознан"
    assert ф.get("principalDebt") == "873 306,77"
    assert ф.get("loanStateDuty17") == "7 017,03"


# --- «судебные расходы» как слагаемое -------------------------------------------

СУДРАСХОДЫ = (
    "ПРОШУ: Включить в реестр требований кредиторов Должника требование "
    "ООО ПКО «Вернём» в размере 20 304 руб. из которых: сумма основного долга "
    "8 000 руб., задолженность по процентам 9 920 руб., судебные расходы "
    "в размере 2 000 руб., неустойку/штраф в размере 384 руб.\n"
)


def test_судебные_расходы_входят_в_итог(analyzer):
    """Без этой подписи итог был 18 304,00 вместо 20 304,00."""
    ф = финансы(analyzer, СУДРАСХОДЫ)
    assert ф.get("totalDebt") == "20 304,00"
    assert ф.get("loanStateDuty17") == "2 000,00"
    assert ф.get("forfeit") == "384,00", "ведущее слово составной подписи"


# --- слитный итог ---------------------------------------------------------------

СЛИТНЫЙ = (
    "ПРОШУ:\n"
    "1. Включить в реестр требований кредиторов Должника требование "
    "АО «БанкРусскийСтандарт» в состав третьей очереди в размере 119498,84 руб., "
    "изкоторых: - 119498,84 руб. – сумма основной задолженности, которая "
    "включает в себя основной долг, проценты, комиссии и государственнуюпошлину; "
    "- 0,00 руб. – сумма неустойки для отдельного учета.\n"
)


def test_слитный_итог_даёт_общую_сумму(analyzer):
    assert финансы(analyzer, СЛИТНЫЙ).get("totalDebt") == "119 498,84"


def test_слитный_итог_не_становится_основным_долгом(analyzer):
    """Разбивка у таких заявлений лежит в ТАБЛИЦЕ — графы не трогаем.

    Иначе юрист видел итог в графе «Осн. долг»: 119 498,84 вместо 117 484,00
    (свежие-10, -11, -12, -13).
    """
    ф = финансы(analyzer, СЛИТНЫЙ)
    assert "principalDebt" not in ф, "слитный итог записан как основной долг"
    assert "interest" not in ф, "разбивка затёрта нулями"


def test_маркер_слитности_ищется_дальше_окна_подписи(analyzer):
    """Сторож на конкретную ловушку: «включает в себя» дальше 45 знаков.

    Окно подписи — 45 знаков, и слова «включает в себя» в него не попадают:
    первая редакция правки опознавала слитный итог только в коротких
    формулировках, а на реальном заявлении молчала.
    """
    ф = финансы(analyzer, СЛИТНЫЙ)
    assert ф.get("totalDebt") == "119 498,84" and "principalDebt" not in ф


def test_обычная_разбивка_слитной_не_считается(analyzer):
    """Обратная сторона: где разбивка настоящая, графы обязаны заполниться."""
    ф = финансы(analyzer, СКЛЕЙКА)
    assert ф.get("principalDebt") == "7 237,60"
    assert ф.get("interest") == "8 500,80"


# --- ссудная ГП словами, без тире -----------------------------------------------

def test_расходы_по_оплате_госпошлины_дают_ссудную(analyzer):
    """свежие-33/-34: «расходы по оплате госпошлины – 2000 руб».

    Арифметический гейт законно отвергает блок целиком (документ пишет
    «на сумму 32952» в заголовке и «ИТОГО – 34952» в конце), поэтому графу
    заполняет смысловой слой `_resolve_duty_graphs`, а итог не трогается.
    """
    текст = (
        "ПРОШУ:\n"
        "1. Включить в реестр требований кредиторов должника - Буниатян Алина "
        "Генриковна в третью очередь требования ООО ПКО «АйДи Коллект» на сумму "
        "32952 руб., из которой: сумма основного долга 15000 руб., сумма долга "
        "по процентам 3264 руб., сумма задолженности по просроченным процентам "
        "14688 руб., расходы по оплате госпошлины – 2000 руб, ИТОГО – 34952 руб.\n"
    )
    ф = {}
    analyzer._resolve_duty_graphs(ф, текст)
    assert ф.get("loanStateDuty17") == "2 000,00"

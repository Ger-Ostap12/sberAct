# -*- coding: utf-8 -*-
"""Тесты блока «Сведения о взыскании» — ранее вынесенный акт о взыскании.

Покрывают три реальные формулировки из корпуса (судебный приказ мирового судьи,
исполнительный документ, приказ с кодом участка вместо названия суда) и главный
риск блока — ложное срабатывание на ТЕКУЩЕМ деле о банкротстве, которое стоит
в тех же заявлениях абзацем выше.
"""
import pytest
from document_analyzer import DocumentAnalyzer


@pytest.fixture(scope="module")
def da():
    return DocumentAnalyzer()


# ── Реальные формулировки корпуса ───────────────────────────────────────────

# «main_Заявление о включении в РТК - 2 л.docx»: мировой судья, суммы через
# запятую-разделитель, госпошлина не упомянута.
TEXT_MAGISTRATE_ORDER = (
    "В соответствии с п. 1 ст. 142 ФЗ «О несостоятельности (банкротстве)» Реестр "
    "требований кредиторов подлежит закрытию по истечении двух месяцев. "
    "Мировым судьей Судебный участок № 1 Обливского судебного района Ростовской "
    "области 16.03.2026 вынесен судебный приказ № 2-253/2026 о взыскании с должника "
    "в пользу ООО ПКО \"ЦДУ Инвест\" задолженности по договору займа № 0437689812 "
    "от 06.10.2025 г. по состоянию на 29.01.2026 в размере 20 854,44 руб. "
    "Вышеуказанный судебный акт, вступил в законную силу 16.04.2026 г."
)

# «пришли коллекторы включаться.docx»: исполнительный документ, госпошлина в
# перечислении «… – госпошлина», дата стоит перед номером дела.
TEXT_ENFORCEMENT_DOC = (
    "Решением АС Ростовской области от 18.05.2026 Мирский Алексей Степанович признан "
    "банкротом. В обоснование заявленных требований сообщаем следующее: "
    "18.03.2025 по гражданскому делу № 2-4-436/2025 Судебный участок № 4 Октябрьского "
    "судебного района г. Ростова-на-Дону был выдан исполнительный документ "
    "№ 2-4-436/2025 о взыскании задолженности с Мирский Алексей Степанович в пользу "
    "ООО «ПКО Воксис» в размере 36658.28 руб., из которых 16890.00 руб. – сумма "
    "задолженности по основному долгу, 17768.28 руб. – проценты, 0.00 руб. – пени, "
    "2000.00 руб. – госпошлина."
)

# «коллекторы пришли включаться.docx»: вместо названия суда — код участка;
# сумма разбита на «а именно…»; рядом абзац про Пленум Верховного суда.
TEXT_COURT_CODE = (
    "При определении начала течения срока следует руководствоваться датой более "
    "позднего публичного извещения (пункт 25 Постановления Пленума Верховного суда "
    "Российской Федерации от 13 октября 2015 года № 45 «О некоторых вопросах»). "
    "19.12.2025 61MS0080 был вынесен судебный приказ № 2-3-2444/2025 о взыскании "
    "задолженности с Медведев Максим Юрьевич в пользу ООО \"ПКО Юнона\" в размере "
    "47999.98, а именно взыскании суммы задолженности в размере 45999.98 руб. и "
    "расходов по оплате государственной пошлины в размере2000.00 руб., который в "
    "установленном порядке вступил в законную силу."
)

# Прежняя формулировка (якорь «по делу №…», вид акта отдельно не назван).
TEXT_LEGACY_BY_CASE = (
    "23.06.2025 Ворошиловским районным судом г.Ростова-на-Дону по делу № 2-2523/2025 "
    "с должника взыскана сумма задолженности в размере 150 000,00 руб."
)


def test_magistrate_order(da):
    r = da._extract_prior_court_decision(TEXT_MAGISTRATE_ORDER)
    assert r["priorCaseNumber"] == "2-253/2026"
    assert r["priorAmount"] == "20 854,44"
    assert r["priorDecisionDate"] == "16.03.2026"
    assert "Судебный участок № 1 Обливского судебного района" in r["priorCourtName"]
    # Госпошлина в этом заявлении не упомянута — поля быть не должно.
    assert "priorStateDuty" not in r
    # Дата договора займа (06.10.2025) и дата вступления в силу — не дата акта.
    assert r["priorDecisionDate"] != "06.10.2025"


def test_enforcement_document(da):
    r = da._extract_prior_court_decision(TEXT_ENFORCEMENT_DOC)
    assert r["priorCaseNumber"] == "2-4-436/2025"      # мировой участок: два дефиса
    assert r["priorAmount"] == "36 658,28"             # общая сумма, включая госпошлину
    assert r["priorStateDuty"] == "2 000,00"
    assert r["priorDecisionDate"] == "18.03.2025"
    assert r["priorCourtName"] == "Судебный участок № 4 Октябрьского судебного района г. Ростова-на-Дону"


def test_court_code_leaves_court_empty(da):
    r = da._extract_prior_court_decision(TEXT_COURT_CODE)
    assert r["priorCaseNumber"] == "2-3-2444/2025"
    assert r["priorAmount"] == "47 999,98"             # общая, не 45 999,98
    assert r["priorStateDuty"] == "2 000,00"
    assert r["priorDecisionDate"] == "19.12.2025"
    # Код участка (61MS0080) названием суда не является, а «Верховный суд» из
    # ссылки на Пленум — чужая фраза.
    assert "priorCourtName" not in r


def test_legacy_by_case_anchor(da):
    r = da._extract_prior_court_decision(TEXT_LEGACY_BY_CASE)
    assert r["priorCaseNumber"] == "2-2523/2025"
    assert r["priorAmount"] == "150 000,00"
    assert r["priorDecisionDate"] == "23.06.2025"
    assert "Ворошиловским районным судом" in r["priorCourtName"]


# ── Негативные: текущее дело о банкротстве ──────────────────────────────────

@pytest.mark.parametrize("text", [
    # Решение о признании банкротом — не взыскание.
    "28.04.2026 г. Арбитражный суд Ростовской области вынес Решение по делу "
    "№ А53-11864/2026, которым Пискова Татьяна Николаевна признана несостоятельным "
    "(банкротом) и в отношении неё введена процедура реализации имущества должника.",
    # То же, но со словом «взыскание» рядом — в абзаце Закона о банкротстве.
    "В производстве АС Ростовской области находится дело № А53-2848/2026 о "
    "несостоятельности (банкротстве) Медведев Максим Юрьевич. Решением от 17.03.2026 "
    "по делу № А53-2848/2026 АС Ростовской области признал банкротом гражданина "
    "Медведев Максим Юрьевич.",
    "требования о взыскании алиментов удовлетворяются в первую очередь",
    "",
])
def test_no_false_positive(da, text):
    assert da._extract_prior_court_decision(text) == {}


def test_case_number_of_bankruptcy_survives(da):
    """Номер текущего дела не должен подменяться номером прежнего акта."""
    r = da._extract_prior_court_decision(TEXT_ENFORCEMENT_DOC)
    assert r["priorCaseNumber"] != "А53-8843/2026"


# ── Валидация номера акта ───────────────────────────────────────────────────

@pytest.mark.parametrize("num,ok", [
    ("2-253/2026", True),        # мировой судья
    ("2-4-436/2025", True),      # мировой участок, два дефиса
    ("2-3-2444/2025", True),
    ("А53-11864/2026", True),    # арбитражный
    ("2а-1234/2024", True),      # КАС
    ("0437689812", False),       # номер договора займа
    ("ЮЗБ/415-Д", False),        # доверенность
    ("13401/26/61066-ИП", False),  # исполнительное производство
    ("", False),
    (None, False),
])
def test_is_valid_prior_act_number(da, num, ok):
    assert da._is_valid_prior_act_number(num) is ok

# -*- coding: utf-8 -*-
"""Блок «Сведения о взыскании»: четыре формы записи прежнего акта (09.10.2026).

Пункты 7 и 10 фазы 4, разбор — handoff §S.47. Все три красных лежали в одном
миксине `prior_collection_mixin`, но корни РАЗНЫЕ:

```
свежие-16  один акт назван ДВАЖДЫ, суд стоит рядом только с первым
           упоминанием; якорь вида акта срабатывал на втором, возвращал
           результат без суда и запирал слой «по делу №», который суд находит
свежие-13  составной номер исполнительного документа «61MS0046#2-95/2025#1»
           обрывался на «#», не проходил проверку формы; плюс сумма записана
           «НА СУММУ», а не «в размере»; плюс рядом нет слова «взыскание» —
           вместо него «принудительное исполнение» и «исполнительное
           производство», и окно признака (90 знаков) до них не дотягивало
свежие-30  акт БЕЗ НОМЕРА вовсе: «МС СУ №6 … вынес судебный акт о взыскании»;
           оба прежних якоря требуют «№ номер», поэтому не опознавалось ничем
```
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def взыскание(analyzer, текст):
    return analyzer._extract_prior_court_decision(текст)


# --- один акт назван дважды, суд рядом только с первым --------------------------

ДВА_УПОМИНАНИЯ = (
    "Судебным актом мирового судьи судебного участка № 8 Советского судебного "
    "района г. Ростова-на-Дону по Делу № 8-2-3913/2025 удовлетворены заявленные "
    "требования НАО ПКО «Первое клиентское бюро», с должника взыскана "
    "задолженность по кредитному договору № 186410 от 11.10.2010. Для "
    "принудительного исполнения изготовлен и выдан судебный приказ "
    "№ 8-2-3913/2025, на основании которого в Советском РОСП г. Ростова-на-Дону "
    "возбуждено исполнительное производство.\n"
)


def test_суд_берётся_у_другого_упоминания_того_же_акта(analyzer):
    """Номер акта у обоих упоминаний ОДИН — значит это один акт."""
    r = взыскание(analyzer, ДВА_УПОМИНАНИЯ)
    assert r.get("priorCourtName") == (
        "Мировой судья судебного участка № 8 Советского судебного района "
        "г. Ростова-на-Дону")


def test_номер_акта_не_теряется_при_дополнении(analyzer):
    assert взыскание(analyzer, ДВА_УПОМИНАНИЯ).get("priorCaseNumber") == "8-2-3913/2025"


# --- составной номер исполнительного документа ----------------------------------

СОСТАВНОЙ_НОМЕР = (
    "Задолженность по кредитному договору подтверждается вступившим в силу "
    "судебным актом и исполнительным документом. По кредитному договору 3199309 "
    "в отношении Должника выдан исполнительный документ № 61MS0046#2-95/2025#1 "
    "на сумму 17738,40 рублей, который впоследствии был предъявлен в службу "
    "судебных приставов-исполнителей на принудительное исполнение, возбуждено "
    "исполнительное производство № 22531/25/61031-ИП.\n"
)


def test_составной_номер_через_решётку_годен(analyzer):
    """«61MS0046#2-95/2025#1» — идентификатор ГАС «Правосудие», внутри номер дела."""
    assert взыскание(analyzer, СОСТАВНОЙ_НОМЕР).get("priorCaseNumber") == \
        "61MS0046#2-95/2025#1"


def test_сумма_на_сумму_а_не_в_размере(analyzer):
    assert взыскание(analyzer, СОСТАВНОЙ_НОМЕР).get("priorAmount") == "17 738,40"


def test_принудительное_исполнение_признак_взыскания(analyzer):
    """Слова «взыскание» рядом нет — есть равносильные формулировки."""
    assert взыскание(analyzer, СОСТАВНОЙ_НОМЕР), "блок не опознал акт вовсе"


# --- акт без номера -------------------------------------------------------------

БЕЗ_НОМЕРА = (
    "По договору уступки права требования № О/66-91/2018 от 31.10.2018 г. "
    "задолженность в отношении Жуменко Ирины Александровны была уступлена "
    "ООО ПКО «АРС ФИНАНС». *МС СУ №6 Советского района г.Ростова-на-Дону вынес "
    "судебный акт о взыскании задолженности с Жуменко Ирины Александровны "
    "в размере 96525 руб.\n"
)


def test_акт_без_номера_даёт_суд(analyzer):
    """Сокращение «МС СУ №6» и точка внутри «г.Ростова-на-Дону»."""
    assert взыскание(analyzer, БЕЗ_НОМЕРА).get("priorCourtName") == \
        "МС СУ №6 Советского района г.Ростова-на-Дону"


def test_акт_без_номера_даёт_сумму(analyzer):
    assert взыскание(analyzer, БЕЗ_НОМЕРА).get("priorAmount") == "96 525,00"


def test_дата_уступки_не_становится_датой_акта(analyzer):
    """Ближайшая слева дата — это дата договора УСТУПКИ, а не акта.

    Пустое поле честнее чужой даты: блок дат юрист заполняет сам.
    """
    assert "priorDecisionDate" not in взыскание(analyzer, БЕЗ_НОМЕРА)


# --- ворота: чужие акты по-прежнему отсекаются ----------------------------------

def test_банкротное_дело_не_считается_прежним_взысканием(analyzer):
    текст = (
        "Решением Арбитражного суда Ростовской области по делу № А53-43675/2025 "
        "должник признан банкротом, введена процедура реализации имущества.\n"
    )
    assert взыскание(analyzer, текст) == {}


def test_без_взыскания_акт_не_берётся(analyzer):
    """Акт есть, признака взыскания нет — не наш случай."""
    текст = (
        "Определением суда № 2-15/2025 утверждено мировое соглашение "
        "между сторонами по вопросу порядка пользования имуществом.\n"
    )
    assert взыскание(analyzer, текст) == {}


def test_проза_с_глаголом_вынес_без_суда_не_берётся(analyzer):
    """Глагол «вынес» не должен утащить в поле любую прозу."""
    текст = (
        "Представитель кредитора вынес на обсуждение вопрос о взыскании "
        "задолженности в размере 50000 руб.\n"
    )
    assert "priorCourtName" not in взыскание(analyzer, текст)

# -*- coding: utf-8 -*-
"""Процедура и адрес кредитора: две одиночные протечки (08.09.2026).

1. ПРОЦЕДУРА. Ветка «должник — юрлицо» безусловно ставила `observation`.
   Это ДОГАДКА по типу лица, а текст называет процедуру прямо: «признан
   несостоятельным (банкротом), в отношении него введена процедура реализации
   имущества гражданина». Разбор это распознавал верно, а догадка затирала
   результат — потому что в тот момент должник ошибочно считался юрлицом:
   в `debtorName` стоял мусор «ФИНАНСОВЫЙ» (колонка шапки «ФИНАНСОВЫЙ
   УПРАВЛЯЮЩИЙ:»), а `legalShortName` держал его же.

   Порядок тут не поправить переносом: имя чинится по КАРТОЧКЕ должника, а она
   собирается позже определения типа. Поэтому правило простое: явно названная
   процедура сильнее догадки.

2. АДРЕС КРЕДИТОРА. В шапке «метки стопкой» имя кредитора и его адрес стоят
   в одной строке через табуляцию:

       Заявитель: АО ПКО «ЦДУ»\t117420, г. Москва, ул. Намёткина, д. 15,
       этаж 1, помещение I, ком. 01-\t06 \tДата гос. регистрации: 11.11.2008

   Такую строку разбор не читал и подставлял кредитору адрес ДОЛЖНИКА.
   Совпадение адресов — верный признак протечки: у банка и у гражданина адрес
   один и тот же не бывает. Замер по корпусу: таких документов ноль.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- процедура ---------------------------------------------------------------

def test_текст_называет_реализацию(analyzer):
    текст = ("Должник признан несостоятельным (банкротом), в отношении него "
             "введена процедура реализации имущества гражданина.")
    assert analyzer.determine_procedure_type(текст)[0] == "realization"


def test_наблюдение_остаётся_догадкой_для_юрлица(analyzer):
    """Когда текст процедуру не назвал, догадка по типу лица уместна."""
    поля = {"debtorName": "ООО «Перспектива»", "applicantName": "ООО «Перспектива»"}
    analyzer._finalize_debtor_type(поля, "Должник: ООО «Перспектива»", "ООО «Перспектива»")
    assert поля.get("entityType") == "legal", "предпосылка теста"
    assert поля.get("procedureType") == "observation"


def test_догадка_не_затирает_названную_процедуру(analyzer):
    """Главное правило: явное сильнее предположения."""
    поля = {"debtorName": "ООО «Перспектива»", "applicantName": "ООО «Перспектива»",
            "procedureType": "realization",
            "procedureTypeRaw": "реализации имущества гражданина"}
    analyzer._finalize_debtor_type(поля, "Должник: ООО «Перспектива»", "ООО «Перспектива»")
    assert поля["procedureType"] == "realization"


# --- адрес кредитора ---------------------------------------------------------

ШАПКА = (
    "Заявитель: АО ПКО «ЦДУ»\t117420, г. Москва, ул. Намёткина, д. 15, "
    "этаж 1, помещение I, ком. 01-\t06 \tДата гос. регистрации: 11.11.2008 \n"
    "\tКуда: Арбитражный суд Ростовской области\n"
)

АДРЕС_ДОЛЖНИКА = ("354024, Краснодарский край, г Сочи, р-н Хостинский, "
                  "пр-кт Курортный, д 96Г, кв 70")


def test_адрес_кредитора_берётся_из_строки_заявителя(analyzer):
    поля = {"creditorAddress": АДРЕС_ДОЛЖНИКА, "applicantAddress": АДРЕС_ДОЛЖНИКА}
    analyzer._fix_creditor_address_leak(поля, ШАПКА)
    assert поля["creditorAddress"] == ("117420, г. Москва, ул. Намёткина, д. 15, "
                                       "этаж 1, помещение I, ком. 01-06")


def test_подпись_следующего_поля_не_едет_в_адрес(analyzer):
    """«Дата гос. регистрации» — сокращённая форма, её пришлось внести в реестр меток."""
    поля = {"creditorAddress": АДРЕС_ДОЛЖНИКА, "applicantAddress": АДРЕС_ДОЛЖНИКА}
    analyzer._fix_creditor_address_leak(поля, ШАПКА)
    assert "регистрац" not in поля["creditorAddress"]
    assert "11.11.2008" not in поля["creditorAddress"]


def test_перенос_внутри_номера_помещения_склеивается(analyzer):
    """«ком. 01-\\t06» — след вёрстки, а не два разных номера."""
    поля = {"creditorAddress": АДРЕС_ДОЛЖНИКА, "applicantAddress": АДРЕС_ДОЛЖНИКА}
    analyzer._fix_creditor_address_leak(поля, ШАПКА)
    assert поля["creditorAddress"].endswith("ком. 01-06")


def test_разные_адреса_не_трогаются(analyzer):
    """Правило срабатывает ТОЛЬКО на совпадении — иначе чинить нечего."""
    поля = {"creditorAddress": "344082, г Ростов-на-Дону, ул Станиславского, д 10",
            "applicantAddress": АДРЕС_ДОЛЖНИКА}
    analyzer._fix_creditor_address_leak(поля, ШАПКА)
    assert поля["creditorAddress"] == "344082, г Ростов-на-Дону, ул Станиславского, д 10"


def test_без_строки_заявителя_адрес_очищается(analyzer):
    """Пусто лучше чужого: адрес должника в поле кредитора уедет в акт."""
    поля = {"creditorAddress": АДРЕС_ДОЛЖНИКА, "applicantAddress": АДРЕС_ДОЛЖНИКА}
    analyzer._fix_creditor_address_leak(поля, "Должник: Андрей Виталий Семенович")
    assert not поля.get("creditorAddress")

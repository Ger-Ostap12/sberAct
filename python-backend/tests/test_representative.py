"""Представитель истца: разбор по метке и по блоку подписи (11.09.2026).

До этой правки представитель извлекался только в ипотечной ветке и только по
метке «Представитель истца:». В заявлениях о банкротстве такой метки почти не
бывает — 40 красных в эталоне.

Тексты в тестах — ДОСЛОВНЫЕ куски заявлений корпуса; в скобках указан документ.
Выдуманная вёрстка здесь бесполезна: вся сложность именно в том, как реальные
банки ломают строку.
"""
import os

def test_обрезанное_фамилия_имя_уступает_инициалам():
    """свежие-33: шапка обрезана до «Зайнуллина Диляра» — это не форма имени.

    Правило «бери из шапки» здесь дало бы обрезок. Две заглавные подряд как
    имя не распознаются вовсе: такой паттерн ловит пол-документа.
    """
    текст = ("Адрес юридический: 121096, Москва г, ул. Василисы Кожиной\n"
             "Представитель взыскателя по доверенности: \nЗайнуллина Диляра\n"
             "Электронная почта:\nДолжник: \nБуниатян Алина\n"
             "9. Доказательства отправки требования.\n"
             "Представитель кредитора по доверенности \t Зайнуллина Д.Р.")
    assert extract_representative(текст) == "Зайнуллина Д.Р."


def test_чужая_подпись_в_приложенном_письме_банка_не_побеждает():
    """корпус-1 — ЛОВУШКА ИПОТЕКИ.

    В конце ипотечного заявления подшито письмо банка должнику со своей
    подписью («Резулов И.А.»). Представитель истца — из шапки. Разводит их
    полнота записи, без единого условия по типу документа.
    """
    текст = ("Представитель истца:\nСтавропольское отделение №2554\n"
             "Чепелов Иван Александрович\nСНИЛС 131-761-878 61\n"
             "заёмщик ЁЛКИН ДЕНИС АЛЕКСАНДРОВИЧ\n"
             "Представитель ПАО Сбербанк\nпо доверенности\nРезулов И.А.\n"
             "Уважаемый клиент! ")
    assert extract_representative(текст) == "Чепелов Иван Александрович"



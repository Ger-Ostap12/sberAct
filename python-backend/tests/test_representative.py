# --- блок подписи ------------------------------------------------------------

def test_подпись_организация_и_доверенность_между_меткой_и_именем():
    """корпус-32: между «Представитель» и ФИО стоят название банка и доверенность."""
    текст = ("49. Копия доверенности представителя ПАО Сбербанк.\n"
             "Представитель ПАО Сбербанк\nпо доверенности\tЮсупова Е.О.\n9")
    assert extract_representative(текст) == "Юсупова Е.О."


def test_номер_доверенности_с_буквами_не_путается_с_именем():
    """корпус-14: «№ПБ/515-Д от 03.10.2023» стоит ровно перед ФИО."""
    текст = ("Представитель ПАО Сбербанк \n"
             "по доверенности №ПБ/515-Д от 03.10.2023  Карпенко Е.А\n"
             "Банк получателя\nЮго-Западный банк ПАО Сбербанк")
    assert extract_representative(текст) == "Карпенко Е.А"


def test_точка_после_последнего_инициала_не_дописывается():
    """«Карпенко Е.А» — так в документе; в акт уходит ровно это."""
    текст = "Представитель ПАО Сбербанк\nпо доверенности  Карпенко Е.А\nБанк получателя"
    assert extract_representative(текст) == "Карпенко Е.А"



def test_исполнитель_строкой_выше_не_перебивает_подпись():
    """корпус-64 — ГЛАВНАЯ ЛОВУШКА взгляда назад.

    «Исполнитель: Евгения Вячеславовна Моисеева» стоит ровно над подписью
    представителя и по форме записи ПОЛНЕЕ верного «М.П. Куницкая». Назад
    смотрим только тогда, когда вперёд пусто, — здесь вперёд не пусто.
    """
    текст = ("Исполнитель: \nЕвгения Вячеславовна Моисеева\n"
             "Представитель ООО «ПКО Воксис»\tМ.П. Куницкая\n"
             "Исполнитель:\nЕвгения Вячеславовна Моисеева\nИНН:\n6670056296")
    assert extract_representative(текст) == "М.П. Куницкая"



"""Назначение роли найденному значению (§S.2.C, шаг C2).

Здесь живёт главный риск всего value-first подхода: **ИНН кредитора уезжает
должнику**. Сканер отвечает «это ИНН», и без правильной роли поле заполняется
чужим значением — молча и правдоподобно.

Поэтому проверки построены вокруг воздержания. Слой обязан молчать, когда:
  * слева нет якоря роли;
  * якорь слишком далеко (между блоками сторон лежит мотивировка);
  * к значению ближе якорь ДРУГОЙ роли.

Пустое поле видно и чинится. Поле с чужим ИНН не видно никому.
"""
import os
import sys

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from role_assignment import (  # noqa: E402
    MAX_ANCHOR_DISTANCE,
    assign_all,
    assign_role,
    best_by_role,
    role_field_name,
)
from value_scanners import scan_inn, valid_only  # noqa: E402


def _one(text):
    """Единственный валидный ИНН текста — так проверки читаются как условие."""
    found = valid_only(scan_inn(text))
    assert len(found) == 1, f"ожидался один ИНН, найдено {len(found)}"
    return found[0]


# --- Назначение роли -----------------------------------------------------------

def test_инн_после_метки_должника_достаётся_должнику():
    text = "Должник: Иванов Иван Иванович, ИНН 612504512780"
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "debtor"


def test_инн_после_метки_кредитора_достаётся_кредитору():
    text = "Кредитор: ПАО Сбербанк, ИНН 7707083893"
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "creditor"


def test_ближайший_якорь_перебивает_более_ранний():
    """Ровно тот случай, ради которого слой теневой.

    Блок должника идёт первым, блок кредитора вторым. Без правила «ближайший
    слева» ИНН банка достался бы должнику — и поле выглядело бы заполненным.
    """
    text = ("Должник: Иванов Иван Иванович. "
            "Кредитор: ПАО Сбербанк, ИНН 7707083893")
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "creditor"


def test_управляющий_отличается_от_должника():
    text = "Финансовый управляющий Теплов Алексей Сергеевич, ИНН 582704406654"
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "manager"


# --- Ограничения формы по роли ---------------------------------------------------
#
# Найдено теневым отчётом на корпусе, а не придумано.

def test_инн_сро_не_достаётся_управляющему():
    """Управляющий — ФИЗЛИЦО, его ИНН всегда 12 знаков (§S.8).

    Рядом со словом «управляющий» стоит и десятизначный ИНН — но он принадлежит
    саморегулируемой организации. Отчёт показал ровно это: по якорю «арбитражных
    управляющих» слой брал 6167065084 (СРО) вместо ИНН человека.
    """
    text = ("из числа членов Ассоциации арбитражных управляющих "
            "«Гарант», ИНН 6167065084")
    found = valid_only(scan_inn(text))
    assert found, "предпосылка: десятизначный ИНН валиден"
    assert assign_role(text, found[0]) is None


def test_двенадцатизначный_инн_управляющему_достаётся():
    """Обратная сторона того же правила — иначе поле молчало бы всегда."""
    text = "арбитражным управляющим утвердить Теплова А.С., ИНН 582704406654"
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "manager"


def test_имя_организации_перекрывает_якорь_и_даёт_воздержание():
    """«Банк» — часть НАЗВАНИЯ, а не подпись роли. Прошли три варианта:

    1. «Банк» КАК ЯКОРЬ КРЕДИТОРА — на заявлениях «Форте» слой брал ИНН «ББР
       Банк» (банка из ЧУЖОГО дела в мотивировке) вместо заявителя АО «ТБАНК»;
    2. «Банк» УБРАН СОВСЕМ — стало ХУЖЕ: ИНН банков провалились к следующему
       якорю слева и достались должнику. Расхождений по `inn` 6 → 10;
    3. «Банк» КАК ЗАПРЕТ — роли не даёт, но перекрывает чужой якорь.

    Оба первых варианта отвергнуты прогоном по корпусу, а не рассуждением.
    """
    text = "по заявлению Акционерного общества «ББР Банк» ИНН 3900001002"
    assert assign_role(text, _one(text)) is None


def test_запрет_не_срабатывает_внутри_названия():
    """«Сбербанк» не содержит слова «Банк» как отдельного слова.

    Без левой границы `\\b` запрет ловил бы «банк» внутри «Сбербанк» и гасил
    роль там, где она определена верно — на этом сразу покраснели три теста.
    """
    text = "Кредитор: ПАО Сбербанк, ИНН 7707083893"
    got = assign_role(text, _one(text))
    assert got is not None and got.role == "creditor"


def test_ближайший_запрет_важнее_дальнего_якоря():
    """Якорь роли левее, имя организации правее — воздержание."""
    text = ("Должник: Иванов Иван Иванович. Требование предъявлено "
            "Акционерным обществом «ББР Банк» ИНН 3900001002")
    assert assign_role(text, _one(text)) is None


# --- Воздержание ---------------------------------------------------------------

def test_без_якоря_слева_воздерживаемся():
    """Без роли значение бесполезно: заполнять им поле наугад нельзя."""
    text = "ИНН 7707083893 указан в приложении"
    assert assign_role(text, _one(text)) is None


def test_далёкий_якорь_не_назначает_роль():
    """Между блоками сторон лежит мотивировка — «ближайший слева» без потолка
    притянул бы роль через полстраницы.

    Тот же дефект без верхней границы дал разлёт на 13 053 символа в определении
    залога (§S.3.1).
    """
    text = ("Должник: Иванов Иван Иванович. "
            + "Текст мотивировочной части заявления. " * 20
            + "ИНН 7707083893")
    assert len(text) > MAX_ANCHOR_DISTANCE
    assert assign_role(text, _one(text)) is None


def test_роль_можно_ограничить_списком():
    """Когда роль известна заранее, чужие якоря не должны мешать."""
    text = "Кредитор: ПАО Сбербанк, ИНН 7707083893"
    assert assign_role(text, _one(text), roles=["debtor"]) is None


# --- Выбор лучшего ---------------------------------------------------------------

def test_на_роль_берётся_ближайшее_к_якорю_значение():
    """«Первый ИНН после слова Должник» — он и есть; «первый в документе» — чужой.

    Оба ИНН здесь ОБЯЗАНЫ быть валидными, иначе выбор делает не этот слой, а
    контрольная сумма, и проверка становится холостой — первая версия так и
    зеленела на заведомо битом втором номере.
    """
    text = ("Должник: Иванов Иван Иванович, ИНН 612504512780, "
            "ранее указывался ИНН 616504512724")
    assert len(valid_only(scan_inn(text))) == 2, "предпосылка: оба ИНН валидны"
    best = best_by_role(assign_all(text, valid_only(scan_inn(text))))
    assert best[("debtor", "inn")].found.value == "612504512780"


def test_разные_роли_не_смешиваются():
    text = ("Должник: Иванов Иван Иванович, ИНН 612504512780. "
            "Кредитор: ПАО Сбербанк, ИНН 7707083893")
    best = best_by_role(assign_all(text, valid_only(scan_inn(text))))
    assert best[("debtor", "inn")].found.value == "612504512780"
    assert best[("creditor", "inn")].found.value == "7707083893"



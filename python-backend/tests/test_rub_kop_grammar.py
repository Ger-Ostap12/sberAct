@pytest.fixture(scope="module")
def центр(analyzer):
    return просьба(analyzer, ЦЕНТР_ИНВЕСТ)


def test_итог_из_просьбы_а_не_лимит_линии(центр):
    """2 800 000,00 — это лимит выдачи, а не долг."""
    assert центр.get("totalDebt") == "1 670 258,05"


def test_копейки_отдельным_словом_не_теряются(центр):
    """1 615 241,33 + 55 011,90 + 4,82 = 1 670 258,05."""
    assert центр.get("principalDebt") == "1 615 241,33"
    assert центр.get("interest") == "55 011,90"
    assert центр.get("forfeit") == "4,82"


def test_уплата_кредита_это_основной_долг(analyzer):
    """«задолженность по уплате КРЕДИТА» — тело долга без слова «основной»."""
    текст = (
        "ПРОСИТ СУД:\n"
        "Включить в реестр требований кредиторов денежные требования на сумму "
        "1 100 руб. 00 коп., из которых:\n"
        "- задолженность по уплате кредита в размере 1 000 руб. 00 коп.;\n"
        "- задолженность по уплате процентов за пользование кредитом в размере "
        "100 руб. 00 коп.\n"
    )
    assert просьба(analyzer, текст).get("principalDebt") == "1 000,00"


def test_проценты_за_пользование_кредитом_не_уходят_в_осн_долг(analyzer):
    """Подпись содержит и «процент», и «кредит» — решает ПОРЯДОК проверок."""
    текст = (
        "ПРОСИТ СУД:\n"
        "Включить требования на сумму 1 100 руб. 00 коп., из которых:\n"
        "- задолженность по уплате кредита в размере 1 000 руб. 00 коп.;\n"
        "- задолженность по уплате процентов за пользование кредитом в размере "
        "100 руб. 00 коп.\n"
    )
    assert просьба(analyzer, текст).get("interest") == "100,00"


def test_пени_по_просроченному_кредиту_не_уходят_в_осн_долг(центр):
    """Подпись содержит «просроченному кредиту» — но «пени» решает раньше."""
    assert центр.get("forfeit") == "4,82"
    assert центр.get("principalDebt") != "4,82"


# --- сама нормализация: что она трогает и что НЕТ ---------------------------------

def test_нормализация_склеивает_рубли_с_копейками():
    сжать = lambda s: AmountsMixin._РУБ_КОП.sub(r"\1,\2 руб.", s)  # noqa: E731
    assert сжать("1 615 241 руб. 33 коп.") == "1 615 241,33 руб."
    assert сжать("2 800 000 рублей 00 копеек") == "2 800 000,00 руб."


def test_нормализация_оставляет_слово_руб():
    """`amt_re` ищет сумму ТОЛЬКО перед «руб» — без него суммы прячутся.

    Первая редакция правки убирала «руб.» из результата, и слой перестал
    видеть суммы вообще: красное не закрывалось, а разбор стал хуже.
    """
    assert "руб" in AmountsMixin._РУБ_КОП.sub(r"\1,\2 руб.", "5 руб. 10 коп.")


def test_сумма_без_копеек_не_тронута():
    """«Госпошлина: 37 554 руб.» — копеек нет, менять нечего."""
    s = "Госпошлина: 37 554 руб."
    assert AmountsMixin._РУБ_КОП.sub(r"\1,\2 руб.", s) == s


def test_не_склеивает_чужое_число_без_слова_коп():
    s = "задолженность 500 руб. 20 договоров"
    assert AmountsMixin._РУБ_КОП.sub(r"\1,\2 руб.", s) == s


# --- ворота: обычная грамматика «N,MM руб.» работает как раньше -------------------

def test_обычная_грамматика_не_задета(analyzer):
    текст = (
        "ПРОШУ:\n"
        "Включить требование в реестр требований кредиторов должника "
        "в размере 100 000,00 рублей, в том числе: 90 000,00 рублей - "
        "основной долг, 10 000,00 рублей - проценты.\n"
    )
    п = просьба(analyzer, текст)
    assert п.get("totalDebt") == "100 000,00"
    assert п.get("principalDebt") == "90 000,00"

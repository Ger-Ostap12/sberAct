# -*- coding: utf-8 -*-
"""Договоры с ОДИНАКОВЫМ подытогом и пошлина требования, 11.10.2026.

Два дефекта на одном документе (свежие-27, Заявление о включении_Часть9.docx):

```
А. ДЕДУП ПО СУММЕ ронял РАЗНЫЙ договор. Защита от повторного чтения одного
   блока шла по ключу round(подытог, 2), а у документа три договора, и у
   первого с третьим совпали И подытог, И вся разбивка:
      № 21030267-1  22 861,25 = 15 000 + 7 424,88 + 436,37
      № 21030267-3   6 097,74 =  3 945 + 1 952,74 + 200
      № 21030267-2  22 861,25 = 15 000 + 7 424,88 + 436,37
   правда 51 820,24, программа давала 28 958,99 — третий договор терялся
   целиком. Отличает блоки только НОМЕР ДОГОВОРА, он и вошёл в ключ.

Б. ПОШЛИНА ТРЕБОВАНИЯ попадала в БАНКРОТНУЮ графу [16]. Пошлина названа
   внутри разбивки («…проценты - 7424,88 руб., госпошлина - 436,37 руб.»),
   значит это ссудная ГП [17]. Словесной метки «за подачу заявления» в такой
   строке нет, поэтому семантический разбор госпошлины её не снимал, и юрист
   видел 436,37 в графе банкротной пошлины — которой документ не называет
   ВООБЩЕ (все шесть упоминаний пошлины стоят внутри требований).
```

Замер радиуса по 98 документам: каждая правка меняет РОВНО ОДИН документ
(дедуп — 6 полей, пошлина — 1 поле).
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def просьба(analyzer, текст):
    поля = {}
    analyzer._apply_prayer_finances(поля, текст)
    return поля


def _пункт(номер, подытог, осн, проц, гп):
    """Пункт просьбы в точности той формы, что у свежие-27."""
    return ("Включить в третью очередь реестра требований кредиторов "
            "Рытченко Ларисы Васильевны требование ООО «СФО Стандарт» "
            "по договору № %s в размере   %s руб. (прописью), "
            "из которых основной долг - %s руб., проценты - %s руб., "
            "госпошлина - %s руб.\n" % (номер, подытог, осн, проц, гп))


# Третий договор дословно повторяет первый по числам — и по подытогу, и по всей
# разбивке. Это и есть условие, на котором дедуп по сумме ронял живой договор.
ТРИ_ДОГОВОРА = (
    "ПРОСИТ СУД:\n"
    + _пункт("21030267-1", "22861,25", "15000", "7424,88", "436,37")
    + _пункт("21030267-3", "6097,74", "3945", "1952,74", "200")
    + _пункт("21030267-2", "22861,25", "15000", "7424,88", "436,37")
)


def test_tretij_dogovor_ne_teryaetsya(analyzer):
    """Дефект А: складываются ВСЕ ТРИ договора, а не два."""
    поля = просьба(analyzer, ТРИ_ДОГОВОРА)
    assert поля.get("totalDebt") == "51 820,24", (
        "потерян договор с совпавшим подытогом: %r" % поля.get("totalDebt"))


@pytest.mark.parametrize(("поле", "ждём"), [
    ("principalDebt", "33 945,00"),   # 15 000 + 3 945 + 15 000
    ("interest", "16 802,50"),        # 7 424,88 + 1 952,74 + 7 424,88
    ("loanStateDuty17", "1 072,74"),  # 436,37 + 200 + 436,37
])
def test_razbivka_skladyvaetsya_po_vsem_trem(analyzer, поле, ждём):
    """Дефект А по каждой графе отдельно: теряется не только итог."""
    assert просьба(analyzer, ТРИ_ДОГОВОРА).get(поле) == ждём


def test_poshlina_trebovaniya_ne_idet_v_bankrotnuyu_grafu(analyzer):
    """Дефект Б: пошлина из разбивки требования не банкротная.

    Стартуем с уже заполненной [16] — так и приходит документ: общий паттерн
    «госпошлина - N руб.» срабатывает раньше слоя просьбы.
    """
    поля = {"stateDuty16": "436,37", "stateDuty": "436,37"}
    analyzer._apply_prayer_finances(поля, ТРИ_ДОГОВОРА)
    assert not поля.get("stateDuty"), (
        "пошлина требования осталась в банкротной графе: %r" % поля.get("stateDuty"))
    assert not поля.get("stateDuty16")
    # и при этом она ЦЕЛИКОМ лежит в ссудной
    assert поля.get("loanStateDuty17") == "1 072,74"


def test_chuzhaya_poshlina_v_grafe_16_ostaetsya(analyzer):
    """Цена правки: снимаем ТОЛЬКО слагаемое ссудной ГП, а не любую пошлину.

    Если в [16] лежит сумма, которой среди слагаемых требования НЕТ, — это
    чужая (например, настоящая банкротная) пошлина, и её трогать нельзя.
    """
    поля = {"stateDuty16": "10 000,00", "stateDuty": "10 000,00"}
    analyzer._apply_prayer_finances(поля, ТРИ_ДОГОВОРА)
    assert поля.get("stateDuty") == "10 000,00"
    assert поля.get("stateDuty16") == "10 000,00"


def test_odin_blok_dvazhdy_vse_eshche_ne_dvoitsya(analyzer):
    """Цена правки: прежняя защита обязана работать.

    Один и тот же блок, прочитанный дважды (тот же номер, тот же подытог),
    по-прежнему считается ОДИН раз — иначе правка дедупа вернула бы
    двойной счёт, от которого он и ставился.
    """
    один = _пункт("21030267-1", "22861,25", "15000", "7424,88", "436,37")
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + один + один)
    assert поля.get("totalDebt") == "22 861,25", (
        "блок посчитан дважды: %r" % поля.get("totalDebt"))


def test_bez_nomera_dogovora_povedenie_prezhnee(analyzer):
    """Ворота, а не запрет: когда номера нет, ключ прежний — одна сумма.

    Два блока с равным подытогом и без номеров неразличимы, значит второй
    по-прежнему отбрасывается. Это сознательно сохранённое поведение.
    """
    безномера = ("Включить в третью очередь реестра требований кредиторов "
                 "требование в размере   22861,25 руб. (прописью), "
                 "из которых основной долг - 15000 руб., "
                 "проценты - 7424,88 руб., госпошлина - 436,37 руб.\n")
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + безномера + безномера)
    assert поля.get("totalDebt") == "22 861,25"

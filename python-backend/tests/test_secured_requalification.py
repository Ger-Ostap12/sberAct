# -*- coding: utf-8 -*-
"""Залоговая переквалификация не прибавляется к требованию, 11.10.2026.

Найдено СПЛОШНОЙ РУЧНОЙ СВЕРКОЙ финансов (не эталоном — эталон хранил
завышенное число как «правду»). корпус-32 «Заявление о признании должника
банкротом Песня 9л.docx»:

```
документ называет итог ТРИЖДЫ:
   шапка        «Сумма требований: 2 100 477,62 руб.»
   тело         «в общем размере 2 100 477,62 руб.»
   п.3 просьбы  «включить … в размере 2 100 477,62 руб., из которых:
                 2 067 174,49 осн. долг, 33 302,82 проценты, 0,31 неустойка»
п.4 просьбы    «Установить … в размере 1 249 122,53 руб. из которых:
                 1 241 195,88 осн. долг, 7 926,65 проценты, КАК ТРЕБОВАНИЯ,
                 ОБЕСПЕЧЕННЫЕ ЗАЛОГОМ имущества Должника»
программа давала 3 349 600,15 — первое обязательство считалось ДВАЖДЫ
```

Залоговый пункт переквалифицирует ЧАСТЬ уже заявленного требования, а не
добавляет второе. Числа 3 349 600,15 в документе нет вообще.

⚠️ Почему дефект жил на ОДНОМ документе из трёх с таким пунктом: у
корпус-18 и корпус-38 он записан БЕЗ разбивки («в размере X, вытекающих из
кредитного договора №…, как требования, обеспеченные залогом»), и
верб-регулярка такой блок не находит — ей нужен якорь «из которых/в том
числе». Радиус правки: 1 документ, 5 полей.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def просьба(analyzer, текст):
    поля = {}
    analyzer._apply_prayer_finances(поля, текст)
    return поля


СОВОКУПНЫЙ = (
    "3. Признать обоснованными и включить требования ПАО Сбербанк в третью "
    "очередь реестра требований кредиторов Песня Сергея Николаевича в размере "
    "2 100 477,62 руб. рублей, из которых: - 2 067 174,49 руб. – просроченный "
    "основной долг - 33 302,82 руб. – задолженность по процентам - 0,31 руб. "
    "- неустойка\n")
ЗАЛОГОВЫЙ = (
    "4. Установить требования ПАО Сбербанк в реестре требований кредиторов "
    "Песня Сергея Николаевича в размере 1 249 122,53 руб. из которых: "
    "- 1 241 195,88 руб. – просроченный основной долг, - 7 926,65 руб. – "
    "задолженность по процентам, как требования, обеспеченные залогом"
    "имущества Должника, а именно: объект недвижимости\n")


def test_zalogovyj_punkt_ne_pribavlyaetsya(analyzer):
    """Итог — только совокупное требование, залоговый пункт не слагаемое."""
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + СОВОКУПНЫЙ + ЗАЛОГОВЫЙ)
    assert поля.get("totalDebt") == "2 100 477,62", (
        "залоговая переквалификация посчитана вторым требованием: %r"
        % поля.get("totalDebt"))


@pytest.mark.parametrize(("поле", "ждём"), [
    ("principalDebt", "2 067 174,49"),
    ("interest", "33 302,82"),
    ("forfeit", "0,31"),
])
def test_razbivka_tolko_iz_sovokupnogo(analyzer, поле, ждём):
    """Разбивка тоже не должна удваиваться по графам."""
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + СОВОКУПНЫЙ + ЗАЛОГОВЫЙ)
    assert поля.get(поле) == ждём


def test_zalogovyj_punkt_edinstvennyj_schitaetsya(analyzer):
    """Цена правки — ВОРОТА, А НЕ ЗАПРЕТ.

    Если залоговый пункт в просьбе единственный, он и есть источник суммы:
    запрещать его нельзя, иначе документ останется без финансов.
    """
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + ЗАЛОГОВЫЙ)
    assert поля.get("totalDebt") == "1 249 122,53", поля.get("totalDebt")


def test_vtoroj_dogovor_bez_zaloga_vse_eshche_skladyvaetsya(analyzer):
    """Цена правки: правило «больше одного договора — складываем» живо.

    Ворота обязаны ловить ТОЛЬКО залоговую переквалификацию, а не любой
    второй пункт просьбы (иначе ломается §S.51).
    """
    второй = ("4. Включить требования ПАО Сбербанк в третью очередь реестра "
              "требований кредиторов по кредитному договору № 1271058 в "
              "размере 1 000,00 руб., из которых: - 900,00 руб. – "
              "просроченный основной долг - 100,00 руб. – проценты\n")
    поля = просьба(analyzer, "ПРОСИТ СУД:\n" + СОВОКУПНЫЙ + второй)
    assert поля.get("totalDebt") == "2 101 477,62", поля.get("totalDebt")

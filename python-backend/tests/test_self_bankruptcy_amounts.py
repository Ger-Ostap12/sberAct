"""Суммы и номер дела в заявлениях, где банк не является заявителем.

Дефекты, найденные 05.08 на реальных заявлениях («заявления CB»):

1. **Чужое значение в поле.** В общем цикле извлечения `cleaned_value` жил
   ДОЛЬШЕ одной итерации: пустой захват («требования:» без числа) не проходил
   фильтр длины, а присваивание в конце тела цикла всё равно отрабатывало — и
   поле получало значение ПРЕДЫДУЩЕГО поля. В requirementsSum так уезжал номер
   дела «А47-7950/2011», а нормализатор сумм, выбрасывающий любые не-цифры,
   печатал его в акте как «4 779 502 011,00 руб.».

2. **Захват через переводы строк.** Класс `[0-9\\s,]+` тянется через `\\n` и
   склеивает соседние ячейки таблицы в одно «число».

3. **Итог самобанкрота.** У заявления гражданина о собственном банкротстве нет
   ни таблицы расчёта, ни просительной с разбивкой: долг перечислен по
   кредиторам, а целое названо один раз («общий объём задолженности
   составляет 824 831,33 рублей»). В итог попадала сумма первого кредитора.

4. **Номер дела мирового участка.** «по делу № 2-7-3490/2025» — ссылка на
   судебный приказ в теле заявления. Спасательная регулярка отрезала ему голову
   и выдавала правдоподобный, но чужой номер «7-3490/2025».
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# Шапка самобанкрота: должник первым, затем кредиторы (без кредитора-заявителя).
SELF_HEADER = """В Арбитражный суд Ростовской области
344002, Ростов-на-Дону, ул. Станиславского, 8а
Должник: Толпыгин Владимир Алексеевич
12.10.1981 года рождения, место рождения хутор Вишневка
СНИЛС: 05274297468, ИНН: 611502169083
Адрес регистрации: обл. Ростовская, р-н. Кашарский, х. Талловеров, ул. Украдыженко, д 75
Кредитор 1. ПАО Сбербанк
ИНН 7707083893, ОГРН 1027700132195
ЗАЯВЛЕНИЕ о признании гражданина несостоятельным (банкротом)
"""


def _self_text(body: str) -> str:
    return SELF_HEADER + body


# --- 1. Денежный токен ------------------------------------------------------

@pytest.mark.parametrize(
    "raw, expected",
    [
        ("180 532,78", "180 532,78"),
        (" 7 013 ", "7 013"),
        ("0,00", "0,00"),
        ("1371499,37", "1371499,37"),
        # Склейка соседних ячеек — берём только первое число.
        ("221 487,12 446 340,73", "221 487,12"),
        # Захват через перевод строки — всё после \n отбрасываем.
        ("221 487,12\n446 340,73", "221 487,12"),
        # Не деньги вовсе.
        ("А47-7950/2011", ""),
        ("Арбитражный суд Ростовской области", ""),
        ("", ""),
        (None, ""),
    ],
)
def test_money_token_from_capture(analyzer, raw, expected):
    assert analyzer.money_token_from_capture(raw) == expected


def test_money_token_keeps_kopeyki_with_ruble_word(analyzer):
    assert analyzer.money_token_from_capture("824 831,33 рублей") == "824 831,33"


# --- 2. Номер дела не превращается в сумму ----------------------------------

def test_case_number_never_becomes_amount(analyzer):
    """Номер дела в шапке не должен попасть ни в одно денежное поле."""
    text = _self_text(
        "Дело № А47-7950/2011\n"
        "Требования:\n"
        "Таким образом, общий объем задолженности составляет 824 831,33 рублей.\n"
    )
    fields = analyzer.analyze_from_text(text)["fields"]
    assert fields.get("caseNumber") == "А47-7950/2011"
    for key in ("totalDebt", "debtAmount", "requirementsSum", "principalDebt", "loanDebt"):
        value = str(fields.get(key) or "")
        assert "4 779 502 011" not in value, f"{key} = {value}"


# --- 3. Итог самобанкрота ---------------------------------------------------

@pytest.mark.parametrize(
    "phrase, expected",
    [
        ("Таким образом, общий объем задолженности составляет 824 831,33 рублей.",
         "824 831,33"),
        ("Общая сумма задолженности перед кредиторами составляет 1 703 617,13 руб.",
         "1 703 617,13"),
        # Скан: копейки оторваны пробелом («24 395 516, 3 руб.»).
        ("По состоянию на дату подачи Заявления размер непогашенной задолженности "
         "Должника перед Кредиторами составляет 24 395 516, 3 руб.:",
         "24 395 516,30"),
    ],
)
def test_self_bankruptcy_total(analyzer, phrase, expected):
    fields = analyzer.analyze_from_text(_self_text(phrase))["fields"]
    assert fields.get("totalDebt") == expected
    assert fields.get("debtAmount") == expected


def test_self_bankruptcy_total_beats_per_creditor_rows(analyzer):
    """Сумма первого кредитора не должна вытеснять названное целое."""
    text = _self_text(
        "Содержание обязательства\n"
        "Кредитор ООО «ПКО «Феникс»\n"
        "В том числе основная задолженность221 487,12\n"
        "446 340,73\n"
        "157 003,48\n"
        "Таким образом, общий объем задолженности составляет 824 831,33 рублей.\n"
    )
    fields = analyzer.analyze_from_text(text)["fields"]
    assert fields.get("totalDebt") == "824 831,33"
    # Разбивка относилась к ОДНОМУ кредитору — в акт как «из них основного долга»
    # её печатать нельзя.
    assert not fields.get("principalDebt")
    assert not fields.get("loanDebt")


def test_per_contract_totals_do_not_win(analyzer):
    """«общая сумма задолженности ПО кредитному договору …» — не грандтотал."""
    text = _self_text(
        "По состоянию на дату подачи Заявления размер непогашенной задолженности "
        "Должника перед Кредиторами составляет 24 395 516, 3 руб.:\n"
        "- общая сумма задолженности по кредитному договору №0306975842 от "
        "04.07.2024 г. составляет 525 866,14 руб.\n"
        "- общая сумма задолженности по кредитному договору №0120276555 от "
        "31.10.2023 г. составляет 194 557,62 руб.\n"
    )
    fields = analyzer.analyze_from_text(text)["fields"]
    assert fields.get("totalDebt") == "24 395 516,30"


def test_creditor_application_total_untouched(analyzer):
    """Кредиторское заявление разбирается по-прежнему (правка на него не влияет)."""
    text = (
        "В Арбитражный суд Ростовской области\n"
        "Кредитор: ПАО Сбербанк\n"
        "Должник: БОЯЧУК ЕВГЕНИЙ СЕРГЕЕВИЧ\n"
        "Дело № А53-21258/2026\n"
        "По состоянию на 06.07.2026 образовалась задолженность в размере 180532,78 руб., из которых:\n"
        "- 144975,40 руб. – просроченный основной долг\n"
        "- 30816,05 руб. – просроченные проценты\n"
        "- 4741,33 руб. – неустойка\n"
        "Госпошлина: 7 013 руб.\n"
    )
    fields = analyzer.analyze_from_text(text)["fields"]
    assert fields.get("totalDebt") == "180 532,78"
    assert fields.get("principalDebt") == "144 975,40"
    assert fields.get("interest") == "30 816,05"


# --- 4. Номер дела мирового участка -----------------------------------------

def test_magistrate_case_number_is_dropped(analyzer):
    """«2-7-3490/2025» — судебный приказ, а не дело; в поле не попадает."""
    text = _self_text(
        "-№ 204754/26/61076-ИП от 04.05.2026 на основании Судебного приказа "
        "от 16.12.2025 по делу № 2-7-3490/2025, выданного судебным участком № 7 "
        "Таганрогского судебного района Ростовской области.\n"
        "Таким образом, общий объем задолженности составляет 824 831,33 рублей.\n"
    )
    fields = analyzer.analyze_from_text(text)["fields"]
    assert not fields.get("caseNumber"), fields.get("caseNumber")


def test_real_case_number_survives(analyzer):
    """Арбитражный номер дела по-прежнему извлекается."""
    text = _self_text("Дело № А53-21258/2026\n")
    assert analyzer.analyze_from_text(text)["fields"].get("caseNumber") == "А53-21258/2026"

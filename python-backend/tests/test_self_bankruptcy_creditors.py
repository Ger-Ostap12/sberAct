# --- ЧЕТЫРЕ РАСКЛАДКИ БЛОКА --------------------------------------------------

def test_нумерованный_список_с_реквизитами(разбор):
    """корпус-41: «Кредиторы:» + «1.» … , ОГРН/ИНН строкой, адрес строкой."""
    текст = (
        "Кредиторы:\n"
        "1.\tПАО \"Банк ПСБ\" \n"
        "ОГРН: 1027739019142 ИНН: 7744000912 \n"
        "150003, Ярославская область, г Ярославль, \n"
        "Республиканская ул, д. 16\n"
        "2.\tООО \"Озон Банк\" \n"
        "ОГРН: 1227700133792 ИНН: 9703077050 \n"
        "123112, город Москва, Пресненская наб, д. 10\n"
        "Третьи лица: \n"
        "Управление образования города Новочеркасска\n"
    )
    записи = извлечь(разбор, текст)
    assert [з["name"] for з in записи] == ['ПАО "Банк ПСБ"', 'ООО "Озон Банк"']
    assert записи[0]["inn"] == "7744000912"
    assert записи[0]["ogrn"] == "1027739019142"
    assert записи[0]["address"].startswith("150003, Ярославская область")



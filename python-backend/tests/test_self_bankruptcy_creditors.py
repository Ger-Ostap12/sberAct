def test_название_приклеено_к_хвосту_адреса(разбор):
    """корпус-43: «… офис 642 АО «Тбанк»» — новая запись внутри строки."""
    текст = (
        "Кредиторы: \n"
        "ООО ПКО «АСВ» \n"
        "195277, город Санкт-Петербург, пр-кт, д. 28 к. 2, офис 642 АО «Тбанк» \n"
        "127287, город Москва, 2-Я Хуторская ул., д. 38а стр. 26 \n"
    )
    записи = извлечь(разбор, текст)
    assert [з["name"] for з in записи] == ["ООО ПКО «АСВ»", "АО «Тбанк»"]
    assert записи[0]["address"].startswith("195277")
    assert записи[1]["address"].startswith("127287")



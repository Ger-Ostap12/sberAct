# -*- coding: utf-8 -*-
"""Итог долга в заявлении самобанкрота (фаза 5, пункт 1).

Семь документов из девяти отдавали в «Общая сумма долга» СОСЕДНЕЕ число:
доход должника, депозит на вознаграждение управляющего, прожиточный минимум,
сумму первого займа. Причина не в выборе числа, а в том, что сводная фраза
была описана всего двумя формами, и на остальных слой молчал — итог оставался
тем, что успел положить общий финансовый каскад.

Ключевая ловушка корпуса: в одном заявлении СЕМЬ строк «общая сумма
задолженности составляет N» — по строке на кредитора. Поэтому общее правило
требует маркер ЦЕЛОГО («перед кредиторами», «всех требований кредиторов»,
«моей задолженности», «по указанным выше основаниям»).
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "app"))

from amounts_mixin import AmountsMixin  # noqa: E402


@pytest.fixture(scope="module")
def счёт():
    """Голый носитель миксина — тот же путь, которым идёт анализатор."""
    class _Счёт(AmountsMixin):
        pass

    return _Счёт()


# --- СЕМЬ КРАСНЫХ ЭТАЛОНА ----------------------------------------------------

@pytest.mark.parametrize("фраза,итог", [
    # корпус-41: без пробелов в разрядах, оговорка «более»
    ("Таким образом, я имею суммарную задолженность перед кредиторами "
     "в размере более 545770,14 рублей.", 545770.14),
    # корпус-42: разряды пробелами
    ("имею суммарную задолженность перед кредиторами в размере более "
     "438 983,73 рублей.", 438983.73),
    # корпус-43: «моей задолженности», прозаический хвост до связки
    ("Общий размер моей задолженности на текущую дату составляет "
     "808 803,58 рублей.", 808803.58),
    # корпус-45: пропись МЕЖДУ рублями и копейками + съехавший разряд «2126 507»
    ("сумма задолженности Должника перед Кредиторами составляет "
     "2126 507 (Два миллиона сто двадцать шесть тысяч пятьсот семь) руб. 25 коп.",
     2126507.25),
    # корпус-46: точка вместо запятой, проза МЕЖДУ связкой и числом
    ("общий размер задолженности по неисполненным кредитным обязательствам "
     "составил на момент подачи Заявления 859764.45 руб.", 859764.45),
    # корпус-47: «не менее» + пропись + «копеек» словом
    ("примерная сумма задолженности по указанным выше основаниям составляет "
     "не менее 1 096 979 (один миллион девяноста шесть тысяч девятьсот "
     "семьдесят девять) рублей 68 копеек.", 1096979.68),
    # корпус-48: «всех требований кредиторов», точка вместо запятой
    ("Общий размер всех требований кредиторов по состоянию на дату подачи "
     "заявления составляет 394270.65 руб.", 394270.65),
])
def test_итог_из_сводной_фразы(счёт, фраза, итог):
    assert счёт._sb_total_from_text(фраза) == pytest.approx(итог, abs=0.005)


# --- ПРЕЖНИЕ ТОЧНЫЕ ФОРМЫ НЕ СЛОМАНЫ -----------------------------------------

@pytest.mark.parametrize("фраза,итог", [
    ("общий объём задолженности составляет 824 831,33 рублей", 824831.33),
    ("размер непогашенной задолженности перед кредиторами составляет "
     "279 733,06 руб.", 279733.06),
    # копейки, оторванные пробелом — так печатает конвертер скана
    ("общий объем задолженности составляет 24 395 516, 3 руб.", 24395516.3),
])
def test_прежние_формы_работают(счёт, фраза, итог):
    assert счёт._sb_total_from_text(фраза) == pytest.approx(итог, abs=0.005)


# --- ГЛАВНЫЙ ГАРД: СТРОКА ОДНОГО КРЕДИТОРА НЕ ЕСТЬ ИТОГ ----------------------

def test_построчный_итог_кредитора_не_берётся(счёт):
    """«общая сумма задолженности составляет N» без маркера целого — это
    строка ОДНОГО кредитора; в корпус-45 таких семь подряд."""
    assert счёт._sb_total_from_text(
        "По кредитному договору № 123 общая сумма задолженности "
        "составляет 9 713 руб. 03 коп.") is None


def test_целое_выигрывает_у_построчных(счёт):
    """Перечень кредиторов идёт ПЕРЕД сводной фразой — берём сводную."""
    текст = (
        "По договору № 1 общая сумма задолженности составляет 9 713 руб. 03 коп.\n"
        "По договору № 2 общая сумма задолженности составляет 16 100 руб. 00 коп.\n"
        "Таким образом, сумма задолженности Должника перед Кредиторами "
        "составляет 2126 507 (Два миллиона сто двадцать шесть тысяч пятьсот "
        "семь) руб. 25 коп."
    )
    assert счёт._sb_total_from_text(текст) == pytest.approx(2126507.25, abs=0.005)


def test_фразы_нет_совсем(счёт):
    assert счёт._sb_total_from_text("Прошу признать меня банкротом.") is None


def test_пустой_текст(счёт):
    assert счёт._sb_total_from_text("") is None


# --- РАЗРЫВ МЕЖДУ СВЯЗКОЙ И ЧИСЛОМ НЕ ПЕРЕПРЫГИВАЕТ ЧЕРЕЗ ЧИСЛО --------------

def test_разрыв_не_перескакивает_через_цифры(счёт):
    """В разрыв цифры не пускаются — иначе связка утащила бы дальнее число."""
    assert счёт._sb_total_from_text(
        "Общий размер моей задолженности составляет 100,00 рублей, "
        "а доход — 116 000,00 рублей.") == pytest.approx(100.0, abs=0.005)


def test_разрыв_ограничен_по_длине(счёт):
    """Слишком далёкое число к фразе уже не относится."""
    длинная_проза = "по " + "весьма " * 12 + "уважительной причине "
    assert счёт._sb_total_from_text(
        "Общий размер моей задолженности составляет " + длинная_проза
        + "500 000,00 рублей.") is None


# --- РАЗБОР СУММЫ ------------------------------------------------------------

@pytest.mark.parametrize("фраза,итог", [
    # копейки отдельным числом: из рублей берём только цифры, т.к. разряды
    # в вёрстке съезжают («2126 507»)
    ("сумма задолженности перед кредиторами составляет 1 000 (одна тысяча) "
     "руб. 05 коп.", 1000.05),
    # без копеек — обычный разбор
    ("сумма задолженности перед кредиторами составляет 1 000,05 руб.", 1000.05),
    ("сумма задолженности перед кредиторами составляет 1000.05 руб.", 1000.05),
])
def test_разбор_суммы(счёт, фраза, итог):
    assert счёт._sb_total_from_text(фраза) == pytest.approx(итог, abs=0.005)

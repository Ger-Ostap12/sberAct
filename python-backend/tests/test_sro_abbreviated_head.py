# -*- coding: utf-8 -*-
"""СРО названа АББРЕВИАТУРОЙ правовой формы: САУ и САМРО, 11.10.2026.

Якорь членства (`_SRO_ANCHOR_RE`) требует, чтобы имя начиналось с известной
правовой формы — `_SRO_LEGAL_HEAD`. В списке уже стояли аббревиатуры «НП» и
«ААУ», но не было «САУ» и «САМРО», и у трёх документов СРО не извлекалась
ВООБЩЕ (поле пустое), хотя реестр это написание опознаёт:

```
свежие-29  «член САУ «Авангард» (ИНН 7705479434 ОГРН 1027705031320 …)»
корпус-60  «из числа членов САМРО "АССОЦИАЦИЯ АНТИКРИЗИСНЫХ УПРАВЛЯЮЩИХ"
            ИНН 6315944042 …»
свежие-22  «член САМРО "Ассоциация антикризисных управляющих"
            (ОГРН 1026300003751, ИНН 6315944042)»
```

Цена дефекта: имя СРО печатается в АКТ, пустое поле — дыра в документе.
Замер радиуса по 99 документам: изменились РОВНО эти три, каждый из None
в каноническое имя реестра.

⚠️ Якорь нельзя расширять свободным поиском: `resolve_sro` канонизирует уже
НАЙДЕННОЕ упоминание, а не проверяет текст — на прозе «…руководствуясь
ст. 213.8 Федерального закона…» он опознаёт СРО «Центрального федерального
округа» по одному слову. Поэтому добавлены именно формы, а не общий случай.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402

САМРО = ('Саморегулируемая межрегиональная общественная организация '
         '«Ассоциация антикризисных управляющих»')
АВАНГАРД = 'Союз арбитражных управляющих "Авангард"'


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


@pytest.mark.parametrize(("фраза", "ждём"), [
    # свежие-29, дословно
    ("Финансовым управляющим утвержден Ширшов Дмитрий Игоревич "
     "(ИНН 614211646210 СНИЛС 144-099-696-91) член САУ «Авангард» "
     "(ИНН 7705479434 ОГРН 1027705031320 рег.номер 005, адрес:101000, Москва)",
     АВАНГАРД),
    # корпус-60, дословно
    ("Утвердить временного управляющего из числа членов САМРО "
     '"АССОЦИАЦИЯ АНТИКРИЗИСНЫХ УПРАВЛЯЮЩИХ" ИНН 6315944042, '
     "адрес регистрации – 443072, САМАРА Г, 18 КМ МОСКОВСКОГО ШОССЕ ТЕР.",
     САМРО),
    # свежие-22, дословно
    ('Финансовым управляющим утвержден Тимченко Павел Иванович '
     '(ИНН 616602539072) - член САМРО "Ассоциация антикризисных управляющих" '
     "(ОГРН 1026300003751, ИНН 6315944042).",
     САМРО),
])
def test_sro_po_abbreviature_izvlekaetsya(analyzer, фраза, ждём):
    поля = {}
    analyzer._resolve_manager_sro(поля, фраза)
    assert поля.get("sroName") == ждём, (
        "СРО не извлечена из аббревиатуры: %r" % поля.get("sroName"))


def test_polnaya_forma_ne_slomana(analyzer):
    """Цена правки: полное написание обязано работать как прежде."""
    поля = {}
    analyzer._resolve_manager_sro(
        поля,
        "утвердить арбитражного управляющего из числа членов Ассоциации "
        '"Саморегулируемая организация арбитражных управляющих "Меркурий" '
        "(ИНН 7710458616 ОГРН 1037710023108)")
    assert поля.get("sroName") == (
        'Ассоциация "Саморегулируемая организация арбитражных управляющих "Меркурий"')


def test_proza_zakona_ne_daet_sro(analyzer):
    """Цена правки: на прозе закона СРО появляться НЕ должна.

    Это ровно та ловушка, из-за которой якорь держат узким: без неё
    `resolve_sro` опознаёт «Центрального федерального округа» в ссылке
    на федеральный закон.
    """
    поля = {}
    analyzer._resolve_manager_sro(
        поля,
        "руководствуясь ст. 213.8 Федерального закона от 26.10.2002 N 127-ФЗ "
        '"О несостоятельности (банкротстве)", прошу суд')
    assert not поля.get("sroName"), поля.get("sroName")

# -*- coding: utf-8 -*-
"""Справочник СРО: «Авангард» в ТЕКУЩЕЙ форме, 11.10.2026.

`sro_data.py` держал дореформенное «Некоммерческое партнерство "Объединение
арбитражных управляющих "Авангард"» и адрес на ул. Макаренко. Документы
корпуса с ТЕМ ЖЕ ИНН 7705479434 / ОГРН 1027705031320 пишут иначе:

```
Форте Пром, Форте Пром Стил  «из числа членов СОЮЗА АРБИТРАЖНЫХ УПРАВЛЯЮЩИХ
                             «АВАНГАРД» (… юридический адрес: 101000,
                             Г.МОСКВА, Б-Р ПОКРОВСКИЙ, Д. 4/17, 1,
                             ПОМЕЩ. IV, ПОМЕЩ. VII)»
свежие-29                    «член САУ «Авангард»» — короткая форма от СОЮЗА
```

Цена дефекта: имя СРО печатается в АКТ, то есть акт называл организацию
юридически несуществующим именем. Старый адрес вдобавок давал ложное
расхождение при сверке.

⚠️ NAIMK (ключ поиска) оставлен дореформенным НАМЕРЕННО — заявления со старым
написанием должны продолжать находиться. Так же сделано у «Меркурия» и
«Гильдии», починенных раньше.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from sro_registry import resolve_sro  # noqa: E402

ТЕКУЩЕЕ = 'Союз арбитражных управляющих "Авангард"'


@pytest.mark.parametrize("как_в_документе", [
    "САУ «Авангард»",                              # свежие-29
    "СОЮЗА АРБИТРАЖНЫХ УПРАВЛЯЮЩИХ «АВАНГАРД»",    # Форте Пром Стил
    "Союз арбитражных управляющих «Авангард»",
    'НП "ОАУ "Авангард"',                          # дореформенное написание
])
def test_avangard_v_tekushchej_forme(как_в_документе):
    """Любое написание даёт ТЕКУЩЕЕ имя, в том числе дореформенное."""
    assert resolve_sro(как_в_документе) == ТЕКУЩЕЕ


def test_adres_avangarda_ne_ustarevshij():
    """Адрес переехал на Покровский бульвар; Макаренко — ложное расхождение."""
    from sro_data import SRO_DATA

    записи = [з for з in SRO_DATA if "вангард" in з.get("NAIM_FULL", "")]
    assert len(записи) == 1, "записей «Авангард» в справочнике: %d" % len(записи)
    адрес = записи[0]["ADDRESS"]
    assert "Покровский" in адрес, адрес
    assert "Макаренко" not in адрес, "адрес остался дореформенным: %r" % адрес


def test_cfop_apk_ostaetsya_nekommercheskim_partnerstvom():
    """Цена правки: НЕ переписывать ОПФ там, где документ сам пишет «НП».

    ЦФОП АПК назван «Некоммерческое партнерство» в самих заявлениях 2025-2026
    (корпус-26, корпус-27), и эталон записан так же. Правило «менять ОПФ»
    здесь применять нельзя — справочник обязан совпадать с документом.
    """
    assert resolve_sro('НП "ЦФОП АПК"') == (
        'Некоммерческое партнерство "Центр финансового оздоровления '
        'предприятий агропромышленного комплекса"')

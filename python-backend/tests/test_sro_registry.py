# -*- coding: utf-8 -*-
"""Тесты сопоставления СРО (`sro_registry.resolve_sro`): упоминание организации из
заявления → каноничное полное имя (NAIM_FULL) из справочника `sro_data`.

Краевые случаи: кавычки-ёлочки/прямые, хвост ИНН/ОГРН/адреса, короткая
аббревиатура, префикс «СРО », отсутствие совпадения → None.
"""
from sro_registry import resolve_sro


def test_yolki_quotes_exact():
    # «Содействие» в ёлочках — точное совпадение по нормализованному NAIMK.
    r = resolve_sro('Ассоциация МСРО «Содействие»')
    assert r == ('Ассоциация "Межрегиональная саморегулируемая организация '
                 'арбитражных управляющих "Содействие"')


def test_tail_inn_stripped():
    # Хвост ИНН не мешает: NAIMK — подстрока нормализованного входа.
    assert resolve_sro('САУ "СРО "ДЕЛО" ИНН 5010029544') == \
        'Союз арбитражных управляющих "Саморегулируемая организация "ДЕЛО"'


def test_tail_ogrn_and_prefix():
    assert resolve_sro('«Содействие» ОГРН: 1025700780071').endswith('"Содействие"')
    assert resolve_sro('- СРО ААУ "Синергия"(ИНН2308980067').endswith('"Синергия"')


def test_abbreviation():
    # Короткая аббревиатура целиком совпадает с NAIMK.
    assert 'Центрального федерального' in (resolve_sro('ПАУ ЦФО') or '')


def test_no_match_returns_none():
    assert resolve_sro('какая-то левая организация без совпадений') is None
    assert resolve_sro('') is None
    assert resolve_sro(None) is None


def test_straight_quotes_distinctive_not_generic():
    # Регресс: родовой токен в кавычках («Саморегулируемая организация…») не должен
    # перебивать отличительный «Меркурий» и уводить в чужую запись (была Эгида).
    r = resolve_sro('Ассоциации "Саморегулируемая организация арбитражных управляющих "Меркурий"')
    assert r == ('Некоммерческое партнерство "Саморегулируемая организация '
                 'арбитражных управляющих "Меркурий"')


def test_abbreviation_expanded_in_full_name():
    # NAIMK-аббревиатуры, развёрнутые словами в NAIM_FULL, всё равно матчатся.
    assert 'СИБИРСКИЙ ЦЕНТР' in (resolve_sro('саморегулируемой организации ААУ «СЦЭАУ»') or '')
    assert resolve_sro('НП"ЦФОП АПК"').startswith('Некоммерческое партнерство "Центр финансового')


def test_spaced_acronym():
    # Разнесённая пробелом аббревиатура «РСО ПАУ» ↔ реестровое «РСОПАУ».
    assert resolve_sro(
        'Ассоциации РСО ПАУ (Региональной саморегулируемой организации '
        'профессиональных арбитражных управляющих)'
    ) == 'Ассоциация "Региональная саморегулируемая организация профессиональных арбитражных управляющих"'


def test_generic_only_name_via_canon():
    # Имя целиком из родовых слов (нет отличительного токена) — матч по
    # каноническому равенству, терпимому к родительному падежу.
    assert resolve_sro(
        'Ассоциации Межрегиональная саморегулируемая организация арбитражных управляющих'
    ) == 'Ассоциация "Межрегиональная саморегулируемая организация арбитражных управляющих"'


def test_membership_full_phrase():
    # Полная многострочная формула членства с внутренним «Содействие».
    assert resolve_sro(
        'Ассоциации «Межрегиональная саморегулируемая организация '
        'арбитражных управляющих «Содействие»'
    ).endswith('"Содействие"')


def test_gildia_straight_nested():
    # main-баг: «Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"».
    assert resolve_sro(
        'Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"'
    ) == 'Некоммерческое партнерство "Саморегулируемая организация "Гильдия арбитражных управляющих"'


def test_egida_short_and_full_split():
    # В исходной выгрузке у «Эгиды» обе колонки содержали склейку
    # «Ассоциация СРО "Эгида" -Ассоциация саморегулируемая организация…» —
    # единственная такая запись справочника. NAIM_FULL должен быть чистым полным
    # именем, короткая форма — резолвиться в него.
    full = 'Ассоциация саморегулируемая организация арбитражных управляющих "Эгида"'
    assert resolve_sro('Ассоциация СРО «Эгида»') == full
    assert resolve_sro('Ассоциация СРО "Эгида"') == full
    # Форма из заявления ФНС (с хвостом адреса) — тоже.
    assert resolve_sro('члена Ассоциация СРО «Эгида» (адрес: 170100, обл. Тверская)') == full

# -*- coding: utf-8 -*-
"""СРО: текущая ОПФ в справочнике и упоминание без слова «член» (22.09.2026).

Три красных класса «сро», два корня:

1. Две записи справочника несли ДОРЕФОРМЕННУЮ правовую форму:
       Меркурий   НП  -> Ассоциация   (свидетельство: корпус-25)
       Гильдия    НП  -> Союз         (свидетельство: корпус-10)
   Документы корпуса пишут текущую форму, справочник подставлял старую.

2. свежие-4 называет СРО ПОСЛЕ ТИРЕ за реквизитами управляющего, без слова
   «член/членство»: «утвержден Селина Ольга Олеговна (ИНН …, СНИЛС …) -
   Ассоциация арбитражных управляющих "…"». Якорь такую запись не видел.

⚠️ СВОБОДНЫЙ ПОИСК С «ПРОВЕРКОЙ СПРАВОЧНИКОМ» НЕДОПУСТИМ. `resolve_sro`
канонизирует УЖЕ НАЙДЕННОЕ упоминание, а не проверяет текст: он сопоставляет
по ОДНОМУ отличительному токену, и на прозе «…руководствуясь ст. 213.8
Федерального закона…» опознаёт СРО «Центрального федерального округа» (замер
поймал это на корпус-19). Поэтому якорь требует и скобку реквизитов, и тире.

Конвенция класса: поле несёт КАНОН справочника, а не запись документа —
пятнадцать зелёных ожиданий помечены «НЕ СЛОМАТЬ», в т.ч. корпус-39, где
справочник исправил опечатку документа.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from sro_registry import resolve_sro  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


# --- текущая правовая форма в справочнике -------------------------------------

@pytest.mark.parametrize("упоминание, ждём", [
    ('Ассоциация "Меркурий"',
     'Ассоциация "Саморегулируемая организация арбитражных управляющих "Меркурий"'),
    ('НП СОАУ "Меркурий"',
     'Ассоциация "Саморегулируемая организация арбитражных управляющих "Меркурий"'),
    ('Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"',
     'Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"'),
    ('НП СРО "Гильдия арбитражных управляющих"',
     'Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"'),
])
def test_справочник_даёт_текущую_опф(упоминание, ждём):
    assert resolve_sro(упоминание) == ждём


def test_дореформенное_написание_всё_ещё_находится(analyzer):
    """NAIMK оставлен старым намеренно: заявления с «НП» должны опознаваться."""
    assert resolve_sro('Некоммерческое партнерство "Саморегулируемая организация '
                       'арбитражных управляющих "Меркурий"') is not None


# --- упоминание после тире, без слова «член» ----------------------------------

ЧЕРЕЗ_ТИРЕ = (
    "Решением Арбитражного суда Ростовской области от 27.01.2026 г. гражданин "
    "признан несостоятельным (банкротом).\n"
    "Финансовым управляющим утвержден Селина Ольга Олеговна "
    "(ИНН 431202681065, СНИЛС 125-151-221 05) - Ассоциация арбитражных "
    'управляющих "СИБИРСКИЙ ЦЕНТР ЭКСПЕРТОВАНТИКРИЗИСНОГО УПРАВЛЕНИЯ" '
    "(ИНН 5406245522, ОГРН 1035402470036).\n")


def test_сро_после_тире_находится(analyzer):
    assert analyzer._extract_sro_mention(ЧЕРЕЗ_ТИРЕ) is not None


def test_склейка_конвертера_чинится_справочником(analyzer):
    """«ЭКСПЕРТОВАНТИКРИЗИСНОГО» в документе — справочник разделяет слова."""
    поля = {}
    analyzer._resolve_manager_sro(поля, ЧЕРЕЗ_ТИРЕ)
    assert поля.get("sroName") == (
        'Ассоциация арбитражных управляющих '
        '"СИБИРСКИЙ ЦЕНТР ЭКСПЕРТОВ АНТИКРИЗИСНОГО УПРАВЛЕНИЯ"')


# --- чего якорь брать НЕ должен -----------------------------------------------

ПРОЗА_БЕЗ_СРО = (
    "На основании вышеизложенного, руководствуясь ст. ст. 16, 71, 138, 213.8 "
    "Федерального закона от 26 октября 2002 г. № 127-ФЗ «О несостоятельности "
    "(банкротстве)», просим суд включить требование в реестр.\n")


def test_проза_о_законе_не_становится_сро(analyzer):
    """Свободный поиск опознал бы здесь СРО «Центрального федерального округа»."""
    assert analyzer._extract_sro_mention(ПРОЗА_БЕЗ_СРО) is None


def test_управляющий_без_скобок_и_тире_не_якорь(analyzer):
    """Якорь требует ОБА признака: скобку реквизитов и тире."""
    текст = ("Финансовым управляющим утвержден Селина Ольга Олеговна. "
             "Ассоциация арбитражных управляющих объединяет специалистов.\n")
    assert analyzer._extract_sro_mention(текст) is None


# --- прежнее поведение --------------------------------------------------------

def test_якорь_членства_не_сломан(analyzer):
    текст = ("Финансовым управляющим утвержден(а) Ермакова Ольга Игоревна "
             '(ИНН 550311410020, членство: Союз "Саморегулируемая организация '
             '"Гильдия арбитражных управляющих").\n')
    поля = {}
    analyzer._resolve_manager_sro(поля, текст)
    assert поля.get("sroName") == (
        'Союз "Саморегулируемая организация "Гильдия арбитражных управляющих"')


def test_сро_вне_справочника_остаётся_сырой(analyzer):
    """Незнакомое имя не выдумываем — отдаём как написано в документе."""
    текст = ("утвержден Каплиёв Михаил Васильевич из числа членов Ассоциации "
             "«ЕвроВостСибирская саморегулируемая организация арбитражных "
             "управляющих».\n")
    поля = {}
    analyzer._resolve_manager_sro(поля, текст)
    assert "ЕвроВостСибирская" in (поля.get("sroName") or "")

# -*- coding: utf-8 -*-
"""Обрезка текста по заголовку заявления — только если это ЗАГОЛОВОК (31.08.2026).

Перед разбором обязательств текст режется по слову «заявление»: всё, что до
него, — шапка, и обязательства оттуда брать нельзя. Но поиск брал ПЕРВОЕ
совпадение где угодно, а в документе, озаглавленном иначе («Требование»), слово
всплывает только в мотивировочной части — «обращения в суд с заявлением о
включении…». Тогда отсекалось 84% текста вместе со всеми договорами.

Замер по корпусу решил, где граница: настоящий заголовок стоит на 7% длины
(медиана), худший законный случай — 22%, выше 30% нет ни одного. Порог 40%
взят вдвое от худшего законного.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402
from obligations_mixin import _TITLE_MAX_OFFSET  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


_BODY = ("Между Обществом и должником заключен договор займа № 107977878 "
         "от 10.08.2024. Должник обязательства не исполнил. ")


def test_заголовок_в_начале_обрезает(analyzer):
    """Штатный случай: слово стоит в шапке, всё до него — реквизиты сторон."""
    text = ("Арбитражный суд Ростовской области. Кредитор: ООО «Ромашка». "
            "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов. " + _BODY)
    obligations = analyzer.extract_obligations(text, {})
    assert obligations, "обязательство после заголовка должно найтись"


def test_слово_в_конце_не_обрезает(analyzer):
    """Документ озаглавлен иначе — резать по слову из мотивировки нельзя.

    Ровно этот случай терял ВСЕ обязательства на двух свежих документах.
    """
    text = (_BODY * 12
            + "Тем самым должник лишил кредитора возможности обращения в суд "
              "с заявлением о включении в реестр требований кредиторов.")
    obligations = analyzer.extract_obligations(text, {})
    assert obligations, "обрезка по слову из мотивировки не должна съедать текст"
    assert any("107977878" in str(o.get("contractNumber")) for o in obligations)


def test_порог_вдвое_выше_худшего_законного_случая():
    """Граница взята по замеру, а не на глаз: худший законный случай — 22%."""
    assert 0.3 < _TITLE_MAX_OFFSET <= 0.5


def test_обрезка_всё_ещё_отсекает_шапку(analyzer):
    """Гарантия в обратную сторону: договор ИЗ ШАПКИ браться не должен.

    Иначе отмена обрезки превратилась бы в отмену самого правила.
    """
    text = ("Кредитор: ООО «Ромашка», ранее работавшее по договору займа "
            "№ 000000001 от 01.01.2000. "
            "ЗАЯВЛЕНИЕ о включении в реестр требований кредиторов. " + _BODY)
    obligations = analyzer.extract_obligations(text, {})
    numbers = {str(o.get("contractNumber")) for o in obligations}
    assert "000000001" not in numbers, "договор из шапки не должен попадать в обязательства"

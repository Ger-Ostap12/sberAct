# -*- coding: utf-8 -*-
"""Стоп-листы границ записей: метка в одном падеже или числе.

Списки литеральные, поэтому форму надо обрезать до основы. Здесь проверены
границы записи управляющего, блока управляющего и записи наследника: радиус
правок по корпусу нулевой, защищает только этот тест.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

import fio_detector  # noqa: E402
from document_analyzer import DocumentAnalyzer  # noqa: E402

# --- граница записи управляющего: сокращение метки почты -------------------------


@pytest.mark.parametrize("строка", [
    "Эл. почта: dy@sellerport.ru",
    "Эл.почта: dy@sellerport.ru",
    "эл. почты: dy@sellerport.ru",
    "Электронная почта: dy@sellerport.ru",
    "Электронной почты: dy@sellerport.ru",
    "Адрес электронной почты: dy@sellerport.ru",
    "Адрес электронной почта: dy@sellerport.ru",
    "E-mail: dy@sellerport.ru",
    "Email: dy@sellerport.ru",
])
def test_почта_обрывает_запись_управляющего(строка):
    """Любая форма метки почты — конец записи: дальше идут не данные лица."""
    assert DocumentAnalyzer._MANAGER_RECORD_END_RE.match(строка), строка


@pytest.mark.parametrize("строка", [
    "Элеонора Петровна Смирнова",      # «Эл» в начале ИМЕНИ — не метка почты
    "127247, Москва, а/я 3",
    "Полейчук Семён Сергеевич",
])
def test_запись_управляющего_не_обрывается_зря(строка):
    assert not DocumentAnalyzer._MANAGER_RECORD_END_RE.match(строка), строка


# --- граница блока управляющего: число метки -------------------------------------


@pytest.mark.parametrize("метка", [
    "Должник", "Должники", "Должника",
    "Кредитор", "Кредиторы",
    "Ответчик", "Ответчики",
    "Заёмщик", "Заемщики",
    "Заявитель", "Заявители",
    "Взыскатель", "Третьи лица", "Заинтересованное лицо",
])
def test_метка_стороны_обрывает_блок_управляющего(метка):
    текст = "Конкурсный управляющий: Полейчук С.С.\n%s: ООО «СПОРТ»\n" % метка
    assert DocumentAnalyzer._MANAGER_BLOCK_END_RE.search(текст), метка


def test_блок_управляющего_не_обрывается_своей_же_меткой():
    """Ворота, а не запрет: собственная метка управляющего границей быть не должна."""
    текст = "Конкурсный управляющий: Полейчук С.С.\n127247, Москва, а/я 3\n"
    assert not DocumentAnalyzer._MANAGER_BLOCK_END_RE.search(текст)


# --- граница записи наследника: все формы управляющего ---------------------------


@pytest.mark.parametrize("метка", [
    "Финансовый управляющий:", "Временный управляющий:",
    "Конкурсный управляющий:", "Арбитражный управляющий:",
    "Поручитель:", "Поручителя:", "Созаёмщик:", "Созаемщик:", "Со-заёмщик:",
    "Должник:", "Заявитель:", "Заявителя:", "Кредитор:", "Нотариус:",
])
def test_метка_обрывает_запись_наследника(метка):
    текст = "Наследник: Ким Эмма Николаевна\n%s Лизогуб Анна Сергеевна\n" % метка
    assert fio_detector._HEIR_STOP_RE.search(текст), метка


def test_запись_наследника_не_обрывается_адресом():
    текст = ("Наследник: Ким Эмма Николаевна\n"
             "346744, Ростовская обл., Азовский р-н, с. Кулешовка\n")
    assert not fio_detector._HEIR_STOP_RE.search(текст)


# --- общая граница чужого лица (та же основа на двух путях) ----------------------


@pytest.mark.parametrize("метка", [
    "Наследник", "Наследница", "Наследники",
    "Поручитель", "поручителя", "Созаёмщик", "созаемщика",
    "Представитель", "Третье лицо", "Третьи лица", "Ответчик",
    "Финансовый управляющий", "Конкурсный управляющий",
    "дети", "детей", "сын", "дочь", "супруга",
])
def test_общая_граница_знает_все_формы(метка):
    """`OTHER_PARTY_LABEL` — один список на запись должника и на окно в теле."""
    assert fio_detector.OTHER_PARTY_LABEL_RE.search(метка), метка


@pytest.mark.parametrize("слово", [
    # Основа без границы поймала бы «детализацию» — поэтому у «детей» граница слова.
    "детализация расчёта", "детальный расчёт",
    "наследственного дела",  # дело — не лицо, границей быть не должно
])
def test_общая_граница_не_ловит_лишнее(слово):
    assert not fio_detector.OTHER_PARTY_LABEL_RE.search(слово), слово

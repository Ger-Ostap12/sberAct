# -*- coding: utf-8 -*-
"""Табличный читатель сумм не должен читать ПРОЗУ (09.10.2026).

Пункт 4 фазы 4, разбор — handoff §S.46.

Читатель «метка в одной строке, значение в соседней» искал первую строку со
словом «проценты» и брал оттуда любое число. У свежие-18 первой такой строкой
оказалась ссылка на условия договора:

> «В соответствии с п. 4.5 Общих условий проценты за пользование кредитом
> уплачиваются Заёмщиком со дня, следующего за днем предоставления кредита…»

Номер пункта 4.5 становился суммой процентов (4,50), а дальше законная сверка
«части обязаны равняться целому» переписывала ОБЩИЙ ДОЛГ: 494 194,58 вместо
названных документом 494 190,08.

⚠️ Дефект был виден ТОЛЬКО по общей сумме: ожидания по процентам у свежие-18
нет вовсе, и 4,50 в графе процентов эталон бы не поймал.

⚠️⚠️ Грабли самих тестов: первая редакция этого файла была ЗЕЛЁНОЙ и на
старом коде. Причина — в синтетике срабатывал слой просительной части и
затирал мусорное значение нулём, а у настоящего свежие-18 он молчит. Текст
ниже подобран так, чтобы слой молчал (в просьбе нет разбивки), и только тогда
тест ловит дефект. Проверять тест на ОБЕ стороны обязательно.

Признак ячейки таблицы: строка — это ОДНА ПОДПИСЬ без цифр, значение лежит
в соседней строке. Своя метка («сумма долга по процентам») работает как и раньше.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from document_analyzer import DocumentAnalyzer  # noqa: E402


@pytest.fixture(scope="module")
def analyzer():
    return DocumentAnalyzer()


def поля(analyzer, текст):
    return analyzer.analyze_from_text(текст)["fields"]


ШАПКА = (
    "Арбитражный суд Ростовской области\n"
    "Заявитель: «Газпромбанк» (Акционерное общество)\n"
    "Должник: РЫТЧЕНКО ЛАРИСА ВАСИЛЬЕВНА\n"
    "ЗАЯВЛЕНИЕ о включении требований в реестр требований кредиторов\n"
)

# Просьба БЕЗ разбивки — иначе слой просительной части сам заполнит проценты
# нулём и мусор станет не виден (см. предупреждение в шапке модуля).
ПРОЗА_С_ПУНКТОМ = ШАПКА + (
    "В соответствии с п. 4.5 Общих условий проценты за пользование кредитом "
    "уплачиваются Заёмщиком со дня, следующего за днем предоставления кредита.\n"
    "Общая сумма задолженности составляет 494190.08\n"
    "Просроченный основной долг\n487314.44\nПени\n6875.64\n"
    "ПРОШУ: Включить требования «Газпромбанк» в реестр требований кредиторов "
    "третьей очереди в сумме 494 190.08 руб.\n"
)


def test_номер_пункта_договора_не_становится_суммой(analyzer):
    """«п. 4.5 Общих условий проценты …» — это ссылка, а не сумма процентов."""
    assert поля(analyzer, ПРОЗА_С_ПУНКТОМ).get("interest") in (None, "", "0,00")


def test_итог_остаётся_названным_документом(analyzer):
    """Обратная сторона: мусор в слагаемом переписывал ОБЩИЙ долг.

    Сверка «части = целое» законна, но запускалась от мусорного слагаемого,
    и в графе общей суммы появлялось число, которого в документе нет.
    """
    assert поля(analyzer, ПРОЗА_С_ПУНКТОМ).get("totalDebt") == "494 190,08"


def test_своя_метка_процентов_по_прежнему_читается(analyzer):
    """Ворота, а не запрет: явная подпись работает и с цифрами в строке."""
    текст = ШАПКА + (
        "ПРОШУ: Включить в реестр требований кредиторов должника требование "
        "в размере 34952 руб. из которой: сумма основного долга 15000 руб., "
        "сумма долга по процентам 17952 руб.\n"
    )
    assert поля(analyzer, текст).get("interest") == "17 952,00"


def test_ячейка_таблицы_читается(analyzer):
    """Подпись без цифр + значение в соседней строке — это таблица, читаем."""
    текст = ШАПКА + (
        "ПРОШУ: Включить в реестр требований кредиторов Должника требование "
        "АО «Банк» в состав третьей очереди в размере 15738,40 руб.\n"
        "Основной долг\n7237,60\nПроценты\n8500,80\nНеустойка\n0,00\n"
    )
    assert поля(analyzer, текст).get("interest") == "8 500,80"

    "2: ООО «ГК Каскад» \n"
    "ОГРН: 1057748678437, ИНН: 7731532684 \n"
    "344002, Ростовская область, г. Ростов-на-Дону, пр-кт Буденновский, зд. 3/3, офис 49\n"
    "3: Денисов А.В.\n"

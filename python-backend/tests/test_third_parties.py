# -*- coding: utf-8 -*-
"""Третьи лица: лишняя карточка, проза в имени, метка вне реестра (14.09.2026).

Пять красных эталона на трёх документах, три разных корня:

  свежие-33/34  блок третьих лиц не знал, где кончается ШАПКА и начинается ТЕЛО,
                дочитывал тело до первого управляющего — и должник, названный
                в теле («…Буниатян А.Г. признана банкротом»), становился вторым
                третьим лицом. Плюс реквизиты в скобках оставались в имени.
  корпус-13     метка «Заинтересованные лица:» есть в реестре меток
                (label_synonyms), но извлекатель в реестр не смотрел — и все
                14 сторон терялись. Перечень к тому же нумерованный, и
                двенадцатая сторона начинается посередине строки одиннадцатой.

Тексты — дословные куски заявлений корпуса.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from fio_detector import (  # noqa: E402
    _clean_party_name,
    _is_party_start,
    _third_parties_block,
    extract_third_parties,
)
from label_synonyms import THIRD_PARTY_HEADER_LABELS  # noqa: E402
from parties_mixin import PartiesMixin  # noqa: E402

# --- метка блока из реестра ---------------------------------------------------

@pytest.mark.parametrize("метка", THIRD_PARTY_HEADER_LABELS)
def test_каждая_метка_реестра_открывает_блок(метка):
    """Сторож реестра: обещание label_synonyms должно быть правдой.

    Буквальная альтернатива из реестра не покрыла бы «Третьи лица» и «Третье
    лицо» одной записью, поэтому регулярка написана с морфологическим зазором —
    и этот тест следит, что зазор накрывает КАЖДОЕ зарегистрированное написание.
    """
    текст = f"Должник: Иванов Иван Иванович\n{метка}: ООО «Перспектива»\nИНН 7701887506\n"
    assert "Перспектива" in _third_parties_block(текст)


def test_метка_в_прозе_блок_не_открывает():
    """Якорь на начало строки: в теле заявления «третьего лица» — цитата закона.

    Без якоря блок открывался бы посреди прозы и тащил бы в карточки всё, что
    стоит следом.
    """
    текст = ("Согласно ч. 1 ст. 51 АПК РФ суд может привлечь к участию в деле "
             "третьи лица: Иванов Иван Иванович заявил ходатайство.\n")
    assert _third_parties_block(текст) == ""


# --- граница шапки и тела (лишняя карточка) -----------------------------------

АЙДИ = (
    "Финансовый управляющий: Заречнев Станислав Евгеньевич (ИНН 420207419377)\n"
    "Третье лицо: ООО МФК «Быстроденьги» (Почтовый адрес: 432071, г. Ульяновск, "
    "ул. К. Маркса, д. 13а, корп.1, ОГРН: 1087325005899, ИНН: 7325081622, "
    "КПП: 771401001)\n"
    "По делу № А53-14250/2025\n"
    "Требование о включении в реестр\n"
    "требований кредиторов должника - \n"
    "Буниатян Алина Генриковна\n"
    "Решением Арбитражного суда Ростовской области от 15.09.2025 г. по делу "
    "№ А53-14250/2025 Буниатян Алина Генриковна (дата рождения: 28.03.2001 г., "
    "СНИЛС 158-801-520 75, ИНН 612504512780, адрес регистрации по месту "
    "жительства: 346496, Ростовская область, хутор Яново-Грушевский, "
    "ул Крестьянская, д 15, кв 2) признана несостоятельной (банкротом).\n"
)


def test_должник_из_тела_не_становится_третьим_лицом():
    """свежие-33/34: одна карточка, а не две.

    Блок кончается на «По делу №» — дальше идёт тело заявления, а не шапка.
    """
    лица = extract_third_parties(АЙДИ)
    assert [л["name"] for л in лица] == ["ООО МФК «Быстроденьги»"]


def test_реквизиты_в_скобках_уходят_из_имени():
    """Почтовый адрес, ОГРН, ИНН и КПП уже разобраны отдельными полями —
    в имени это проза, которую юрист вычищает руками."""
    лицо = extract_third_parties(АЙДИ)[0]
    assert лицо["name"] == "ООО МФК «Быстроденьги»"
    assert лицо["inn"] == "7325081622"
    assert лицо["ogrn"] == "1087325005899"
    assert лицо["address"] == "432071, г. Ульяновск, ул. К. Маркса, д. 13а, корп.1"


def test_правовая_форма_в_скобках_остаётся_в_имени():
    """«Банк ВТБ (ПАО)» — скобки часть настоящего наименования.

    Поэтому режем не любые скобки, а только те, внутри которых РЕКВИЗИТЫ.
    """
    assert _clean_party_name("Банк ВТБ (ПАО)") == "Банк ВТБ (ПАО)"
    assert _clean_party_name(
        "ООО «Ромашка» (ИНН 7701887506)") == "ООО «Ромашка»"


@pytest.mark.parametrize("начало_тела", [
    "По делу № А53-14250/2025",
    "Требование о включении в реестр требований кредиторов",
    "В производстве Арбитражного суда Ростовской области находится дело",
    "Решением Арбитражного суда Ростовской области от 15.09.2025 г.",
    "Определением Арбитражного суда Ростовской области от 15.09.2025 г.",
    "Государственная пошлина: 100 000 руб.",
])
def test_блок_кончается_на_начале_тела(начало_тела):
    текст = ("Третье лицо: ООО «Перспектива»\n"
             f"{начало_тела}\n"
             "Сидоров Сидор Сидорович признан банкротом\n")
    блок = _third_parties_block(текст)
    assert "Перспектива" in блок
    assert "Сидоров" not in блок



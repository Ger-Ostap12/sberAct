def test_нумерованный_перечень_разбирается_целиком():
    """корпус-13: четырнадцать сторон под меткой «Заинтересованные лица».

    Номер надёжнее начала строки: двенадцатая сторона в документе начинается
    ПОСЕРЕДИНЕ строки с адресом одиннадцатой.
    """
    лица = extract_third_parties(ФОРТЕ)
    assert [л["name"] for л in лица] == [
        "ООО «Перспектива»", "ООО «ГК Каскад»", "Денисов А.В.", "Родина Н.А."]


def test_сторона_склеенная_со_строкой_предыдущей_не_теряется():
    лица = {л["name"]: л for л in extract_third_parties(ФОРТЕ)}
    assert лица["Денисов А.В."]["address"] == (
        "143582, Московская область, г. Истра, д. Воронино, ул. Сосновая, д. 11/9")
    assert лица["Родина Н.А."]["inn"] == "616703936076"


def test_адрес_голой_строкой_без_метки():
    """В перечне у стороны ОГРН и ИНН с метками, а адрес — просто индекс и текст."""
    лица = {л["name"]: л for л in extract_third_parties(ФОРТЕ)}
    assert лица["ООО «Перспектива»"]["address"] == (
        "344082, Ростовская область, г. Ростов-на-Дону, ул. Согласия, д.18, 1")


def test_шестизначный_кусок_огрн_за_индекс_не_принимается():
    """ОГРН 13 цифр, ИНН 12 — без границ по цифрам их хвост сошёл бы за индекс."""
    текст = ("Третье лицо: ООО «Ромашка»\n"
             "ОГРН: 1107746649625, ИНН: 7701887506\n")
    assert "address" not in extract_third_parties(текст)[0]


def test_фамилия_с_инициалами_начинает_запись():
    assert _is_party_start("Денисов А.В.")
    assert _is_party_start("Родина Н. А.")
    assert not _is_party_start("Согласно п. 1 ст. 384 ГК РФ")


def test_единственный_номер_перечнем_не_считается():
    """«1:» может оказаться куском адреса или времени — один номер ни о чём
    не говорит, перечень начинается с единицы и идёт подряд."""
    текст = ("Третье лицо: ООО «Перспектива»\n"
             "Адрес: 344082, г. Ростов-на-Дону, ул. Согласия, д.18, офис 1: Приёмная\n")
    assert [л["name"] for л in extract_third_parties(текст)] == ["ООО «Перспектива»"]


# --- третье лицо не может быть должником --------------------------------------

def test_запись_должника_выкидывается_из_третьих_лиц():
    """Правило «третьи лица — это НЕ ответчики и НЕ истец» было записано только
    для LLM-пути (llm/prompts.py); регексовый путь его не знал."""
    лица = [{"name": "ООО МФК «Быстроденьги»"}, {"name": "Буниатян Алина Генриковна"}]
    поля = {"debtorName": "БУНИАТЯН АЛИНА ГЕНРИКОВНА"}
    оставшиеся = PartiesMixin._drop_debtor_from_third_parties(лица, поля, [])
    assert [л["name"] for л in оставшиеся] == ["ООО МФК «Быстроденьги»"]


def test_чужие_записи_защита_не_трогает():
    лица = [{"name": "ООО МФК «Быстроденьги»"}, {"name": "Управление Росреестра"}]
    поля = {"debtorName": "Буниатян Алина Генриковна"}
    оставшиеся = PartiesMixin._drop_debtor_from_third_parties(лица, поля, [])
    assert len(оставшиеся) == 2


def test_должник_из_записи_блока_тоже_учитывается():
    """Плоского debtorName может не быть — тогда имя берём из разобранной записи."""
    лица = [{"name": "Иванов Иван Иванович"}]
    оставшиеся = PartiesMixin._drop_debtor_from_third_parties(
        лица, {}, [{"name": "Иванов Иван Иванович"}])
    assert оставшиеся == []

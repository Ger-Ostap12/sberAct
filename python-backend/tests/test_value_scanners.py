# -*- coding: utf-8 -*-
"""Сканеры значений по типу, без опоры на метку (§S.2.C, шаг C1).

Ставка слоя: новый банк меняет формулировку метки, но НЕ МЕНЯЕТ форму ИНН.
Поэтому проверки здесь двух родов, и второй важнее первого:

  * находит ли сканер значение в разных написаниях;
  * НЕ находит ли он там, где значения нет.

Ложное срабатывание тут дороже пропуска: пропуск оставляет поле пустым и виден,
а ложная находка молча заполняет поле неправдой. Отсюда перекос в сторону
отрицательных проверок — «десять цифр подряд» и «17 знаков» встречаются в
заявлениях сплошь и рядом, и без контрольных сумм слой был бы вредным.
"""
import os
import sys

import pytest

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_THIS, "..", "app")))

from value_scanners import (  # noqa: E402
    by_kind,
    dedupe,
    scan_address,
    scan_all,
    scan_case_number,
    scan_date,
    scan_fio,
    scan_inn,
    scan_kpp,
    scan_money,
    scan_ogrn,
    scan_snils,
    scan_vin,
    valid_only,
)


def _values(found):
    return [f.value for f in found]


# --- ИНН ----------------------------------------------------------------------

def test_инн_юрлица_и_физлица_различаются_длиной():
    """Длина — единственный надёжный признак роли: 12 знаков это физлицо.

    На корпусе он отсёк 16 ложных ИНН управляющего из 21 (§S.8): рядом со
    словом «управляющий» десятизначный ИНН принадлежит СРО, а не человеку.
    """
    found = valid_only(scan_inn("Банк ИНН 7707083893, должник ИНН 612504512780"))
    assert _values(found) == ["7707083893", "612504512780"]


def test_невалидная_контрольная_сумма_помечается_а_не_выбрасывается():
    """Отчёту нужно различать «в документе опечатка» и «сканер слеп»."""
    found = scan_inn("ИНН 1234567890")
    assert len(found) == 1
    assert found[0].valid is False
    assert valid_only(found) == []


def test_из_двенадцатизначного_инн_не_вырезается_десятизначный():
    """`(?<!\\d)`/`(?!\\d)` — единственное, что стоит между нами и этим багом.

    Без границ «612504512780» отдал бы «6125045127» и прошёл бы как ИНН ЮЛ.
    """
    found = scan_inn("612504512780")
    assert _values(found) == ["612504512780"]


def test_номер_счёта_не_становится_инн():
    """20 цифр подряд — расчётный счёт, а не два ИНН."""
    assert valid_only(scan_inn("сч. 40817810570000123456")) == []


def test_валидный_инн_внутри_длинного_числа_не_берётся():
    """Контрольная сумма тут НЕ спасает — спасают только границы.

    Первая версия этой проверки брала расчётный счёт и зеленела даже со снятыми
    границами: обрезок случайно не проходил контрольную сумму. Настоящий случай —
    длинное число, чьи первые 12 цифр СОСТАВЛЯЮТ валидный ИНН (13 знаков как у
    ОГРН). Без `(?!\\d)` сканер уверенно отдаёт из него чужой «ИНН».
    """
    from requisites_validation import is_valid_inn

    assert is_valid_inn("612504512780"), "предпосылка проверки: 12 цифр валидны"
    assert valid_only(scan_inn("номер 6125045127805")) == []


# --- ОГРН / ОГРНИП --------------------------------------------------------------

def test_огрн_и_огрнип_различаются_длиной_и_суммой():
    found = valid_only(scan_ogrn("ОГРН 1027700132195, ОГРНИП 304500116000157"))
    assert [(f.kind, f.value) for f in found] == [
        ("ogrn", "1027700132195"), ("ogrnip", "304500116000157"),
    ]


def test_битый_огрн_не_проходит():
    assert valid_only(scan_ogrn("ОГРН 1027700132199")) == []


# --- СНИЛС ----------------------------------------------------------------------

@pytest.mark.parametrize("text", [
    "СНИЛС 112-233-445 95",
    "СНИЛС 112 233 445 95",
    "СНИЛС 11223344595",
])
def test_снилс_в_разных_написаниях(text):
    assert valid_only(scan_snils(text)), f"не найден в написании: {text}"


def test_снилс_с_битой_контрольной_суммой_отсеивается():
    assert valid_only(scan_snils("СНИЛС 112-233-445 99")) == []


# --- Деньги ----------------------------------------------------------------------

def test_суммы_с_разделителем_разрядов():
    found = scan_money("задолженность 1 234 567,89 руб. и 500 руб.")
    assert len(found) == 2


def test_год_и_номер_не_становятся_суммой():
    """Валюта в паттерне обязательна — иначе деньгами станет что угодно.

    «2024» и «А53-2848/2026» встречаются в каждом заявлении, и без требования
    валюты финансовый каскад набрал бы мусора.
    """
    assert scan_money("дело № А53-2848/2026 от 2024 года") == []


# --- Даты -------------------------------------------------------------------------

def test_даты_в_разных_разделителях():
    assert len(scan_date("27.11.1961, 05-03-1975, 01/01/2024")) == 3


def test_несуществующая_дата_помечается_невалидной():
    """Формат верный, календарь — нет. Молча принимать нельзя."""
    found = scan_date("32.13.2024")
    assert len(found) == 1 and found[0].valid is False


# --- Номер дела ---------------------------------------------------------------------

def test_номер_дела_с_латинской_а():
    """OCR путает «А» и «A» — обе буквы должны срабатывать."""
    assert len(scan_case_number("дело А53-2848/2026 и A40-1/2024")) == 2


# --- ФИО и адрес ----------------------------------------------------------------------

def test_фио_по_форме_три_слова_с_заглавной():
    assert "Иванов Иван Иванович" in _values(scan_fio("должник Иванов Иван Иванович, 1980"))


def test_фио_это_кандидат_а_не_приговор():
    """Форма ФИО и принадлежность человеку — разные вопросы.

    «Ассоциация Саморегулируемая Организация» по форме неотличима от ФИО;
    отбраковка — задача назначения ролей (C2), а не сканера.
    """
    assert _values(scan_fio("Ассоциация Саморегулируемая Организация")) != []


def test_адрес_якорится_на_индекс():
    found = scan_address("Адрес: 344002, г. Ростов-на-Дону, ул. Станиславского, 10")
    assert found and found[0].value.startswith("344002")


# --- VIN ------------------------------------------------------------------------------

def test_vin_без_запрещённых_букв():
    """I, O, Q в VIN не используются — это часть стандарта, а не придирка."""
    assert _values(scan_vin("VIN XTA21093041234567")) == ["XTA21093041234567"]
    assert scan_vin("VIN IOQ21093041234567") == []


# --- КПП --------------------------------------------------------------------------------

def test_кпп_по_формату():
    assert _values(valid_only(scan_kpp("КПП 770701001"))) == ["770701001"]


# --- Сборка ------------------------------------------------------------------------------

def test_находки_упорядочены_по_позиции():
    """Назначение ролей (C2) ищет ближайший слева якорь — ему нужен порядок."""
    text = "ИНН 7707083893, ОГРН 1027700132195, СНИЛС 112-233-445 95"
    found = scan_all(text)
    assert [f.start for f in found] == sorted(f.start for f in found)


def test_группировка_по_типу():
    groups = by_kind(scan_all("ИНН 7707083893 и ИНН 612504512780"))
    assert len(groups["inn"]) == 2


def test_дедуп_не_склеивает_одинаковые_значения_из_разных_мест():
    """Один и тот же ИНН в шапке и в реквизитах — две находки, не одна.

    Позиция входит в ключ намеренно: C2 назначает роль по близости, и склейка
    по значению стёрла бы информацию о том, где именно он стоял.
    """
    text = "ИНН 7707083893 ... в реквизитах ИНН 7707083893"
    assert len(dedupe(scan_inn(text))) == 2


def test_выбор_типов_ограничивает_сканирование():
    found = scan_all("ИНН 7707083893, дата 01.01.2024", kinds=["inn"])
    assert {f.kind for f in found} == {"inn"}

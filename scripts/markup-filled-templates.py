def replace_in_paragraph(paragraph, old: str, new: str) -> bool:
    """Замена по склейке абзаца с записью в первый затронутый run."""
    text = paragraph.text
    idx = text.find(old)
    if idx < 0:
        return False
    end = idx + len(old)
    pos = 0
    written = False
    for run in paragraph.runs:
        start, stop = pos, pos + len(run.text)
        pos = stop
        if stop <= idx or start >= end:
            continue
        keep_left = run.text[: max(0, idx - start)]
        keep_right = run.text[max(0, end - start):]
        if not written:
            run.text = keep_left + new + keep_right
            written = True
        else:
            run.text = keep_left + keep_right
    return written


def fix_judge_in_text(paragraph) -> bool:
    if not JUDGE_IN_TEXT.search(paragraph.text) or "[415]" in paragraph.text:
        return False
    m = JUDGE_IN_TEXT.search(paragraph.text)
    return replace_in_paragraph(paragraph, m.group(0), m.group(1) + "[415]")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--templates", default=str(Path(__file__).resolve().parents[1] / "Templates"))
    args = parser.parse_args()

    root = Path(args.templates)
    backup_root = Path(__file__).resolve().parents[1] / ".template-backups"
    total = 0

    for path in sorted(root.rglob("*.docx")):
        if path.name.startswith("~$"):
            continue
        rel = path.relative_to(root)
        key = str(rel).replace("\\", "/")
        doc = Document(str(path))
        changed = 0
        notes: list[str] = []

        for paragraph in doc.paragraphs:
            if fix_judge_in_text(paragraph):
                changed += 1
                notes.append(f"судья -> [415]: {paragraph.text.strip()[:60]!r}")

        for old, new in FILE_REPLACEMENTS.get(key, []):
            for paragraph in doc.paragraphs:
                if replace_in_paragraph(paragraph, old, new):
                    changed += 1
                    notes.append(f"{old[:45]!r} -> {new[:45]!r}")
                    break
            else:
                notes.append(f"!! не найдено: {old[:60]!r}")

        if not notes:
            continue
        print(f"== {rel}")
        for n in notes:
            print(f"   {n}")
        if changed and not args.dry_run:
            backup = backup_root / rel
            backup.parent.mkdir(parents=True, exist_ok=True)
            if not backup.exists():
                shutil.copy(path, backup)
            doc.save(str(path))
        total += changed

    print(f"\nзамен применено: {total}{' (dry-run)' if args.dry_run else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
